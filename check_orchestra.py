def часть_7(отчёт: Отчёт, агент: MemoryAgent, мок: МокТрекера, база: str,
            конфиг: str, память: str) -> dict:
    отчёт.часть(7, "Пауза на подтверждении и продолжение другим экземпляром агента")
    было = _комментарии(мок, ЗАДАЧА)
    агент.включить_инструменты(["tracker", "pipeline"])
    агент.подключить_инструменты()
    текст = f"Разбор проверкой оркестровки {time.strftime('%H:%M:%S')}"
    сценарий = _Сценарий(
        _план("прокомментировать задачу", "tracker__get_issue", "tracker__add_comment"),
        _вызов("c1", "tracker__get_issue", {"key": ЗАДАЧА}),
        _вызов("c2", "tracker__add_comment", {"key": ЗАДАЧА, "text": текст}))
    прежний = агент.client
    агент.client = сценарий
    try:
        флоу = агент.флоу(f"Прокомментируй {ЗАДАЧА}")
    finally:
        агент.client = прежний

    отчёт.пункт(флоу["состояние"] == "ждёт",
                f"флоу остановлен на меняющем шаге: состояние «{флоу['состояние']}»")
    отчёт.пункт(флоу["заявка"] > 0,
                f"заведена заявка №{флоу['заявка']} на "
                f"«{флоу['ожидание']['инструмент']}»")
    отчёт.пункт(_комментарии(мок, ЗАДАЧА) == было,
                "до подтверждения в трекере ничего не изменилось")
    строки = _прямо_из_базы(база, "SELECT состояние, заявка, length(цепочка) FROM флоу "
                                  "WHERE номер = ?", (флоу["номер"],))
    отчёт.пункт(строки and строки[0][0] == "ждёт" and строки[0][2] > 100,
                f"в базе сохранены и состояние, и вся переписка: {строки}")
    добытое = [ш["инструмент"] for ш in флоу["шаги"] if ш["состояние"] == "выполнен"]
    отчёт.пункт(добытое == ["tracker__get_issue"],
                f"добытое до паузы сохранено: {добытое} — переделывать не придётся")

    # Подтверждает человек — тем же путём, что и всегда, через заявку.
    агент.confirm_call(флоу["заявка"])
    стало = _комментарии(мок, ЗАДАЧА)
    отчёт.пункт(len(стало) == len(было) + 1 and текст in стало[-1],
                "после подтверждения комментарий появился в трекере по-настоящему")

    # А продолжает работу другой экземпляр агента: так же, как это сделал бы
    # другой процесс — консоль, страница или завтрашний запуск.
    другой = MemoryAgent(base_dir=память, tools=["tracker", "pipeline"], mcp_config=конфиг,
                         judge_semantic=False, router_mode="выкл", seed_project=False)
    другой.client = _Сценарий(Reply(text="Комментарий добавлен, задача разобрана.",
                                    model_key="сценарий"))
    try:
        продолженный = другой.продолжить_флоу(флоу["номер"])
    finally:
        другой.close()
    отчёт.пункт(продолженный["состояние"] == "готов",
                f"другой экземпляр довёл флоу до конца: «{продолженный['состояние']}»")
    подтверждённые = [ш for ш in продолженный["шаги"]
                      if ш["инструмент"] == "tracker__add_comment"
                      and ш["состояние"] == "выполнен"]
    отчёт.пункт(len(подтверждённые) == 1,
                "подтверждённый вызов записан результатом заявки, а не выполнен второй раз")
    отчёт.пункт(len(_комментарии(мок, ЗАДАЧА)) == len(стало),
                "и в трекере от продолжения не появилось второго комментария")
    отчёт.пункт(продолженный["сверка"]["по_плану"] == 2,
                f"сверка после продолжения: {продолженный['сверка']['словами']}")
    return продолженный


def часть_8(отчёт: Отчёт, база: str, флоу: dict) -> None:
    отчёт.часть(8, "Протокол флоу читается прямым запросом к базе")
    таблицы = {с[0] for с in _прямо_из_базы(
        база, "SELECT name FROM sqlite_master WHERE type = 'table'")}
    отчёт.пункт({"флоу", "шаги_флоу"} <= таблицы,
                f"таблицы на месте: {sorted(т for т in таблицы if 'флоу' in т)}")
    # Файл один на всю фоновую жизнь агента. Чтобы это увидеть, достаточно
    # открыть хранилища прошлых дней тем же путём: каждое заводит свои таблицы
    # рядом, а не второй файл.
    from agent.pipeline.store import PipelineStore
    from agent.scheduler.store import ScheduleStore

    расписание = ScheduleStore(база)
    прогоны = PipelineStore(база)
    try:
        соседи = {с[0] for с in _прямо_из_базы(
            база, "SELECT name FROM sqlite_master WHERE type = 'table'")}
    finally:
        расписание.close()
        прогоны.close()
    отчёт.пункт({"задания", "прогоны", "флоу"} <= соседи,
                "и лежат в том же файле, что расписание Дня 18 и прогоны Дня 19: "
                + ", ".join(sorted(соседи & {"задания", "запуски", "прогоны",
                                             "шаги_конвейера", "флоу", "шаги_флоу"})))
    строка = _прямо_из_базы(база, "SELECT запрос, состояние, план, сверка, серверы "
                                  "FROM флоу WHERE номер = ?", (флоу["номер"],))[0]
    план = json.loads(строка[2] or "{}")
    сверка = json.loads(строка[3] or "{}")
    отчёт.пункт(bool(план.get("шаги")),
                f"план сохранён целиком: {len(план.get('шаги', []))} шагов")
    отчёт.пункт(bool(сверка.get("словами")), f"сверка сохранена: {сверка.get('словами')}")
    шаги = _прямо_из_базы(база, "SELECT место, инструмент, состояние, по_плану FROM шаги_флоу "
                                "WHERE флоу = ? ORDER BY место", (флоу["номер"],))
    отчёт.пункт(len(шаги) == len(флоу["шаги"]),
                f"шагов в базе столько же, сколько в протоколе: {len(шаги)}")
    порядок_в_базе = [с[1] for с in шаги]
    порядок_в_ответе = [ш["инструмент"] for ш in флоу["шаги"]]
    отчёт.пункт(порядок_в_базе == порядок_в_ответе,
                f"и порядок тот же: {' → '.join(порядок_в_базе)}")
    отчёт.пункт(all(с[3] in (0, 1, 2, 3, 4, 5, 6) for с in шаги),
                "у каждого шага записано, какому пункту плана он отвечает")


def часть_9(отчёт: Отчёт, конфиг: str, маршрут_итоги: dict, флоу: dict,
            офлайн: bool) -> None:
    отчёт.часть(9, "Цена оркестровки")
    все_серверы = amcp.Toolbox([], конфиг)
    выбранные = amcp.Toolbox(["tracker", "pipeline"], конфиг)
    try:
        все_серверы.открыть()
        выбранные.открыть()
        всего = все_серверы.токенов()
        часть = выбранные.токенов()
        отчёт.пункт(всего > 0,
                    f"описания ВСЕХ серверов: {len(все_серверы.инструменты)} инструментов, "
                    f"{всего} токенов в каждом запросе")
        отчёт.пункт(часть < всего,
                    f"описания выбранных двух: {len(выбранные.инструменты)} инструментов, "
                    f"{часть} токенов — экономия {всего - часть} на каждый запрос")
        отчёт(f"      маршрут стоит одного круга дешёвой модели (~{всего // 20} токенов "
              "описаний серверов), а экономит эту разницу в каждом круге флоу")
        отчёт(f"      по серверам: " + ", ".join(
            f"{имя} {sum(и.tokens() for и in список)}"
            for имя, список in sorted(
                {и.сервер: [т for т in все_серверы.инструменты if т.сервер == и.сервер]
                 for и in все_серверы.инструменты}.items())))
    finally:
        все_серверы.close()
        выбранные.close()
    if not офлайн and флоу:
        отчёт.пункт(флоу.get("кругов", 0) > 0,
                    f"живой флоу: кругов модели {флоу.get('кругов')}, "
                    f"вызовов {флоу.get('вызовов')}, "
                    f"время {_секунды(флоу.get('секунд', 0))}")
    if маршрут_итоги:
        отчёт.пункт(True, "маршрут выбирал серверы для "
                          f"{len(маршрут_итоги)} запросов — ни один не получил все шесть")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 20: оркестровка MCP.")
    разбор.add_argument("--без-модели", dest="offline", action="store_true",
                        help="только те части, которым модель не нужна")
    разбор.add_argument("--модель", dest="model", default="ds-flash",
                        help="ключ модели для живых частей")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ",
                        help="дописать отчёт в markdown-файл")
    аргументы = разбор.parse_args()

    отчёт = Отчёт()
    отчёт("Проверка Дня 20: оркестровка нескольких MCP-серверов")
    отчёт(f"Время: {time.strftime('%Y-%m-%d %H:%M')}; модель: "
          + ("не вызывается" if аргументы.offline else аргументы.model))
    начало = time.monotonic()

    мок = МокТрекера()
    мок.запустить()
    каталог = tempfile.mkdtemp(prefix="check-orchestra-")
    память = os.path.join(каталог, "memory")
    отчёты = os.path.join(каталог, "reports")
    os.makedirs(память, exist_ok=True)
    os.makedirs(отчёты, exist_ok=True)
    _наполнить_память(память)
    база = os.path.join(память, "scheduler.db")
    конфиг = _файл_серверов(каталог, мок.адрес, база, отчёты,
                            модель="" if аргументы.offline else аргументы.model)
    os.environ["FLOW_RULES"] = os.path.join(КОРЕНЬ, "flow-rules.json")

    вопрос = (f"Разбери задачу {ЗАДАЧА}: прочитай её в трекере, подними, что о ней знает "
              "наша память, уточни в документации django рекомендации по теме задачи и "
              "сохрани короткий отчёт файлом")
    агент = MemoryAgent(model_key=аргументы.model, base_dir=память, tools=[],
                        mcp_config=конфиг, judge_semantic=False, router_mode="выкл",
                        seed_project=False)
    флоу: dict = {}
    маршрут_итоги: dict = {}
    try:
        серверы = часть_1(отчёт, конфиг)
        часть_2(отчёт, серверы)
        if not аргументы.offline:
            маршрут_итоги = часть_3(отчёт, агент, серверы)
            часть_4(отчёт, агент, вопрос)
            флоу = часть_5(отчёт, агент, база, отчёты, вопрос)
        else:
            for номер, имя in ((3, "Маршрут моделью"), (4, "План"),
                               (5, "Длинный флоу по нескольким серверам")):
                отчёт.часть(номер, имя)
                отчёт("  (пропущено: запуск с «--без-модели»)")
        часть_6(отчёт, агент, мок, база)
        продолженный = часть_7(отчёт, агент, мок, база, конфиг, память)
        часть_8(отчёт, база, флоу or продолженный)
        часть_9(отчёт, конфиг, маршрут_итоги, флоу, аргументы.offline)
    finally:
        агент.close()
        мок.остановить()

    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}. Отчёты: {отчёты}")

    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as файл_отчёта:
            файл_отчёта.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
