def _прямо_из_базы(база: str, запрос: str, параметры: tuple = ()) -> list[tuple]:
    """Запрос к файлу SQLite мимо нашего кода: данные проверяются, а не пересказываются."""
    соединение = sqlite3.connect(база)
    try:
        return соединение.execute(запрос, параметры).fetchall()
    finally:
        соединение.close()


def _шаги_из_базы(база: str, прогон: int) -> list[dict]:
    строки = _прямо_из_базы(
        база, "SELECT место, имя, инструмент, ок, вход, подстановки, выход, ошибка "
              "FROM шаги_конвейера WHERE прогон = ? ORDER BY место", (прогон,))
    return [{"место": с[0], "имя": с[1], "инструмент": с[2], "ок": bool(с[3]),
             "вход": json.loads(с[4] or "{}"), "подстановки": json.loads(с[5] or "[]"),
             "выход": json.loads(с[6]) if с[6] else None, "ошибка": с[7]}
            for с in строки]


