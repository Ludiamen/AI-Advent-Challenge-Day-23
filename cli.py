def разобрать_вход(пары: list[str]) -> dict:
    """«ключ=значение» из командной строки в объект входа конвейера.

    Значение остаётся строкой, кроме случая, когда это число или JSON: так
    «--вход сколько=3» даёт число, а «--вход запрос=PostGIS индексы» — строку.
    """
    итог: dict = {}
    for пара in пары or []:
        ключ, знак, значение = пара.partition("=")
        ключ = ключ.strip()
        if not знак or not ключ:
            raise ValueError(f"«{пара}» — не «ключ=значение».")
        значение = значение.strip()
        if значение[:1] in "{[\"" or значение.lstrip("-").isdigit():
            try:
                итог[ключ] = json.loads(значение)
                continue
            except json.JSONDecodeError:
                pass
        итог[ключ] = значение
    return итог


