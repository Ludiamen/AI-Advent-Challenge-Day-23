def часть_6(отчёт: Отчёт, агент: MemoryAgent, ящик: amcp.Toolbox) -> None:
    отчёт.часть(6, "Рубеж подтверждения: заявка на всю цепочку до первого шага")
    матрица = [
        ("pipeline__run_pipeline", {"pipeline": КОНВЕЙЕР}, False,
         "конвейер «отчёт» только читает и пишет в свои отчёты — без заявки"),
        ("pipeline__run_pipeline", {"pipeline": "в-трекер"}, True,
         "конвейер «в-трекер» пишет в чужую систему — нужна заявка"),
        ("pipeline__run_pipeline", {"pipeline": "нетакого"}, True,
         "неизвестный конвейер считается меняющим"),
        ("pipeline__search", None, False, "search — чтение"),
        ("pipeline__save_to_file", None, False,
         "save_to_file пишет в своё хозяйство агента — без заявки"),
        ("tracker__add_comment", None, True, "прямой вызов в чужую систему — заявка"),
    ]
    for имя, аргументы, ожидание, объяснение in матрица:
        отчёт.пункт(ящик.меняет(имя, аргументы) is ожидание, объяснение)
    отчёт.пункт(ящик.меняющие_шаги("в-трекер") == ["tracker__add_comment"],
                "агент называет шаг, из-за которого спрашивает: tracker__add_comment")

    заявки: list = []
    from agent.llm import ToolCall

    просьба = ToolCall(ид="c1", имя="pipeline__run_pipeline",
                       аргументы={"pipeline": "в-трекер", "input": {"задача": "MIG-1"}})
    текст = агент._исполнить_просьбу(просьба, "запиши сводку в MIG-1", [], заявки)
    отчёт.пункт(len(заявки) == 1 and "конвейер «в-трекер»" in текст,
                "просьба модели стала заявкой, а не вызовом")
    отчёт(f"      {текст[:180]}")
    ждут = [з for з in агент.pending_calls()]
    отчёт.пункт(bool(ждут), f"заявка ждёт человека: №{ждут[0]['номер'] if ждут else '—'}")


def часть_7(отчёт: Отчёт, ящик: amcp.Toolbox, хранилище: ScheduleStore, база: str,
            конфиг: str, отчёты: str) -> None:
    отчёт.часть(7, "Конвейер по расписанию: выполняет отдельный процесс")
    было = len(_прямо_из_базы(база, "SELECT номер FROM прогоны"))
    задание = ящик.вызвать("scheduler__schedule_job", {
        "tool": "pipeline__run_pipeline", "schedule": "каждые 3с",
        "arguments": {"pipeline": "память", "input": {"запрос": "миграция"}},
        "why": "регулярная выжимка"})
    номер = int((задание.данные or {}).get("задание", {}).get("номер", 0))
    отчёт.пункт(задание.ок and номер > 0,
                f"конвейер поставлен в расписание Дня 18: задание №{номер}, каждые 3с")

    работник = Работник(база, конфиг, тик=1.0)
    работник.запустить(секунд=9)
    стало = _ждать(lambda: len(_прямо_из_базы(база, "SELECT номер FROM прогоны")) > было,
                   предел=40)
    работник.дождаться(предел=60)
    отчёт.пункт(стало, "работник в ОТДЕЛЬНОМ процессе выполнил конвейер, пока здесь ничего не шло")
    прогоны = _прямо_из_базы(база, "SELECT номер, конвейер, состояние, задание FROM прогоны "
                                   "WHERE задание = ?", (номер,))
    отчёт.пункт(bool(прогоны) and all(п[2] == "готов" for п in прогоны),
                f"прогонов по заданию: {len(прогоны)}, все готовы; "
                f"в базе записано, каким заданием запущены")
    хранилище.отменить(номер, почему="проверка закончена")

    цифры = scheduler_digest.собрать(хранилище, за="час")
    отчёт.пункт(цифры["конвейеры"]["прогонов"] >= len(прогоны),
                f"сводка Дня 18 знает про конвейеры: прогонов {цифры['конвейеры']['прогонов']}")
    строка = [с for с in scheduler_digest.словами(цифры).splitlines()
              if с.startswith("Конвейеров")]
    отчёт.пункт(bool(строка), f"и называет их словами: {строка[0] if строка else '—'}")


def часть_8(отчёт: Отчёт, агент: MemoryAgent, база: str, отчёты: str) -> dict:
    отчёт.часть(8, "Живая модель: одна просьба — одна цепочка")
    было = len(_прямо_из_базы(база, "SELECT номер FROM прогоны"))
    вопрос = ("Собери отчёт о состоянии миграции и сохрани его файлом. "
              "Посмотри, какие есть конвейеры, и выполни подходящий.")
    ответ = агент.ask(вопрос)
    отчёт.пункт(bool(ответ.text), f"модель ответила ({ответ.usage.get('model_key', '')})")
    отчёт(f"      {' '.join(ответ.text.split())[:220]}")

    вызовы = [в["полное_имя"] for в in ответ.вызовы]
    отчёт.пункт("pipeline__run_pipeline" in вызовы,
                f"модель запустила цепочку одним вызовом: {', '.join(вызовы) or 'вызовов не было'}")
    стало = _прямо_из_базы(база, "SELECT номер, конвейер, состояние, кто FROM прогоны "
                                 "ORDER BY номер DESC LIMIT 1")
    отчёт.пункт(len(_прямо_из_базы(база, "SELECT номер FROM прогоны")) > было,
                f"в базе появился новый прогон: {стало[0] if стало else '—'}")
    отчёт.пункт(bool(ответ.прогон) and ответ.прогон.get("состояние") == "готов",
                "протокол цепочки вернулся вместе с ответом — человеку видно, что было сделано")
    if ответ.прогон:
        for шаг in ответ.прогон.get("шаги", []):
            отчёт(f"      {шаг['шаг']} → {шаг['инструмент']}: "
                  + ("; ".join(шаг.get("получил", [])) or "без подстановок"))
        путь = ответ.прогон.get("итог", "")
        полный = путь if os.path.isabs(путь) else os.path.join(КОРЕНЬ, путь)
        отчёт.пункт(bool(путь) and os.path.exists(полный),
                    f"и файл отчёта лежит на диске: {os.path.basename(полный)}")
    return ответ.usage


def часть_9(отчёт: Отчёт, ящик: amcp.Toolbox, расход: dict, офлайн: bool) -> None:
    отчёт.часть(9, "Цена: во что обходятся описания и что экономит композиция")
    свои = [и for и in ящик.инструменты if и.сервер == "pipeline"]
    цена = {и.имя: и.tokens() for и in свои}
    всего = sum(цена.values())
    for имя, токенов in sorted(цена.items(), key=lambda п: -п[1]):
        отчёт(f"      {имя}: ≈ {токенов} ток.")
    отчёт.пункт(всего > 0, f"описания конвейерного сервера — ≈ {всего} ток. в каждом запросе")
    отчёт.пункт(len(свои) == len(ИНСТРУМЕНТЫ),
                f"инструментов ровно {len(ИНСТРУМЕНТЫ)}: отдельного инструмента на каждый "
                "шаг нет — цепочка описана в файле, а не в схеме")
    весь = ящик.токенов()
    отчёт(f"      весь набор (конвейеры + трекер + планировщик): ≈ {весь} ток.")

    # Композиция экономит не только круги, но и провоз данных через модель:
    # результат шага в контекст не попадает вовсе.
    цепочка = Каталог(os.path.join(КОРЕНЬ, "pipelines.json")).конвейер(КОНВЕЙЕР)
    отчёт.пункт(len(цепочка.шаги) >= 3,
                f"цепочка «{КОНВЕЙЕР}» — {len(цепочка.шаги)} вызова за один круг модели "
                "вместо стольких же кругов с полной историей")
    if офлайн or not расход:
        отчёт("  (расход живого запроса не мерялся: запуск с «--без-модели»)")
        return
    отчёт.пункт(расход.get("prompt_tokens", 0) > всего,
                f"живой запрос с инструментами: {расход.get('prompt_tokens')} входных токенов "
                f"(из них ≈ {весь} — описания инструментов)")


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Проверка Дня 19: композиция MCP-инструментов.")
    разбор.add_argument("--модель", dest="model", default="ds-flash", metavar="КЛЮЧ",
                        help="модель для живых частей (по умолчанию ds-flash)")
    разбор.add_argument("--без-модели", dest="offline", action="store_true",
                        help="пропустить части с живыми вызовами модели")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ",
                        help="дописать отчёт в markdown-файл")
    аргументы = разбор.parse_args()

    отчёт = Отчёт()
    отчёт("Проверка Дня 19: композиция MCP-инструментов")
    отчёт(f"Время: {time.strftime('%Y-%m-%d %H:%M')}; модель: "
          + ("не вызывается" if аргументы.offline else аргументы.model))
    начало = time.monotonic()

    мок = МокТрекера()
    мок.запустить()
    каталог = tempfile.mkdtemp(prefix="check-pipeline-")
    память = os.path.join(каталог, "memory")
    отчёты = os.path.join(каталог, "reports")
    os.makedirs(память, exist_ok=True)
    os.makedirs(отчёты, exist_ok=True)
    _наполнить_память(память)
    база = os.path.join(память, "scheduler.db")
    конфиг = _файл_серверов(каталог, мок.адрес, база, отчёты,
                            модель="" if аргументы.offline else аргументы.model)

    агент = MemoryAgent(model_key=аргументы.model, base_dir=память,
                        tools=["pipeline", "tracker", "scheduler"], mcp_config=конфиг,
                        judge_semantic=False, router_mode="выкл")
    хранилище = ScheduleStore(база)
    try:
        агент.подключить_инструменты()
        ящик = агент.toolbox
        часть_1(отчёт, ящик)
        часть_2(отчёт, ящик, память, отчёты)
        прогон = часть_3(отчёт, ящик, база, отчёты)
        часть_4(отчёт, ящик, база, мок, прогон)
        часть_5(отчёт, ящик, база, отчёты)
        часть_6(отчёт, агент, ящик)
        часть_7(отчёт, ящик, хранилище, база, конфиг, отчёты)
        расход: dict = {}
        if not аргументы.offline:
            расход = часть_8(отчёт, агент, база, отчёты)
        else:
            отчёт.часть(8, "Живая модель: одна просьба — одна цепочка")
            отчёт("  (пропущено: запуск с «--без-модели»)")
        часть_9(отчёт, ящик, расход, аргументы.offline)
    finally:
        хранилище.close()
        агент.close()
        мок.остановить()

    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}. Отчёты: {отчёты}")

    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as файл_отчёта:
            файл_отчёта.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
