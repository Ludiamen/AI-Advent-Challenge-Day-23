def _серверы_оркестра(трекер: "МокТрекера") -> dict:
    """Серверы Дня 20: те же, что у конвейеров, плюс поля маршрутизации.

    Маршрутизатору нужны описания и «темы» — по ним он выбирает, когда модель
    недоступна, и ими же добирает то, что модель пропустила. Боевой Трекер
    здесь представлен тем же сервером с пометками «по_просьбе» и «замещает»:
    проверяется не второй API, а то, что агент не откроет оба разом и не полезет
    в боевую систему без просьбы.
    """
    серверы = _серверы_конвейера(трекер, "нет")
    серверы["tracker"]["темы"] = ["задач", "трекер", "тикет", "mig-", "комментар", "статус"]
    серверы["pipeline"]["темы"] = ["отчёт", "выжимк", "поиск", "память", "сохрани", "файл"]
    серверы["scheduler"]["темы"] = ["расписан", "запланир", "напомн", "сводк", "ежедневн"]
    серверы["tracker-real"] = {
        **{к: з for к, з in серверы["tracker"].items() if к != "темы"},
        "описание": "Тот же сервер, но настоящий Яндекс.Трекер — только по явной просьбе",
        "темы": ["настоящий трекер", "боевой трекер", "яндекс.трекер"],
        "по_просьбе": True,
        "замещает": "tracker",
    }
    return серверы


