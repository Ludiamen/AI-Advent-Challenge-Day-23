"""Поиск в два этапа: запросы → первый этап → слияние → реранкер → фильтр.

    вопрос ─┬──────────────────────────────▶ bge-m3: top-K_до ─┐
            └─ rewrite: 2–3 запроса ───────▶ bge-m3: top-K_до ─┴─ RRF ─▶ порог косинуса
                                                                          │
                              top-K_после ◀─ порог оценки ◀─ реранкер ◀───┘
                                  │           (кросс / эвристика / llm)
                                  ▼
                          фрагменты в промпт

Четыре режима — ровно то, что сравнивается в задании дня:

  база      день 22 как есть: top-5 по косинусу, порог косинуса 0,45;
  фильтр    + второй этап: берём top-K_до, реранкер переупорядочивает, всё ниже
            порога отсекается, остаётся top-K_после;
  rewrite   + переписывание запроса, без реранкера: запросы сливаются RRF;
  полный    rewrite и второй этап вместе.

Порог, K_до, K_после и выбранный реранкер берутся из rag-settings.json — его
пишет подбор (calibrate.py) по 24 вопросам и 5 ловушкам поиска Дня 21. Без
файла действуют значения по умолчанию ниже, и режим так и называется в отчёте.

Каждый этап записывается в Отбор: что пришло, что ушло и почему, сколько
длилось. Это то, что показывают страница, консоль и видео — фильтр, который
нельзя увидеть, нельзя и настроить.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass, field, replace
from typing import Any

from agent.rag import rerank as rr
from agent.rag.rewrite import Переписано, Переписчик, слить
from agent.rag.store import Находка

БАЗА, ФИЛЬТР, REWRITE, ПОЛНЫЙ = "база", "фильтр", "rewrite", "полный"
РЕЖИМЫ_ПОИСКА = (БАЗА, ФИЛЬТР, REWRITE, ПОЛНЫЙ)
ФАЙЛ_НАСТРОЕК = "rag-settings.json"

ПОРОГ_КОСИНУСА = 0.45     # первый этап Дня 22
K_БАЗЫ = 5


@dataclass
class Настройки:
    """Параметры одного прогона поиска. Режим — это набор таких значений."""

    rewrite: bool = False
    реранкер: str = ""               # "" — без второго этапа
    k_до: int = K_БАЗЫ               # кандидатов первого этапа (на каждый запрос)
    k_после: int = K_БАЗЫ            # фрагментов в промпт после фильтра
    порог: float = 0.0               # по оценке реранкера, [0, 1]
    порог_косинуса: float = ПОРОГ_КОСИНУСА
    вариантов: int = 3               # запросов у переписывания
    имя: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# Значения по умолчанию до подбора — осторожные: порог низкий, чтобы не резать
# верное, K_до вчетверо больше K_после, чтобы реранкеру было что поднимать.
# Порог косинуса первого этапа — свойство эмбеддера, а не реранкера: у bge-m3
# посторонние чанки лежат ниже 0,45, у другого эмбеддера полоса будет своя.
ПО_УМОЛЧАНИЮ = {"реранкер": rr.КРОСС, "k_до": 20, "k_после": 5, "порог": 0.05,
                "порог_косинуса": ПОРОГ_КОСИНУСА}


def путь_настроек() -> str:
    from agent.rag.indexer import КОРЕНЬ
    return os.path.abspath(os.getenv("RAG_SETTINGS") or os.path.join(КОРЕНЬ, ФАЙЛ_НАСТРОЕК))


def прочитать_настройки(путь: str = "") -> dict[str, Any]:
    путь = путь or путь_настроек()
    if not os.path.exists(путь):
        return {**ПО_УМОЛЧАНИЮ, "источник": "значения по умолчанию (подбора не было)"}
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    выбрано = данные.get("выбрано", данные)
    итог = {к: выбрано.get(к, з) for к, з in ПО_УМОЛЧАНИЮ.items()}
    итог["источник"] = f"{os.path.basename(путь)} (подбор {данные.get('когда', '?')})"
    return итог


def режимы(путь: str = "") -> dict[str, Настройки]:
    """Четыре режима с подобранными параметрами второго этапа."""
    п = прочитать_настройки(путь)
    косинус = float(п["порог_косинуса"])
    второй = dict(реранкер=п["реранкер"], k_до=int(п["k_до"]), k_после=int(п["k_после"]),
                  порог=float(п["порог"]), порог_косинуса=косинус)
    return {
        БАЗА: Настройки(имя=БАЗА, порог_косинуса=косинус),
        ФИЛЬТР: Настройки(имя=ФИЛЬТР, **второй),
        # rewrite без реранкера: на каждый запрос берётся столько же кандидатов,
        # сколько у второго этапа, а в промпт — те же K_после после слияния.
        REWRITE: Настройки(имя=REWRITE, rewrite=True, k_до=второй["k_до"],
                           k_после=второй["k_после"], порог_косинуса=косинус),
        ПОЛНЫЙ: Настройки(имя=ПОЛНЫЙ, rewrite=True, **второй),
    }


@dataclass
class Кандидат:
    """Судьба одного чанка в отборе — для таблицы на странице и в отчёте."""

    находка: Находка
    rrf: float = 0.0
    судьба: str = ""               # в промпт | ниже порога | за пределами K | порог косинуса

    def to_dict(self) -> dict[str, Any]:
        н = self.находка
        return {"chunk_id": н.чанк.chunk_id, "source": н.чанк.источник, "section": н.чанк.раздел,
                "pages": н.чанк.страницы, "clause": н.чанк.пункт, "cos": round(н.оценка, 4),
                "rrf": self.rrf, "rerank": None if н.реранк is None else round(н.реранк, 4),
                "rank_before": н.место_до, "rank": н.место, "fate": self.судьба}


@dataclass
class Отбор:
    вопрос: str
    настройки: Настройки
    фрагменты: list[Находка] = field(default_factory=list)
    кандидаты: list[Кандидат] = field(default_factory=list)
    этапы: list[dict[str, Any]] = field(default_factory=list)
    переписано: Переписано | None = None
    секунд: float = 0.0
    ошибки: list[str] = field(default_factory=list)

    @property
    def запросы(self) -> list[str]:
        return self.переписано.все if self.переписано else [self.вопрос]

    def to_dict(self) -> dict[str, Any]:
        return {"question": self.вопрос, "settings": self.настройки.to_dict(),
                "queries": self.запросы,
                "rewrite": self.переписано.to_dict() if self.переписано else None,
                "stages": self.этапы, "candidates": [к.to_dict() for к in self.кандидаты],
                "kept": len(self.фрагменты), "seconds": round(self.секунд, 2),
                "errors": list(self.ошибки)}


class Поисковик:
    """Второй этап поверх индекса Дня 21. Реранкеры и переписчик — ленивые."""

    def __init__(self, индексатор, клиент=None, стратегия: str = "структура",
                 путь_настроек_: str = "") -> None:
        self.индексатор = индексатор
        self.клиент = клиент
        self.стратегия = стратегия
        self.путь_настроек = путь_настроек_
        self._реранкеры: dict[str, rr.Реранкер] = {}
        self._переписчик: Переписчик | None = None

    # --- составные части ------------------------------------------------------

    def реранкер(self, имя: str) -> rr.Реранкер:
        if имя not in self._реранкеры:
            self._реранкеры[имя] = rr.создать(
                имя, клиент=self.клиент, хранилище=self.индексатор.хранилище,
                база=self.индексатор.база, стратегия=self.стратегия)
        return self._реранкеры[имя]

    def переписчик(self) -> Переписчик:
        if self._переписчик is None:
            if self.клиент is None:
                raise rr.ОшибкаРеранкера("Переписыванию запроса нужен клиент модели")
            self._переписчик = Переписчик(self.клиент, self.индексатор.база, self._документы())
        return self._переписчик

    def _документы(self) -> list[str]:
        """Названия файлов и листов — словарь корпуса для переписывания."""
        имена: list[str] = []
        for д in self.индексатор.хранилище.документы(self.стратегия):
            имена.append(os.path.splitext(д["источник"])[0])
        for ч in self.индексатор.хранилище.чанки(self.стратегия):
            if ч.раздел.startswith("Лист «") and ч.раздел not in имена:
                имена.append(ч.раздел)
        return имена

    def режимы(self) -> dict[str, Настройки]:
        return режимы(self.путь_настроек)

    def настройки(self, режим: str | Настройки) -> Настройки:
        if isinstance(режим, Настройки):
            return режим
        все = self.режимы()
        if режим not in все:
            raise ValueError(f"Нет режима поиска «{режим}». Есть: {', '.join(РЕЖИМЫ_ПОИСКА)}")
        return все[режим]

    # --- сам поиск ------------------------------------------------------------

    def найти(self, вопрос: str, режим: str | Настройки = БАЗА) -> Отбор:
        н = self.настройки(режим)
        отбор = Отбор(вопрос=вопрос, настройки=н)
        старт = time.monotonic()

        # 1. Запросы: исходный вопрос и, если нужно, переписанные.
        if н.rewrite:
            try:
                отбор.переписано = self.переписчик().переписать(вопрос)
            except rr.ОшибкаРеранкера as exc:
                отбор.переписано = Переписано(вопрос=вопрос, ошибка=str(exc))
            if отбор.переписано.ошибка:
                отбор.ошибки.append(отбор.переписано.ошибка)
            отбор.этапы.append({"этап": "запросы", **отбор.переписано.to_dict(),
                                "all": отбор.переписано.все})

        # 2. Первый этап: bge-m3 по каждому запросу.
        t = time.monotonic()
        списки = [self.индексатор.найти(з, self.стратегия, н.k_до) for з in отбор.запросы]
        слито = слить(списки) if len(списки) > 1 else [(х, 0.0, х.оценка) for х in списки[0]]
        # Слияние даёт кандидатов больше, чем K_до на один запрос; реранкеру
        # отдаём не больше K_до × число запросов — это и есть «top-K до».
        кандидаты = [Кандидат(находка=х, rrf=rrf) for х, rrf, _ in слито]
        отбор.этапы.append({"этап": "поиск", "запросов": len(списки),
                            "по_запросам": [len(с) for с in списки],
                            "кандидатов": len(кандидаты), "k_до": н.k_до,
                            "секунд": round(time.monotonic() - t, 2)})
        for место, к in enumerate(кандидаты, 1):
            к.находка = replace(к.находка, место=место, место_до=место, реранк=None)

        # 3. Порог косинуса — фильтр откровенно посторонних.
        живые = []
        for к in кандидаты:
            if к.находка.оценка < н.порог_косинуса:
                к.судьба = "порог косинуса"
            else:
                живые.append(к)
        отбор.этапы.append({"этап": "порог косинуса", "порог": н.порог_косинуса,
                            "осталось": len(живые), "отсечено": len(кандидаты) - len(живые)})

        # 4. Второй этап: реранкер переупорядочивает, порог и K_после режут.
        if н.реранкер and живые:
            реранкер = self.реранкер(н.реранкер)
            t = time.monotonic()
            из_кэша, посчитано = реранкер.из_кэша, реранкер.посчитано
            try:
                оценки = реранкер.оценить(вопрос, [к.находка for к in живые])
            except rr.ОшибкаРеранкера as exc:
                # Реранкер недоступен — отвечаем по первому этапу, но честно
                # пишем, что второго этапа не было.
                отбор.ошибки.append(str(exc))
                оценки = None
            этап: dict[str, Any] = {"этап": "реранк", "реранкер": н.реранкер,
                                    "секунд": round(time.monotonic() - t, 2),
                                    "из_кэша": реранкер.из_кэша - из_кэша,
                                    "посчитано": реранкер.посчитано - посчитано}
            if оценки is not None:
                for к, о in zip(живые, оценки):
                    к.находка = replace(к.находка, реранк=о)
                живые.sort(key=lambda к: (-к.находка.реранк, к.находка.место_до))
                прошли = [к for к in живые if к.находка.реранк >= н.порог]
                for к in живые:
                    if к.находка.реранк < н.порог:
                        к.судьба = "ниже порога"
                этап["ошибка"] = ""
            else:
                прошли = живые
                этап["ошибка"] = отбор.ошибки[-1]
            отбор.этапы.append(этап)
        else:
            прошли = живые
        оставлены = прошли[:н.k_после]
        for к in прошли[н.k_после:]:
            к.судьба = "за пределами K"
        for место, к in enumerate(оставлены, 1):
            к.судьба = "в промпт"
            к.находка = replace(к.находка, место=место)
        отбор.этапы.append({"этап": "фильтр", "порог": н.порог if н.реранкер else None,
                            "k_после": н.k_после, "осталось": len(оставлены),
                            "ниже_порога": sum(к.судьба == "ниже порога" for к in кандидаты),
                            "за_пределами_k": sum(к.судьба == "за пределами K" for к in кандидаты)})
        # Порядок в таблице: сначала то, что ушло в промпт, дальше — остальное
        # по оценке второго этапа (или первого, если его не было).
        кандидаты.sort(key=lambda к: (к.судьба != "в промпт",
                                      -(к.находка.реранк if к.находка.реранк is not None else -1),
                                      к.находка.место_до))
        отбор.кандидаты = кандидаты
        отбор.фрагменты = [к.находка for к in оставлены]
        отбор.секунд = time.monotonic() - старт
        return отбор
