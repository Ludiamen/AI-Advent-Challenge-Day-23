"""Конвейер индексации целиком: каталог документов → индекс в SQLite.

    документы ──извлечь──▶ блоки ──нарезать──▶ чанки ──эмбеддер──▶ векторы ──▶ docs.db
                 (OCR сканов)        (фикс | структура)     (кэш по хэшу)

Индексатор — единственное место, которое знает, где лежат документы и индекс;
консоль, веб и MCP-сервер зовут его, а не собирают конвейер каждый по-своему.
Пути берутся из окружения (DOCS_DIR, RAG_DIR), как MEMORY_DIR у памяти:
свой MCP-сервер запускается отдельным процессом и должен видеть тот же индекс.

Ход работы сообщается обратным вызовом `прогресс(этап, сделано, всего, что)`.
Консоль печатает его строкой, веб — полоской: индексация на CPU идёт минуты,
и молчащая страница выглядит как зависшая.
"""

from __future__ import annotations

import os
import time
from typing import Callable

from agent.rag.chunking import (МАКС, МИН, ПЕРЕКРЫТИЕ, РАЗМЕР, СТРАТЕГИИ, Чанк, нарезать,
                                статистика)
from agent.rag.embed import создать_эмбеддер
from agent.rag.extract import Документ, извлечь, найти_документы
from agent.rag.store import Находка, ОшибкаИндекса, ХранилищеИндекса, хэш_текста

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

Прогресс = Callable[[str, int, int, str], None]

# Сколько новых векторов считать между записями в кэш.
ПАЧКА_КЭША = 64


def настройки_по_умолчанию() -> dict:
    каталог_индекса = os.path.abspath(os.getenv("RAG_DIR") or os.path.join(КОРЕНЬ, "index"))
    return {
        "документы": os.path.abspath(os.getenv("DOCS_DIR") or os.path.join(КОРЕНЬ, "DocsSample")),
        "индекс": каталог_индекса,
        "база": os.path.join(каталог_индекса, "docs.db"),
        "кэш_ocr": os.path.join(каталог_индекса, "ocr"),
        "эмбеддер": os.getenv("RAG_EMBEDDER") or "ollama",
    }


def _молча(этап: str, сделано: int, всего: int, что: str) -> None:
    pass


class Индексатор:
    def __init__(self, документы: str = "", индекс: str = "", эмбеддер: str = "",
                 ocr: bool = True) -> None:
        умолчания = настройки_по_умолчанию()
        self.каталог = os.path.abspath(документы or умолчания["документы"])
        каталог_индекса = os.path.abspath(индекс or умолчания["индекс"])
        self.база = os.path.join(каталог_индекса, "docs.db")
        self.кэш_ocr = os.path.join(каталог_индекса, "ocr")
        self.эмбеддер = создать_эмбеддер(эмбеддер or умолчания["эмбеддер"])
        self.ocr = ocr
        self.хранилище = ХранилищеИндекса(self.база)

    # --- извлечение -----------------------------------------------------------

    def извлечь(self, прогресс: Прогресс = _молча) -> list[Документ]:
        файлы = найти_документы(self.каталог)
        документы = []
        for i, путь in enumerate(файлы, start=1):
            прогресс("извлечение", i - 1, len(файлы), os.path.basename(путь))
            документы.append(извлечь(путь, self.каталог, self.кэш_ocr, self.ocr))
        прогресс("извлечение", len(файлы), len(файлы), "готово")
        return документы

    # --- сборка ---------------------------------------------------------------

    def построить(self, стратегии: tuple[str, ...] | list[str] = СТРАТЕГИИ,
                  размер: int = РАЗМЕР, перекрытие: int = ПЕРЕКРЫТИЕ, макс: int = МАКС,
                  мин: int = МИН, прогресс: Прогресс = _молча,
                  документы: list[Документ] | None = None) -> dict:
        """Пересобрать индекс указанных стратегий. Возвращает отчёт для человека."""
        беда = self.эмбеддер.проверить()
        if беда:
            raise ОшибкаИндекса(беда)
        начало = time.monotonic()
        документы = документы if документы is not None else self.извлечь(прогресс)
        секунд_извлечения = time.monotonic() - начало
        отчёт: dict = {
            "каталог": self.каталог, "база": self.база, "эмбеддер": self.эмбеддер.имя,
            "документов": len(документы), "секунд_извлечения": round(секунд_извлечения, 1),
            "документы": [д.кратко() for д in документы], "стратегии": {},
        }
        for стратегия in стратегии:
            старт = time.monotonic()
            параметры = ({"размер": размер, "перекрытие": перекрытие}
                         if стратегия == "фикс" else {"макс": макс, "мин": мин})
            чанки: list[Чанк] = []
            for д in документы:
                чанки.extend(нарезать(д, стратегия, размер, перекрытие, макс, мин))
            прогресс(f"векторы «{стратегия}»", 0, len(чанки), "")
            векторы, из_кэша, секунд_векторов = self._векторы(чанки, стратегия, прогресс)
            размерность = len(векторы[0]) if векторы else 0
            self.хранилище.записать(
                стратегия, self.эмбеддер.имя, размерность, параметры, self.каталог,
                документы, чанки, векторы, time.monotonic() - старт + секунд_извлечения,
                секунд_векторов, из_кэша)
            отчёт["стратегии"][стратегия] = {
                "параметры": параметры, "размерность": размерность, "из_кэша": из_кэша,
                "секунд_векторов": round(секунд_векторов, 1),
                "секунд": round(time.monotonic() - старт, 1), **статистика(чанки),
            }
        отчёт["секунд"] = round(time.monotonic() - начало, 1)
        прогресс("готово", 1, 1, "")
        return отчёт

    def _векторы(self, чанки: list[Чанк], стратегия: str,
                 прогресс: Прогресс) -> tuple[list[list[float]], int, float]:
        тексты = [ч.текст_для_вектора for ч in чанки]
        готовые = self.хранилище.из_кэша(self.эмбеддер.имя, тексты)
        нужно = list(dict.fromkeys(т for т in тексты if хэш_текста(т) not in готовые))
        старт = time.monotonic()
        # Векторы считаются пачками по ПАЧКА_КЭША и сразу ложатся в кэш: первая
        # сборка на CPU идёт около часа, и сбой на сороковой минуте без этого
        # выбрасывал бы всё посчитанное. Повторный запуск продолжит с места.
        for начало in range(0, len(нужно), ПАЧКА_КЭША):
            пачка = нужно[начало:начало + ПАЧКА_КЭША]
            новые = self.эмбеддер.векторы(
                пачка, прогресс=lambda с, в, н=начало: прогресс(
                    f"векторы «{стратегия}»", len(тексты) - len(нужно) + н + с,
                    len(тексты), f"новых {н + с}/{len(нужно)}"))
            self.хранилище.в_кэш(self.эмбеддер.имя, list(zip(пачка, новые)))
            готовые.update({хэш_текста(т): в for т, в in zip(пачка, новые)})
        секунд = time.monotonic() - старт
        return ([готовые[хэш_текста(т)] for т in тексты], len(тексты) - len(нужно), секунд)

    # --- поиск ----------------------------------------------------------------

    def проверить_эмбеддер(self, стратегия: str) -> None:
        """Индекс должен быть собран тем же эмбеддером, что считает запрос."""
        индекс = self.хранилище.индекс(стратегия)
        if not индекс:
            raise ОшибкаИндекса(
                f"Индекса стратегии «{стратегия}» нет. Соберите: python cli.py --индексировать")
        if индекс["эмбеддер"] != self.эмбеддер.имя:
            raise ОшибкаИндекса(
                f"Индекс «{стратегия}» собран эмбеддером {индекс['эмбеддер']}, а запрос считает "
                f"{self.эмбеддер.имя}. Векторы разных моделей несравнимы — укажите "
                f"--эмбеддер {индекс['эмбеддер']} или пересоберите индекс")

    def найти(self, запрос: str, стратегия: str = "структура", сколько: int = 5,
              источник: str = "") -> list[Находка]:
        if not запрос.strip():
            raise ОшибкаИндекса("Пустой запрос")
        self.проверить_эмбеддер(стратегия)
        вектор = self.эмбеддер.векторы([запрос], запрос=True)[0]
        return self.хранилище.искать(стратегия, вектор, сколько, источник)

    def найти_везде(self, запрос: str, сколько: int = 5) -> dict[str, list[Находка]]:
        """Один запрос во все собранные стратегии — для сравнения бок о бок.

        Вектор запроса считается один раз: стратегии отличаются чанками, а не
        моделью, и второй вызов эмбеддера был бы лишним.
        """
        индексы = [и["стратегия"] for и in self.хранилище.индексы()]
        if not индексы:
            raise ОшибкаИндекса("Индекс пуст. Соберите: python cli.py --индексировать")
        for с in индексы:
            self.проверить_эмбеддер(с)
        вектор = self.эмбеддер.векторы([запрос], запрос=True)[0]
        return {с: self.хранилище.искать(с, вектор, сколько) for с in индексы}
