def _секунды(значение: float) -> str:
    return f"{значение:.1f}".replace(".", ",") + " с"


def показать_осмотр(о: mcp.Inspection, схема: bool = False) -> None:
    с = о.сервер
    значок = "●" if о.ок else ("○" if о.пропущен else "✗")
    print(f"{значок} {с.имя} — {с.транспорт}: {с.куда}")
    if с.описание:
        print(f"  {с.описание}")
    if о.пропущен:
        print(f"  Пропущен: {о.ошибка}")
        return
    if not о.ок:
        print(f"  Соединение НЕ установлено (этап «{о.этап}»): {о.ошибка}")
        if о.подсказка:
            print(f"  Подсказка: {о.подсказка}")
        if о.журнал:
            print("  Журнал сервера (stderr):")
            for строка in о.журнал.splitlines():
                print(f"    | {строка}")
        return

    р = о.рукопожатие
    print(f"  Соединение: установлено за {_секунды(о.подключение_с)} · "
          f"рукопожатие {р.способ} · протокол {р.протокол}")
    о_сервере = " ".join(ч for ч in (р.имя, р.версия) if ч)
    if р.заголовок:
        о_сервере += f" («{р.заголовок}»)"
    print(f"  Сервер: {о_сервере or 'не назвался'}")
    print(f"  Возможности: {', '.join(р.возможности) or 'не заявлены'}")
    if р.инструкции:
        первая = р.инструкции.splitlines()[0]
        print(f"  Инструкции сервера: {первая[:150]}{'…' if len(первая) > 150 else ''}")
    закрыто = len(о.инструменты) - len(о.разрешено)
    print(f"  Инструменты: {len(о.инструменты)}"
          + (f" (разрешено {len(о.разрешено)}, закрыто {закрыто})" if закрыто else "")
          + f" · получены за {_секунды(о.список_с)}, страниц {о.страниц}"
          + f" · схема ≈ {tokens.format_tokens(о.токенов)} ток. в каждом запросе")
    for номер, и in enumerate(о.инструменты, 1):
        заголовок = f" — {и.заголовок}" if и.заголовок and и.заголовок != и.имя else ""
        пометки = [и.доступ]
        if not и.разрешён:
            пометки.append(f"ЗАКРЫТ: {и.почему_закрыт}")
        print(f"  {номер:>3}. {и.имя}{заголовок}  [{'; '.join(пометки)}]")
        if и.описание:
            первая = " ".join(и.описание.split())
            print(f"       {первая[:200]}{'…' if len(первая) > 200 else ''}")
        параметры = и.parameters()
        if параметры:
            for п in параметры:
                звезда = "*" if п.обязательный else ""
                пояснение = f" — {п.описание[:90]}" if п.описание else ""
                print(f"       · {п.имя}{звезда} ({п.тип}){пояснение}")
        else:
            print("       · без параметров")
        if схема:
            for строка in json.dumps(и.входная_схема, ensure_ascii=False, indent=2).splitlines():
                print(f"       {строка}")


def показать_mcp(имя: str, путь: str = "", схема: bool = False) -> int:
    """Подключиться к серверам и показать их инструменты."""
    реестр = _реестр(путь)
    if реестр is None:
        return 1
    if not реестр.servers:
        print(f"В {реестр.path} нет серверов.")
        return 1
    try:
        имена = None if имя == "*" else [реестр.server(имя).имя]
    except mcp.MCPConfigError as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1

    print(LINE)
    print(f"MCP: подключение к серверам из {реестр.path}")
    print(LINE)
    осмотры = реестр.inspect(имена)
    for о in осмотры:
        показать_осмотр(о, схема)
        print(LINE)
    итог = mcp.summary(осмотры)
    print(f"Подключено {итог['подключено']} из {итог['серверов']}"
          + (f", пропущено {итог['пропущено']}" if итог["пропущено"] else "")
          + (f", сбоев {итог['сбоев']}" if итог["сбоев"] else "")
          + f". Инструментов {итог['инструментов']}, разрешено {итог['разрешено']}"
          + f"; их схема ≈ {tokens.format_tokens(итог['токенов'])} ток. на каждый запрос к модели.")
    if итог["повторы_имён"]:
        print("Повторяются имена для модели: " + ", ".join(итог["повторы_имён"]))
    print("Звёздочка — обязательный параметр. «*» в фильтре — любой хвост имени.")
    return 1 if итог["сбоев"] else 0


