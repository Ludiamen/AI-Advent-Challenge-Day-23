#!/usr/bin/env python3
"""Проверка задания Дня 19: композиция MCP-инструментов.

Задание требует трёх инструментов (получить данные — обработать — сохранить),
пайплайна из них и двух доказательств: что цепочка выполняется автоматически и
что данные между инструментами передаются корректно. Скрипт устроен по этим
пунктам и проверяет настоящую цепочку из pipelines.json репозитория, а не
придуманную на время проверки.

  Часть 1  РЕГИСТРАЦИЯ. pipeline_server.py поднимается настоящим MCP-сервером
           (stdio) и отдаёт tools/list: шесть инструментов, пометки поведения,
           описания параметров. Здесь же видно, что цепочки описаны в файле и
           модель может о них спросить (list_pipelines).
  Часть 2  ТРИ ИНСТРУМЕНТА ПО ОТДЕЛЬНОСТИ. search находит то, что лежит в
           памяти агента (сверка с файлами памяти напрямую), summarize считает
           по данным, save_to_file кладёт файл на диск — и файл читается мимо
           нашего кода.
  Часть 3  ЦЕПОЧКА ВЫПОЛНЯЕТСЯ САМА. Один вызов run_pipeline — четыре шага
           через три разных MCP-сервера, никто не подсказывает следующий.
           Протокол прогона ищется в SQLite прямым запросом.
  Часть 4  ДАННЫЕ ПЕРЕДАЮТСЯ КОРРЕКТНО. Вход каждого шага сверяется с выходом
           предыдущего — по записям в базе. Затем данные в трекере меняются
           через его API, и новое значение доезжает до файла отчёта: это
           сквозная проверка «от чужой системы до диска».
  Часть 5  СБОЙ ПОСРЕДИНЕ. Шаг, которому нечего вернуть, останавливает цепочку:
           следующий шаг не выполняется, файл не появляется, в протоколе видно,
           на чём встали. Отдельно — обрыв передачи: ссылка на поле, которого
           в ответе нет.
  Часть 6  РУБЕЖ ПОДТВЕРЖДЕНИЯ. Конвейер с шагом в чужую систему модель не
           запускает сама: заявка заводится целиком на цепочку, до первого шага.
  Часть 7  ПО РАСПИСАНИЮ. Конвейер ставится в расписание Дня 18 и выполняется
           отдельным процессом-работником; сводка называет его прогоны.
  Часть 8  ЖИВАЯ МОДЕЛЬ. Модель сама выбирает конвейер и запускает его одним
           вызовом вместо трёх, а результат — файл на диске.
  Часть 9  ЦЕНА. Во сколько обходятся описания и сколько экономит композиция.

Мок-трекера, работника и сервер скрипт поднимает сам и гасит в конце.

Запуск:
    python check_pipeline.py                    # всё, включая живые вызовы модели
    python check_pipeline.py --без-модели       # части 1-7, 9: ни одного запроса к LLM
    python check_pipeline.py --модель ds-flash  # какой моделью проверять
    python check_pipeline.py --в RESULTS.md     # дописать отчёт в файл
"""

