def подготовить_индекс() -> str:
    """Копия рабочего index/ в каталог прогона; возвращает chunk_id пункта об оплате.

    Чек-лист пересобирает индекс, а делать это на рабочем index/ незачем. Копия
    несёт все векторы в кэше, поэтому пересборка попадает в кэш и идёт секунды,
    а не час на CPU. chunk_id для шага «--чанк» берётся прямо из базы: он
    зависит от имени файла и порядка резки, и вписывать его в скрипт руками
    значило бы сломать шаг при первой правке разбиения.
    """
    исходный = os.path.join(КОРЕНЬ, "index")
    копия = os.path.join(КОРЕНЬ, ИНДЕКС_ОТН)
    if not os.path.exists(os.path.join(исходный, "docs.db")):
        return ""
    shutil.rmtree(копия, ignore_errors=True)
    shutil.copytree(исходный, копия)
    # Настройки второго этапа (День 23) — тоже копия: шаг подбора их переписывает,
    # а рабочий rag-settings.json чек-листу трогать незачем. Путь уходит всем
    # командам через окружение.
    настройки = os.path.join(КОРЕНЬ, "rag-settings.json")
    if os.path.exists(настройки):
        shutil.copy(настройки, os.path.join(копия, "rag-settings.json"))
    os.environ["RAG_SETTINGS"] = os.path.join(копия, "rag-settings.json")
    import sqlite3
    с = sqlite3.connect(os.path.join(копия, "docs.db"))
    try:
        ряд = с.execute("SELECT chunk_id FROM чанки WHERE стратегия='структура' "
                        "AND текст LIKE '%не позднее 20 числа%' ORDER BY номер LIMIT 1").fetchone()
    finally:
        с.close()
    return ряд[0] if ряд else ""


