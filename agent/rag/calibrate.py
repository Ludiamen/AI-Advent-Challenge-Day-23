        f"порог = {в['порог']}. В среднем по режимам без rewrite и с ним: полнота "
        f"{в['среднее']['полнота']:.2f}, MRR {в['среднее']['mrr']:.2f}, hit@1 {в['среднее']['hit@1']:.2f}, "
        f"фрагментов {в['среднее']['фрагментов']:.1f}, ловушек с пустым контекстом "
        f"{в['среднее']['ловушки_пусто']:.0%}.",
