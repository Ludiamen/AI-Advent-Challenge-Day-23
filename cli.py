def мастер_настройки(agent: MemoryAgent) -> int:
    """Интерактивный мастер: вопросы берутся из описания предпочтений."""
    print(LINE)
    print(f"НАСТРОЙКА ПРОФИЛЯ «{agent.user_id}»")
    print(LINE)
    print("Enter — оставить как есть. Ctrl+C — выйти, ничего не меняя.")
    профиль = agent.profile()
    ответы: dict[str, object] = {}
    try:
        for вопрос in agent.setup_questions():
            текущее = профиль[вопрос["раздел"]][вопрос["ключ"]]
            показ = {True: "да", False: "нет"}.get(текущее, текущее) or "—"
            print(f"\n{вопрос['вопрос']}")
            if вопрос["пояснение"]:
                print(f"  {вопрос['пояснение']}")
            if вопрос["варианты"]:
                print(f"  варианты: {', '.join(вопрос['варианты'])}")
            ответ = input(f"  [{показ}] > ").strip()
            if ответ:
                ответы[f"{вопрос['раздел']}/{вопрос['ключ']}"] = ответ
    except (EOFError, KeyboardInterrupt):
        print("\nОтменено, профиль не тронут.")
        return 1

    try:
        профиль = agent.setup(ответы)
    except AgentError as exc:
        print(f"\nОшибка: {exc}")
        return 1
    print(LINE)
    print("Профиль сохранён:", preferences.summary(профиль))
    print("Файл:", agent.memory.long.profile.path)
    return 0


