"""Описание конвейера: шаги, вход и проверка связей между ними.

Конвейер — это список шагов, записанный человеком в pipelines.json рядом с
mcp-servers.json. Шаг — вызов одного инструмента MCP с аргументами, в которых
могут стоять ссылки на результаты предыдущих шагов (agent/pipeline/values.py).

Почему описание лежит в файле, а не собирается моделью на ходу. Пайплайн
должен быть повторяемым: тот же конвейер на тех же данных обязан дать тот же
порядок вызовов. Модель же каждый раз сочиняет последовательность заново — это
удобно в разговоре, но проверить «корректность передачи данных» в таком
порядке нельзя, потому что и порядка-то нет. Здесь наоборот: порядок известен
заранее, он в репозитории, и его можно проверить до единого вызова.

Именно это и делает `Конвейер.проверить()`: пока не потрачено ни секунды на
вызовы, она убеждается, что имена шагов уникальны, что каждая ссылка ведёт на
шаг, который стоит РАНЬШЕ, а не позже, и что «${вход.…}» просит только то, что
у конвейера объявлено входом. Ошибка в описании должна стоить сообщения, а не
половины прогона.

Что лежит в файле:

    {"конвейеры": {"отчёт": {
        "описание": "…",
        "вход": {"очередь": {"описание": "…", "по_умолчанию": "MIG"}},
        "шаги": [{"имя": "задачи", "инструмент": "tracker__list_issues",
                  "аргументы": {"queue": "${вход.очередь}"}}]}}}

Публичное API:
  Каталог(path)              — конвейеры из файла
  .имена() / .конвейер(имя) / .все() / .to_dict()
  Конвейер.проверить() / .собрать_вход(данные) / .инструменты() / .словами()
  ОшибкаКонвейера            — описание испорчено или конвейера нет
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from typing import Any

from agent.pipeline.values import ссылки

DEFAULT_PATH = "pipelines.json"

# Имя шага — данные (его пишет человек по-русски), но оно становится корнем
# ссылки «${имя.данные.…}», поэтому точки и фигурные скобки в нём недопустимы.
_ИМЯ_ШАГА = re.compile(r"^[^\s{}.$][^{}.$]{0,39}$")
# Имя инструмента — всегда латиница: это требование MCP к именам серверов и
# инструментов, и заодно защита от «../../etc/passwd» в описании конвейера.
_ИНСТРУМЕНТ = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,40}(__[A-Za-z][A-Za-z0-9_]{0,60})?$")

ВХОД = "вход"
ПРЕДЕЛ_ШАГОВ = 12


class ОшибкаКонвейера(ValueError):
    """Описание конвейера испорчено, или такого конвейера нет."""


@dataclass(frozen=True)
class Поле:
    """Один параметр запуска: что человек (или модель) может передать конвейеру."""

    имя: str
    описание: str = ""
    по_умолчанию: Any = None
    обязательное: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {"имя": self.имя, "описание": self.описание,
                "по_умолчанию": self.по_умолчанию, "обязательное": self.обязательное}


@dataclass(frozen=True)
class Шаг:
    """Один вызов инструмента MCP в составе конвейера."""

    имя: str
    инструмент: str
    аргументы: dict[str, Any] = field(default_factory=dict)
    описание: str = ""

    @property
    def сервер(self) -> str:
        return self.инструмент.split("__")[0] if "__" in self.инструмент else ""

    def ссылки(self) -> list[str]:
        return ссылки(self.аргументы)

    def to_dict(self) -> dict[str, Any]:
        return {"имя": self.имя, "инструмент": self.инструмент, "сервер": self.сервер,
                "аргументы": json.loads(json.dumps(self.аргументы, ensure_ascii=False)),
                "описание": self.описание, "ссылки": self.ссылки()}


@dataclass(frozen=True)
class Конвейер:
    """Цепочка шагов с объявленным входом."""

    имя: str
    шаги: tuple[Шаг, ...] = ()
    описание: str = ""
    вход: tuple[Поле, ...] = ()
    файл: str = ""

    # --- проверка -------------------------------------------------------------

    def проверить(self) -> "Конвейер":
        """Проверяет описание целиком. Ошибка — до первого вызова инструмента."""
        if not self.шаги:
            raise ОшибкаКонвейера(f"Конвейер «{self.имя}»: нет ни одного шага.")
        if len(self.шаги) > ПРЕДЕЛ_ШАГОВ:
            raise ОшибкаКонвейера(
                f"Конвейер «{self.имя}»: {len(self.шаги)} шагов, предел — {ПРЕДЕЛ_ШАГОВ}. "
                "Длинная цепочка чаще всего значит, что это два конвейера.")

        поля = {п.имя for п in self.вход}
        готовы: set[str] = set()
        for номер, шаг in enumerate(self.шаги, 1):
            if not _ИМЯ_ШАГА.match(шаг.имя or ""):
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}», шаг {номер}: имя «{шаг.имя}» не годится. "
                    "Имя короткое, без точек, пробелов по краям и «${}» — на него "
                    "ссылаются другие шаги.")
            if шаг.имя == ВХОД:
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}»: шаг нельзя назвать «{ВХОД}» — так зовётся "
                    "то, с чем конвейер запустили.")
            if шаг.имя in готовы:
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}»: два шага с именем «{шаг.имя}». Имена шагов "
                    "различают их результаты, поэтому должны быть разными.")
            if not _ИНСТРУМЕНТ.match(шаг.инструмент or ""):
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}», шаг «{шаг.имя}»: «{шаг.инструмент}» не похоже "
                    "на имя инструмента. Нужно «сервер__инструмент» латиницей.")
            if not isinstance(шаг.аргументы, dict):
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}», шаг «{шаг.имя}»: аргументы — объект JSON.")

            for путь in шаг.ссылки():
                корень = путь.split(".")[0].strip()
                if корень == ВХОД:
                    поле = путь.split(".")[1].strip() if "." in путь else ""
                    if поле not in поля:
                        raise ОшибкаКонвейера(
                            f"Конвейер «{self.имя}», шаг «{шаг.имя}»: ссылка «{путь}» просит "
                            f"вход «{поле}», которого у конвейера нет. Объявлено: "
                            f"{', '.join(sorted(поля)) or 'ничего'}.")
                elif корень in готовы:
                    continue
                elif корень in {ш.имя for ш in self.шаги}:
                    raise ОшибкаКонвейера(
                        f"Конвейер «{self.имя}», шаг «{шаг.имя}»: ссылка «{путь}» смотрит на "
                        f"шаг «{корень}», который идёт позже. Данные передаются только "
                        "вперёд.")
                else:
                    известно = ", ".join(sorted(готовы | {ВХОД})) or ВХОД
                    raise ОшибкаКонвейера(
                        f"Конвейер «{self.имя}», шаг «{шаг.имя}»: ссылка «{путь}» ведёт в "
                        f"никуда. Доступны: {известно}.")
            готовы.add(шаг.имя)
        return self

    # --- запуск ---------------------------------------------------------------

    def собрать_вход(self, данные: dict[str, Any] | None = None) -> dict[str, Any]:
        """Значения входа: что передали, поверх умолчаний; лишнее — ошибка.

        Лишний ключ не проглатывается молча намеренно: «очередь» вместо
        «queue» иначе просто не сработала бы, а конвейер отработал бы на
        умолчании и отдал отчёт не о том.
        """
        данные = dict(данные or {})
        объявлено = {п.имя: п for п in self.вход}
        лишние = [к for к in данные if к not in объявлено]
        if лишние:
            raise ОшибкаКонвейера(
                f"Конвейер «{self.имя}»: не знает вход {', '.join(f'«{к}»' for к in лишние)}. "
                f"Принимает: {', '.join(объявлено) or 'ничего'}.")
        итог: dict[str, Any] = {}
        for имя, поле in объявлено.items():
            if имя in данные and данные[имя] not in (None, ""):
                итог[имя] = данные[имя]
            elif поле.обязательное:
                raise ОшибкаКонвейера(
                    f"Конвейер «{self.имя}»: нужен вход «{имя}»"
                    + (f" — {поле.описание}" if поле.описание else "") + ".")
            else:
                итог[имя] = поле.по_умолчанию
        return итог

    def шаг(self, имя: str) -> Шаг | None:
        for шаг in self.шаги:
            if шаг.имя == имя:
                return шаг
        return None

    def инструменты(self) -> list[str]:
        """Инструменты конвейера по порядку, без повторов."""
        итог: list[str] = []
        for шаг in self.шаги:
            if шаг.инструмент not in итог:
                итог.append(шаг.инструмент)
        return итог

    def серверы(self) -> list[str]:
        итог: list[str] = []
        for шаг in self.шаги:
            if шаг.сервер and шаг.сервер not in итог:
                итог.append(шаг.сервер)
        return итог

    def словами(self) -> str:
        """Цепочка одной строкой: «задачи → память → выжимка → файл»."""
        return " → ".join(ш.имя for ш in self.шаги)

    def to_dict(self) -> dict[str, Any]:
        return {
            "имя": self.имя, "описание": self.описание, "шагов": len(self.шаги),
            "цепочка": self.словами(),
            "вход": [п.to_dict() for п in self.вход],
            "шаги": [ш.to_dict() for ш in self.шаги],
            "инструменты": self.инструменты(), "серверы": self.серверы(),
        }


def из_словаря(имя: str, данные: Any, файл: str = "") -> Конвейер:
    """Собирает конвейер из куска JSON и сразу проверяет его."""
    if not isinstance(данные, dict):
        raise ОшибкаКонвейера(f"Конвейер «{имя}»: описание должно быть объектом JSON.")
    сырые = данные.get("шаги", [])
    if not isinstance(сырые, list):
        raise ОшибкаКонвейера(f"Конвейер «{имя}»: «шаги» — список.")

    шаги: list[Шаг] = []
    for номер, шаг in enumerate(сырые, 1):
        if not isinstance(шаг, dict):
            raise ОшибкаКонвейера(f"Конвейер «{имя}», шаг {номер}: описание — объект JSON.")
        шаги.append(Шаг(
            имя=str(шаг.get("имя", "") or f"шаг{номер}").strip(),
            инструмент=str(шаг.get("инструмент", "")).strip(),
            аргументы=шаг.get("аргументы", {}) if isinstance(шаг.get("аргументы", {}), dict)
            else шаг.get("аргументы"),
            описание=str(шаг.get("описание", "")),
        ))

    вход: list[Поле] = []
    сырой_вход = данные.get("вход", {})
    if сырой_вход and not isinstance(сырой_вход, dict):
        raise ОшибкаКонвейера(f"Конвейер «{имя}»: «вход» — объект JSON.")
    for поле, описание in (сырой_вход or {}).items():
        if isinstance(описание, dict):
            вход.append(Поле(имя=str(поле), описание=str(описание.get("описание", "")),
                             по_умолчанию=описание.get("по_умолчанию"),
                             обязательное=bool(описание.get("обязательное", False))))
        else:
            # Короткая форма: "очередь": "MIG" — значение по умолчанию.
            вход.append(Поле(имя=str(поле), по_умолчанию=описание))

    return Конвейер(имя=имя, шаги=tuple(шаги), описание=str(данные.get("описание", "")),
                    вход=tuple(вход), файл=файл).проверить()


class Каталог:
    """Конвейеры из pipelines.json. Файла нет — каталог пуст, и это не ошибка."""

    def __init__(self, path: str = "") -> None:
        self.путь = os.path.abspath(path or os.getenv("PIPELINES_FILE", "") or DEFAULT_PATH)
        self._конвейеры: dict[str, Конвейер] = {}
        self.загружен = False

    def загрузить(self) -> dict[str, Конвейер]:
        if self.загружен:
            return self._конвейеры
        self._конвейеры = {}
        self.загружен = True
        if not os.path.exists(self.путь):
            return self._конвейеры
        try:
            with open(self.путь, encoding="utf-8") as файл:
                данные = json.load(файл)
        except json.JSONDecodeError as exc:
            raise ОшибкаКонвейера(
                f"Файл конвейеров «{self.путь}» испорчен: {exc}") from exc
        except OSError as exc:
            raise ОшибкаКонвейера(
                f"Файл конвейеров «{self.путь}» не читается: {exc}") from exc

        раздел = данные.get("конвейеры", данные) if isinstance(данные, dict) else None
        if not isinstance(раздел, dict):
            raise ОшибкаКонвейера(
                f"Файл конвейеров «{self.путь}»: ожидался объект «конвейеры».")
        for имя, описание in раздел.items():
            self._конвейеры[str(имя)] = из_словаря(str(имя), описание, self.путь)
        return self._конвейеры

    def имена(self) -> list[str]:
        return sorted(self.загрузить())

    def все(self) -> list[Конвейер]:
        return [self.загрузить()[и] for и in self.имена()]

    def есть(self, имя: str) -> bool:
        return (имя or "").strip() in self.загрузить()

    def конвейер(self, имя: str) -> Конвейер:
        имя = (имя or "").strip()
        конвейеры = self.загрузить()
        if имя not in конвейеры:
            известны = ", ".join(f"«{и}»" for и in self.имена()) or "ни одного"
            raise ОшибкаКонвейера(
                f"Конвейера «{имя}» нет. Есть: {известны}. Описания — в {self.путь}.")
        return конвейеры[имя]

    def to_dict(self) -> dict[str, Any]:
        return {"файл": self.путь, "конвейеров": len(self.загрузить()),
                "конвейеры": [к.to_dict() for к in self.все()]}


