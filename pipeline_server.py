#!/usr/bin/env python3
"""MCP-сервер конвейеров: search → summarize → save_to_file и запуск цепочки.

Третий свой сервер в проекте. Первый (tracker_server.py, День 17) ходил в чужой
API, второй (scheduler_server.py, День 18) вёл расписание. Этот делает три
вещи из задания дня — находит данные, обрабатывает их и сохраняет результат — и
умеет выполнить всю цепочку сам, одним вызовом.

Почему цепочка запускается одним инструментом, а не тремя вызовами подряд.
Лекция недели предупреждала о квадратичном росте: описания инструментов уходят
в КАЖДЫЙ запрос, и разговор, в котором модель ведёт цепочку сама, платит за них
на каждом круге — плюс платит за то, чтобы провезти данные первого шага через
свой контекст во второй. Конвейер описан в pipelines.json, исполняется кодом, а
модели достаётся один вызов run_pipeline и короткий протокол. Данные между
шагами при этом не проходят через модель вовсе: их передаёт подстановка
«${шаг.данные.поле}» (agent/pipeline/values.py).

Сервер здесь — ещё и клиент MCP: шаг конвейера может звать инструмент другого
сервера (tracker__list_issues), и тогда сервер открывает к нему соединение сам.
Свои три инструмента он зовёт напрямую, без второго соединения с самим собой.
Так «композиция» получается настоящей: цепочка пересекает границы серверов.

Про ключ модели. summarize просит модель написать выжимку, поэтому ключ ему
нужен — он передаётся через env в mcp-servers.json, как токен трекера в Дне 17.
Без ключа инструмент не падает: он собирает выжимку по правилам (сколько чего
пришло, первые строки) и честно помечает «модель: нет».

Запуск:
    python pipeline_server.py                    # stdio: так его запускает клиент
    python pipeline_server.py --http 8769        # Streamable HTTP на 127.0.0.1:8769/mcp
    python pipeline_server.py --конвейеры ПУТЬ   # другой pipelines.json
"""

