"""Заявки на изменяющие вызовы: то, что модель просит сделать, а человек решает.

Читающий инструмент агент вызывает сам: «покажи задачи трекера» ничего не
портит, а спрашивать разрешения на каждый просмотр — значит сделать агента
бесполезным. Меняющий — другое дело. Между «модель решила добавить
комментарий» и «комментарий появился в трекере у коллег» должен стоять
человек.

Способ поставить его туда выбран такой: модель просит вызов, агент его НЕ
делает, а записывает заявку и говорит об этом в ответе. Человек смотрит, что
именно предлагается — инструмент, аргументы, из-за какого вопроса, — и
отвечает «да» или «нет» отдельной командой. Альтернатива «спросить прямо в
диалоге и подождать ввода» работала бы только в консоли: в вебе и в
проверочных скриптах это зависший запрос.

Заявка живёт в файле, а не в памяти процесса. Это не перестраховка: ответ
пришёл в одном процессе (веб-запрос, команда консоли), а подтверждение придёт
в другом — ровно как пауза задачи в Дне 13. Здесь же видно и историю: что
предлагалось и чем кончилось, включая отклонённое.

Публичное API:
  ЖДЁТ, ВЫПОЛНЕНА, ОТКЛОНЕНА, СБОЙ  — состояния заявки
  Заявка                            — одна заявка
  CallStore(path)                   — заявки в файле memory/tool-calls.json
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

ЖДЁТ = "ждёт"
ВЫПОЛНЕНА = "выполнена"
ОТКЛОНЕНА = "отклонена"
СБОЙ = "сбой"
СОСТОЯНИЯ = (ЖДЁТ, ВЫПОЛНЕНА, ОТКЛОНЕНА, СБОЙ)

# Сколько заявок хранить. Это журнал для человека, а не архив: старые решения
# ничего не меняют, а файл, который растёт без предела, однажды перестают
# открывать.
ПРЕДЕЛ = 200


class CallStoreError(RuntimeError):
    """Файл заявок не читается или не пишется."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@dataclass
class Заявка:
    """Просьба модели выполнить изменяющий вызов — и что с ней стало."""

    номер: int
    инструмент: str                  # полное имя: «сервер__инструмент»
    сервер: str = ""
    аргументы: dict[str, Any] = field(default_factory=dict)
    зачем: str = ""                  # вопрос человека, из-за которого она возникла
    описание: str = ""               # что инструмент делает, словами сервера
    кто: str = ""
    сессия: str = ""
    задача: str = ""
    состояние: str = ЖДЁТ
    создана: str = field(default_factory=_now)
    решена: str = ""
    почему: str = ""                 # причина отказа или текст сбоя
    результат: dict[str, Any] = field(default_factory=dict)

    @property
    def ждёт(self) -> bool:
        return self.состояние == ЖДЁТ

    def словами(self) -> str:
        """Одна строка для списка: что именно предлагается сделать."""
        аргументы = ", ".join(f"{к}={_коротко(з)}" for к, з in self.аргументы.items())
        return f"№{self.номер} {self.инструмент}({аргументы})"

    def to_dict(self) -> dict[str, Any]:
        return {
            "номер": self.номер, "инструмент": self.инструмент, "сервер": self.сервер,
            "аргументы": self.аргументы, "зачем": self.зачем, "описание": self.описание,
            "кто": self.кто, "сессия": self.сессия, "задача": self.задача,
            "состояние": self.состояние, "создана": self.создана, "решена": self.решена,
            "почему": self.почему, "результат": self.результат,
            "словами": self.словами(),
        }

    @classmethod
    def from_dict(cls, данные: dict[str, Any]) -> "Заявка":
        return cls(
            номер=int(данные.get("номер", 0)),
            инструмент=str(данные.get("инструмент", "")),
            сервер=str(данные.get("сервер", "")),
            аргументы=dict(данные.get("аргументы") or {}),
            зачем=str(данные.get("зачем", "")),
            описание=str(данные.get("описание", "")),
            кто=str(данные.get("кто", "")),
            сессия=str(данные.get("сессия", "")),
            задача=str(данные.get("задача", "")),
            состояние=str(данные.get("состояние", ЖДЁТ)),
            создана=str(данные.get("создана", "")),
            решена=str(данные.get("решена", "")),
            почему=str(данные.get("почему", "")),
            результат=dict(данные.get("результат") or {}),
        )


def _коротко(значение: Any, предел: int = 60) -> str:
    текст = значение if isinstance(значение, str) else json.dumps(значение, ensure_ascii=False)
    текст = текст.replace("\n", " ")
    return текст if len(текст) <= предел else текст[:предел] + "…"


class CallStore:
    """Заявки на изменяющие вызовы в одном файле."""

    def __init__(self, path: str) -> None:
        self.path = path

    def all(self) -> list[Заявка]:
        try:
            with open(self.path, encoding="utf-8") as файл:
                данные = json.load(файл)
        except FileNotFoundError:
            return []
        except (OSError, json.JSONDecodeError) as exc:
            raise CallStoreError(f"Файл заявок «{self.path}» испорчен: {exc}") from exc
        if not isinstance(данные, list):
            return []
        return [Заявка.from_dict(з) for з in данные if isinstance(з, dict)]

    def pending(self) -> list[Заявка]:
        return [з for з in self.all() if з.ждёт]

    def get(self, номер: int) -> Заявка | None:
        for заявка in self.all():
            if заявка.номер == номер:
                return заявка
        return None

    def add(self, заявка: Заявка) -> Заявка:
        все = self.all()
        заявка.номер = max((з.номер for з in все), default=0) + 1
        заявка.создана = заявка.создана or _now()
        все.append(заявка)
        self._save(все[-ПРЕДЕЛ:])
        return заявка

    def resolve(self, номер: int, состояние: str, почему: str = "",
                результат: dict[str, Any] | None = None) -> Заявка:
        """Закрывает заявку. Повторно закрыть уже закрытую нельзя."""
        if состояние not in СОСТОЯНИЯ:
            raise CallStoreError(f"Неизвестное состояние заявки «{состояние}».")
        все = self.all()
        for заявка in все:
            if заявка.номер != номер:
                continue
            if not заявка.ждёт:
                raise CallStoreError(
                    f"Заявка №{номер} уже {заявка.состояние}: повторно её не исполнить.")
            заявка.состояние = состояние
            заявка.почему = почему
            заявка.результат = результат or {}
            заявка.решена = _now()
            self._save(все)
            return заявка
        raise CallStoreError(f"Заявки №{номер} нет. Список ждущих — «--заявки».")

    def _save(self, заявки: list[Заявка]) -> None:
        временный = self.path + ".tmp"
        try:
            os.makedirs(os.path.dirname(os.path.abspath(self.path)), exist_ok=True)
            with open(временный, "w", encoding="utf-8") as файл:
                json.dump([з.to_dict() for з in заявки], файл, ensure_ascii=False, indent=2)
            os.replace(временный, self.path)
        except OSError as exc:
            raise CallStoreError(f"Не удалось записать заявки: {exc}") from exc
