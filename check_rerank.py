def верный(находка) -> bool:
    return "2.2.7" in находка.чанк.текст and "Ростелеком VPN" in находка.чанк.источник


def место_верного(отбор) -> tuple[int, str, int]:
    """(место в промпте или 0, судьба, место «было») верного чанка в отборе."""
    for к in отбор.кандидаты:
        if верный(к.находка):
            return (к.находка.место if к.судьба == "в промпт" else 0), к.судьба, к.находка.место_до
    return 0, "не найден первым этапом", 0


