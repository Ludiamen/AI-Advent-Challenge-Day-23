#!/usr/bin/env python3
"""MCP-сервер планировщика: отложенные и периодические вызовы инструментов.

Это второй свой сервер в проекте. Первый (tracker_server.py, День 17) ходил в
чужой API; этот работает со своим хранилищем — файлом SQLite, в котором лежат
задания, история запусков, сводки и напоминания.

Сервер ничего не выполняет. Он только принимает задания и отдаёт накопленное;
исполняет их отдельный процесс — работник (worker.py), который тоже клиент MCP
и зовёт инструменты так же, как их зовёт модель. Разделение намеренное:
stdio-сервер живёт ровно столько, сколько открыт сеанс агента, и поручить ему
работу «24/7» значило бы обещать то, чего он не может.

Три вещи, которые требует задание дня, живут здесь:

  1. Сохранение данных — SQLite (agent/scheduler/store.py): задания переживают
     перезапуск всего, а история запусков — то, из чего потом считается сводка.
  2. Выполнение по расписанию — расписание разбирается при постановке задания
     («каждые 30м», «ежедневно в 09:00»), срок хранится готовым, а работник
     раз в несколько секунд смотрит, чему пора.
  3. Агрегированный результат — build_digest считает сводку по истории: сколько
     было запусков, что изменилось между последними сборами данных, о чём
     просили напомнить. Текст по этим цифрам пишет модель, но уже в работнике:
     серверу незачем знать ни про ключи провайдеров, ни про роли моделей.

Инструментов намеренно шесть, а не десять: описания уходят в каждый запрос к
модели, и каждый лишний инструмент — это расход на всём разговоре. Истории
запусков отдельным инструментом нет — её видно в сводке и в консоли.

Запуск:
    python scheduler_server.py                  # stdio: так его запускает клиент
    python scheduler_server.py --http 8768      # Streamable HTTP на 127.0.0.1:8768/mcp
    python scheduler_server.py --база ПУТЬ      # другой файл хранилища
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from typing import Annotated, Any

from pydantic import Field

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КОРЕНЬ)

from mcp.server import MCPServer  # noqa: E402
from mcp.server.mcpserver.exceptions import ToolError  # noqa: E402
from mcp_types import ToolAnnotations  # noqa: E402

from agent.scheduler import digest  # noqa: E402
from agent.scheduler.schedule import ОшибкаРасписания, разобрать  # noqa: E402
from agent.scheduler.store import ScheduleStore, ScheduleStoreError  # noqa: E402

ИМЯ = "scheduler"
ВЕРСИЯ = "18.0"

ИНСТРУКЦИИ = """\
Планировщик агента миграции ГИС газовых сетей: отложенные и периодические \
вызовы инструментов MCP. Задание — это «какой инструмент вызвать, с какими \
аргументами и когда»; выполняет их фоновый работник, а здесь они заводятся и \
отсюда же забирается накопленное. Расписание пишется словами: «через 15м», \
«каждые 30м», «ежедневно в 09:00». Начинайте с list_jobs; что накопилось — \
latest_digest."""

# Пометки: что инструмент делает с данными. Читающие объявлены явно — по этой
# пометке агент решает, можно ли звать инструмент без подтверждения человека.
ЧТЕНИЕ = ToolAnnotations(read_only_hint=True, destructive_hint=False,
                         idempotent_hint=True, open_world_hint=False)
# Добавляющие: заводят запись, ничего не портят и наружу не ходят.
ДОБАВЛЕНИЕ = ToolAnnotations(read_only_hint=False, destructive_hint=False,
                             idempotent_hint=False, open_world_hint=False)
# Отмена убирает будущую работу — это уже разрушающее действие.
ОТМЕНА = ToolAnnotations(read_only_hint=False, destructive_hint=True,
                         idempotent_hint=True, open_world_hint=False)

# Имя инструмента приходит от модели. Оно станет тем, что работник будет звать
# раз в полчаса неделю подряд, поэтому проверяется формой: «сервер__инструмент»
# латиницей. Так отсекается и мусор вроде «../../etc/passwd».
_ИНСТРУМЕНТ = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,40}(__[A-Za-z][A-Za-z0-9_]{0,60})?$")

# Аннотации — на уровне модуля. Из-за «from __future__ import annotations» SDK
# разбирает их по именам в глобальном пространстве: синоним внутри функции
# фабрики он не нашёл бы (проверено в Дне 17).
Инструмент = Annotated[str, Field(
    description="Какой инструмент вызывать: имя вида «сервер__инструмент», "
                "например «tracker__list_issues». Список — в описании инструментов агента.")]
Когда = Annotated[str, Field(
    description="Расписание словами: «через 15м» (один раз), «каждые 30м» "
                "(периодически), «ежедневно в 09:00», «в 18:30». Единицы: с, м, ч, д.")]
Аргументы = Annotated[dict[str, Any], Field(
    description="Аргументы вызова — объект JSON, ровно такой, какой принимает "
                "сам инструмент. Например {\"queue\": \"MIG\", \"status\": \"inProgress\"}.")]
Зачем = Annotated[str, Field(
    description="Зачем это задание нужно — одной строкой для человека.")]
Номер = Annotated[int, Field(description="Номер задания из list_jobs.", ge=1)]
Период = Annotated[str, Field(
    description="За какое время считать сводку: «час», «сутки», «неделя», «всё» "
                "или промежуток вроде «30м».")]
Сколько = Annotated[int, Field(description="Сколько записей вернуть, 1–50.", ge=1, le=50)]
Текст = Annotated[str, Field(
    description="Текст напоминания — то, что нужно сказать человеку словами.",
    min_length=1)]


class ОшибкаПланировщика(ToolError):
    """Неверный аргумент или невыполнимая просьба.

    Наследник ToolError: только его текст доходит до модели. Любое другое
    исключение SDK покажет как «Error executing tool», и модель не узнает, что
    расписание просто написано не в той форме.
    """


def путь_базы() -> str:
    """Где лежит хранилище: SCHEDULER_DB, иначе scheduler.db в каталоге памяти."""
    прямо = os.getenv("SCHEDULER_DB", "").strip()
    if прямо:
        return os.path.abspath(прямо)
    память = os.getenv("MEMORY_DIR") or os.path.join(КОРЕНЬ, "memory")
    return os.path.abspath(os.path.join(память, "scheduler.db"))


def _инструмент(значение: str) -> str:
    значение = (значение or "").strip()
    if not _ИНСТРУМЕНТ.match(значение):
        raise ОшибкаПланировщика(
            f"«{значение}» не похоже на имя инструмента. Имя пишется латиницей в виде "
            "«сервер__инструмент», например «tracker__list_issues».")
    return значение


def _расписание(значение: str) -> str:
    try:
        разобрать(значение)
    except ОшибкаРасписания as exc:
        raise ОшибкаПланировщика(str(exc)) from exc
    return значение


def создать_сервер(хранилище: ScheduleStore | None = None) -> MCPServer:
    """Собирает сервер. Хранилище можно подменить — этим пользуются проверки."""
    база = хранилище or ScheduleStore(путь_базы())
    сервер = MCPServer(ИМЯ, title="Планировщик фоновых заданий", version=ВЕРСИЯ,
                       instructions=ИНСТРУКЦИИ, log_level="WARNING")
    сервер.хранилище = база        # для main() и для проверок

    @сервер.tool(title="Задания планировщика", annotations=ЧТЕНИЕ)
    def list_jobs(
        active: Annotated[bool, Field(
            description="Только те, что ещё сработают. False — вместе с отменёнными "
                        "и исполненными.")] = True,
        limit: Сколько = 20,
    ) -> dict[str, Any]:
        """Что стоит в расписании: инструмент, аргументы, когда сработает снова,
        сколько раз уже срабатывало и чем кончилось в последний раз.

        Здесь же видно, жив ли работник: если он не запущен, задания просто
        ждут, и ни одно из них не выполнится."""
        задания = база.задания(только_активные=active, сколько=limit)
        return {
            "заданий": len(задания),
            "задания": [_коротко(з) for з in задания],
            "работник": база.работник(),
        }

    @сервер.tool(title="Поставить задание в расписание", annotations=ДОБАВЛЕНИЕ)
    def schedule_job(
        tool: Инструмент,
        schedule: Когда,
        arguments: Аргументы = {},  # noqa: B006 — значение не меняется, см. ниже
        why: Зачем = "",
    ) -> dict[str, Any]:
        """Ставит вызов инструмента в расписание: один раз («через 15м») или
        периодически («каждые 30м», «ежедневно в 09:00»).

        Задание переживает перезапуск агента и выполняется фоновым работником.
        Проверить, что инструмент существует и аргументы ему подходят, лучше
        заранее — обычным вызовом: планировщик проверяет только форму имени."""
        # arguments={} в сигнатуре — общий словарь по умолчанию, и менять его
        # нельзя; здесь он только читается и копируется в хранилище.
        try:
            задание = база.добавить_задание(
                инструмент=_инструмент(tool), расписание=_расписание(schedule),
                аргументы=dict(arguments or {}), зачем=why)
        except (ScheduleStoreError, ОшибкаРасписания) as exc:
            raise ОшибкаПланировщика(str(exc)) from exc
        жив = база.работник()
        return {
            "задание": _коротко(задание),
            "поставлено": True,
            "первый_срок": задание.срок,
            "работник_запущен": жив["запущен"],
            "предупреждение": "" if жив["запущен"] else
                "Работник не запущен — задание будет ждать. Запустите: python worker.py",
        }

    @сервер.tool(title="Снять задание", annotations=ОТМЕНА)
    def cancel_job(job: Номер) -> dict[str, Any]:
        """Снимает задание с расписания. История его запусков остаётся."""
        try:
            задание = база.отменить(job, почему="снято через MCP")
        except ScheduleStoreError as exc:
            raise ОшибкаПланировщика(str(exc)) from exc
        return {"задание": _коротко(задание), "снято": True}

    @сервер.tool(title="Напоминание", annotations=ДОБАВЛЕНИЕ)
    def remind(text: Текст) -> dict[str, Any]:
        """Сохраняет напоминание — строку, которую человек увидит в консоли, на
        странице и в ближайшей сводке.

        Обычно этот инструмент ставят в расписание: «напомнить через 2ч» — это
        задание remind с текстом напоминания."""
        try:
            напоминание = база.напомнить(text)
        except ScheduleStoreError as exc:
            raise ОшибкаПланировщика(str(exc)) from exc
        return {"напоминание": напоминание.to_dict(), "сохранено": True}

    @сервер.tool(title="Собрать сводку", annotations=ДОБАВЛЕНИЕ)
    def build_digest(period: Период = "сутки") -> dict[str, Any]:
        """Считает и сохраняет сводку фоновой работы за период: сколько было
        запусков и сбоев, что изменилось между последними сборами данных, какие
        появились напоминания.

        Это и есть агрегированный результат планировщика. Обычно стоит в
        расписании («ежедневно в 09:00»), а прочитать последнюю можно
        инструментом latest_digest."""
        try:
            запись = digest.собрать_и_сохранить(база, за=period)
        except ScheduleStoreError as exc:
            raise ОшибкаПланировщика(str(exc)) from exc
        return {"сводка": запись.номер, "создана": запись.создана, "цифры": запись.цифры,
                "словами": digest.словами(запись.цифры)}

    @сервер.tool(title="Последняя сводка", annotations=ЧТЕНИЕ)
    def latest_digest(
        unread_only: Annotated[bool, Field(
            description="Только если её ещё не показывали человеку.")] = False,
    ) -> dict[str, Any]:
        """Последняя сводка целиком: цифры, текст и свежие напоминания.

        Если сводок ещё нет, отвечает «нет» — это не ошибка: работник мог быть
        запущен минуту назад."""
        сводка = база.непрочитанная_сводка() if unread_only else база.последняя_сводка()
        if сводка is None:
            return {"есть": False, "сводка": None,
                    "почему": "сводок ещё нет — поставьте build_digest в расписание "
                              "или вызовите его напрямую"}
        напоминания = [н.to_dict() for н in база.напоминания(сколько=10, только_новые=True)]
        итог = сводка.to_dict()
        итог["словами"] = сводка.текст or digest.словами(сводка.цифры)
        return {"есть": True, "сводка": итог, "новые_напоминания": напоминания}

    return сервер


def _коротко(задание: Any) -> dict[str, Any]:
    """Карточка задания для модели: без полей, которые ей ничего не говорят."""
    данные = задание.to_dict()
    for лишнее in ("вид", "секунд", "сервер", "создано", "расписание"):
        данные.pop(лишнее, None)
    return данные


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="MCP-сервер планировщика: отложенные и периодические вызовы.")
    разбор.add_argument("--http", type=int, default=0, metavar="ПОРТ",
                        help="слушать Streamable HTTP на 127.0.0.1:ПОРТ/mcp вместо stdio")
    разбор.add_argument("--база", dest="db", default="", metavar="ПУТЬ",
                        help="файл хранилища (по умолчанию memory/scheduler.db)")
    разбор.add_argument("--память-в", dest="memory", default="", metavar="ПУТЬ",
                        help="каталог памяти агента, внутри которого лежит scheduler.db")
    аргументы = разбор.parse_args()
    if аргументы.memory:
        os.environ["MEMORY_DIR"] = os.path.abspath(аргументы.memory)
    if аргументы.db:
        os.environ["SCHEDULER_DB"] = os.path.abspath(аргументы.db)

    сервер = создать_сервер()
    if аргументы.http:
        сервер.run("streamable-http", host="127.0.0.1", port=аргументы.http)
    else:
        сервер.run("stdio")
    return 0


if __name__ == "__main__":
    sys.exit(main())
