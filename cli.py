    print(f"{значок} Прогон №{прогон['номер']} «{прогон['конвейер']}» — "
          f"{прогон['состояние']}, шагов {прогон['сделано']} из {прогон['шагов']}, "
          f"{прогон['секунд']:g} с ({_время_коротко(прогон['начат'])})")
    if прогон.get("вход"):
        print(f"   вход: {_аргументы_кратко(прогон['вход'])}")
    if прогон.get("кто"):
        print(f"   запустил: {прогон['кто']}" + (f" · зачем: {прогон['зачем']}"
                                                 if прогон.get("зачем") else ""))
    for шаг in прогон.get("шаги", []):
        метка = "✓" if шаг["ок"] else "✗"
