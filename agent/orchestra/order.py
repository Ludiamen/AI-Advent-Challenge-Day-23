"""Правила порядка вызовов: чего нельзя делать, не сделав другого.

Задание Дня 20 требует проверить «корректность выбора и порядка вызовов». Выбор
проверяется сверкой с планом (plan.py), а порядок — здесь, и проверяется он не
постфактум, а до вызова: отчёт о нарушении, которое уже случилось в чужой
системе, никому не помогает.

Правило выглядит так: «add_comment — только после того, как задача прочитана».
Смысл не в бюрократии. Модель, которая пишет комментарий, не прочитав задачу,
пишет его по памяти диалога — то есть по тому, что сама же и придумала. Ровно
так в Дне 17 появился комментарий про «статус изменён», которого никто не менял.

Нарушение стоит вызова: инструмент не зовётся, а модель получает текст с
объяснением и списком того, что нужно сделать раньше. Это не тупик — в
следующем круге модель обычно сама зовёт недостающее чтение, и флоу идёт
дальше. В протоколе шаг остаётся с пометкой «отклонён по порядку»: видно и
попытку, и то, что её остановил код, а не удача.

Правила лежат в flow-rules.json рядом с mcp-servers.json, потому что зависят от
набора инструментов, а не от кода. Файла нет — работают встроенные правила
ПО_УМОЛЧАНИЮ: без них новый день молча остался бы без защиты.

Публичное API:
  Правило(инструмент, после, почему)   — одно правило
  Вердикт(можно, почему, правило)      — решение о вызове
  Порядок(правила, путь)               — .проверить(инструмент, сделано)
                                         .проверить_план(шаги)
                                         .словами() / .to_dict()
  загрузить(путь) -> Порядок           — прочитать файл (или взять встроенные)
  ОшибкаПорядка                        — файл есть, но описан неверно
"""

from __future__ import annotations

import fnmatch
import json
import os
from dataclasses import dataclass, field
from typing import Any

ФАЙЛ = "flow-rules.json"

# Встроенные правила. Это не «пример для копирования», а рабочий набор для того
# состава серверов, который лежит в mcp-servers.json: файла может не быть, и
# тогда порядок всё равно должен проверяться.
ПО_УМОЛЧАНИЮ: list[dict[str, Any]] = [
    {
        "инструмент": "tracker__add_comment",
        "после": ["tracker__get_issue", "tracker__list_issues"],
        "почему": "Комментарий пишется в конкретную задачу: сначала её надо прочитать, "
                  "иначе текст будет основан на догадке, а не на данных трекера.",
    },
    {
        "инструмент": "tracker__move_issue",
        "после": ["tracker__get_issue"],
        "почему": "Статус меняют, зная текущий: список задач его не показывает, "
                  "а перевод в тот же статус трекер отклонит.",
    },
    {
        "инструмент": "pipeline__summarize",
        "после": ["pipeline__search", "tracker__list_issues", "tracker__get_issue",
                  "deepwiki__*", "agent-state__*", "filesystem__read*"],
        "почему": "Обрабатывать нечего, пока данные не получены: выжимка из пустоты — "
                  "это пересказ модели, а не выжимка.",
    },
    {
        "инструмент": "pipeline__save_to_file",
        "после": ["pipeline__summarize", "pipeline__run_pipeline"],
        "почему": "Отчёт сохраняют после обработки: иначе в файл ляжет сырой ответ "
                  "инструмента или выдумка модели.",
    },
]


class ОшибкаПорядка(RuntimeError):
    """Файл правил порядка не читается или описан неверно."""


@dataclass
class Правило:
    """«Инструмент X — только после одного из Y»."""

    инструмент: str
    после: list[str] = field(default_factory=list)
    почему: str = ""

    def подходит(self, имя: str) -> bool:
        """Про этот ли инструмент правило. Шаблоны — как в фильтрах серверов."""
        return fnmatch.fnmatchcase(имя, self.инструмент)

    def выполнено(self, сделано: list[str]) -> str:
        """Какой из требуемых вызовов уже был. Пусто — ни одного."""
        for имя in сделано:
            for шаблон in self.после:
                if fnmatch.fnmatchcase(имя, шаблон):
                    return имя
        return ""

    def словами(self) -> str:
        return f"{self.инструмент} — после {' или '.join(self.после)}"

    def to_dict(self) -> dict[str, Any]:
        return {"инструмент": self.инструмент, "после": list(self.после),
                "почему": self.почему}


@dataclass
class Вердикт:
    """Можно ли звать инструмент прямо сейчас."""

    можно: bool = True
    почему: str = ""
    правило: Правило | None = None
    закрыто: str = ""        # какой вызов открыл дорогу (когда можно)

    def to_dict(self) -> dict[str, Any]:
        return {"можно": self.можно, "почему": self.почему,
                "правило": self.правило.to_dict() if self.правило else None,
                "закрыто": self.закрыто}


class Порядок:
    """Набор правил и две проверки: плана целиком и одного вызова."""

    def __init__(self, правила: list[Правило] | None = None, путь: str = "") -> None:
        self.правила = list(правила or [])
        self.путь = путь

    # --- проверки -------------------------------------------------------------

    def проверить(self, инструмент: str, сделано: list[str]) -> Вердикт:
        """Вызов против уже сделанного. «сделано» — только УСПЕШНЫЕ вызовы.

        Неуспешный вызов данных не принёс, и считать его выполненным условием
        значило бы разрешить писать комментарий после неудачного чтения задачи.
        """
        имя = (инструмент or "").strip()
        for правило in self.правила:
            if not правило.подходит(имя):
                continue
            был = правило.выполнено(list(сделано))
            if был:
                return Вердикт(можно=True, правило=правило, закрыто=был)
            нужно = " или ".join(f"«{ш}»" for ш in правило.после) or "предыдущий шаг"
            return Вердикт(
                можно=False, правило=правило,
                почему=(f"Сначала нужен вызов {нужно}. {правило.почему}").strip())
        return Вердикт(можно=True)

    def проверить_план(self, шаги: list[str]) -> list[str]:
        """Замечания к порядку шагов плана — до того, как флоу начнётся.

        Плану замечание не мешает: исполнение всё равно идёт по факту, и модель
        часто исправляется сама. Но человеку видно сразу, что предложенный
        порядок не выдержит проверки, и это половина ответа на вопрос задания
        «корректен ли порядок».
        """
        замечания: list[str] = []
        сделано: list[str] = []
        for место, имя in enumerate(шаги, 1):
            вердикт = self.проверить(имя, сделано)
            if not вердикт.можно:
                замечания.append(f"шаг {место} «{имя}»: {вердикт.почему}")
            сделано.append(имя)
        return замечания

    # --- показать -------------------------------------------------------------

    def словами(self) -> str:
        if not self.правила:
            return "Правил порядка нет."
        return "; ".join(п.словами() for п in self.правила)

    def to_dict(self) -> dict[str, Any]:
        return {"файл": self.путь, "правила": [п.to_dict() for п in self.правила]}

    def __len__(self) -> int:
        return len(self.правила)


def _правило(данные: Any, где: str) -> Правило:
    if not isinstance(данные, dict):
        raise ОшибкаПорядка(f"{где}: правило должно быть объектом JSON.")
    имя = str(данные.get("инструмент", "")).strip()
    if not имя:
        raise ОшибкаПорядка(f"{где}: не сказано, к какому инструменту относится правило.")
    после = данные.get("после", [])
    if isinstance(после, str):
        после = [после]
    if not isinstance(после, list) or not после:
        raise ОшибкаПорядка(f"{где}: «после» должно быть непустым списком имён инструментов.")
    return Правило(инструмент=имя, после=[str(ш).strip() for ш in после if str(ш).strip()],
                   почему=str(данные.get("почему", "")).strip())


def разобрать(данные: Any, путь: str = "") -> Порядок:
    """Разбирает содержимое файла правил. Пустой список правил — это тоже ответ."""
    if isinstance(данные, dict):
        правила = данные.get("правила", [])
    else:
        правила = данные
    if not isinstance(правила, list):
        raise ОшибкаПорядка("В файле правил ожидался список «правила».")
    return Порядок([_правило(п, f"правило {номер}") for номер, п in enumerate(правила, 1)],
                   путь=путь)


def загрузить(путь: str = "") -> Порядок:
    """Читает flow-rules.json. Нет файла — возвращает встроенные правила."""
    путь = (путь or "").strip()
    if not путь or not os.path.exists(путь):
        return разобрать(ПО_УМОЛЧАНИЮ, путь="встроенные")
    try:
        with open(путь, "r", encoding="utf-8") as файл:
            данные = json.load(файл)
    except (OSError, json.JSONDecodeError) as exc:
        raise ОшибкаПорядка(f"Файл правил «{путь}» не читается: {exc}") from exc
    return разобрать(данные, путь=путь)


