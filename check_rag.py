#!/usr/bin/env python3
"""Проверка задания Дня 21: индексация документов.

Задание требует пайплайна «чанки → эмбеддинги → сохранённый индекс» на наборе
от 20–30 страниц, метаданных у каждого чанка и сравнения двух стратегий
разбиения. Скрипт идёт по этим пунктам на настоящих документах из DocsSample/
и на настоящем индексе index/docs.db, а то, что можно проверить мимо нашего
кода, проверяет мимо него: базу читает прямым SQL, а поиск спрашивает у
MCP-сервера docs, запущенного отдельным процессом.

  Часть 1  ДОКУМЕНТЫ. Каждый файл прочитан: текстовый слой PDF, сканы через
           OCR, листы Excel. Сколько страниц и символов набралось.
  Часть 2  СБОРКА. Обе стратегии собраны одним конвейером; повторная сборка
           берёт векторы из кэша и идёт секунды.
  Часть 3  ЧАНКИ И МЕТАДАННЫЕ. У каждого чанка source, title, section,
           chunk_id (уникальный), страницы; «структура» не режет абзацы, «фикс»
           держит размер и перекрывается.
  Часть 4  ЭМБЕДДИНГИ. Размерность модели, векторы нормированы, перефразировка
           ближе к оригиналу, чем посторонний текст.
  Часть 5  ИНДЕКС НА ДИСКЕ. Таблицы, число строк и длина BLOB — прямым SQL и
           numpy, без нашего кода.
  Часть 6  ПОИСК ЧЕРЕЗ MCP. Сервер docs отдельным процессом находит пункт
           договора и возвращает паспорт чанка для ссылки.
  Часть 7  СРАВНЕНИЕ СТРАТЕГИЙ. Статистика нарезки и эталонные вопросы:
           hit@1/3/5, MRR; отчёт RAG-COMPARISON.md.

Запуск:
    python check_rag.py                      # индекс index/ с Ollama (bge-m3)
    python check_rag.py --пересобрать        # собрать индекс заново, а не взять готовый
    python check_rag.py --эмбеддер хэш       # без Ollama: во временный индекс
    python check_rag.py --в RESULTS.md       # дописать отчёт в файл
"""

