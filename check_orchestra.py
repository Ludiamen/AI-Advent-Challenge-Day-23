def _прямо_из_базы(база: str, запрос: str, параметры: tuple = ()) -> list[tuple]:
    """Запрос к файлу SQLite мимо нашего кода: данные проверяются, а не пересказываются."""
    соединение = sqlite3.connect(база)
    try:
        return соединение.execute(запрос, параметры).fetchall()
    finally:
        соединение.close()


def _комментарии(мок: МокТрекера, ключ: str) -> list[str]:
    """Комментарии задачи прямо из API мока — мимо агента и его протокола."""
    ответ = мок.запрос("GET", f"/v3/issues/{ключ}/comments")
    записи = ответ.json() if ответ.status_code == 200 else []
    return [з.get("text", "") for з in записи if isinstance(з, dict)]


class _Сценарий:
    """Модель-заглушка: отвечает заготовленным, чтобы проверять код, а не модель."""

    def __init__(self, *ответы):
        self.очередь = list(ответы)
        self.запросы: list[dict] = []

    def call(self, ключ, сообщения, **кв):
        self.запросы.append({"сообщения": сообщения, "tools": кв.get("tools")})
        return self.очередь.pop(0) if self.очередь else Reply(text="итог", model_key="сценарий")

    def close(self):
        pass


def _план(цель: str, *инструменты: str) -> Reply:
    шаги = [{"инструмент": и, "зачем": f"шаг {н}"} for н, и in enumerate(инструменты, 1)]
    return Reply(text=json.dumps({"цель": цель, "шаги": шаги}, ensure_ascii=False),
                 model_key="сценарий")


def _вызов(ид: str, имя: str, аргументы: dict) -> Reply:
    сырые = json.dumps(аргументы, ensure_ascii=False)
    запись = [{"id": ид, "function": {"name": имя, "arguments": сырые}}]
    return Reply(text="", model_key="сценарий", tool_calls=разобрать_вызовы(запись),
                 message={"role": "assistant", "content": "",
                          "tool_calls": [{"id": ид, "type": "function",
                                          "function": запись[0]["function"]}]})


