def часть_2(отчёт: Отчёт, поисковик: retrieval.Поисковик) -> None:
    отчёт.часть(2, "Отбор по шагам на промахе Дня 22 (c03)")
    отчёт(f"  вопрос: «{ВОПРОС}»")
    база = поисковик.найти(ВОПРОС, retrieval.БАЗА)
    место, судьба, было = место_верного(база)
    отчёт(f"  база: в промпт {len(база.фрагменты)}; верный чанк — {судьба}"
          + (f", место по косинусу {было}" if было else ""))
    отчёт.пункт(место == 0, "в базе Дня 22 чанка с п. 2.2.7 в промпте нет — это и был промах")
    отбор = поисковик.найти(ВОПРОС, retrieval.ФИЛЬТР)
    н = отбор.настройки
    for этап in отбор.этапы:
        отчёт("    " + json.dumps({к: з for к, з in этап.items() if к not in ("all",)},
                                  ensure_ascii=False)[:200])
    for к in отбор.кандидаты[:8]:
        х = к.находка
        отчёт(f"    {х.место if к.судьба == 'в промпт' else '·':>3} было {х.место_до:>2} · cos "
              f"{х.оценка:.3f} · реранк {х.реранк if х.реранк is None else round(х.реранк, 3)} · "
              f"{к.судьба:<15} {х.чанк.источник[:30]} · {х.чанк.раздел[:34]}"
              + (" ← п. 2.2.7" if верный(х) else ""))
    место, судьба, было = место_верного(отбор)
    отчёт.пункт(место > 0 and было > retrieval.K_БАЗЫ,
                f"с фильтром верный чанк в промпте на {место}-м месте; по косинусу он был {было}-м")
    оценки = [ф.реранк for ф in отбор.фрагменты]
    отчёт.пункт(оценки == sorted(оценки, reverse=True) and all(о >= н.порог for о in оценки),
                f"в промпте {len(оценки)} ≤ K_после {н.k_после}, по убыванию оценки, все ≥ порога {н.порог}")
    отчёт.пункт(len(отбор.фрагменты) <= н.k_после, "K после соблюдён")


def часть_3(отчёт: Отчёт, поисковик: retrieval.Поисковик, подбор: dict) -> None:
    отчёт.часть(3, "Три реранкера на одном вопросе: качество и цена")
    н = поисковик.настройки(retrieval.ФИЛЬТР)
    отчёт("  | реранкер | место верного | оценка верного | лучшая чужая | посчитано / из кэша | секунд |")
    отчёт("  |---|---:|---:|---:|---:|---:|")
    места = {}
    for имя in rr.РЕРАНКЕРЫ:
        отбор = поисковик.найти(ВОПРОС, replace(н, имя=имя, реранкер=имя, порог=0.0, k_после=н.k_до))
        реранк = next((э for э in отбор.этапы if э["этап"] == "реранк"), {})
        верн = next((к.находка for к in отбор.кандидаты if верный(к.находка)), None)
        чужие = [к.находка.реранк for к in отбор.кандидаты
                 if not верный(к.находка) and к.находка.реранк is not None]
        места[имя] = верн.место if верн else 0
        оценка = f"{верн.реранк:.3f}" if верн and верн.реранк is not None else "—"
        if отбор.ошибки:
            оценка = "недоступен"
        отчёт(f"  | {имя} | {места[имя] or '—'} | {оценка} | {max(чужие, default=0):.3f} | "
              f"{реранк.get('посчитано', 0)} / {реранк.get('из_кэша', 0)} | {реранк.get('секунд', 0)} |")
    выбранный = н.реранкер
    отчёт.пункт(0 < места.get(выбранный, 0) <= 3,
                f"выбранный реранкер «{выбранный}» ставит чанк с п. 2.2.7 в первую тройку; места: " +
                ", ".join(f"{и} — {м or 'нет'}" for и, м in места.items()))
    if места.get(rr.КРОСС, 0) > 3:
        отчёт(f"  кросс-энкодер видит пару до {rr.ДЛИНА_ПАРЫ} токенов, а п. 2.2.7 стоит в конце "
              "чанка ≈ 700 токенов: ответ ему не виден — так выглядит обрезка длинного чанка")
    задержка = подбор.get("задержка", {})
    if задержка:
        отчёт.пункт(задержка.get(rr.ЭВРИСТИКА, 99) < 1 <= задержка.get(rr.КРОСС, 0),
                    "цена разная по порядку величины: эвристика — доли секунды, кросс-энкодер на CPU "
                    f"— {_секунды(задержка.get(rr.КРОСС, 0))} на вопрос, LLM — "
                    f"{_секунды(задержка.get(rr.LLM, 0))} (вызов облака)")


def часть_4(отчёт: Отчёт, поисковик: retrieval.Поисковик) -> None:
    отчёт.часть(4, "Порог отсечения и top-K до и после")
    н = поисковик.настройки(retrieval.ФИЛЬТР)
    строки = []
    for порог in sorted({0.0, н.порог, 0.3, 0.6, 0.9}):
        отбор = поисковик.найти(ВОПРОС, replace(н, имя="порог", порог=порог))
        строки.append((порог, len(отбор.фрагменты), место_верного(отбор)[0]))
    отчёт("  порог → в промпт (место верного): " + "; ".join(
        f"{п} → {к} ({м or 'нет'})" for п, к, м in строки))
    отчёт.пункт(all(а[1] >= б[1] for а, б in zip(строки, строки[1:])),
                "чем выше порог, тем меньше фрагментов: порог режет монотонно")
    для_k = []
    for k_после in (1, 3, 5, 8):
        отбор = поисковик.найти(ВОПРОС, replace(н, имя="k", k_после=k_после, порог=0.0))
        для_k.append((k_после, len(отбор.фрагменты)))
    отчёт("  K после → в промпт: " + "; ".join(f"{k} → {в}" for k, в in для_k))
    отчёт.пункт(all(в == k for k, в in для_k), "K после ровно ограничивает промпт")
    # K до — сколько кандидатов первого этапа видит реранкер. Поднять он может
    # только то, что ему дали: при K до = 5 (как в базе) верного чанка среди
    # кандидатов нет вовсе.
    для_kдо = []
    for k_до in (5, 10, 20):
        отбор = поисковик.найти(ВОПРОС, replace(н, имя="kдо", k_до=k_до))
        для_kдо.append((k_до, отбор.этапы[0]["кандидатов"], место_верного(отбор)))
    отчёт("  K до → кандидатов реранкеру → верный чанк: " + "; ".join(
        f"{k} → {к} → {м[1]}" + (f" на {м[0]}-м месте" if м[0] else "") for k, к, м in для_kдо))
    отчёт.пункт(для_kдо[0][2][0] == 0 and для_kдо[-1][2][0] > 0,
                "K до решает, дойдёт ли верный чанк до реранкера: при 5 кандидатах его не "
                "поднять, при 20 он в промпте")
    база = поисковик.найти(ЛОВУШКА, retrieval.БАЗА)
    фильтр = поисковик.найти(ЛОВУШКА, retrieval.ФИЛЬТР)
    отчёт(f"  ловушка «{ЛОВУШКА}»: база — {len(база.фрагменты)} фрагментов (лучший cos "
          f"{max((ф.оценка for ф in база.фрагменты), default=0):.2f}), фильтр — {len(фильтр.фрагменты)}"
          f" (лучшая оценка {max((ф.реранк for ф in фильтр.фрагменты), default=0):.3f})")
    отчёт.пункт(len(фильтр.фрагменты) <= len(база.фрагменты),
                "у ловушки фильтр пропускает в промпт не больше, чем база")


def часть_5(отчёт: Отчёт, поисковик: retrieval.Поисковик) -> None:
    отчёт.часть(5, "Query rewrite: запросы на языке документов и слияние RRF")
    переписчик = поисковик.переписчик()
    for вопрос in (ВОПРОС, "Сколько дней даётся на оплату счёта по договору с ВымпелКомом?"):
        итог = переписчик.переписать(вопрос)
        отчёт(f"  «{вопрос}» ({'из кэша' if итог.из_кэша else _секунды(итог.секунд)}, {итог.модель}):")
        for з in итог.запросы:
            отчёт(f"      → {з}")
        отчёт.пункт(2 <= len(итог.запросы) <= 3 and not итог.ошибка,
                    f"   запросов {len(итог.запросы)}, исходный вопрос идёт первым и не заменяется")
    повтор = переписчик.переписать(ВОПРОС)
    отчёт.пункт(повтор.из_кэша, "повторное переписывание — из кэша: сравнение режимов не мерит разброс модели")
    отбор = поисковик.найти(ВОПРОС, retrieval.REWRITE)
    поиск = next(э for э in отбор.этапы if э["этап"] == "поиск")
    отчёт.пункт(поиск["запросов"] >= 3 and поиск["кандидатов"] > поиск["k_до"],
                f"поиск по {поиск['запросов']} запросам по {поиск['k_до']} кандидатов → после RRF "
                f"{поиск['кандидатов']} разных чанков")
    место, судьба, было = место_верного(отбор)
    отчёт(f"  rewrite без реранкера: верный чанк — {судьба}" + (f" на {место}-м месте" if место else ""))


