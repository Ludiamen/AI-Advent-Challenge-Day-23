"""Хранилище прогонов конвейера: что и куда передавалось на каждом шаге.

Файл тот же, что у планировщика Дня 18 (memory/scheduler.db), а таблицы свои —
«прогоны» и «шаги_конвейера». Так сделано потому, что фоновая жизнь агента
одна: работник запускает конвейер по расписанию, сводка считает его прогоны,
консоль и страница читают и то и другое. Держать это в двух файлах значило бы
две блокировки, два пути в настройках и вечный вопрос, какой из них свежее.
Класс при этом отдельный: пакет конвейера не зависит от планировщика, и
наоборот — общий у них только файл, а SQLite в режиме WAL разводит писателей
сам.

Главное здесь — не история ради истории. В каждом шаге хранится ВХОД (уже
подставленные аргументы) и ВЫХОД (то, что вернул инструмент), а рядом — список
сработавших подстановок вида «выжимка.данные.текст → 412 симв.». Это и есть
ответ на требование задания «проверьте корректность передачи данных между
инструментами»: вход третьего шага можно поставить рядом с выходом второго и
сравнить — руками, тестом или проверочным скриптом.

Публичное API:
  PipelineStore(path)       — открыть (и создать) базу
  .начать(...) -> Прогон
  .записать_шаг(...) -> ШагПрогона
  .завершить(...) -> Прогон
  .прогон(номер) / .прогоны(...) / .последний(конвейер)
  .счётчики(с, по)          — сколько прогонов и сбоев за окно (для сводки)
  .close()
"""

from __future__ import annotations

import json
import os
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

ИДЁТ = "идёт"
ГОТОВ = "готов"
СБОЙ = "сбой"
СОСТОЯНИЯ = (ИДЁТ, ГОТОВ, СБОЙ)

# Сколько символов результата шага держать в базе. Инструмент может вернуть
# мегабайт; для сверки передачи нужны первые строки и структура, а не всё.
ПРЕДЕЛ_ВЫХОДА = 4000
ПРЕДЕЛ_ВХОДА = 4000
ПРЕДЕЛ_ИТОГА = 300

_SCHEMA = """
CREATE TABLE IF NOT EXISTS прогоны (
    номер     INTEGER PRIMARY KEY AUTOINCREMENT,
    конвейер  TEXT NOT NULL,
    начат     TEXT NOT NULL,
    кончен    TEXT NOT NULL DEFAULT '',
    секунд    REAL NOT NULL DEFAULT 0,
    состояние TEXT NOT NULL DEFAULT 'идёт',
    вход      TEXT NOT NULL DEFAULT '{}',
    шагов     INTEGER NOT NULL DEFAULT 0,
    сделано   INTEGER NOT NULL DEFAULT 0,
    итог      TEXT NOT NULL DEFAULT '',
    ошибка    TEXT NOT NULL DEFAULT '',
    зачем     TEXT NOT NULL DEFAULT '',
    кто       TEXT NOT NULL DEFAULT '',
    задание   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_прогоны_начат ON прогоны(начат);

CREATE TABLE IF NOT EXISTS шаги_конвейера (
    номер        INTEGER PRIMARY KEY AUTOINCREMENT,
    прогон       INTEGER NOT NULL,
    место        INTEGER NOT NULL,
    имя          TEXT NOT NULL,
    инструмент   TEXT NOT NULL,
    начат        TEXT NOT NULL DEFAULT '',
    секунд       REAL NOT NULL DEFAULT 0,
    ок           INTEGER NOT NULL DEFAULT 0,
    вход         TEXT NOT NULL DEFAULT '{}',
    подстановки  TEXT NOT NULL DEFAULT '[]',
    выход        TEXT NOT NULL DEFAULT '',
    текст        TEXT NOT NULL DEFAULT '',
    ошибка       TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_шаги_прогон ON шаги_конвейера(прогон, место);
"""


class PipelineStoreError(RuntimeError):
    """База прогонов не открывается или её просят о невозможном."""


def _сейчас() -> datetime:
    return datetime.now().replace(microsecond=0)


def _строка(момент: datetime | None) -> str:
    return момент.replace(microsecond=0).isoformat(sep=" ") if момент else ""


def _json(значение: Any) -> str:
    try:
        return json.dumps(значение, ensure_ascii=False)
    except (TypeError, ValueError):
        return json.dumps(str(значение), ensure_ascii=False)


def _из_json(текст: str, по_умолчанию: Any) -> Any:
    if not текст:
        return по_умолчанию
    try:
        return json.loads(текст)
    except (TypeError, ValueError):
        return по_умолчанию


def _обрезать(текст: str, предел: int) -> str:
    текст = текст or ""
    return текст if len(текст) <= предел else текст[:предел] + f"… (всего {len(текст)} симв.)"


@dataclass
class ШагПрогона:
    """След одного шага: что ушло в инструмент и что он вернул."""

    номер: int = 0
    прогон: int = 0
    место: int = 0
    имя: str = ""
    инструмент: str = ""
    начат: str = ""
    секунд: float = 0.0
    ок: bool = True
    вход: Any = field(default_factory=dict)
    подстановки: list[list[str]] = field(default_factory=list)
    выход: Any = None
    текст: str = ""
    ошибка: str = ""

    def словами(self) -> str:
        откуда = ", ".join(f"{путь} → {что}" for путь, что in self.подстановки)
        хвост = f" ← {откуда}" if откуда else ""
        знак = "ок" if self.ок else "сбой"
        return f"{self.место}. {self.имя} ({self.инструмент}): {знак}{хвост}"

    def to_dict(self) -> dict[str, Any]:
        return {"номер": self.номер, "прогон": self.прогон, "место": self.место,
                "имя": self.имя, "инструмент": self.инструмент, "начат": self.начат,
                "секунд": round(self.секунд, 3), "ок": self.ок, "вход": self.вход,
                "подстановки": [list(п) for п in self.подстановки], "выход": self.выход,
                "текст": self.текст, "ошибка": self.ошибка}


@dataclass
class Прогон:
    """Один запуск конвейера целиком."""

    номер: int = 0
    конвейер: str = ""
    начат: str = ""
    кончен: str = ""
    секунд: float = 0.0
    состояние: str = ИДЁТ
    вход: dict[str, Any] = field(default_factory=dict)
    шагов: int = 0
    сделано: int = 0
    итог: str = ""
    ошибка: str = ""
    зачем: str = ""
    кто: str = ""
    задание: int = 0
    шаги: list[ШагПрогона] = field(default_factory=list)

    @property
    def ок(self) -> bool:
        return self.состояние == ГОТОВ

    @property
    def идёт(self) -> bool:
        return self.состояние == ИДЁТ

    def словами(self) -> str:
        цепочка = " → ".join(ш.имя for ш in self.шаги) or "—"
        если_сбой = f"; встали на «{self.шаги[-1].имя}»: {self.ошибка}" if (
            self.состояние == СБОЙ and self.шаги) else (
            f": {self.ошибка}" if self.состояние == СБОЙ else "")
        return (f"Прогон №{self.номер} «{self.конвейер}» — {self.состояние} "
                f"({self.сделано} из {self.шагов}): {цепочка}{если_сбой}")

    def to_dict(self) -> dict[str, Any]:
        return {"номер": self.номер, "конвейер": self.конвейер, "начат": self.начат,
                "кончен": self.кончен, "секунд": round(self.секунд, 3),
                "состояние": self.состояние, "ок": self.ок, "вход": dict(self.вход),
                "шагов": self.шагов, "сделано": self.сделано, "итог": self.итог,
                "ошибка": self.ошибка, "зачем": self.зачем, "кто": self.кто,
                "задание": self.задание, "шаги": [ш.to_dict() for ш in self.шаги]}


class PipelineStore:
    """Прогоны конвейеров и их шаги — в том же файле, что и расписание."""

    def __init__(self, path: str) -> None:
        self.path = path
        каталог = os.path.dirname(os.path.abspath(path)) if path != ":memory:" else ""
        if каталог:
            os.makedirs(каталог, exist_ok=True)
        try:
            # Те же настройки, что у планировщика: автофиксация (иначе открытая
            # транзакция одного процесса заперла бы базу другому) и WAL.
            self._db = sqlite3.connect(path, check_same_thread=False, isolation_level=None,
                                       timeout=10.0)
            self._db.row_factory = sqlite3.Row
            if path != ":memory:":
                self._db.execute("PRAGMA journal_mode=WAL")
            self._db.execute("PRAGMA busy_timeout=10000")
            self._db.executescript(_SCHEMA)
        except sqlite3.Error as exc:
            raise PipelineStoreError(f"База конвейеров «{path}» не открывается: {exc}") from exc

    # --- прогон ---------------------------------------------------------------

    def начать(self, конвейер: str, шагов: int, вход: dict[str, Any] | None = None,
               зачем: str = "", кто: str = "", задание: int = 0,
               сейчас: datetime | None = None) -> Прогон:
        """Заводит запись о прогоне до первого вызова: упавший прогон тоже виден."""
        конвейер = (конвейер or "").strip()
        if not конвейер:
            raise PipelineStoreError("Не сказано, какой конвейер запускается.")
        сейчас = сейчас or _сейчас()
        курсор = self._db.execute(
            "INSERT INTO прогоны (конвейер, начат, состояние, вход, шагов, зачем, кто, задание) "
            "VALUES (?,?,?,?,?,?,?,?)",
            (конвейер, _строка(сейчас), ИДЁТ, _json(вход or {}), int(шагов),
             зачем, кто, int(задание)))
        return Прогон(номер=int(курсор.lastrowid), конвейер=конвейер, начат=_строка(сейчас),
                      состояние=ИДЁТ, вход=dict(вход or {}), шагов=int(шагов), зачем=зачем,
                      кто=кто, задание=int(задание))

    def записать_шаг(self, прогон: int, место: int, имя: str, инструмент: str,
                     ок: bool, вход: Any = None, подстановки: Any = None,
                     выход: Any = None, текст: str = "", секунд: float = 0.0,
                     ошибка: str = "", сейчас: datetime | None = None) -> ШагПрогона:
        """Записывает шаг вместе с тем, что в него подставилось."""
        сейчас = сейчас or _сейчас()
        пары = [[str(п), str(з)] for п, з in (подстановки or [])]
        строка_входа = _обрезать(_json(вход if вход is not None else {}), ПРЕДЕЛ_ВХОДА)
        строка_выхода = _обрезать(_json(выход), ПРЕДЕЛ_ВЫХОДА) if выход is not None else ""
        курсор = self._db.execute(
            "INSERT INTO шаги_конвейера (прогон, место, имя, инструмент, начат, секунд, ок, "
            "вход, подстановки, выход, текст, ошибка) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
            (int(прогон), int(место), имя, инструмент, _строка(сейчас), float(секунд),
             1 if ок else 0, строка_входа, _json(пары), строка_выхода,
             _обрезать(текст, ПРЕДЕЛ_ВЫХОДА), ошибка))
        if ок:
            # «Сделано» — это шаги, которые ДОШЛИ до конца. Упавший шаг в счёт не
            # идёт: иначе «3 из 3» стояло бы и у прогона, который встал на третьем.
            self._db.execute("UPDATE прогоны SET сделано = сделано + 1 WHERE номер = ?",
                             (int(прогон),))
        return ШагПрогона(
            номер=int(курсор.lastrowid), прогон=int(прогон), место=int(место), имя=имя,
            инструмент=инструмент, начат=_строка(сейчас), секунд=float(секунд), ок=ок,
            вход=_из_json(строка_входа, вход), подстановки=пары,
            выход=_из_json(строка_выхода, выход), текст=текст, ошибка=ошибка)

    def завершить(self, прогон: int, состояние: str, итог: str = "", ошибка: str = "",
                  секунд: float = 0.0, сейчас: datetime | None = None) -> Прогон:
        """Закрывает прогон. Состояние — «готов» или «сбой»."""
        if состояние not in (ГОТОВ, СБОЙ):
            raise PipelineStoreError(
                f"Состояние прогона «{состояние}» не бывает: только «{ГОТОВ}» или «{СБОЙ}».")
        сейчас = сейчас or _сейчас()
        self._db.execute(
            "UPDATE прогоны SET состояние = ?, кончен = ?, секунд = ?, итог = ?, ошибка = ? "
            "WHERE номер = ?",
            (состояние, _строка(сейчас), float(секунд), _обрезать(итог, ПРЕДЕЛ_ИТОГА),
             ошибка, int(прогон)))
        готовый = self.прогон(прогон)
        if готовый is None:  # pragma: no cover — прогон только что был
            raise PipelineStoreError(f"Прогона №{прогон} нет.")
        return готовый

    def привязать(self, прогон: int, задание: int, кто: str = "") -> None:
        """Отмечает, каким заданием планировщика запущен прогон.

        Делает это работник Дня 18 после вызова: сам сервер конвейеров не знает,
        кто его позвал — он видит только вызов инструмента. Связь нужна, чтобы
        в истории было видно, что прогон случился по расписанию, а не руками.
        """
        поля, значения = ["задание = ?"], [int(задание)]
        if кто:
            поля.append("кто = ?")
            значения.append(кто)
        значения.append(int(прогон))
        self._db.execute(f"UPDATE прогоны SET {', '.join(поля)} WHERE номер = ?", значения)

    # --- чтение ---------------------------------------------------------------

    def прогон(self, номер: int, с_шагами: bool = True) -> Прогон | None:
        строка = self._db.execute("SELECT * FROM прогоны WHERE номер = ?",
                                  (int(номер),)).fetchone()
        if строка is None:
            return None
        прогон = self._прогон(строка)
        if с_шагами:
            прогон.шаги = self.шаги(прогон.номер)
        return прогон

    def шаги(self, прогон: int) -> list[ШагПрогона]:
        строки = self._db.execute(
            "SELECT * FROM шаги_конвейера WHERE прогон = ? ORDER BY место, номер",
            (int(прогон),)).fetchall()
        return [self._шаг(с) for с in строки]

    def прогоны(self, конвейер: str = "", сколько: int = 10,
                с_шагами: bool = False) -> list[Прогон]:
        запрос = "SELECT * FROM прогоны"
        параметры: list[Any] = []
        if конвейер:
            запрос += " WHERE конвейер = ?"
            параметры.append(конвейер)
        запрос += " ORDER BY номер DESC LIMIT ?"
        параметры.append(max(1, int(сколько)))
        прогоны = [self._прогон(с) for с in self._db.execute(запрос, параметры).fetchall()]
        if с_шагами:
            for прогон in прогоны:
                прогон.шаги = self.шаги(прогон.номер)
        return прогоны

    def последний(self, конвейер: str = "", с_шагами: bool = True) -> Прогон | None:
        прогоны = self.прогоны(конвейер, сколько=1, с_шагами=с_шагами)
        return прогоны[0] if прогоны else None

    def счётчики(self, с: datetime | None = None, по: datetime | None = None) -> dict[str, Any]:
        """Сколько прогонов и сбоев за окно — цифры для сводки планировщика."""
        условия, параметры = [], []
        if с is not None:
            условия.append("начат >= ?")
            параметры.append(_строка(с))
        if по is not None:
            условия.append("начат <= ?")
            параметры.append(_строка(по))
        где = (" WHERE " + " AND ".join(условия)) if условия else ""
        строки = self._db.execute(
            f"SELECT конвейер, состояние, COUNT(*) AS сколько FROM прогоны{где} "
            "GROUP BY конвейер, состояние", параметры).fetchall()
        всего = сбоев = 0
        по_конвейерам: dict[str, dict[str, int]] = {}
        for строка in строки:
            сколько = int(строка["сколько"])
            всего += сколько
            запись = по_конвейерам.setdefault(строка["конвейер"], {"прогонов": 0, "сбоев": 0})
            запись["прогонов"] += сколько
            if строка["состояние"] == СБОЙ:
                сбоев += сколько
                запись["сбоев"] += сколько
        return {"прогонов": всего, "сбоев": сбоев, "конвейеры": по_конвейерам}

    def close(self) -> None:
        try:
            self._db.close()
        except sqlite3.Error:  # pragma: no cover — закрытие уже закрытой базы
            pass

    # --- разбор строк ---------------------------------------------------------

    @staticmethod
    def _прогон(строка: sqlite3.Row) -> Прогон:
        return Прогон(
            номер=int(строка["номер"]), конвейер=строка["конвейер"], начат=строка["начат"],
            кончен=строка["кончен"], секунд=float(строка["секунд"]),
            состояние=строка["состояние"], вход=_из_json(строка["вход"], {}),
            шагов=int(строка["шагов"]), сделано=int(строка["сделано"]), итог=строка["итог"],
            ошибка=строка["ошибка"], зачем=строка["зачем"], кто=строка["кто"],
            задание=int(строка["задание"]))

    @staticmethod
    def _шаг(строка: sqlite3.Row) -> ШагПрогона:
        return ШагПрогона(
            номер=int(строка["номер"]), прогон=int(строка["прогон"]),
            место=int(строка["место"]), имя=строка["имя"], инструмент=строка["инструмент"],
            начат=строка["начат"], секунд=float(строка["секунд"]), ок=bool(строка["ок"]),
            вход=_из_json(строка["вход"], {}), подстановки=_из_json(строка["подстановки"], []),
            выход=_из_json(строка["выход"], None), текст=строка["текст"],
            ошибка=строка["ошибка"])


