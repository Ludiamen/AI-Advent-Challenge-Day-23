def _напечатать_находку(н, отступ: str = "  ") -> None:
    ч = н.чанк
    место = f"стр. {ч.страницы}" if ч.страницы else ""
    пункт = f", п. {ч.пункт}" if ч.пункт else ""
    print(f"{отступ}{н.место}. [{н.оценка:.3f}] {ч.источник} · {ч.раздел}{пункт} · {место}")
    print(f"{отступ}   {ч.chunk_id}, {ч.токенов} ток."
          + (", поперёк: " + " | ".join(ч.разделы[1:3]) if len(ч.разделы) > 1 else ""))
    текст = " ".join(ч.текст.split())
    print(f"{отступ}   «{текст[:220]}{'…' if len(текст) > 220 else ''}»")


def найти_в_документах(аргументы) -> int:
    индексатор = _индексатор(аргументы)
    запрос = аргументы.rag_search
    if аргументы.rag_strategy == "обе":
        итог = индексатор.найти_везде(запрос, аргументы.rag_limit)
    else:
        итог = {аргументы.rag_strategy: индексатор.найти(запрос, аргументы.rag_strategy,
                                                         аргументы.rag_limit)}
    print(LINE)
    print(f"Запрос: «{запрос}» · эмбеддер {индексатор.эмбеддер.имя}")
    for стратегия, находки in итог.items():
        print(LINE)
        print(f"Стратегия «{стратегия}»:")
        if not находки:
            print("  ничего не найдено")
        for н in находки:
            _напечатать_находку(н)
    return 0


