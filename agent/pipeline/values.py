"""Подстановка значений между шагами конвейера.

Это то самое место, где задание дня требует «корректности передачи данных
между инструментами». Передача устроена так: у каждого шага есть имя, и после
вызова его результат кладётся в портфель под этим именем. Следующий шаг
ссылается на него прямо в своих аргументах:

    {"text": "${выжимка.данные.текст}"}

Почему ссылки, а не «результат предыдущего шага целиком». Инструменты пишут
разные люди, и подгонять их друг под друга — значит переписывать сервер всякий
раз, когда меняется порядок шагов. Ссылка же говорит буквально: «возьми из
шага „выжимка“ поле „текст“ его структурного результата». Её видно в описании
конвейера, её видно в протоколе прогона, и если поля нет — ошибка приходит с
перечнем того, что есть, а не «None» тремя шагами позже.

Два вида подстановки. Если вся строка — одна ссылка, подставляется значение
как есть: список остаётся списком, число числом. Если ссылка стоит внутри
текста, значение превращается в строку (не-строки — компактным JSON), потому
что склеить строку со словарём нельзя.

Портфель — обычный словарь: {"вход": {...}, "<имя шага>": {"данные": ...,
"текст": "...", "ок": True}}. Ключ «вход» — то, с чем конвейер запустили.

Публичное API:
  ссылки(значение)                  -> list[str] — все пути, встреченные внутри
  подставить(значение, портфель)    -> (значение, [(путь, что получилось)])
  достать(портфель, путь)           -> значение по пути
  ОшибкаПодстановки                 — путь никуда не ведёт
"""

from __future__ import annotations

import json
import re
from typing import Any

# ${шаг.данные.поле}. Внутри — путь через точку; пробелы по краям съедаются.
# Вложенные фигурные скобки не поддерживаются намеренно: выражений здесь нет,
# только путь к уже полученным данным.
ССЫЛКА = re.compile(r"\$\{([^{}]+)\}")

# Сколько элементов списка показывать, когда значение подставляется в текст.
ПОКАЗАТЬ = 20


class ОшибкаПодстановки(ValueError):
    """Ссылка ведёт туда, где ничего нет: нет шага, нет поля, короткий список."""


def ссылки(значение: Any) -> list[str]:
    """Все пути, на которые ссылается значение, в порядке появления.

    Обходит словари и списки целиком: ссылка может лежать глубоко внутри
    аргумента-объекта, и проверять конвейер надо по всем.
    """
    найдено: list[str] = []
    _обойти(значение, найдено)
    return найдено


def _обойти(значение: Any, найдено: list[str]) -> None:
    if isinstance(значение, str):
        for совпадение in ССЫЛКА.finditer(значение):
            путь = совпадение.group(1).strip()
            if путь and путь not in найдено:
                найдено.append(путь)
    elif isinstance(значение, dict):
        for вложенное in значение.values():
            _обойти(вложенное, найдено)
    elif isinstance(значение, (list, tuple)):
        for вложенное in значение:
            _обойти(вложенное, найдено)


def подставить(значение: Any, портфель: dict[str, Any]) -> tuple[Any, list[tuple[str, str]]]:
    """Заменяет ссылки на значения из портфеля.

    Возвращает получившееся значение и список пар «путь — что подставилось»
    для протокола: по нему потом видно, что именно ушло в инструмент, и это
    и есть доказательство передачи данных.
    """
    след: list[tuple[str, str]] = []
    итог = _подставить(значение, портфель, след)
    return итог, след


def _подставить(значение: Any, портфель: dict[str, Any],
                след: list[tuple[str, str]]) -> Any:
    if isinstance(значение, str):
        целиком = ССЫЛКА.fullmatch(значение.strip())
        if целиком:
            путь = целиком.group(1).strip()
            взято = достать(портфель, путь)
            след.append((путь, коротко(взято)))
            return взято
        def замена(совпадение: re.Match[str]) -> str:
            путь = совпадение.group(1).strip()
            взято = достать(портфель, путь)
            след.append((путь, коротко(взято)))
            return взято if isinstance(взято, str) else _в_строку(взято)
        return ССЫЛКА.sub(замена, значение)
    if isinstance(значение, dict):
        return {к: _подставить(з, портфель, след) for к, з in значение.items()}
    if isinstance(значение, (list, tuple)):
        return [_подставить(з, портфель, след) for з in значение]
    return значение


def достать(портфель: dict[str, Any], путь: str) -> Any:
    """Значение по пути «шаг.поле.поле». Нет такого — ОшибкаПодстановки.

    Ошибка называет, где именно оборвался путь, и перечисляет, что было
    доступно на этом месте. Иначе разбор сломанного конвейера превращается в
    гадание: инструмент получил пустоту, а почему — неизвестно.
    """
    части = [ч.strip() for ч in (путь or "").split(".") if ч.strip()]
    if not части:
        raise ОшибкаПодстановки("Пустая ссылка «${}»: в ней должен быть путь к данным.")

    текущее: Any = портфель
    пройдено: list[str] = []
    for часть in части:
        if isinstance(текущее, dict):
            if часть not in текущее:
                raise ОшибкаПодстановки(
                    f"Ссылка «{путь}»: {_где(пройдено)} нет поля «{часть}». "
                    f"Есть: {_перечислить(sorted(текущее))}.")
            текущее = текущее[часть]
        elif isinstance(текущее, (list, tuple)):
            if not часть.lstrip("-").isdigit():
                raise ОшибкаПодстановки(
                    f"Ссылка «{путь}»: {_где(пройдено)} список, а «{часть}» — не номер. "
                    f"Номера от 0 до {len(текущее) - 1}.")
            номер = int(часть)
            if not -len(текущее) <= номер < len(текущее):
                raise ОшибкаПодстановки(
                    f"Ссылка «{путь}»: в списке {_где(пройдено)} {len(текущее)} шт., "
                    f"а спрошен номер {номер}.")
            текущее = текущее[номер]
        else:
            raise ОшибкаПодстановки(
                f"Ссылка «{путь}»: {_где(пройдено)} не объект и не список "
                f"({type(текущее).__name__}), внутрь идти некуда.")
        пройдено.append(часть)
    return текущее


def _где(пройдено: list[str]) -> str:
    return f"в «{'.'.join(пройдено)}»" if пройдено else "в портфеле конвейера"


def _перечислить(имена: list[str], предел: int = 12) -> str:
    if not имена:
        return "ничего"
    видно = имена[:предел]
    хвост = "" if len(имена) <= предел else f" и ещё {len(имена) - предел}"
    return ", ".join(f"«{и}»" for и in видно) + хвост


def _в_строку(значение: Any) -> str:
    """Значение внутри текста: JSON, но без лишних пробелов и экранирования."""
    if значение is None:
        return ""
    if isinstance(значение, bool):
        return "да" if значение else "нет"
    if isinstance(значение, (int, float)):
        return str(значение)
    if isinstance(значение, (list, tuple)):
        куски = [_в_строку(э) if not isinstance(э, str) else э for э in значение[:ПОКАЗАТЬ]]
        хвост = "" if len(значение) <= ПОКАЗАТЬ else f" … (всего {len(значение)})"
        return "; ".join(куски) + хвост
    try:
        return json.dumps(значение, ensure_ascii=False)
    except (TypeError, ValueError):  # pragma: no cover — на всякий случай
        return str(значение)


def коротко(значение: Any, предел: int = 80) -> str:
    """Что подставилось — одной строкой для протокола и для человека."""
    if isinstance(значение, (list, tuple)):
        описание = f"список из {len(значение)}"
    elif isinstance(значение, dict):
        описание = "объект: " + ", ".join(list(значение)[:5])
    elif isinstance(значение, str):
        описание = значение.replace("\n", " ")
    else:
        описание = _в_строку(значение)
    описание = " ".join(описание.split())
    return описание if len(описание) <= предел else описание[:предел] + "…"


__all__ = ["ССЫЛКА", "ОшибкаПодстановки", "ссылки", "подставить", "достать", "коротко"]
