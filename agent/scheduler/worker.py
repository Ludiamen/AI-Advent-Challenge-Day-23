"""Работник: тот, кто держит агента живым, пока никто не спрашивает.

Это отдельный процесс (запускается через worker.py в корне дня). Он делает
ровно три вещи по кругу:

  1. смотрит в хранилище, чему настал срок;
  2. вызывает инструмент MCP, который указан в задании, и записывает результат;
  3. если задание построило сводку — просит модель написать по цифрам абзац.

Почему отдельный процесс, а не поток внутри сервера. MCP-сервер по stdio живёт
ровно столько, сколько открыт сеанс агента: закрыли консоль — и «работа 24/7»
кончилась вместе с ней. Работник же переживает и консоль, и страницу, и саму
машину (его можно положить в systemd), а связь с агентом у него через файл
базы — как пауза задачи в Дне 13, которую продолжает другой процесс.

Почему работник — клиент MCP, хотя хранилище у него под рукой. Задание — это
вызов инструмента, а не «вид работы из списка». Работник не знает, что такое
трекер: он знает, что надо позвать «tracker__list_issues» с такими-то
аргументами и сохранить, что вернули. Поэтому в расписание можно поставить
любой инструмент любого сервера — и того, которого ещё не написали.

Пропущенные сроки не догоняются. Если работника не было дольше, чем окно
опоздания (по умолчанию минута), задание не выполняется вовсе: в историю
ложится отметка «срок пропущен», а следующий срок считается от «сейчас».
Иначе после ночи простоя работник начал бы утро залпом из сорока вызовов и
сорока сводок — и все они рассказывали бы об одном и том же моменте. Опоздание
внутри окна (обычный случай: обход раз в пять секунд) не пропуск, задание
просто выполняется чуть позже.

Публичное API:
  Работник(хранилище, …)  — собрать
  .шаг(сейчас)            — выполнить всё, чему срок (один обход)
  .работать(сколько)      — цикл с тиком, пока не остановят
  .остановить()           — попросить цикл закончиться
"""

from __future__ import annotations

import logging
import os
import threading
import time
from datetime import datetime
from typing import Any, Callable

from agent.mcp.toolbox import Toolbox, ToolboxError
from agent.scheduler import digest
from agent.scheduler.store import ScheduleStore, Задание, Запуск

log = logging.getLogger("agent.scheduler")

# Тик: как часто работник заглядывает в хранилище. Пять секунд — компромисс
# между «сработало вовремя» и «не жжёт процессор впустую»; при задании «каждые
# 30м» разница в пять секунд никого не волнует.
ТИК = 5.0

# Инструмент сводки узнаётся по короткому имени: его результат — номер сводки,
# которую после этого надо озвучить моделью. Имя сервера может быть любым
# (в mcp-servers.json планировщик можно назвать иначе), поэтому сверяется хвост.
ИМЯ_СВОДКИ = "build_digest"

# Инструмент конвейера узнаётся так же по короткому имени: его результат — номер
# прогона, которому надо проставить, каким заданием он запущен (День 19).
ИМЯ_КОНВЕЙЕРА = "run_pipeline"

# На сколько задание может опоздать и всё-таки быть выполненным. Минута — это
# «работник жив, просто занят»; больше — это «работника не было», и тогда
# выполнять старый срок поздно (см. пропуск в шаг()).
ОКНО_ОПОЗДАНИЯ = 60.0

# Сколько ждать модель, которая пишет текст сводки. Фоновая работа не должна
# застревать на провайдере: цифры уже сохранены, текст — приятное дополнение.
ОЖИДАНИЕ_МОДЕЛИ = 60


class Работник:
    """Цикл планировщика: срок → вызов инструмента MCP → запись результата."""

    def __init__(self, хранилище: ScheduleStore, mcp_config: str = "", тик: float = ТИК,
                 ящик: Toolbox | None = None, клиент: Any = None, модель: str = "",
                 озвучивать: bool = True, опоздание: float = ОКНО_ОПОЗДАНИЯ,
                 часы: Callable[[], datetime] | None = None) -> None:
        self.хранилище = хранилище
        self.mcp_config = mcp_config
        self.тик = max(0.2, float(тик))
        self.опоздание = max(0.0, float(опоздание))
        self.ящик = ящик
        # Свой ящик работник вправе пересобрать, чужой (его дают проверки и
        # тот, кто встраивает работника к себе) — не трогает.
        self._свой_ящик = ящик is None
        self.клиент = клиент
        self.модель = модель
        self.озвучивать = озвучивать
        self.часы = часы or (lambda: datetime.now().replace(microsecond=0))
        self._стоп = threading.Event()
        self._серверы: set[str] = set()

    # --- соединения -----------------------------------------------------------

    def _ящик_для(self, задание: Задание) -> Toolbox:
        """Инструментарий, в котором открыт нужный заданию сервер.

        Соединения переживают обходы: stdio-сервер запускается секунду-две, и
        поднимать его заново каждые пять минут значило бы платить этой секундой
        за каждый запуск. Сервер, которого в ящике ещё нет, ДОБАВЛЯЕТСЯ к уже
        открытым, а не заменяет их: задания на трекер и на планировщик обычно
        чередуются, и «ящик на один сервер» означал бы перезапуск процессов на
        каждом обходе.
        """
        имя = задание.сервер or задание.инструмент.split("__")[0]
        if not self._свой_ящик:
            return self.ящик
        if имя and имя not in self._серверы:
            self._серверы.add(имя)
            if self.ящик is not None:
                self.ящик.close()
                self.ящик = None
        if self.ящик is None:
            self.ящик = Toolbox(sorted(self._серверы), self.mcp_config)
            self.ящик.открыть()
        return self.ящик

    # --- один обход -----------------------------------------------------------

    def шаг(self, сейчас: datetime | None = None) -> list[Запуск]:
        """Выполняет всё, чему настал срок, и переносит сроки. Один обход."""
        сейчас = сейчас or self.часы()
        запуски = []
        for задание in self.хранилище.к_сроку(сейчас):
            срок = _момент(задание.срок)
            опоздал = (сейчас - срок).total_seconds() if срок else 0.0
            if опоздал > self.опоздание:
                запуски.append(self.пропустить(задание, опоздал, сейчас))
            else:
                запуски.append(self.выполнить(задание, сейчас))
        self.хранилище.пульс(тик=self.тик, pid=os.getpid(), сейчас=сейчас)
        return запуски

    def пропустить(self, задание: Задание, опоздал: float,
                   сейчас: datetime | None = None) -> Запуск:
        """Срок прошёл слишком давно: вызова не делаем, но и не молчим.

        Отметка ложится в историю и попадает в сводку — человек увидит, что
        задание должно было сработать и не сработало, и почему.
        """
        сейчас = сейчас or self.часы()
        срок = _момент(задание.срок)
        пропущено = задание.правило.пропущено(срок or сейчас, сейчас) + 1
        текст = (f"Срок {задание.срок} пропущен: работника не было "
                 f"{_длительность(опоздал)}. Задание не догонялось.")
        запуск = self.хранилище.записать_запуск(
            задание=задание.номер, ок=True, текст=текст, данные=None, секунд=0.0,
            инструмент=задание.инструмент, пропущено=пропущено, пропуск=True, сейчас=сейчас)
        self.хранилище.перенести(задание.номер, задание.правило.следующий(сейчас))
        log.info("Задание №%s: срок пропущен (%s)", задание.номер, _длительность(опоздал))
        return запуск

    def выполнить(self, задание: Задание, сейчас: datetime | None = None) -> Запуск:
        """Один вызов инструмента MCP по заданию: результат и следующий срок.

        Исключений отсюда не выходит: сбой одного задания — обстоятельство, а
        не повод уронить работника, который ведёт ещё десяток заданий.
        """
        сейчас = сейчас or self.часы()
        пропущено = задание.правило.пропущено(_момент(задание.срок) or сейчас, сейчас)
        начало = time.monotonic()
        ок, текст, данные = True, "", None
        try:
            ящик = self._ящик_для(задание)
            результат = ящик.вызвать(задание.инструмент, задание.аргументы)
            ок = результат.ок
            текст = результат.текст
            данные = результат.данные
        except ToolboxError as exc:
            ок, текст = False, str(exc)
        except Exception as exc:  # noqa: BLE001 — работник не имеет права падать
            ок, текст = False, f"{type(exc).__name__}: {exc}"
            log.exception("Задание №%s уронило вызов", задание.номер)

        запуск = self.хранилище.записать_запуск(
            задание=задание.номер, ок=ок, текст=текст, данные=данные,
            секунд=time.monotonic() - начало, инструмент=задание.инструмент,
            пропущено=пропущено, сейчас=сейчас)
        self.хранилище.перенести(задание.номер, задание.правило.следующий(сейчас))
        log.info("Задание №%s (%s): %s за %.2f с", задание.номер, задание.инструмент,
                 "ок" if ок else "сбой", запуск.секунд)

        if ок:
            self._после(задание, данные)
        return запуск

    def _после(self, задание: Задание, данные: Any) -> None:
        """Что делать с удачным результатом сверх записи в историю.

        Случая два. Сводка: инструмент сохранил цифры и вернул её номер —
        работник просит модель написать по ним абзац. Модель зовётся здесь, а
        не в MCP-сервере, намеренно: сервер отдаёт данные и не должен знать ни
        про ключи провайдеров, ни про роли моделей.

        Конвейер (День 19): сервер выполнил цепочку и вернул номер прогона, но
        о том, КЕМ он запущен, сервер не знает — он видит только вызов
        инструмента. Работник знает и дописывает это в прогон: иначе в истории
        нельзя отличить запуск по расписанию от запуска руками.
        """
        if not isinstance(данные, dict):
            return
        короткое = задание.инструмент.split("__")[-1]
        if короткое == ИМЯ_КОНВЕЙЕРА:
            self._отметить_прогон(задание, данные)
            return
        if not self.озвучивать or короткое != ИМЯ_СВОДКИ:
            return
        номер = данные.get("сводка") or данные.get("номер")
        if not isinstance(номер, int):
            return
        self.озвучить(int(номер))

    def _отметить_прогон(self, задание: Задание, данные: dict) -> None:
        """Связывает прогон конвейера с заданием, по которому он случился."""
        номер = данные.get("прогон")
        if not isinstance(номер, int) or номер <= 0:
            return
        try:
            from agent.pipeline.store import PipelineStore

            прогоны = PipelineStore(self.хранилище.path)
        except Exception as exc:  # noqa: BLE001 — работник не имеет права падать
            log.info("Прогон конвейера не отмечен: %s", exc)
            return
        try:
            прогоны.привязать(номер, задание.номер, кто="работник")
        except Exception as exc:  # noqa: BLE001
            log.info("Прогон №%s не привязан к заданию №%s: %s", номер, задание.номер, exc)
        finally:
            прогоны.close()

    def озвучить(self, номер: int) -> str:
        """Просит модель написать текст сводки по её цифрам. Сбой — не беда."""
        сводка = self.хранилище.сводка(номер)
        if сводка is None or сводка.текст:
            return ""
        клиент = self._модель()
        if клиент is None:
            return ""
        try:
            ответ = клиент.call(self.модель, [{"role": "user",
                                               "content": digest.промпт(сводка.цифры)}])
            текст = (ответ.text or "").strip()
        except Exception as exc:  # noqa: BLE001 — провайдер лежит, сводка остаётся
            log.warning("Сводку №%s озвучить не удалось: %s", номер, exc)
            return ""
        if текст:
            self.хранилище.озвучить(номер, текст,
                                    модель=ответ.model_key or self.модель)
        return текст

    def _модель(self) -> Any:
        """Клиент модели — по требованию: без сводок он не нужен вовсе."""
        if self.клиент is not None:
            return self.клиент
        # Импорт местный: работнику без сводок ни каталог моделей, ни клиент
        # не нужны, а тянуть их при старте — лишние секунды на каждый запуск.
        from agent.catalog import for_role
        from agent.llm import Client
        try:
            self.модель = self.модель or for_role("сжатие")
            self.клиент = Client(timeout=ОЖИДАНИЕ_МОДЕЛИ)
        except Exception as exc:  # noqa: BLE001 — нет ключа: цифры важнее текста
            log.info("Модель для сводки недоступна: %s", exc)
            self.клиент = None
        return self.клиент

    # --- цикл -----------------------------------------------------------------

    def работать(self, сколько: float = 0.0, обходов: int = 0) -> int:
        """Крутит обходы, пока не попросят остановиться.

        сколько — сколько секунд работать (0 — без предела), обходов — сколько
        обходов сделать (0 — без предела). Оба предела нужны проверкам: живой
        работник останавливается сигналом.
        """
        начало = time.monotonic()
        сделано = 0
        self.хранилище.пульс(тик=self.тик, pid=os.getpid(), сейчас=self.часы())
        while not self._стоп.is_set():
            self.шаг()
            сделано += 1
            if обходов and сделано >= обходов:
                break
            if сколько and time.monotonic() - начало >= сколько:
                break
            self._стоп.wait(self.тик)
        return сделано

    def остановить(self) -> None:
        self._стоп.set()

    def close(self) -> None:
        self.остановить()
        if self.ящик is not None:
            self.ящик.close()
            self.ящик = None


def _длительность(секунд: float) -> str:
    """Сколько времени прошло — словами, для журнала и сводки."""
    секунд = int(секунд)
    if секунд < 60:
        return f"{секунд} с"
    if секунд < 3600:
        return f"{секунд // 60} мин"
    if секунд < 86400:
        return f"{секунд // 3600} ч {(секунд % 3600) // 60} мин"
    return f"{секунд // 86400} дн {(секунд % 86400) // 3600} ч"


def _момент(текст: str) -> datetime | None:
    try:
        return datetime.fromisoformat(текст) if текст else None
    except ValueError:  # pragma: no cover — в базу пишет только этот пакет
        return None


def сводка_сейчас(хранилище: ScheduleStore, за: str = "сутки", озвучить: bool = False,
                  работник: Работник | None = None) -> dict[str, Any]:
    """Собрать сводку немедленно, не дожидаясь расписания.

    Тем же кодом, что и по расписанию: иначе «сводка сейчас» и «сводка в 9:00»
    незаметно разъехались бы.
    """
    запись = digest.собрать_и_сохранить(хранилище, за=за)
    if озвучить and работник is not None:
        работник.озвучить(запись.номер)
        запись = хранилище.сводка(запись.номер) or запись
    return запись.to_dict()


