"""Инструментарий агента: открытые соединения и вызовы по имени.

Реестр (registry.py) отвечает на вопрос «какие серверы бывают и что у них
есть» — он подключается, смотрит и отключается. Инструментарий отвечает на
другой вопрос: «чем агент может пользоваться прямо сейчас». Поэтому соединения
он не закрывает, пока жив агент: сервер запускается один раз, а вызовов за
разговор бывает несколько.

Что он делает сверх реестра:

  * складывает инструменты всех выбранных серверов в один плоский список под
    именами «сервер__инструмент» — модель видит плоский список функций и о
    серверах не знает;
  * отдаёт их в формате function calling (Tool.for_model) и считает, во что
    это обходится в каждом запросе;
  * находит по имени, к какому серверу идти с вызовом, и делает вызов;
  * отделяет читающие инструменты от меняющих. Это граница, на которой стоит
    подтверждение человеком: читающий вызывается сразу, меняющий — только
    после явного «да» (заявки живут в памяти агента, см. memory/calls.py).
    Граница проходит по ЧУЖИМ системам: сервер, помеченный в файле как «своё»,
    пишет в собственную память агента, и её агент ведёт сам — как задачи и
    знания, без заявки на каждую запись;
  * видит отложенное изменение. Планировщик (День 18) умеет ставить в
    расписание чужой вызов, и «запланируй закрыть все задачи через минуту»
    было бы обходом подтверждения: сам schedule_job чужих данных не трогает,
    трогает их потом работник. Поэтому у такого инструмента спрашивается не
    только его собственная пометка, но и пометка того, что он планирует
    (поле «планирует» в mcp-servers.json);
  * видит изменение внутри конвейера. Конвейер Дня 19 — это несколько вызовов
    подряд, и меняющим может быть любой его шаг. Запуск такой цепочки
    спрашивается у человека ЦЕЛИКОМ и до первого шага: он подтверждает не
    «запустить конвейер», а то, что цепочка в конце напишет в чужую систему
    (поле «конвейеры» в mcp-servers.json и описание в pipelines.json).

Про доверие к пометкам. readOnlyHint — слово сервера, а не гарантия, и
спецификация прямо велит не доверять ему у непроверенных серверов. Поэтому
«читающим» считается только инструмент, который сам себя таким объявил; всё
остальное, включая инструменты вовсе без пометок, считается меняющим. Ошибка в
эту сторону стоит лишнего вопроса человеку, в обратную — испорченных данных.

Исключение одно, и оно не про доверие к серверу, а про доверие к человеку:
пометка «только_чтение» в mcp-servers.json. Её ставит составитель файла и за
неё же отвечает. Без неё публичный сервер документации, который не объявляет
пометок вовсе (deepwiki), требовал бы подтверждения на каждый заданный ему
вопрос — и длинный флоу Дня 20 останавливался бы на чтении.

Публичное API:
  Toolbox(servers, path)      — инструментарий по списку серверов
  .открыть()                  — подключиться (идемпотентно)
  .инструменты                — разрешённые инструменты всех серверов
  .для_модели()               — список функций для поля tools запроса
  .токенов()                  — во сколько токенов обходится этот список
  .найти(имя) / .меняет(имя, аргументы) — инструмент по имени «сервер__инструмент»
  .планируемый(имя, аргументы)— что именно этот вызов поставит в расписание
  .конвейер_вызова(имя, аргументы) — какую цепочку запустит этот вызов
  .меняющие_шаги(конвейер)    — шаги цепочки, которые меняют чужие данные
  .вызвать(имя, аргументы)    -> ToolResult
  .сводка() / .close()
"""

from __future__ import annotations

import logging
import os
import threading
from concurrent.futures import ThreadPoolExecutor
from typing import Any

from agent.mcp.client import Inspection, MCPClientError, Session, ToolResult
from agent.mcp.config import MCPConfigError, Server
from agent.mcp.registry import Registry
from agent.mcp.tools import ТОЛЬКО_ЧТЕНИЕ, Tool

log = logging.getLogger("agent.mcp")

ВСЕ = "*"


class ToolboxError(RuntimeError):
    """Инструмент нельзя вызвать: нет такого, закрыт фильтром или сервер не отвечает."""


class Toolbox:
    """Открытые соединения с выбранными серверами и вызовы их инструментов."""

    def __init__(self, servers: list[str] | None = None, path: str = "") -> None:
        # Имена серверов: пусто или «*» — все из файла. Список нужен потому, что
        # каждый подключённый сервер стоит токенов в каждом запросе к модели:
        # включать всё подряд «на всякий случай» — прямой расход.
        self.имена = [и for и in (servers or []) if и != ВСЕ]
        self.путь = path
        self.реестр: Registry | None = None
        self.сеансы: dict[str, Session] = {}
        self.осмотры: list[Inspection] = []
        self.инструменты: list[Tool] = []
        self.открыт = False
        self.повторы: list[str] = []
        # «сервер__инструмент» → имя аргумента, в котором лежит планируемый вызов.
        self.планирующие: dict[str, str] = {}
        # «сервер__инструмент» → имя аргумента, в котором лежит имя конвейера.
        self.запускающие: dict[str, str] = {}
        # Серверы, которые ведут собственную память агента, а не чужую систему.
        self.свои: set[str] = set()
        # Серверы, за которые поручился человек в файле («только_чтение»).
        self.доверенные: set[str] = set()
        # Каталог конвейеров читается по требованию: без них он не нужен вовсе.
        self._конвейеры: Any = None
        # Подключение идёт под замком: страница умеет прислать два изменения
        # настроек подряд (галочка «давать инструменты» и поле серверов), Flask
        # отвечает в разных потоках, и тогда два вызова «открыть» собирали
        # список инструментов одновременно — каждый по разу. Получался список
        # из двух одинаковых половин, и провайдер отвечал на него «Tool names
        # must be unique», то есть отказом на весь запрос.
        self._замок = threading.Lock()

    # --- подключение ----------------------------------------------------------

    def серверы(self) -> list[Server]:
        if self.реестр is None:
            self.реестр = Registry(self.путь)
        if not self.имена:
            return [с for с in self.реестр.servers if с.готов]
        return [self.реестр.server(и) for и in self.имена]

    def открыть(self) -> list[Inspection]:
        """Подключается к серверам и собирает общий список инструментов.

        Сбой одного сервера не отменяет остальные: агент должен работать с тем,
        что доступно, а о недоступном — сказать. Поэтому итог осмотра хранится
        целиком, вместе с причинами сбоев.
        """
        if self.открыт:
            return self.осмотры
        with self._замок:
            if self.открыт:      # пока ждали замок, соседний поток всё открыл
                return self.осмотры
            return self._открыть()

    def _открыть(self) -> list[Inspection]:
        """Само подключение. Зовётся только под замком (см. «открыть»)."""
        серверы = self.серверы()
        self.осмотры = []
        self.инструменты = []
        self.повторы = []
        self.планирующие = {}
        self.запускающие = {}
        self.свои = set()
        self.доверенные = set()

        # Серверы независимы, а запуск stdio-сервера — это секунда-две. Ждать их
        # друг за другом значит сложить все задержки вместо самой долгой.
        with ThreadPoolExecutor(max_workers=max(1, min(8, len(серверы)))) as пул:
            пары = list(пул.map(self._подключить, серверы))

        занятые: dict[str, str] = {}
        for сервер, (сеанс, осмотр) in zip(серверы, пары):
            self.осмотры.append(осмотр)
            if сеанс is None:
                continue
            self.сеансы[сервер.имя] = сеанс
            for инструмент in осмотр.разрешено:
                # Имя для модели должно быть уникальным: два одинаковых имени в
                # поле tools — и неизвестно, к какому серверу она обращается.
                прежний = занятые.get(инструмент.полное_имя)
                if прежний:
                    self.повторы.append(f"{инструмент.полное_имя} (уже есть у «{прежний}»)")
                    continue
                занятые[инструмент.полное_имя] = сервер.имя
                self.инструменты.append(инструмент)
                аргумент = сервер.планирует.get(инструмент.имя)
                if аргумент:
                    self.планирующие[инструмент.полное_имя] = аргумент
                цепочка = сервер.конвейеры.get(инструмент.имя)
                if цепочка:
                    self.запускающие[инструмент.полное_имя] = цепочка
            if сервер.своё:
                self.свои.add(сервер.имя)
            if сервер.только_чтение:
                self.доверенные.add(сервер.имя)
        self.открыт = True
        return self.осмотры

    def _подключить(self, сервер: Server) -> tuple[Session | None, Inspection]:
        осмотр = Inspection(сервер=сервер)
        if not сервер.готов:
            осмотр.пропущен = True
            осмотр.ошибка = сервер.почему_не_готов
            return None, осмотр
        сеанс = Session(сервер)
        try:
            осмотр.рукопожатие = сеанс.open()
            осмотр.подключение_с = сеанс.подключение_с
            осмотр.инструменты, осмотр.страниц = сеанс.tools()
            осмотр.ок = True
            return сеанс, осмотр
        except MCPClientError as exc:
            осмотр.этап, осмотр.ошибка, осмотр.подсказка = exc.этап, exc.причина, exc.подсказка
            осмотр.журнал = сеанс.журнал()
            сеанс.close()
            log.info("MCP %s недоступен: %s", сервер.имя, exc.причина)
            return None, осмотр

    # --- что отдавать модели --------------------------------------------------

    def для_модели(self) -> list[dict[str, Any]]:
        return [и.for_model() for и in self.инструменты]

    def токенов(self) -> int:
        """Цена списка инструментов в каждом запросе к модели."""
        return sum(и.tokens() for и in self.инструменты)

    def найти(self, имя: str) -> Tool | None:
        имя = (имя or "").strip()
        for инструмент in self.инструменты:
            if инструмент.полное_имя == имя or инструмент.имя == имя:
                return инструмент
        return None

    def меняет(self, имя: str, аргументы: dict[str, Any] | None = None) -> bool:
        """Меняет ли вызов данные. Всё, кроме явного «только чтение», — да.

        Аргументы нужны планировщику и конвейерам: вызов schedule_job или
        run_pipeline сам по себе безобиден, но данные изменит то, что он
        запустит, — просто позже или в глубине цепочки. Такой вызов считается
        меняющим, и подтверждение спрашивается сейчас, до запуска.
        """
        инструмент = self.найти(имя)
        if инструмент is None:
            return True     # неизвестный инструмент — считаем опасным
        своё = инструмент.сервер in self.свои
        доверен = инструмент.сервер in self.доверенные
        if инструмент.доступ != ТОЛЬКО_ЧТЕНИЕ and not своё and not доверен:
            return True
        планируемый = self.планируемый(имя, аргументы)
        if планируемый:
            return self.меняет(планируемый)
        цепочка = self.конвейер_вызова(имя, аргументы)
        if цепочка:
            return bool(self.меняющие_шаги(цепочка))
        return False

    def планируемый(self, имя: str, аргументы: dict[str, Any] | None = None) -> str:
        """Какой инструмент поставит в расписание этот вызов. Пусто — никакой."""
        return self._из_аргумента(self.планирующие, имя, аргументы)

    def конвейер_вызова(self, имя: str, аргументы: dict[str, Any] | None = None) -> str:
        """Какой конвейер запустит этот вызов. Пусто — никакой."""
        return self._из_аргумента(self.запускающие, имя, аргументы)

    def _из_аргумента(self, откуда: dict[str, str], имя: str,
                      аргументы: dict[str, Any] | None) -> str:
        инструмент = self.найти(имя)
        if инструмент is None or not аргументы:
            return ""
        аргумент = откуда.get(инструмент.полное_имя)
        значение = аргументы.get(аргумент or "", "")
        return значение.strip() if isinstance(значение, str) else ""

    # --- конвейеры ------------------------------------------------------------

    def конвейеры(self) -> Any:
        """Каталог конвейеров: pipelines.json рядом с файлом серверов."""
        if self._конвейеры is None:
            # Импорт местный: инструментарий работает и там, где конвейеров нет,
            # и тянуть за собой их пакет при каждом подключении незачем.
            from agent.pipeline.spec import Каталог
            self._конвейеры = Каталог(self._путь_конвейеров())
        return self._конвейеры

    def _путь_конвейеров(self) -> str:
        """Где искать описания цепочек — общий для ящика и агента ответ."""
        if self.реестр is None:
            try:
                self.реестр = Registry(self.путь)
            except (MCPConfigError, MCPClientError):
                return путь_конвейеров(self.путь, [])
        return путь_конвейеров(self.путь, self.реестр.servers)

    def меняющие_шаги(self, конвейер: str, глубина: int = 3) -> list[str]:
        """Шаги цепочки, которые меняют ЧУЖИЕ данные, — по именам инструментов.

        Пустой список значит «конвейер только читает и пишет в своё»: такой
        запускается без заявки. Неизвестный конвейер и неизвестный инструмент
        считаются меняющими: ошибка в эту сторону стоит лишнего вопроса
        человеку, в обратную — испорченных данных в чужой системе.
        """
        from agent.pipeline.spec import ОшибкаКонвейера

        if глубина <= 0:
            return [f"{конвейер} (цепочка ссылается сама на себя)"]
        try:
            описание = self.конвейеры().конвейер(конвейер)
        except ОшибкаКонвейера:
            return [f"{конвейер} (такого конвейера нет)"]

        меняют: list[str] = []
        for шаг in описание.шаги:
            вложенный = self.запускающие.get(шаг.инструмент)
            if вложенный:
                имя = шаг.аргументы.get(вложенный, "")
                if isinstance(имя, str) and имя and self.меняющие_шаги(имя, глубина - 1):
                    меняют.append(шаг.инструмент)
                continue
            if self._шаг_меняет(шаг.инструмент):
                меняют.append(шаг.инструмент)
        return меняют

    def _шаг_меняет(self, инструмент: str) -> bool:
        """Меняет ли данные шаг цепочки — и когда его сервер даже не подключён.

        Подключённый инструмент отвечает за себя сам. О неподключённом известно
        только имя сервера, и решает пометка «своё» из файла: своё хозяйство
        агент ведёт сам, чужое — с подтверждения. Сервера нет в файле вовсе —
        значит меняет.
        """
        известный = self.найти(инструмент)
        if известный is not None:
            return self.меняет(инструмент)
        сервер = инструмент.split("__")[0] if "__" in инструмент else ""
        if not сервер:
            return True
        try:
            if self.реестр is None:
                self.реестр = Registry(self.путь)
            описание = self.реестр.server(сервер)
        except (MCPConfigError, MCPClientError, KeyError, ValueError):
            return True
        return not описание.своё

    # --- вызов ----------------------------------------------------------------

    def вызвать(self, имя: str, аргументы: dict[str, Any] | None = None) -> ToolResult:
        """Вызывает инструмент по имени «сервер__инструмент».

        Имя приходит от модели, поэтому сначала проверяется, что такой
        инструмент вообще есть в списке разрешённых. Выдуманное имя — обычное
        дело: модель может «вспомнить» инструмент, которого нет.
        """
        if not self.открыт:
            self.открыть()
        инструмент = self.найти(имя)
        if инструмент is None:
            известные = ", ".join(и.полное_имя for и in self.инструменты) or "ни одного"
            закрытый = self._закрытый(имя)
            if закрытый:
                raise ToolboxError(
                    f"Инструмент «{имя}» закрыт настройками: {закрытый}. "
                    "Список разрешённых задаётся в mcp-servers.json.")
            raise ToolboxError(f"Инструмента «{имя}» нет. Доступны: {известные}.")

        сеанс = self.сеансы.get(инструмент.сервер)
        if сеанс is None:
            raise ToolboxError(f"Сервер «{инструмент.сервер}» не подключён.")
        try:
            return сеанс.call_tool(инструмент.имя, аргументы)
        except MCPClientError as exc:
            # Сбой связи — не то же самое, что ошибка инструмента: инструмент
            # ответить не успел. Наружу это должно выйти ошибкой вызова, а не
            # «инструмент сказал».
            подсказка = f" {exc.подсказка}" if exc.подсказка else ""
            raise ToolboxError(
                f"Сервер «{инструмент.сервер}» не выполнил вызов ({exc.этап}): "
                f"{exc.причина}.{подсказка}") from exc

    def _закрытый(self, имя: str) -> str:
        """Почему инструмент с таким именем не попал в список разрешённых."""
        for осмотр in self.осмотры:
            for инструмент in осмотр.инструменты:
                if инструмент.полное_имя == имя or инструмент.имя == имя:
                    return инструмент.почему_закрыт or "закрыт"
        return ""

    # --- сводка и закрытие ----------------------------------------------------

    def сводка(self) -> dict[str, Any]:
        подключены = [о for о in self.осмотры if о.ок]
        return {
            "серверов": len(self.осмотры),
            "подключено": len(подключены),
            "серверы": [о.сервер.имя for о in подключены],
            "недоступны": [{"сервер": о.сервер.имя, "причина": о.ошибка}
                           for о in self.осмотры if not о.ок],
            "инструментов": len(self.инструменты),
            "читающих": sum(1 for и in self.инструменты if и.доступ == ТОЛЬКО_ЧТЕНИЕ),
            "меняющих": sum(1 for и in self.инструменты if и.доступ != ТОЛЬКО_ЧТЕНИЕ),
            "токенов": self.токенов(),
            "повторы_имён": list(self.повторы),
        }

    def close(self) -> None:
        for сеанс in self.сеансы.values():
            сеанс.close()
        self.сеансы.clear()
        self.инструменты = []
        self.открыт = False

    def __enter__(self) -> "Toolbox":
        self.открыть()
        return self

    def __exit__(self, *exc: Any) -> None:
        self.close()


def путь_конвейеров(конфиг: str = "", серверы: list[Server] | None = None) -> str:
    """Файл с описаниями цепочек: сначала тот, куда смотрит сам сервер конвейеров.

    Путь объявлен в его «env» в mcp-servers.json, и брать его оттуда значит
    держать один источник правды. Иначе агент и сервер читали бы РАЗНЫЕ файлы:
    решение «нужна ли заявка» принималось бы не по той цепочке, которая
    выполнится, а консоль показывала бы не те конвейеры, которые запускаются.
    """
    if серверы is None:
        try:
            серверы = Registry(конфиг).servers
        except (MCPConfigError, MCPClientError):
            серверы = []
    for сервер in серверы:
        if сервер.конвейеры:
            значение = (сервер.окружение.get("PIPELINES_FILE") or "").strip()
            if значение:
                return значение
    прямо = os.getenv("PIPELINES_FILE", "").strip()
    if прямо:
        return прямо
    рядом = os.path.dirname(os.path.abspath(конфиг)) if конфиг else ""
    return os.path.join(рядом, "pipelines.json") if рядом else "pipelines.json"


def открыть(servers: list[str] | None = None, path: str = "") -> Toolbox:
    """Инструментарий, уже подключённый. Ошибка конфигурации выходит наружу."""
    ящик = Toolbox(servers, path)
    try:
        ящик.открыть()
    except MCPConfigError:
        ящик.close()
        raise
    return ящик
