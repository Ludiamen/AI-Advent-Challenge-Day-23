"""Список MCP-серверов: файл mcp-servers.json в общепринятом формате mcpServers.

Формат тот же, что у Claude Desktop, Claude Code и Cursor, поэтому описание
сервера из его документации переносится сюда как есть:

    {
      "mcpServers": {
        "имя": {"command": "npx", "args": ["-y", "пакет"], "env": {...}},
        "имя2": {"type": "http", "url": "https://…/mcp", "headers": {...}}
      }
    }

Сверх стандарта у сервера есть несколько полей проекта, все русскими ключами,
чтобы их нельзя было спутать со стандартными:

    "описание"  — зачем серверу место в списке, для человека;
    "разрешить" — какие инструменты агенту доступны (шаблоны вида read_*);
    "запретить" — какие закрыты, даже если подходят под «разрешить»;
    "таймаут"   — сколько секунд ждать соединения (npx при первом запуске
                  скачивает пакет, и 30 секунд ему мало);
    "отключён"  — оставить в файле, но не подключаться;
    "своё"      — сервер пишет только в собственную память агента (планировщик
                  пишет в memory/scheduler.db). Подтверждение человеком стоит
                  перед изменением ЧУЖИХ систем, а свою память агент ведёт сам,
                  как ведёт задачи и знания, — поэтому меняющие инструменты
                  такого сервера вызываются без заявки;
    "планирует" — {"инструмент сервера": "имя аргумента"}: этот инструмент не
                  делает работу сам, а ставит в расписание чужой вызов, имя
                  которого лежит в названном аргументе. Нужно, чтобы через
                  планировщик нельзя было обойти подтверждение человека:
                  «запланируй закрыть все задачи через минуту» — такое же
                  изменение чужих данных, как и прямой вызов (см. toolbox.py);
    "только_чтение" — составитель файла ручается, что сервер ничего не меняет.
                  Нужно для чужих серверов, которые не объявляют пометок вовсе:
                  по умолчанию такой инструмент считается меняющим (так велит
                  спецификация), и публичная документация требовала бы
                  подтверждения на каждый вопрос. Доверие здесь — решение
                  человека, записанное в файл, а не слово сервера;
    "темы"      — слова, по которым запрос узнаётся как «про этот сервер».
                  Маршрутизатор Дня 20 выбирает серверы под запрос моделью, а
                  по темам работает его запасной путь — и по ним же видно, что
                  человек назвал сервер сам;
    "по_просьбе"— сервер подключается только когда его назвали явно (именем или
                  темой). Так стоит настоящий Яндекс.Трекер: инструменты у него
                  те же, что у мока, и попасть в него «заодно» нельзя;
    "замещает"  — имя сервера, который этот подменяет. Два сервера с одинаковыми
                  по смыслу инструментами не открываются разом: модель выбирала
                  бы между ними наугад;
    "конвейеры" — {"инструмент сервера": "имя аргумента"}: то же самое для
                  конвейеров Дня 19. Инструмент запускает описанную в
                  pipelines.json цепочку, имя которой лежит в названном
                  аргументе, и менять данные будут её шаги. Подтверждение
                  спрашивается за весь конвейер сразу, до первого шага.

Секреты в файл не пишутся: вместо значения — ссылка «${GITHUB_TOKEN}», а само
значение берётся из .env рядом с файлом или из окружения. Поддерживается и
запасное значение: «${NAME:-по умолчанию}». Две переменные подставляются всегда:
${PYTHON} — интерпретатор, в котором запущен агент (иначе свой сервер
запустится системным python3, где нет нужных пакетов), и ${PROJECT_DIR} —
каталог, где лежит сам файл.

Ссылки хранятся как написаны, подставленные значения — отдельно. Наружу, в
консоль и на страницу, уходит только написанное: токен не должен оказаться на
экране оттого, что пользователь попросил показать список серверов.

Публичное API:
  load(path)             -> list[Server]  — прочитать файл
  Server                                  — один сервер: транспорт, адрес, фильтр
  MCPConfigError                          — файл не читается или описан неверно
  DEFAULT_PATH                            — путь к файлу по умолчанию
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import shlex
import sys
from dataclasses import dataclass, field
from typing import Any

from dotenv import dotenv_values

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FILE_NAME = "mcp-servers.json"
DEFAULT_PATH = os.path.join(КОРЕНЬ, FILE_NAME)

STDIO = "stdio"
HTTP = "http"
TRANSPORTS = (STDIO, HTTP)
# Как транспорт называют в чужих конфигурациях. «sse» — прежний HTTP-транспорт
# MCP, его спецификация заменила на Streamable HTTP ещё в 2025 году.
СИНОНИМЫ = {"stdio": STDIO, "http": HTTP, "streamable-http": HTTP, "streamableHttp": HTTP}

# Сколько ждать соединения, если в файле не сказано. Удалённому серверу хватает
# нескольких секунд, но запуск через npx в первый раз тянет пакет из реестра.
DEFAULT_TIMEOUT = 30.0

_ПЕРЕМЕННАЯ = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-([^}]*))?\}")
_ИМЯ = re.compile(r"^[A-Za-z0-9_-]{1,40}$")


class MCPConfigError(ValueError):
    """Файл серверов не читается или сервер в нём описан неверно."""


def _встроенные(каталог: str) -> dict[str, str]:
    return {"PYTHON": sys.executable, "PROJECT_DIR": каталог}


def _окружение(каталог: str) -> dict[str, str]:
    """Значения для подстановки: окружение, поверх него непустые значения .env.

    .env читается заново при каждой загрузке и главнее окружения — вопреки
    обычному порядку, и вот почему. Агент при старте сам загружает .env в
    окружение (load_dotenv), и если бы окружение побеждало, то правка токена в
    .env при запущенной странице не действовала бы до перезапуска: в окружении
    так и сидело бы прежнее значение. Пустое значение в .env окружение не
    затирает — иначе строка «GITHUB_TOKEN=» из примера отменила бы токен,
    заданный снаружи.

    os.environ не меняется: подстановка — дело этого файла.
    """
    из_файла = {к: з for к, з in dotenv_values(os.path.join(каталог, ".env")).items() if з}
    return {**os.environ, **из_файла, **_встроенные(каталог)}


def _подставить(текст: str, значения: dict[str, str], нет: list[str]) -> str:
    def замена(совпадение: re.Match) -> str:
        имя, запасное = совпадение.group(1), совпадение.group(2)
        значение = значения.get(имя, "")
        if значение:
            return значение
        if запасное is not None:
            return запасное
        if имя not in нет:
            нет.append(имя)
        return ""

    итог = _ПЕРЕМЕННАЯ.sub(замена, текст)
    # Ссылка, которую шаблон не узнал, ушла бы на сервер буквально: заголовок
    # «Bearer ${ТОКЕН}» — это отказ авторизации, похожий на поломку сервера.
    # Чаще всего причина — кириллица в имени: у переменных окружения её не бывает.
    if "${" in итог:
        raise MCPConfigError(
            f"Не понял ссылку на переменную в «{текст}». Имя переменной окружения "
            "пишется латиницей, цифрами и «_»: ${GITHUB_TOKEN}, ${NAME:-запасное}."
        )
    return итог


def _список_строк(данные: dict, ключ: str, имя: str) -> list[str]:
    значение = данные.get(ключ, [])
    if isinstance(значение, str):
        значение = [значение]
    if not isinstance(значение, list) or not all(isinstance(з, str) for з in значение):
        raise MCPConfigError(f"Сервер «{имя}»: «{ключ}» должен быть списком строк.")
    return list(значение)


def _словарь_строк(данные: dict, ключ: str, имя: str) -> dict[str, str]:
    значение = данные.get(ключ, {})
    if not isinstance(значение, dict) or not all(
        isinstance(к, str) and isinstance(з, str) for к, з in значение.items()
    ):
        raise MCPConfigError(f"Сервер «{имя}»: «{ключ}» должен быть словарём строк.")
    return dict(значение)


@dataclass
class Server:
    """Один MCP-сервер из файла: как до него добраться и что у него разрешено."""

    имя: str
    транспорт: str
    # --- stdio: запустить процесс и говорить с ним через stdin/stdout ---------
    команда: str = ""
    аргументы: list[str] = field(default_factory=list)
    окружение: dict[str, str] = field(default_factory=dict)
    каталог: str = ""
    # --- http: Streamable HTTP по адресу -----------------------------------
    адрес: str = ""
    заголовки: dict[str, str] = field(default_factory=dict)
    # --- поля проекта --------------------------------------------------------
    описание: str = ""
    разрешить: list[str] = field(default_factory=list)
    запретить: list[str] = field(default_factory=list)
    # Инструменты, которые ставят в расписание чужой вызов: имя инструмента →
    # имя аргумента, в котором лежит то, что будет вызвано.
    планирует: dict[str, str] = field(default_factory=dict)
    # Инструменты, которые запускают конвейер: имя инструмента → имя аргумента,
    # в котором лежит имя цепочки из pipelines.json.
    конвейеры: dict[str, str] = field(default_factory=dict)
    # Сервер ведёт собственное хозяйство агента, а не чужую систему.
    своё: bool = False
    # Человек ручается, что сервер ничего не меняет. Пометкам самого сервера
    # доверять нельзя (спецификация прямо это запрещает у непроверенных), а
    # вот составителю файла — можно: он и отвечает за то, что сюда вписал.
    только_чтение: bool = False
    # --- маршрутизация запросов по серверам (День 20) -------------------------
    # Слова, по которым видно, что запрос про этот сервер. Нужны дважды: как
    # запасной путь маршрутизатора, когда модель недоступна, и как признак
    # «человек назвал сервер сам» для серверов с пометкой «по_просьбе».
    темы: list[str] = field(default_factory=list)
    # Сервер берётся только тогда, когда человек назвал его явно. Так стоит
    # настоящий Яндекс.Трекер рядом с моком: одинаковые инструменты, но писать
    # в боевую систему «заодно» агент не должен.
    по_просьбе: bool = False
    # Имя сервера, который этот подменяет. Оба сразу не открываются: у них
    # одинаковые по смыслу инструменты, и модель выбирала бы между ними
    # наугад — а цена ошибки здесь «комментарий ушёл не туда».
    замещает: str = ""
    таймаут: float = DEFAULT_TIMEOUT
    отключён: bool = False
    # Переменные, на которые файл ссылается, но которых нет ни в окружении, ни
    # в .env. Такой сервер описан верно, но подключаться к нему бессмысленно:
    # без токена GitHub ответит отказом, и это будет выглядеть как поломка.
    не_хватает: list[str] = field(default_factory=list)
    # То, что написано в файле, — для показа. Секреты в нём остаются ссылками.
    как_в_файле: dict[str, Any] = field(default_factory=dict)

    @property
    def готов(self) -> bool:
        return not self.отключён and not self.не_хватает

    @property
    def почему_не_готов(self) -> str:
        if self.отключён:
            return "отключён в mcp-servers.json («отключён»: true)"
        if self.не_хватает:
            имена = ", ".join(self.не_хватает)
            return f"не хватает переменных {имена}: задайте их в .env или в окружении"
        return ""

    @property
    def куда(self) -> str:
        """Адрес сервера в одну строку — как он записан в файле, без секретов."""
        if self.транспорт == HTTP:
            return self.как_в_файле.get("url", self.адрес)
        команда = [self.как_в_файле.get("command", self.команда),
                   *self.как_в_файле.get("args", self.аргументы)]
        # В кавычки — только то, что без них распалось бы на части: «${PYTHON}»
        # в кавычках читается хуже, а смысл тот же.
        return " ".join(shlex.quote(ч) if any(з.isspace() for з in ч) else ч
                        for ч in команда)

    def доступ(self, инструмент: str) -> tuple[bool, str]:
        """Разрешён ли агенту инструмент и почему нет.

        Запрет сильнее разрешения: «разрешить read_*», «запретить read_secret»
        закрывает ровно одно исключение. Пустой список разрешений означает
        «всё, что не запрещено» — иначе новый сервер без фильтра оказался бы
        целиком закрытым, и это выглядело бы как поломка.
        """
        for шаблон in self.запретить:
            if fnmatch.fnmatchcase(инструмент, шаблон):
                return False, f"запрещён шаблоном «{шаблон}»"
        if not self.разрешить:
            return True, ""
        for шаблон in self.разрешить:
            if fnmatch.fnmatchcase(инструмент, шаблон):
                return True, ""
        return False, "не входит в «разрешить»"

    def to_dict(self) -> dict[str, Any]:
        """Описание для интерфейсов. Секретных значений в нём нет."""
        return {
            "имя": self.имя,
            "транспорт": self.транспорт,
            "куда": self.куда,
            "описание": self.описание,
            "разрешить": list(self.разрешить),
            "запретить": list(self.запретить),
            "планирует": dict(self.планирует),
            "конвейеры": dict(self.конвейеры),
            "своё": self.своё,
            "только_чтение": self.только_чтение,
            "темы": list(self.темы),
            "по_просьбе": self.по_просьбе,
            "замещает": self.замещает,
            "таймаут": self.таймаут,
            "готов": self.готов,
            "почему_не_готов": self.почему_не_готов,
            "заголовки": sorted(self.как_в_файле.get("headers", {})),
        }


def _сервер(имя: str, данные: Any, каталог: str, значения: dict[str, str]) -> Server:
    if not _ИМЯ.match(имя):
        raise MCPConfigError(
            f"Имя сервера «{имя}» недопустимо: нужны латинские буквы, цифры, дефис и "
            "подчёркивание, до 40 символов. Из имени сервера и имени инструмента "
            "потом складывается имя функции для модели, а там кириллица запрещена."
        )
    if not isinstance(данные, dict):
        raise MCPConfigError(f"Сервер «{имя}» должен быть описан объектом.")

    тип = данные.get("type")
    if тип is None:
        тип = HTTP if "url" in данные else STDIO
    if тип == "sse":
        raise MCPConfigError(
            f"Сервер «{имя}»: транспорт SSE устарел и здесь не поддерживается. "
            "Спецификация MCP заменила его на Streamable HTTP — укажите \"type\": \"http\"."
        )
    if тип not in СИНОНИМЫ:
        raise MCPConfigError(
            f"Сервер «{имя}»: неизвестный транспорт «{тип}». Бывают: stdio, http."
        )
    транспорт = СИНОНИМЫ[тип]

    нет: list[str] = []
    сервер = Server(
        имя=имя,
        транспорт=транспорт,
        описание=str(данные.get("описание", "")),
        разрешить=_список_строк(данные, "разрешить", имя),
        запретить=_список_строк(данные, "запретить", имя),
        планирует=_словарь_строк(данные, "планирует", имя),
        конвейеры=_словарь_строк(данные, "конвейеры", имя),
        своё=bool(данные.get("своё", False)),
        только_чтение=bool(данные.get("только_чтение", False)),
        темы=[т.strip().lower() for т in _список_строк(данные, "темы", имя) if т.strip()],
        по_просьбе=bool(данные.get("по_просьбе", False)),
        замещает=str(данные.get("замещает", "")).strip(),
        отключён=bool(данные.get("отключён", False)),
        как_в_файле={к: з for к, з in данные.items()
                     if к in ("type", "command", "args", "url", "headers", "env", "cwd")},
    )

    таймаут = данные.get("таймаут", DEFAULT_TIMEOUT)
    if not isinstance(таймаут, (int, float)) or isinstance(таймаут, bool) or таймаут <= 0:
        raise MCPConfigError(f"Сервер «{имя}»: «таймаут» — положительное число секунд.")
    сервер.таймаут = float(таймаут)

    if транспорт == STDIO:
        команда = данные.get("command")
        if not isinstance(команда, str) or not команда.strip():
            raise MCPConfigError(f"Сервер «{имя}»: для stdio нужна «command».")
        команда = _подставить(команда, значения, нет)
        # Относительный путь к программе считается от файла, а не от того
        # каталога, из которого случайно запустили агента.
        if os.sep in команда and not os.path.isabs(команда):
            команда = os.path.normpath(os.path.join(каталог, команда))
        сервер.команда = команда
        сервер.аргументы = [_подставить(а, значения, нет)
                            for а in _список_строк(данные, "args", имя)]
        сервер.окружение = {к: _подставить(з, значения, нет)
                            for к, з in _словарь_строк(данные, "env", имя).items()}
        рабочий = _подставить(str(данные.get("cwd", "")), значения, нет)
        if рабочий and not os.path.isabs(рабочий):
            рабочий = os.path.normpath(os.path.join(каталог, рабочий))
        сервер.каталог = рабочий or каталог
    else:
        адрес = данные.get("url")
        if not isinstance(адрес, str) or not адрес.startswith(("http://", "https://")):
            raise MCPConfigError(
                f"Сервер «{имя}»: для http нужен «url», начинающийся с http:// или https://."
            )
        сервер.адрес = _подставить(адрес, значения, нет)
        сервер.заголовки = {к: _подставить(з, значения, нет)
                            for к, з in _словарь_строк(данные, "headers", имя).items()}

    сервер.не_хватает = нет
    return сервер


def load(path: str = "") -> list[Server]:
    """Читает файл серверов. Нет файла — пустой список, испорчен — ошибка."""
    путь = os.path.abspath(path or os.getenv("MCP_CONFIG", "") or DEFAULT_PATH)
    try:
        with open(путь, encoding="utf-8") as файл:
            данные = json.load(файл)
    except FileNotFoundError:
        return []
    except json.JSONDecodeError as exc:
        raise MCPConfigError(f"Файл «{путь}» — не JSON: {exc}") from exc
    except OSError as exc:
        raise MCPConfigError(f"Файл «{путь}» не читается: {exc}") from exc

    серверы = данные.get("mcpServers") if isinstance(данные, dict) else None
    if not isinstance(серверы, dict):
        raise MCPConfigError(
            f"В «{путь}» нет объекта «mcpServers» — формат файла тот же, что у "
            "Claude Desktop и Claude Code."
        )
    каталог = os.path.dirname(путь)
    значения = _окружение(каталог)
    return [_сервер(имя, описание, каталог, значения) for имя, описание in серверы.items()]


def config_path(path: str = "") -> str:
    """Какой файл будет прочитан — для сообщений «серверы взяты из …»."""
    return os.path.abspath(path or os.getenv("MCP_CONFIG", "") or DEFAULT_PATH)
