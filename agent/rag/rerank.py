"""Второй этап поиска: реранкеры — модель, эвристика и LLM — за одним интерфейсом.

Первый этап (bge-m3) сравнивает ВЕКТОРЫ вопроса и чанка, посчитанные порознь:
быстро, но грубо — «похоже по теме» ещё не значит «отвечает на вопрос». Второй
этап смотрит на пару «вопрос + фрагмент» целиком и переупорядочивает немногих
кандидатов первого этапа. Лекция недели: кросс-энкодер точнее, но медленнее;
это компромисс, и его надо мерить, а не угадывать.

Три реализации — чтобы сравнить их числами на одном стенде:

  кросс      bge-reranker-v2-m3 (ONNX int8, onnxruntime) — родной кросс-энкодер
             к эмбеддеру bge-m3, многоязычный, локальный: документы не
             покидают машину. Пара «вопрос + текст» — до 512 токенов, поэтому
             длинный чанк оценивается окнами, и берётся лучшее окно. На CPU
             ≈ 1,5–2 с на пару; оценки кэшируются в базе индекса.
  эвристика  без модели: косинус первого этапа + совпадение основ слов вопроса
             с текстом чанка (с весом редкости слова, как в BM25) + бонус,
             если вопрос называет файл или контрагента («ВымпелКом»,
             «OpenScape»). Нижняя планка и запасной путь.
  llm        дешёвая модель получает вопрос и пронумерованные фрагменты и
             возвращает оценку 0–10 каждому (JSON). Быстро и хорошо понимает
             русский, но это вызов облака на каждый вопрос.

Все оценки приведены к [0, 1] — только тогда один порог отсечения имеет смысл
для разных реранкеров. Абсолютные значения у них, однако, разные по природе:
кросс-энкодер дал верному пункту о сроке оплаты 0,06 при правильном порядке.
Поэтому порог подбирается замером (calibrate.py), а не выставляется на глаз.
"""

from __future__ import annotations

import hashlib
import json
import math
import os
import re
import sqlite3
import threading
import time
from typing import Any

from agent.rag.store import Находка

КРОСС = "кросс"
ЭВРИСТИКА = "эвристика"
LLM = "llm"
РЕРАНКЕРЫ = (КРОСС, ЭВРИСТИКА, LLM)
РОЛЬ_LLM = "реранкер"

# Кросс-энкодер: ONNX-сборка bge-reranker-v2-m3 с квантованием int8. fp32 весит
# 2,3 ГБ и считает в разы дольше; int8 на четырёх ядрах — ≈ 1,5 с на пару.
МОДЕЛЬ_КРОСС = "onnx-community/bge-reranker-v2-m3-ONNX"
ФАЙЛ_КРОСС = "onnx/model_int8.onnx"
# Длина пары в токенах модели. 384 ускоряет на треть, но замер показал цену:
# пункт о неустойке, стоящий в конце длинного чанка, выпадал из оценки, и
# верный фрагмент уходил вниз. 512 — длина, с которой модель обычно работает.
ДЛИНА_ПАРЫ = 512
ПАЧКА_КРОСС = 8
# Окна по чанку. Даже в 512 токенов пара «вопрос + чанк» не влезает у 352
# чанков «структуры» из 459: медиана пары — 589 токенов, самая длинная — 1175.
# Обрезанный хвост кросс-энкодер не видел вовсе — у c03 пункт 2.2.7 в конце
# чанка получал 0,005 и девятое место. Теперь длинный чанк режется на окна,
# каждое вместе с вопросом помещается в пару, а оценка чанка — лучшее окно
# (MaxP). Перекрытие — чтобы пункт на границе окна целиком попал хотя бы в
# одно из них; паспорт чанка («документ › раздел») идёт в каждое окно. Цена —
# ≈ 1,7 пары на чанк вместо одной (замер подбора: 1957 пар на 1163 чанка).
ПЕРЕКРЫТИЕ_ОКОН = 128

# LLM-реранкер видит фрагмент целиком. Сначала он видел первые 1500 символов
# ради экономии — и треть чанков «структуры» (153 из 459) теряла конец. Так
# пропал ответ c03: пункт 2.2.7 стоит на 2259-м символе чанка, и LLM поставил
# верному фрагменту 0 из 10. Самый длинный чанк — 2836 символов; двадцать
# кандидатов целиком — ≈ 8 тысяч токенов на вопрос, это доли цента.
СИМВОЛОВ_LLM = 3000


class ОшибкаРеранкера(RuntimeError):
    """Реранкер недоступен: модели нет, провайдер не ответил."""


# --- кэш оценок -----------------------------------------------------------------

class КэшОценок:
    """Оценка пары «вопрос + чанк» реранкером — в таблице базы индекса.

    Кросс-энкодер на CPU считает секунды на пару, а подбор порога и контрольные
    вопросы задают одни и те же пары снова и снова. Оценка детерминирована
    (для LLM — почти), так что второй раз она берётся из базы.
    """

    СХЕМА = """CREATE TABLE IF NOT EXISTS кэш_реранка (
        реранкер TEXT NOT NULL, вопрос TEXT NOT NULL, chunk_id TEXT NOT NULL,
        оценка REAL NOT NULL, PRIMARY KEY (реранкер, вопрос, chunk_id))"""

    def __init__(self, база: str) -> None:
        self.база = база
        self._замок = threading.Lock()
        if база:
            with sqlite3.connect(база) as с:
                с.execute(self.СХЕМА)

    @staticmethod
    def ключ(вопрос: str) -> str:
        return hashlib.sha1(вопрос.strip().encode("utf-8")).hexdigest()

    def взять(self, реранкер: str, вопрос: str, ключи: list[str]) -> dict[str, float]:
        if not self.база or not ключи:
            return {}
        with sqlite3.connect(self.база) as с:
            метки = ",".join("?" * len(ключи))
            ряды = с.execute(f"SELECT chunk_id, оценка FROM кэш_реранка WHERE реранкер=? AND "
                             f"вопрос=? AND chunk_id IN ({метки})",
                             [реранкер, self.ключ(вопрос), *ключи]).fetchall()
        return dict(ряды)

    def положить(self, реранкер: str, вопрос: str, оценки: dict[str, float]) -> None:
        if not self.база or not оценки:
            return
        with self._замок, sqlite3.connect(self.база) as с:
            с.executemany("INSERT OR REPLACE INTO кэш_реранка VALUES (?, ?, ?, ?)",
                          [(реранкер, self.ключ(вопрос), к, float(о)) for к, о in оценки.items()])


# --- общий интерфейс --------------------------------------------------------------

class Реранкер:
    имя = ""

    def __init__(self, кэш: КэшОценок | None = None) -> None:
        self.кэш = кэш
        self.из_кэша = 0
        self.посчитано = 0
        self.секунд = 0.0

    @property
    def ключ_кэша(self) -> str:
        """Под каким именем оценки лежат в кэше. Меняется вместе со схемой оценки."""
        return self.имя

    def оценить(self, вопрос: str, находки: list[Находка]) -> list[float]:
        """Оценки в [0, 1] в порядке находок. Кэш — по chunk_id."""
        старт = time.monotonic()
        готовые = self.кэш.взять(self.ключ_кэша, вопрос, [н.чанк.chunk_id for н in находки]) \
            if self.кэш else {}
        нужно = [н for н in находки if н.чанк.chunk_id not in готовые]
        if нужно:
            новые = self._оценить(вопрос, нужно)
            свежие = {н.чанк.chunk_id: о for н, о in zip(нужно, новые)}
            if self.кэш:
                self.кэш.положить(self.ключ_кэша, вопрос, свежие)
            готовые.update(свежие)
        self.из_кэша += len(находки) - len(нужно)
        self.посчитано += len(нужно)
        self.секунд += time.monotonic() - старт
        return [float(готовые[н.чанк.chunk_id]) for н in находки]

    def _оценить(self, вопрос: str, находки: list[Находка]) -> list[float]:
        raise NotImplementedError


# --- кросс-энкодер ------------------------------------------------------------------

class КроссЭнкодер(Реранкер):
    имя = КРОСС

    def __init__(self, кэш: КэшОценок | None = None, модель: str = МОДЕЛЬ_КРОСС,
                 файл: str = ФАЙЛ_КРОСС, длина: int = ДЛИНА_ПАРЫ,
                 перекрытие: int = ПЕРЕКРЫТИЕ_ОКОН) -> None:
        super().__init__(кэш)
        self.модель, self.файл, self.длина, self.перекрытие = модель, файл, длина, перекрытие
        self._сессия = None
        self._токенизатор = None      # пары: обрезка и выравнивание пачки
        self._разметка = None         # окна: тот же словарь без обрезки, со смещениями
        self._замок = threading.Lock()
        self.пар = 0                  # сколько пар «вопрос + окно» посчитано

    @property
    def ключ_кэша(self) -> str:
        # Схема окон — в ключе: оценки обрезанных пар (прежний «кросс») с
        # оценками окон не смешиваются, старый кэш просто не используется.
        return f"{self.имя} · окна {self.длина}/{self.перекрытие}"

    def загрузить(self) -> None:
        """Модель скачивается в кэш Hugging Face при первом вопросе (≈ 0,6 ГБ)."""
        with self._замок:
            if self._сессия is not None:
                return
            try:
                import onnxruntime as ort
                from huggingface_hub import hf_hub_download
                from tokenizers import Tokenizer
            except ImportError as exc:
                raise ОшибкаРеранкера(
                    "Для кросс-энкодера нужны onnxruntime, tokenizers и huggingface_hub "
                    "(pip install -r requirements.txt)") from exc
            try:
                # Сначала локальный кэш: иначе каждый запуск сверяется с Hugging
                # Face по сети и без неё реранкер не поднимается вовсе.
                путь_модели = hf_hub_download(self.модель, self.файл, local_files_only=True)
                путь_токенизатора = hf_hub_download(self.модель, "tokenizer.json",
                                                    local_files_only=True)
            except Exception:  # noqa: BLE001 — модели ещё нет на диске
                try:
                    путь_модели = hf_hub_download(self.модель, self.файл)
                    путь_токенизатора = hf_hub_download(self.модель, "tokenizer.json")
                except Exception as exc:  # noqa: BLE001 — сеть, диск, неверное имя
                    raise ОшибкаРеранкера(f"Модель {self.модель} не скачалась: {exc}") from exc
            настройки = ort.SessionOptions()
            настройки.intra_op_num_threads = max(1, os.cpu_count() or 1)
            self._сессия = ort.InferenceSession(путь_модели, настройки,
                                                providers=["CPUExecutionProvider"])
            токенизатор = Tokenizer.from_file(путь_токенизатора)
            токенизатор.enable_truncation(max_length=self.длина)
            токенизатор.enable_padding(pad_id=1, pad_token="<pad>")
            self._токенизатор = токенизатор
            self._разметка = Tokenizer.from_file(путь_токенизатора)

    def окна(self, вопрос: str, чанк) -> list[str]:
        """Тексты окон чанка: каждое вместе с вопросом помещается в пару.

        Короткий чанк — одно окно, как было. Длинный режется по токенам с
        перекрытием; границы берутся из смещений токенов, поэтому окно — это
        кусок исходного текста, а не пересобранные токены.
        """
        # Окна нужны и тогда, когда оценки пришли из кэша и модель ещё не
        # загружалась (так упал доказательный прогон в чек-листе).
        if self._разметка is None:
            self.загрузить()
        контекст = f"{чанк.контекст}\n" if чанк.контекст else ""
        занято = (len(self._разметка.encode(вопрос, add_special_tokens=False).ids)
                  + len(self._разметка.encode(контекст, add_special_tokens=False).ids) + 4)
        место = max(self.длина - занято, 2 * self.перекрытие, 16)
        разметка = self._разметка.encode(чанк.текст, add_special_tokens=False)
        n = len(разметка.ids)
        if n <= место:
            return [контекст + чанк.текст]
        смещения = разметка.offsets
        шаг = max(1, место - self.перекрытие)
        итог = []
        начало = 0
        while True:
            конец = min(начало + место, n)
            итог.append(контекст + чанк.текст[смещения[начало][0]:смещения[конец - 1][1]])
            if конец == n:
                return итог
            начало += шаг

    def _оценить(self, вопрос: str, находки: list[Находка]) -> list[float]:
        import numpy as np
        self.загрузить()
        входы = {и.name for и in self._сессия.get_inputs()}
        пары: list[tuple[str, str]] = []
        чей: list[int] = []
        for i, н in enumerate(находки):
            for кусок in self.окна(вопрос, н.чанк):
                пары.append((вопрос, кусок))
                чей.append(i)
        self.пар += len(пары)
        оценки: list[float] = []
        # Пачки небольшие: паддинг до самой длинной пары в пачке, и восемь пар
        # по 512 токенов — разумный кусок памяти на CPU.
        for начало in range(0, len(пары), ПАЧКА_КРОСС):
            закодировано = self._токенизатор.encode_batch(пары[начало:начало + ПАЧКА_КРОСС])
            ids = np.array([п.ids for п in закодировано], dtype=np.int64)
            маска = np.array([п.attention_mask for п in закодировано], dtype=np.int64)
            данные = {"input_ids": ids, "attention_mask": маска}
            if "token_type_ids" in входы:
                данные["token_type_ids"] = np.zeros_like(ids)
            логиты = self._сессия.run(None, данные)[0].reshape(-1)
            оценки.extend(float(1 / (1 + math.exp(-float(л)))) for л in логиты)
        # Оценка чанка — лучшее из его окон (MaxP).
        итог = [0.0] * len(находки)
        for i, о in zip(чей, оценки):
            итог[i] = max(итог[i], о)
        return итог


# --- эвристика ----------------------------------------------------------------------

_СЛОВО = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)
# Слова вопроса, которые ничего не говорят о содержании: без них «сколько
# стоит» не перевешивает «OpenScape».
СТОП = {
    "какой", "какая", "какое", "какие", "каков", "какова", "сколько", "когда", "почему", "где",
    "кто", "что", "как", "это", "для", "при", "про", "над", "под", "без", "или", "ли", "по",
    "на", "за", "из", "от", "до", "об", "обо", "нужно", "надо", "есть", "был", "была", "будет",
    "наш", "наша", "наши", "мы", "нам", "году", "год", "также", "всего", "каждый",
}
ОСНОВА = 5


def основы(текст: str) -> list[str]:
    """Основы значимых слов: первые пять букв, как в поиске по памяти Дня 19."""
    return [с.lower().replace("ё", "е")[:ОСНОВА] for с in _СЛОВО.findall(текст or "")
            if len(с) > 2 and с.lower() not in СТОП]


class Эвристика(Реранкер):
    """Косинус + лексическое совпадение с весом редкости + совпадение с источником.

    Вес редкости (idf) считается по чанкам той же стратегии: «договор» есть в
    половине чанков и почти ничего не значит, «OpenScape» — в трёх и значит
    много. Кэш оценок эвристике не нужен: она считает микросекунды.
    """

    имя = ЭВРИСТИКА
    ВЕС_КОСИНУСА = 0.45
    ВЕС_СЛОВ = 0.40
    ВЕС_ИСТОЧНИКА = 0.15

    def __init__(self, хранилище=None, стратегия: str = "структура") -> None:
        super().__init__(None)
        self.хранилище = хранилище
        self.стратегия = стратегия
        self._idf: dict[str, float] | None = None

    def _словарь(self) -> dict[str, float]:
        if self._idf is None:
            частоты: dict[str, int] = {}
            чанки = self.хранилище.чанки(self.стратегия) if self.хранилище else []
            for ч in чанки:
                for о in set(основы(ч.текст_для_вектора)):
                    частоты[о] = частоты.get(о, 0) + 1
            всего = max(1, len(чанки))
            self._idf = {о: math.log(1 + всего / (1 + ч)) for о, ч in частоты.items()}
            self._idf_по_умолчанию = math.log(1 + всего)
        return self._idf

    def _оценить(self, вопрос: str, находки: list[Находка]) -> list[float]:
        idf = self._словарь()
        слова = list(dict.fromkeys(основы(вопрос)))
        вес = {с: idf.get(с, getattr(self, "_idf_по_умолчанию", 1.0)) for с in слова}
        сумма = sum(вес.values()) or 1.0
        итог = []
        for н in находки:
            текст = set(основы(н.чанк.текст_для_вектора))
            источник = set(основы(f"{н.чанк.источник} {н.чанк.название}"))
            слов = sum(вес[с] for с in слова if с in текст) / сумма
            имя = sum(вес[с] for с in слова if с in источник) / сумма
            # Косинус bge-m3 здесь живёт в полосе 0,4–0,75: растягиваем её на [0, 1].
            косинус = min(1.0, max(0.0, (н.оценка - 0.4) / 0.35))
            итог.append(round(self.ВЕС_КОСИНУСА * косинус + self.ВЕС_СЛОВ * слов
                              + self.ВЕС_ИСТОЧНИКА * min(1.0, имя * 2), 4))
        return итог


# --- LLM-реранкер -------------------------------------------------------------------

LLM_ПРОМПТ = """\
Ты оцениваешь, насколько каждый фрагмент документа помогает ответить на вопрос \
пользователя. Оценка от 0 до 10: 10 — фрагмент содержит прямой ответ; 5 — \
близкая тема, но ответа нет; 0 — не о том. Похожие слова без ответа — это 3–5, \
а не 8. Верни ТОЛЬКО объект JSON вида {"оценки": {"1": 7, "2": 0, ...}} — по \
одной оценке на каждый номер фрагмента."""


class LLMРеранкер(Реранкер):
    имя = LLM

    def __init__(self, клиент, кэш: КэшОценок | None = None, модель: str = "") -> None:
        super().__init__(кэш)
        self.клиент = клиент
        self.модель = модель
        self.токенов = 0

    def _оценить(self, вопрос: str, находки: list[Находка]) -> list[float]:
        from agent import catalog
        from agent.llm import LLMError
        модель = self.модель or catalog.for_role(РОЛЬ_LLM, 0)
        куски = []
        for i, н in enumerate(находки, 1):
            текст = " ".join(н.чанк.текст_для_вектора.split())[:СИМВОЛОВ_LLM]
            куски.append(f"[{i}] {н.чанк.источник} · {н.чанк.раздел}\n{текст}")
        сообщения = [{"role": "system", "content": LLM_ПРОМПТ},
                     {"role": "user", "content": "Фрагменты:\n\n" + "\n\n".join(куски)
                      + f"\n\nВопрос: {вопрос}"}]
        try:
            ответ = self.клиент.call(модель, сообщения, max_tokens=600, low_effort=True)
        except LLMError as exc:
            raise ОшибкаРеранкера(f"LLM-реранкер не ответил: {exc}") from exc
        self.токенов += ответ.prompt_tokens + ответ.completion_tokens
        найдено = re.search(r"\{.*\}", ответ.text or "", re.S)
        try:
            данные = json.loads(найдено.group(0)) if найдено else {}
        except json.JSONDecodeError:
            данные = {}
        оценки = данные.get("оценки", данные) if isinstance(данные, dict) else {}
        if not isinstance(оценки, dict) or not оценки:
            raise ОшибкаРеранкера(f"LLM-реранкер вернул не оценки: {(ответ.text or '')[:120]}")
        итог = []
        for i in range(1, len(находки) + 1):
            try:
                итог.append(min(10.0, max(0.0, float(оценки.get(str(i), 0)))) / 10)
            except (TypeError, ValueError):
                итог.append(0.0)
        return итог


def создать(имя: str, *, клиент=None, хранилище=None, база: str = "",
            стратегия: str = "структура", модель_llm: str = "") -> Реранкер:
    кэш = КэшОценок(база) if база else None
    if имя == КРОСС:
        return КроссЭнкодер(кэш)
    if имя == ЭВРИСТИКА:
        return Эвристика(хранилище, стратегия)
    if имя == LLM:
        if клиент is None:
            raise ОшибкаРеранкера("LLM-реранкеру нужен клиент модели")
        return LLMРеранкер(клиент, кэш, модель_llm)
    raise ОшибкаРеранкера(f"Нет реранкера «{имя}». Есть: {', '.join(РЕРАНКЕРЫ)}")


def сводка(реранкер: Реранкер) -> dict[str, Any]:
    итог = {"реранкер": реранкер.имя, "посчитано": реранкер.посчитано,
            "из_кэша": реранкер.из_кэша, "секунд": round(реранкер.секунд, 2)}
    if isinstance(реранкер, КроссЭнкодер):
        итог["пар"] = реранкер.пар
    return итог
