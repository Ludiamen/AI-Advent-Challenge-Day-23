    ответ = мок.запрос("GET", "/v3/issues/MIG-2")
    было = ответ.json().get("status", {}).get("display", "")
    переходы = мок.запрос("GET", "/v3/issues/MIG-2/transitions").json()
    целевой = next((п for п in переходы if п.get("to", {}).get("key") == "testing"), None)
    if целевой is None:  # pragma: no cover — у мока переход есть всегда
        отчёт.пункт(False, "в моке нет перехода MIG-2 → testing")
        return
