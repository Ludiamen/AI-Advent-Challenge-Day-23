#!/usr/bin/env python3
"""Проверка задания Дня 18: планировщик и фоновые задачи.

Задание требует от инструмента трёх вещей — сохранять данные, выполняться по
расписанию, возвращать агрегированный результат — и одной от агента в целом:
работать 24/7 и периодически выдавать сводку. Скрипт устроен по этим пунктам.

  Часть 1  РЕГИСТРАЦИЯ. Свой сервер scheduler_server.py поднимается как
           настоящий MCP-сервер (stdio) и отдаёт tools/list. Проверяются
           пометки поведения и описания параметров: расписание модель пишет
           словами, и «как писать» должно быть в описании, а не в голове.
  Часть 2  СОХРАНЕНИЕ ДАННЫХ. Задание, поставленное через MCP, ищется в файле
           SQLite прямым запросом мимо нашего кода — как в Дне 17 результат
           инструмента сверялся с ответом самого API. Проверяется и то, что
           задание переживает перезапуск сервера.
  Часть 3  ВЫПОЛНЕНИЕ ПО РАСПИСАНИЮ. Работник запускается ОТДЕЛЬНЫМ процессом
           (worker.py) и выполняет задания, пока в этом процессе никого нет:
           периодическое срабатывает несколько раз, отложенное — ровно один и
           уходит из расписания. Это и есть «агент работает 24/7».
  Часть 4  АГРЕГИРОВАННЫЙ РЕЗУЛЬТАТ. Данные в трекере меняются напрямую, через
           его API; следующий сбор это видит, и сводка называет изменение
           словами — «MIG-2: В работе → Тестируется». Сравниваются края окна
           сводки, а не два последних опроса.
  Часть 5  ПРОПУЩЕННОЕ НЕ ДОГОНЯЕТСЯ. Заданию ставится срок в прошлом: вызова
           не происходит, в истории появляется отметка о пропуске, следующий
           срок считается от «сейчас».
  Часть 6  РУБЕЖ ПОДТВЕРЖДЕНИЯ. Запланировать меняющий инструмент — то же
           изменение чужих данных, только позже. Проверяется, что агент видит
           это через аргументы вызова, а не только по пометке самого
           schedule_job.
  Часть 7  ЖИВАЯ МОДЕЛЬ. Модель сама ставит задание в расписание, сама берёт
           сводку и получает заявку, когда планирует изменение. Работник пишет
           текст сводки моделью.
  Часть 8  ЦЕНА. Во сколько обходится описание планировщика в каждом запросе.

Мок-трекера и работника скрипт поднимает сам и гасит в конце: проверка не
должна зависеть от того, что кто-то что-то запустил заранее.

Запуск:
    python check_scheduler.py                    # всё, включая живые вызовы модели
    python check_scheduler.py --без-модели       # части 1-6, 8: ни одного запроса к LLM
    python check_scheduler.py --модель ds-flash  # какой моделью проверять
    python check_scheduler.py --в RESULTS.md     # дописать отчёт в файл
"""

