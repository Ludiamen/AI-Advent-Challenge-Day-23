"""Переписывание запроса: вопрос человека → 2–3 поисковых запроса к индексу.

Эмбеддер сравнивает то, что написано. Человек спрашивает «сколько дней на
оплату счёта Билайна», а в договоре написано «Заказчик обязан в течение 30
(тридцати) календарных дней с даты выставления счёта… ВымпелКом». Вопросительные
слова, разговорные названия и порядок слов тянут вектор вопроса в сторону от
вектора пункта. Переписывание делает из вопроса несколько запросов на языке
документов; поиск идёт по каждому, списки сливаются (RRF — reciprocal rank
fusion: у чанка, найденного несколькими запросами высоко, сумма 1/(60 + место)
больше), а реранкер потом сравнивает кандидатов с ИСХОДНЫМ вопросом — чтобы
перефразировка не увела смысл.

Модель видит список документов и листов индекса: так она знает, как вещи
называются в корпусе («Лист «Касперский»», «ВымпелКом»), но не видит их
содержания и не должна добавлять фактов и чисел — только слова для поиска.

Переписанные запросы кэшируются в базе индекса по вопросу и модели: подбор
порога, контрольные вопросы и показ должны работать с одними и теми же
формулировками, иначе сравнение режимов мерило бы ещё и разброс модели.
"""

from __future__ import annotations

import hashlib
import json
import re
import sqlite3
import time
from dataclasses import dataclass, field

РОЛЬ = "переписывание-запроса"
ВАРИАНТОВ = 3
RRF_K = 60

ПРОМПТ = """\
Ты готовишь поисковые запросы к базе документов организации: договоры связи \
(Ростелеком, ВымпелКом), бюджетные формы и заявки по ИТ (лицензии, \
сопровождение ПО, амортизация), сметы ЦФО. Перепиши вопрос пользователя в \
{n} коротких поисковых запроса так, как об этом написано в документах:
- термины договоров и бюджета («срок оплаты», «неустойка», «общая стоимость \
услуг», «количество лицензий», «сумма без НДС», «извещать об изменении \
тарифов»);
- официальные названия вместо разговорных («Билайн» → «ВымпелКом»), \
расшифровка сокращений;
- запросы должны отличаться друг от друга; вопросительные слова убери;
- НЕ добавляй фактов и чисел, которых нет в вопросе, и не отвечай на вопрос.
Документы и листы в базе (чтобы знать их язык): {документы}
Верни ТОЛЬКО объект JSON: {{"запросы": ["…", "…"]}}"""


class ОшибкаПереписывания(RuntimeError):
    pass


@dataclass
class Переписано:
    вопрос: str
    запросы: list[str] = field(default_factory=list)   # без исходного вопроса
    модель: str = ""
    секунд: float = 0.0
    из_кэша: bool = False
    ошибка: str = ""

    @property
    def все(self) -> list[str]:
        """Исходный вопрос всегда первый: переписывание добавляет, а не заменяет."""
        return [self.вопрос] + [з for з in self.запросы if з.strip().lower() != self.вопрос.lower()]

    def to_dict(self) -> dict:
        return {"question": self.вопрос, "queries": list(self.запросы), "model": self.модель,
                "seconds": round(self.секунд, 2), "cached": self.из_кэша, "error": self.ошибка}


class Переписчик:
    СХЕМА = """CREATE TABLE IF NOT EXISTS кэш_переписывания (
        модель TEXT NOT NULL, вопрос TEXT NOT NULL, запросы TEXT NOT NULL,
        PRIMARY KEY (модель, вопрос))"""

    def __init__(self, клиент, база: str = "", документы: list[str] | None = None,
                 модель: str = "", вариантов: int = ВАРИАНТОВ) -> None:
        self.клиент = клиент
        self.база = база
        self.документы = документы or []
        self.модель = модель
        self.вариантов = вариантов
        if база:
            with sqlite3.connect(база) as с:
                с.execute(self.СХЕМА)

    def _ключ(self, вопрос: str) -> str:
        return hashlib.sha1(f"{self.вариантов}|{вопрос.strip()}".encode("utf-8")).hexdigest()

    def переписать(self, вопрос: str) -> Переписано:
        from agent import catalog
        from agent.llm import LLMError
        модель = self.модель or catalog.for_role(РОЛЬ, 0)
        итог = Переписано(вопрос=вопрос, модель=модель)
        if self.база:
            with sqlite3.connect(self.база) as с:
                ряд = с.execute("SELECT запросы FROM кэш_переписывания WHERE модель=? AND вопрос=?",
                                (модель, self._ключ(вопрос))).fetchone()
            if ряд:
                итог.запросы, итог.из_кэша = json.loads(ряд[0]), True
                return итог
        сообщения = [
            {"role": "system", "content": ПРОМПТ.format(
                n=self.вариантов, документы="; ".join(self.документы[:40]) or "—")},
            {"role": "user", "content": вопрос},
        ]
        старт = time.monotonic()
        try:
            ответ = self.клиент.call(модель, сообщения, max_tokens=400, low_effort=True)
        except LLMError as exc:
            итог.ошибка = f"переписывание не удалось: {exc}"[:200]
            return итог
        итог.секунд = time.monotonic() - старт
        найдено = re.search(r"\{.*\}", ответ.text or "", re.S)
        try:
            данные = json.loads(найдено.group(0)) if найдено else {}
        except json.JSONDecodeError:
            данные = {}
        запросы = данные.get("запросы") if isinstance(данные, dict) else None
        if not isinstance(запросы, list) or not запросы:
            итог.ошибка = f"модель вернула не запросы: {(ответ.text or '')[:120]}"
            return итог
        итог.запросы = [" ".join(str(з).split())[:200] for з in запросы
                        if str(з).strip()][:self.вариантов]
        if self.база and итог.запросы:
            with sqlite3.connect(self.база) as с:
                с.execute("INSERT OR REPLACE INTO кэш_переписывания VALUES (?, ?, ?)",
                          (модель, self._ключ(вопрос), json.dumps(итог.запросы, ensure_ascii=False)))
        return итог


def слить(списки: list[list], k: int = RRF_K) -> list[tuple]:
    """RRF: чанк получает сумму 1/(k + место) по всем спискам, где он найден.

    Возвращает [(находка, сумма, лучший косинус)] по убыванию суммы. Находка
    берётся с лучшим косинусом — им потом пользуется порог первого этапа и
    эвристика.
    """
    суммы: dict[str, float] = {}
    лучшие: dict[str, object] = {}
    for находки in списки:
        for н in находки:
            ид = н.чанк.chunk_id
            суммы[ид] = суммы.get(ид, 0.0) + 1.0 / (k + н.место)
            if ид not in лучшие or н.оценка > лучшие[ид].оценка:
                лучшие[ид] = н
    порядок = sorted(суммы, key=lambda ид: (-суммы[ид], -лучшие[ид].оценка))
    return [(лучшие[ид], round(суммы[ид], 5), лучшие[ид].оценка) for ид in порядок]
