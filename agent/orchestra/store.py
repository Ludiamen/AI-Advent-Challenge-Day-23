"""Хранилище длинных флоу: план, маршрут, каждый вызов и место остановки.

Файл тот же, что у планировщика Дня 18 и конвейеров Дня 19 — memory/scheduler.db,
— а таблицы свои: «флоу» и «шаги_флоу». Причина та же, по которой конвейеры не
завели себе отдельный файл: фоновая жизнь агента одна, и сводка, консоль и
страница должны читать её из одного места.

Хранить флоу в базе, а не в памяти процесса, нужно по двум причинам.

Первая — пауза. Флоу упирается в шаг, меняющий чужую систему, и ждёт, пока
человек подтвердит заявку. Подтверждение приходит другой командой, часто в
другом процессе (веб-запрос, консоль, завтра). Всё добытое к этому моменту
должно пережить остановку, иначе после «да» пришлось бы начинать сначала — и
платить за те же вызовы второй раз.

Вторая — доказательство. Задание Дня 20 требует проверить «корректность выбора
и порядка вызовов». Проверить можно только то, что записано: план, фактический
порядок, отклонённые по порядку попытки и сверку одного с другим.

Публичное API:
  FlowStore(path)
    .начать(...) -> Флоу            .записать_шаг(...) -> ШагФлоу
    .приостановить(...) / .возобновить(...)  — пауза на подтверждении
    .отметить_круг(...)             .завершить(...)
    .флоу(номер) / .список(...) / .последний() / .ждущие()
    .счётчики(с, по)                — цифры для сводки планировщика
  Флоу, ШагФлоу                     — записи
  Состояния флоу: ИДЁТ, ЖДЁТ, ГОТОВ, СБОЙ, ОБОРВАН
  Состояния шага:  ВЫПОЛНЕН, ОТКЛОНЁН, ОЖИДАНИЕ, ОТКАЗАНО, ОШИБКА, ОТЛОЖЕН
"""

from __future__ import annotations

import json
import os
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

# --- состояния флоу -----------------------------------------------------------
ИДЁТ = "идёт"
ЖДЁТ = "ждёт"          # остановлен на заявке: человек ещё не решил
ГОТОВ = "готов"
СБОЙ = "сбой"
ОБОРВАН = "оборван"    # кончился бюджет кругов или вызовов
СОСТОЯНИЯ = (ИДЁТ, ЖДЁТ, ГОТОВ, СБОЙ, ОБОРВАН)
ЗАКРЫТЫЕ = (ГОТОВ, СБОЙ, ОБОРВАН)

# --- состояния шага -----------------------------------------------------------
ВЫПОЛНЕН = "выполнен"
ОТКЛОНЁН = "отклонён"      # правило порядка не пустило
ОЖИДАНИЕ = "ожидание"      # заведена заявка, ждём человека
ОТКАЗАНО = "отказано"      # человек отклонил заявку
ОШИБКА = "ошибка"          # инструмент ответил сбоем
ОТЛОЖЕН = "отложен"        # вызов из того же круга, до которого не дошли
ШАГИ = (ВЫПОЛНЕН, ОТКЛОНЁН, ОЖИДАНИЕ, ОТКАЗАНО, ОШИБКА, ОТЛОЖЕН)

ПРЕДЕЛ_ТЕКСТА = 4000
ПРЕДЕЛ_ЦЕПОЧКИ = 60000     # переписка с моделью на паузе: хватит на длинный флоу
ПРЕДЕЛ_ИТОГА = 600

_SCHEMA = """
CREATE TABLE IF NOT EXISTS флоу (
    номер       INTEGER PRIMARY KEY AUTOINCREMENT,
    запрос      TEXT NOT NULL,
    цель        TEXT NOT NULL DEFAULT '',
    начат       TEXT NOT NULL,
    кончен      TEXT NOT NULL DEFAULT '',
    секунд      REAL NOT NULL DEFAULT 0,
    состояние   TEXT NOT NULL DEFAULT 'идёт',
    серверы     TEXT NOT NULL DEFAULT '[]',
    маршрут     TEXT NOT NULL DEFAULT '{}',
    план        TEXT NOT NULL DEFAULT '{}',
    сверка      TEXT NOT NULL DEFAULT '{}',
    ожидание    TEXT NOT NULL DEFAULT '{}',
    цепочка     TEXT NOT NULL DEFAULT '[]',
    кругов      INTEGER NOT NULL DEFAULT 0,
    вызовов     INTEGER NOT NULL DEFAULT 0,
    заявка      INTEGER NOT NULL DEFAULT 0,
    итог        TEXT NOT NULL DEFAULT '',
    ошибка      TEXT NOT NULL DEFAULT '',
    кто         TEXT NOT NULL DEFAULT '',
    пользователь TEXT NOT NULL DEFAULT '',
    задача      TEXT NOT NULL DEFAULT '',
    модель      TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_флоу_начат ON флоу(начат);
CREATE INDEX IF NOT EXISTS idx_флоу_состояние ON флоу(состояние);

CREATE TABLE IF NOT EXISTS шаги_флоу (
    номер       INTEGER PRIMARY KEY AUTOINCREMENT,
    флоу        INTEGER NOT NULL,
    место       INTEGER NOT NULL,
    круг        INTEGER NOT NULL DEFAULT 0,
    инструмент  TEXT NOT NULL,
    сервер      TEXT NOT NULL DEFAULT '',
    зачем       TEXT NOT NULL DEFAULT '',
    аргументы   TEXT NOT NULL DEFAULT '{}',
    состояние   TEXT NOT NULL DEFAULT 'выполнен',
    ок          INTEGER NOT NULL DEFAULT 0,
    по_плану    INTEGER NOT NULL DEFAULT 0,
    текст       TEXT NOT NULL DEFAULT '',
    причина     TEXT NOT NULL DEFAULT '',
    начат       TEXT NOT NULL DEFAULT '',
    секунд      REAL NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_шаги_флоу ON шаги_флоу(флоу, место);
"""


class FlowStoreError(RuntimeError):
    """База флоу не открывается или её просят о невозможном."""


def _сейчас() -> datetime:
    return datetime.now().replace(microsecond=0)


def _строка(момент: datetime | None) -> str:
    return момент.replace(microsecond=0).isoformat(sep=" ") if момент else ""


def _json(значение: Any) -> str:
    try:
        return json.dumps(значение, ensure_ascii=False)
    except (TypeError, ValueError):
        return json.dumps(str(значение), ensure_ascii=False)


def _из_json(текст: str, по_умолчанию: Any) -> Any:
    if not текст:
        return по_умолчанию
    try:
        return json.loads(текст)
    except (TypeError, ValueError):
        return по_умолчанию


def _обрезать(текст: str, предел: int) -> str:
    текст = текст or ""
    return текст if len(текст) <= предел else текст[:предел] + f"… (всего {len(текст)} симв.)"


@dataclass
class ШагФлоу:
    """Один вызов внутри флоу — включая тот, который не состоялся."""

    номер: int = 0
    флоу: int = 0
    место: int = 0
    круг: int = 0
    инструмент: str = ""
    сервер: str = ""
    зачем: str = ""
    аргументы: dict[str, Any] = field(default_factory=dict)
    состояние: str = ВЫПОЛНЕН
    ок: bool = True
    по_плану: int = 0        # номер шага плана или 0 — вызов сверх плана
    текст: str = ""
    причина: str = ""
    начат: str = ""
    секунд: float = 0.0

    def словами(self) -> str:
        метка = "по плану" if self.по_плану else "сверх плана"
        хвост = f" — {self.причина}" if self.причина else ""
        return (f"{self.место}. {self.инструмент} ({метка}): "
                f"{self.состояние}{хвост}")

    def to_dict(self) -> dict[str, Any]:
        return {"номер": self.номер, "флоу": self.флоу, "место": self.место,
                "круг": self.круг, "инструмент": self.инструмент, "сервер": self.сервер,
                "зачем": self.зачем, "аргументы": self.аргументы,
                "состояние": self.состояние, "ок": self.ок, "по_плану": self.по_плану,
                "текст": self.текст, "причина": self.причина, "начат": self.начат,
                "секунд": round(self.секунд, 3)}


@dataclass
class Флоу:
    """Длинный флоу целиком: зачем начат, что задумано, что случилось."""

    номер: int = 0
    запрос: str = ""
    цель: str = ""
    начат: str = ""
    кончен: str = ""
    секунд: float = 0.0
    состояние: str = ИДЁТ
    серверы: list[str] = field(default_factory=list)
    маршрут: dict[str, Any] = field(default_factory=dict)
    план: dict[str, Any] = field(default_factory=dict)
    сверка: dict[str, Any] = field(default_factory=dict)
    ожидание: dict[str, Any] = field(default_factory=dict)
    цепочка: list[dict[str, Any]] = field(default_factory=list)
    кругов: int = 0
    вызовов: int = 0
    заявка: int = 0
    итог: str = ""
    ошибка: str = ""
    кто: str = ""
    пользователь: str = ""
    задача: str = ""
    модель: str = ""
    шаги: list[ШагФлоу] = field(default_factory=list)

    @property
    def ок(self) -> bool:
        return self.состояние == ГОТОВ

    @property
    def ждёт(self) -> bool:
        return self.состояние == ЖДЁТ

    @property
    def закрыт(self) -> bool:
        return self.состояние in ЗАКРЫТЫЕ

    def выполненные(self) -> list[str]:
        """Инструменты, которые действительно отработали, — в порядке вызова."""
        return [ш.инструмент for ш in self.шаги if ш.состояние == ВЫПОЛНЕН and ш.ок]

    def словами(self) -> str:
        цепочка = " → ".join(ш.инструмент for ш in self.шаги) or "—"
        хвост = ""
        if self.состояние == ЖДЁТ and self.ожидание:
            хвост = (f"; ждёт подтверждения заявки №{self.заявка} "
                     f"на «{self.ожидание.get('инструмент', '')}»")
        elif self.ошибка:
            хвост = f"; {self.ошибка}"
        return (f"Флоу №{self.номер} — {self.состояние} "
                f"({len(self.выполненные())} вызовов из {self.вызовов}): {цепочка}{хвост}")

    def to_dict(self, с_цепочкой: bool = False) -> dict[str, Any]:
        итог = {"номер": self.номер, "запрос": self.запрос, "цель": self.цель,
                "начат": self.начат, "кончен": self.кончен,
                "секунд": round(self.секунд, 3), "состояние": self.состояние,
                "ок": self.ок, "ждёт": self.ждёт, "серверы": list(self.серверы),
                "маршрут": dict(self.маршрут), "план": dict(self.план),
                "сверка": dict(self.сверка), "ожидание": dict(self.ожидание),
                "кругов": self.кругов, "вызовов": self.вызовов, "заявка": self.заявка,
                "итог": self.итог, "ошибка": self.ошибка, "кто": self.кто,
                "пользователь": self.пользователь, "задача": self.задача,
                "модель": self.модель, "шаги": [ш.to_dict() for ш in self.шаги]}
        if с_цепочкой:
            итог["цепочка"] = list(self.цепочка)
        return итог


class FlowStore:
    """Флоу и их шаги — в том же файле, что расписание и прогоны конвейеров."""

    def __init__(self, path: str) -> None:
        self.path = path
        каталог = os.path.dirname(os.path.abspath(path)) if path != ":memory:" else ""
        if каталог:
            os.makedirs(каталог, exist_ok=True)
        try:
            self._db = sqlite3.connect(path, check_same_thread=False, isolation_level=None,
                                       timeout=10.0)
            self._db.row_factory = sqlite3.Row
            if path != ":memory:":
                self._db.execute("PRAGMA journal_mode=WAL")
            self._db.execute("PRAGMA busy_timeout=10000")
            self._db.executescript(_SCHEMA)
        except sqlite3.Error as exc:
            raise FlowStoreError(f"База флоу «{path}» не открывается: {exc}") from exc

    # --- жизнь флоу -----------------------------------------------------------

    def начать(self, запрос: str, серверы: list[str] | None = None,
               маршрут: dict[str, Any] | None = None, план: dict[str, Any] | None = None,
               кто: str = "", пользователь: str = "", задача: str = "",
               модель: str = "", сейчас: datetime | None = None) -> Флоу:
        """Заводит запись до первого вызова: упавший флоу тоже должен быть виден."""
        запрос = (запрос or "").strip()
        if not запрос:
            raise FlowStoreError("Не сказано, с какого вопроса начинается флоу.")
        сейчас = сейчас or _сейчас()
        цель = str((план or {}).get("цель", ""))
        курсор = self._db.execute(
            "INSERT INTO флоу (запрос, цель, начат, состояние, серверы, маршрут, план, "
            "кто, пользователь, задача, модель) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (запрос, цель, _строка(сейчас), ИДЁТ, _json(list(серверы or [])),
             _json(маршрут or {}), _json(план or {}), кто, пользователь, задача, модель))
        return Флоу(номер=int(курсор.lastrowid), запрос=запрос, цель=цель,
                    начат=_строка(сейчас), состояние=ИДЁТ, серверы=list(серверы or []),
                    маршрут=dict(маршрут or {}), план=dict(план or {}), кто=кто,
                    пользователь=пользователь, задача=задача, модель=модель)

    def записать_план(self, флоу: int, план: dict[str, Any]) -> None:
        """План приходит после первого круга модели — запись заводится раньше."""
        self._db.execute("UPDATE флоу SET план = ?, цель = ? WHERE номер = ?",
                         (_json(план), str(план.get("цель", "")), int(флоу)))

    def записать_шаг(self, флоу: int, место: int, инструмент: str, состояние: str = ВЫПОЛНЕН,
                     ок: bool = True, аргументы: Any = None, текст: str = "",
                     причина: str = "", круг: int = 0, по_плану: int = 0,
                     зачем: str = "", секунд: float = 0.0,
                     сейчас: datetime | None = None) -> ШагФлоу:
        """Записывает вызов — состоявшийся, отклонённый или ждущий человека."""
        if состояние not in ШАГИ:
            raise FlowStoreError(f"Состояние шага «{состояние}» не бывает: {', '.join(ШАГИ)}.")
        сейчас = сейчас or _сейчас()
        сервер = инструмент.split("__", 1)[0] if "__" in инструмент else ""
        строка_аргументов = _обрезать(_json(аргументы if аргументы is not None else {}),
                                      ПРЕДЕЛ_ТЕКСТА)
        курсор = self._db.execute(
            "INSERT INTO шаги_флоу (флоу, место, круг, инструмент, сервер, зачем, аргументы, "
            "состояние, ок, по_плану, текст, причина, начат, секунд) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (int(флоу), int(место), int(круг), инструмент, сервер, зачем, строка_аргументов,
             состояние, 1 if ок else 0, int(по_плану), _обрезать(текст, ПРЕДЕЛ_ТЕКСТА),
             причина, _строка(сейчас), float(секунд)))
        # Счётчик вызовов считает попытки, а не удачи: бюджет тратится и на
        # вызов, который инструмент отверг ошибкой.
        self._db.execute("UPDATE флоу SET вызовов = вызовов + 1 WHERE номер = ?", (int(флоу),))
        return ШагФлоу(номер=int(курсор.lastrowid), флоу=int(флоу), место=int(место),
                       круг=int(круг), инструмент=инструмент, сервер=сервер, зачем=зачем,
                       аргументы=_из_json(строка_аргументов, {}), состояние=состояние,
                       ок=ок, по_плану=int(по_плану), текст=_обрезать(текст, ПРЕДЕЛ_ТЕКСТА),
                       причина=причина, начат=_строка(сейчас), секунд=float(секунд))

    def отметить_круг(self, флоу: int, кругов: int) -> None:
        self._db.execute("UPDATE флоу SET кругов = ? WHERE номер = ?",
                         (int(кругов), int(флоу)))

    def приостановить(self, флоу: int, заявка: int, ожидание: dict[str, Any],
                      цепочка: list[dict[str, Any]], секунд: float = 0.0) -> None:
        """Замораживает флоу на заявке вместе со всей перепиской с моделью.

        Цепочка нужна целиком: после подтверждения флоу продолжится в другом
        процессе, и модель должна увидеть ровно то, что видела до остановки,
        включая свои же просьбы о вызовах.
        """
        # Время копится и через паузу: флоу могли подтвердить назавтра, но
        # потраченные на него минуты работы — это минуты до остановки плюс
        # минуты после, а не сутки ожидания человека.
        self._db.execute(
            "UPDATE флоу SET состояние = ?, заявка = ?, ожидание = ?, цепочка = ?, "
            "секунд = ? WHERE номер = ?",
            (ЖДЁТ, int(заявка), _json(ожидание),
             _обрезать(_json(цепочка), ПРЕДЕЛ_ЦЕПОЧКИ), float(секунд), int(флоу)))

    def возобновить(self, флоу: int) -> None:
        """Снимает паузу. Ожидание стирается: заявка уже решена человеком."""
        self._db.execute(
            "UPDATE флоу SET состояние = ?, ожидание = '{}', цепочка = '[]' WHERE номер = ?",
            (ИДЁТ, int(флоу)))

    def завершить(self, флоу: int, состояние: str, итог: str = "", ошибка: str = "",
                  сверка: dict[str, Any] | None = None, секунд: float = 0.0,
                  сейчас: datetime | None = None) -> Флоу:
        """Закрывает флоу и стирает ожидание: продолжать уже нечего."""
        if состояние not in ЗАКРЫТЫЕ:
            raise FlowStoreError(
                f"Закрыть флоу можно как {', '.join(ЗАКРЫТЫЕ)}, а не «{состояние}».")
        сейчас = сейчас or _сейчас()
        self._db.execute(
            "UPDATE флоу SET состояние = ?, кончен = ?, секунд = ?, итог = ?, ошибка = ?, "
            "сверка = ?, ожидание = '{}', цепочка = '[]' WHERE номер = ?",
            (состояние, _строка(сейчас), float(секунд), _обрезать(итог, ПРЕДЕЛ_ИТОГА),
             ошибка, _json(сверка or {}), int(флоу)))
        готовый = self.флоу(флоу)
        if готовый is None:  # pragma: no cover — запись только что была
            raise FlowStoreError(f"Флоу №{флоу} нет.")
        return готовый

    # --- чтение ---------------------------------------------------------------

    def флоу(self, номер: int, с_шагами: bool = True) -> Флоу | None:
        строка = self._db.execute("SELECT * FROM флоу WHERE номер = ?",
                                  (int(номер),)).fetchone()
        if строка is None:
            return None
        запись = self._флоу(строка)
        if с_шагами:
            запись.шаги = self.шаги(запись.номер)
        return запись

    def шаги(self, флоу: int) -> list[ШагФлоу]:
        строки = self._db.execute(
            "SELECT * FROM шаги_флоу WHERE флоу = ? ORDER BY место, номер",
            (int(флоу),)).fetchall()
        return [self._шаг(с) for с in строки]

    def список(self, сколько: int = 10, состояние: str = "",
               с_шагами: bool = False) -> list[Флоу]:
        запрос = "SELECT * FROM флоу"
        параметры: list[Any] = []
        if состояние:
            запрос += " WHERE состояние = ?"
            параметры.append(состояние)
        запрос += " ORDER BY номер DESC LIMIT ?"
        параметры.append(max(1, int(сколько)))
        записи = [self._флоу(с) for с in self._db.execute(запрос, параметры).fetchall()]
        if с_шагами:
            for запись in записи:
                запись.шаги = self.шаги(запись.номер)
        return записи

    def последний(self, с_шагами: bool = True) -> Флоу | None:
        записи = self.список(сколько=1, с_шагами=с_шагами)
        return записи[0] if записи else None

    def ждущие(self) -> list[Флоу]:
        """Флоу, остановленные на подтверждении, — их показывают человеку."""
        return self.список(сколько=20, состояние=ЖДЁТ)

    def счётчики(self, с: datetime | None = None, по: datetime | None = None) -> dict[str, Any]:
        """Сколько флоу, готовых, сбойных и ждущих за окно — цифры для сводки."""
        условия, параметры = [], []
        if с is not None:
            условия.append("начат >= ?")
            параметры.append(_строка(с))
        if по is not None:
            условия.append("начат <= ?")
            параметры.append(_строка(по))
        где = (" WHERE " + " AND ".join(условия)) if условия else ""
        строки = self._db.execute(
            f"SELECT состояние, COUNT(*) AS сколько, SUM(вызовов) AS вызовов FROM флоу{где} "
            "GROUP BY состояние", параметры).fetchall()
        итог = {"флоу": 0, "готовых": 0, "сбоев": 0, "ждут": 0, "вызовов": 0}
        for строка in строки:
            сколько = int(строка["сколько"])
            итог["флоу"] += сколько
            итог["вызовов"] += int(строка["вызовов"] or 0)
            if строка["состояние"] == ГОТОВ:
                итог["готовых"] += сколько
            elif строка["состояние"] in (СБОЙ, ОБОРВАН):
                итог["сбоев"] += сколько
            elif строка["состояние"] == ЖДЁТ:
                итог["ждут"] += сколько
        return итог

    def close(self) -> None:
        try:
            self._db.close()
        except sqlite3.Error:  # pragma: no cover — закрытие уже закрытой базы
            pass

