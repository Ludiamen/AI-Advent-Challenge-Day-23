class Отчёт:
    def __init__(self) -> None:
        self.строки: list[str] = []
        self.провалов = 0
        self.проверок = 0

    def __call__(self, текст: str = "") -> None:
        print(текст)
        self.строки.append(текст)

    def пункт(self, ок: bool, текст: str) -> bool:
        self.проверок += 1
        if not ок:
            self.провалов += 1
        self(f"  {'✓' if ок else '✗'} {текст}")
        return ок

    def часть(self, номер: int, заголовок: str) -> None:
        self(LINE)
        self(f"ЧАСТЬ {номер}. {заголовок}")
        self(LINE)


def _секунды(значение: float) -> str:
    return f"{значение:.1f}".replace(".", ",") + " с"


def _свободный_порт() -> int:
    with socket.socket() as гнездо:
        гнездо.bind(("127.0.0.1", 0))
        return гнездо.getsockname()[1]


class МокТрекера:
    """Мок-API трекера отдельным процессом — как он и работает в жизни."""

    def __init__(self) -> None:
        self.порт = _свободный_порт()
        self.каталог = tempfile.mkdtemp(prefix="check-tools-трекер-")
        self.данные = os.path.join(self.каталог, "tracker-data.json")
        self.адрес = f"http://127.0.0.1:{self.порт}"
        self.процесс: subprocess.Popen | None = None

    def запустить(self) -> None:
        self.процесс = subprocess.Popen(
            [sys.executable, os.path.join(КОРЕНЬ, "tracker_api.py"),
             "--порт", str(self.порт), "--данные", self.данные, "--сброс"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL)
        предел = time.monotonic() + 30
        while time.monotonic() < предел:
            try:
                socket.create_connection(("127.0.0.1", self.порт), timeout=0.5).close()
                return
            except OSError:
                time.sleep(0.2)
        raise RuntimeError(f"мок-трекер не поднялся на порту {self.порт}")

    def запрос(self, метод: str, путь: str, **аргументы) -> httpx.Response:
        """Прямой запрос к API мимо MCP — им и сверяется результат инструмента."""
        return httpx.request(метод, f"{self.адрес}{путь}", timeout=20, headers={
            "Authorization": "OAuth mock-token", "X-Cloud-Org-ID": "mock-org"}, **аргументы)

    def остановить(self) -> None:
        if self.процесс is not None:
            self.процесс.terminate()
            self.процесс.wait(timeout=10)
            self.процесс = None


def _файл_серверов(каталог: str, адрес: str, запись: bool = True) -> str:
    """Свой mcp-servers.json, указывающий на поднятый мок."""
    путь = os.path.join(каталог, "mcp-servers.json")
    with open(путь, "w", encoding="utf-8") as файл:
        json.dump({"mcpServers": {"tracker": {
            "command": "${PYTHON}",
            "args": [os.path.join(КОРЕНЬ, "tracker_server.py")],
            "env": {"TRACKER_URL": адрес, "TRACKER_TOKEN": "mock-token",
                    "TRACKER_ORG": "mock-org", "TRACKER_QUEUE": "MIG",
                    "TRACKER_WRITE": "1" if запись else "0"},
            "таймаут": 40,
        }}}, файл, ensure_ascii=False)
    return путь


