"""Сравнение стратегий разбиения: как нарезано и как находится.

Две половины, потому что каждая по отдельности вводит в заблуждение.

Статистика чанков говорит, КАК нарезан текст: сколько чанков, какого они
размера, сколько текста продублировано перекрытием, сколько чанков лежат
поперёк двух разделов и сколько абзацев или строк таблицы разрезано границей.
Но «аккуратно нарезано» ещё не значит «лучше находится».

Эталонные вопросы говорят, КАК находится. Лекция предлагает ровно эту
метрику: нашлись ли правильные чанки. Вопрос сформулирован своими словами, не
цитатой, а к нему приложены документ и опорная фраза ответа («не позднее 20
числа»). Попадание — это чанк из нужного документа, в тексте которого эта фраза
есть целиком. Правило одно для обеих стратегий, и оно не знает о разделах:
структурная стратегия не получает очков за «правильный раздел», а
фиксированная теряет их ровно тогда, когда граница разрезала сам ответ.

  hit@k  доля вопросов, где попадание есть среди первых k находок;
  MRR    среднее 1/место первого попадания (0, если в первых k его нет) —
         награждает не только «нашёл», но и «поставил выше».

Этот же набор вопросов — стенд для следующих дней недели: реранкинг должен
поднять MRR, не уронив hit@5, а ответ со ссылками — опираться на найденное.
"""

from __future__ import annotations

import json
import os
import re
import time
from datetime import datetime

from agent.rag.chunking import СТРАТЕГИИ, Чанк, статистика
from agent.rag.extract import Документ

ВОПРОСЫ_ПО_УМОЛЧАНИЮ = "rag-questions.json"
ГЛУБИНА = 5


def _норм(текст: str) -> str:
    return re.sub(r"\s+", " ", текст).strip().lower()


# --- статистика нарезки --------------------------------------------------------

def статистика_стратегии(документы: list[Документ], чанки: list[Чанк]) -> dict:
    """Числа, по которым видно, как стратегия обошлась с текстом."""
    итог = статистика(чанки)
    if not чанки:
        return итог
    по_документу: dict[str, list[Чанк]] = {}
    for ч in чанки:
        по_документу.setdefault(ч.источник, []).append(ч)

    блоков = разорвано = 0
    for д in документы:
        тексты = [_норм(ч.текст) for ч in по_документу.get(д.источник, [])]
        for б in д.блоки:
            if б.вид == "заголовок" or len(б.текст) < 20:
                continue
            блоков += 1
            образец = _норм(б.текст)
            if not any(образец in т for т in тексты):
                разорвано += 1

    токенов_документов = sum(
        sum(ч.токенов for ч in по_документу.get(д.источник, [])) for д in документы)
    исходных = sum(_токены_документа(д) for д in документы) or 1
    поперёк = sum(1 for ч in чанки if len(ч.разделы) > 1)
    с_середины = sum(1 for ч in чанки if _начало_посреди(ч.текст))
    итог.update({
        "избыточность": round(токенов_документов / исходных, 3),
        "поперёк_разделов": поперёк,
        "доля_поперёк": round(поперёк / len(чанки), 3),
        "с_середины_фразы": с_середины,
        "доля_с_середины": round(с_середины / len(чанки), 3),
        "блоков": блоков,
        "разорвано_блоков": разорвано,
        "доля_разорванных": round(разорвано / блоков, 3) if блоков else 0.0,
        "документов": len(по_документу),
    })
    return итог


def _токены_документа(документ: Документ) -> int:
    from agent.tokens import estimate
    return sum(estimate(б.текст) for б in документ.блоки)


def _начало_посреди(текст: str) -> bool:
    """Чанк начинается не с начала фразы: с маленькой буквы или со знака препинания."""
    первый = текст.lstrip()[:1]
    return bool(первый) and (первый.islower() or первый in ",;:)»")


# --- эталонные вопросы ---------------------------------------------------------

def записать_атомарно(путь: str, текст: str) -> None:
    """Временный файл и замена. Страница читает отчёты (qa.json, calibration.json),
    пока фоновая работа их пишет, и с прямой записью ловила пустой или
    недописанный JSON — /api/rag отвечал 500 посреди прогона контрольных."""
    временный = f"{путь}.{os.getpid()}.tmp"
    with open(временный, "w", encoding="utf-8") as f:
        f.write(текст)
    os.replace(временный, путь)


def загрузить_вопросы(путь: str) -> list[dict]:
    if not os.path.exists(путь):
        raise FileNotFoundError(f"Нет файла эталонных вопросов: {путь}")
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    вопросы = данные.get("вопросы", данные) if isinstance(данные, dict) else данные
    for в in вопросы:
        if not в.get("вопрос") or not (в.get("маркеры") or в.get("ловушка")):
            raise ValueError(f"У вопроса {в.get('id', '?')} нет текста или маркеров")
    return вопросы


def с_ответом(вопросы: list[dict]) -> list[dict]:
    """Вопросы, у которых в документах есть ответ, — только они идут в hit@k.

    Ловушки (День 23) нужны подбору порога: у них правильный итог фильтра —
    пустой контекст, а «попадания» не бывает по определению.
    """
    return [в for в in вопросы if not в.get("ловушка")]


def попадание(чанк: Чанк, вопрос: dict) -> bool:
    """Нужный документ и опорная фраза ответа в тексте чанка."""
    источник = вопрос.get("источник", "")
    if источник and _норм(источник) not in _норм(чанк.источник):
        return False
    текст = _норм(чанк.текст)
    return any(_норм(м) in текст for м in вопрос["маркеры"])


def оценить_поиск(индексатор, вопросы: list[dict], стратегии: list[str] | None = None,
                  глубина: int = ГЛУБИНА, прогресс=None) -> dict:
    """Прогнать вопросы через индексы стратегий и посчитать hit@k и MRR.

    Вектор вопроса считается один раз на все стратегии — разница в итоге
    получается только от нарезки, а не от случайностей эмбеддера.
    """
    стратегии = стратегии or [и["стратегия"] for и in индексатор.хранилище.индексы()]
    for с in стратегии:
        индексатор.проверить_эмбеддер(с)
    старт = time.monotonic()
    векторы = индексатор.эмбеддер.векторы([в["вопрос"] for в in вопросы], запрос=True)
    итог: dict = {"глубина": глубина, "вопросов": len(вопросы), "стратегии": {}, "вопросы": []}
    по_вопросам = [{"id": в.get("id", str(i + 1)), "вопрос": в["вопрос"],
                    "источник": в.get("источник", ""), "маркеры": в["маркеры"], "места": {}}
                   for i, в in enumerate(вопросы)]
    for с in стратегии:
        hits = {1: 0, 3: 0, глубина: 0}
        обратных = 0.0
        верный_документ = 0
        for i, (вопрос, вектор) in enumerate(zip(вопросы, векторы)):
            находки = индексатор.хранилище.искать(с, вектор, глубина)
            место = next((н.место for н in находки if попадание(н.чанк, вопрос)), 0)
            for k in hits:
                if место and место <= k:
                    hits[k] += 1
            обратных += 1 / место if место else 0.0
            if находки and (not вопрос.get("источник") or
                            _норм(вопрос["источник"]) in _норм(находки[0].чанк.источник)):
                верный_документ += 1
            по_вопросам[i]["места"][с] = {
                "место": место,
                "первый": находки[0].чанк.паспорт() if находки else None,
                "оценка": round(находки[0].оценка, 4) if находки else 0.0,
            }
            if прогресс:
                прогресс(f"вопросы «{с}»", i + 1, len(вопросы), вопрос["вопрос"][:40])
        n = len(вопросы) or 1
        итог["стратегии"][с] = {
            "hit@1": round(hits[1] / n, 3), "hit@3": round(hits[3] / n, 3),
            f"hit@{глубина}": round(hits[глубина] / n, 3), "mrr": round(обратных / n, 3),
            "документ@1": round(верный_документ / n, 3),
        }
    итог["вопросы"] = по_вопросам
    итог["секунд"] = round(time.monotonic() - старт, 2)
    return итог


# --- всё сравнение ------------------------------------------------------------

def путь_вопросов_по_умолчанию() -> str:
    """RAG_QUESTIONS, иначе rag-questions.json в корне проекта.

    Не «рядом с документами»: каталог документов бывает любым (демо, проверки),
    а эталонные вопросы — часть проекта. Искать их возле документов значило
    молча получить сравнение без половины «как находится».
    """
    from agent.rag.indexer import КОРЕНЬ
    return os.path.abspath(os.getenv("RAG_QUESTIONS") or os.path.join(КОРЕНЬ, ВОПРОСЫ_ПО_УМОЛЧАНИЮ))


def сравнить(индексатор, путь_вопросов: str = "", прогресс=None,
             документы: list[Документ] | None = None) -> dict:
    """Статистика обеих стратегий и поиск по эталонным вопросам — одним отчётом."""
    документы = документы if документы is not None else индексатор.извлечь()
    индексы = {и["стратегия"]: и for и in индексатор.хранилище.индексы()}
    стратегии = [с for с in СТРАТЕГИИ if с in индексы]
    if not стратегии:
        raise RuntimeError("Индекс пуст: сравнивать нечего. Сначала --индексировать")
    нарезка = {с: статистика_стратегии(документы, индексатор.хранилище.чанки(с))
               for с in стратегии}
    отчёт = {
        "когда": datetime.now().isoformat(timespec="seconds"),
        "эмбеддер": индексы[стратегии[0]]["эмбеддер"],
        "размерность": индексы[стратегии[0]]["размерность"],
        "документов": len(документы),
        "страниц": sum(д.страниц for д in документы if д.вид == "pdf"),
        "листов": sum(д.страниц for д in документы if д.вид == "таблица"),
        "распознано_страниц": sum(len(д.распознано) for д in документы),
        "символов": sum(д.символов for д in документы),
        "параметры": {с: индексы[с]["параметры"] for с in стратегии},
        "нарезка": нарезка,
    }
    путь = путь_вопросов or путь_вопросов_по_умолчанию()
    if os.path.exists(путь):
        отчёт["поиск"] = оценить_поиск(индексатор, с_ответом(загрузить_вопросы(путь)),
                                       стратегии, прогресс=прогресс)
        отчёт["вопросы_из"] = os.path.basename(путь)
    return отчёт


def _число(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def лучшая(отчёт: dict) -> str:
    """Какая стратегия выиграла по поиску: MRR, при равенстве — hit@1."""
    поиск = отчёт.get("поиск", {}).get("стратегии", {})
    if len(поиск) < 2:
        return ""
    return max(поиск, key=lambda с: (поиск[с]["mrr"], поиск[с]["hit@1"]))


def в_markdown(отчёт: dict) -> str:
    """Отчёт сравнения для человека — таблицы в Markdown."""
    с = list(отчёт["нарезка"])
    н = отчёт["нарезка"]
    строки = [
        "# Сравнение стратегий разбиения",
        "",
        f"Собрано {отчёт['когда']}. Эмбеддер `{отчёт['эмбеддер']}`, вектор "
        f"{отчёт['размерность']} чисел. Документов {отчёт['документов']}: страниц PDF "
        f"{отчёт['страниц']} (из них распознано OCR {отчёт['распознано_страниц']}), листов "
        f"таблиц {отчёт['листов']}, символов текста {_число(отчёт['символов'])}.",
        "",
        "Параметры: " + "; ".join(
            f"«{к}» — " + ", ".join(f"{п} {з}" for п, з in отчёт["параметры"][к].items())
            for к in с) + " (токены).",
        "",
        "## Как нарезано",
        "",
        "| показатель | " + " | ".join(f"«{к}»" for к in с) + " |",
        "|---|" + "---:|" * len(с),
    ]
    показатели = [
        ("чанков", "чанков", "{}"), ("токенов в чанках", "токенов_всего", "{}"),
        ("размер: мин / медиана / p90 / макс", None, ""),
        ("избыточность (токены чанков ÷ токены текста)", "избыточность", "{:.2f}"),
        ("чанков поперёк двух разделов и больше", None, "поперёк"),
        ("чанков, начатых посреди фразы", None, "середина"),
        ("абзацев и строк таблиц, разрезанных границей", None, "разрыв"),
    ]
    for имя, ключ, формат in показатели:
        ячейки = []
        for к in с:
            х = н[к]
            if ключ:
                ячейки.append(формат.format(х.get(ключ, 0)))
            elif формат == "поперёк":
                ячейки.append(f"{х['поперёк_разделов']} ({х['доля_поперёк']:.0%})")
            elif формат == "середина":
                ячейки.append(f"{х['с_середины_фразы']} ({х['доля_с_середины']:.0%})")
            elif формат == "разрыв":
                ячейки.append(f"{х['разорвано_блоков']} из {х['блоков']} "
                              f"({х['доля_разорванных']:.0%})")
            else:
                ячейки.append(f"{х['мин']} / {х['медиана']} / {х['p90']} / {х['макс']}")
        строки.append(f"| {имя} | " + " | ".join(ячейки) + " |")

    поиск = отчёт.get("поиск")
    if поиск:
        г = поиск["глубина"]
        строки += [
            "",
            "## Как находится",
            "",
            f"Эталонных вопросов {поиск['вопросов']} (файл `{отчёт.get('вопросы_из', '')}`). "
            "Попадание — чанк нужного документа, где опорная фраза ответа есть целиком.",
            "",
            "| метрика | " + " | ".join(f"«{к}»" for к in поиск["стратегии"]) + " |",
            "|---|" + "---:|" * len(поиск["стратегии"]),
        ]
        for м in ("hit@1", "hit@3", f"hit@{г}", "mrr", "документ@1"):
            строки.append(f"| {м} | " + " | ".join(
                f"{поиск['стратегии'][к][м]:.2f}" for к in поиск["стратегии"]) + " |")
        победитель = лучшая(отчёт)
        if победитель:
            строки += ["", f"По MRR выигрывает стратегия **«{победитель}»**."]
        строки += ["", "### По вопросам", "",
                   "| # | вопрос | " + " | ".join(f"место «{к}»" for к in поиск["стратегии"]) + " |",
                   "|---|---|" + "---:|" * len(поиск["стратегии"])]
        for в in поиск["вопросы"]:
            места = [str(в["места"][к]["место"] or "—") for к in поиск["стратегии"]]
            строки.append(f"| {в['id']} | {в['вопрос']} | " + " | ".join(места) + " |")
    return "\n".join(строки) + "\n"


def записать(отчёт: dict, каталог_индекса: str) -> str:
    """Сохранить сравнение: JSON — для страницы, Markdown — для человека.

    Markdown кладётся в корень проекта, если индекс стандартный (так его видно
    в репозитории рядом с README), и рядом с индексом — если индекс свой
    («--индекс-в», проверки): иначе прогон тестов переписывал бы отчёт дня.
    Возвращает путь к Markdown.
    """
    from agent.rag.indexer import КОРЕНЬ
    каталог_индекса = os.path.abspath(каталог_индекса)
    os.makedirs(каталог_индекса, exist_ok=True)
    записать_атомарно(os.path.join(каталог_индекса, "comparison.json"),
                      json.dumps(отчёт, ensure_ascii=False, indent=1))
    свой = каталог_индекса != os.path.abspath(os.path.join(КОРЕНЬ, "index"))
    путь = os.path.join(каталог_индекса if свой else КОРЕНЬ, "RAG-COMPARISON.md")
    записать_атомарно(путь, в_markdown(отчёт))
    return путь


def прочитать(каталог_индекса: str) -> dict | None:
    путь = os.path.join(os.path.abspath(каталог_индекса), "comparison.json")
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as f:
        return json.load(f)
