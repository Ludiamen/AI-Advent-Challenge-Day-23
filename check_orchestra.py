"""Проверка задания Дня 20: оркестровка нескольких MCP-серверов.

Задание требует трёх вещей — чтобы агент выбирал нужный инструмент, корректно
маршрутизировал запросы и выполнял длинный флоу, — и двух доказательств: что в
сценарии участвуют инструменты с РАЗНЫХ серверов и что выбор и порядок вызовов
корректны. Скрипт устроен по этим пунктам и работает с настоящими серверами из
репозитория: мок трекера поднимается процессом, свои серверы запускаются по
stdio, документация спрашивается у публичного deepwiki по сети.

  Часть 1  РЕГИСТРАЦИЯ. Шесть серверов в файле, у каждого описание, темы и
           пометки: «по_просьбе», «замещает», «только_чтение». Из этого файла
           и выбирает маршрутизатор.
  Часть 2  МАРШРУТ БЕЗ МОДЕЛИ. Правила по темам: запрос про задачи поднимает
           трекер, запрос про документацию — deepwiki, боевой Трекер сам не
           берётся, а когда его просят — вытесняет мок.
  Часть 3  МАРШРУТ МОДЕЛЬЮ. Дешёвый круг выбирает серверы по описаниям, и на
           запросе из двух частей берёт оба нужных. Здесь же цена: сколько
           токенов стоили бы все серверы и сколько стоят выбранные.
  Часть 4  ПЛАН. Модель называет шаги до первого вызова: инструменты
           существуют, порядок не нарушает правил зависимостей.
  Часть 5  ДЛИННЫЙ ФЛОУ. Один запрос — вызовы к трём серверам подряд: трекер,
           своя память, публичная документация, отчёт файлом. Проверяется, что
           инструменты выбраны верно, порядок соблюдён, файл лежит на диске.
  Часть 6  ПОРЯДОК ПРОВЕРЯЕТСЯ ДО ВЫЗОВА. Комментарий раньше чтения задачи не
           исполняется: в моке трекера комментария нет, в протоколе — отказ.
  Часть 7  ПАУЗА И ПРОДОЛЖЕНИЕ. Меняющий шаг останавливает флоу на заявке, всё
           добытое сохраняется, а продолжает работу ДРУГОЙ экземпляр агента —
           и комментарий появляется в трекере по-настоящему.
  Часть 8  ПРОТОКОЛ. Таблицы флоу читаются прямым SQL мимо нашего кода: план,
           порядок шагов, пометки «по плану», сверка.
  Часть 9  ЦЕНА. Во что обходится оркестровка и что она экономит.

Запуск:
    python check_orchestra.py                   # всё, включая живые вызовы модели
    python check_orchestra.py --без-модели      # части 1, 2, 6-9: без запросов к LLM
    python check_orchestra.py --модель ds-flash # какой моделью проверять
    python check_orchestra.py --в RESULTS.md    # дописать отчёт в файл
"""

