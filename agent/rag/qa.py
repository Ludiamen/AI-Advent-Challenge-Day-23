РОЛЬ_СУДЬИ = "судья-ответов"
ОЦЕНКИ = ("верно", "частично", "неверно")

СУДЬЯ = """\
Ты проверяешь ответ помощника на вопрос по документам организации. Тебе дано \
ожидание — что должно быть в правильном ответе (его составил человек по \
документам), — и сам ответ. Оцени:
1. «оценка»: «верно» — ответ содержит ожидаемое по существу (формулировка \
может отличаться; подробности сверх ожидания, которые ему не противоречат, \
оценку не снижают); «частично» — есть часть ожидаемого или верное утонуло в \
оговорках; «неверно» — ожидаемого нет или сказано противоположное.
2. «выдумка»: true, если ответ утверждает КОНКРЕТНЫЕ факты (числа, сроки, \
суммы, названия статей, тарифы), которых нет в ожидании и которые противоречат \
ему или ничем не подтверждены. Честное «не знаю» или «в документах этого нет» \
— не выдумка. Общие оговорки без конкретики — не выдумка.
Если ожидание говорит, что в документах этого нет, то «верно» — только ответ, \
который так и говорит; любой ответ с конкретными цифрами — «неверно» и \
«выдумка»: true.
Ответь ТОЛЬКО объектом JSON без пояснений вокруг:
{"оценка": "верно|частично|неверно", "выдумка": true|false, "пояснение": "одна фраза"}"""


def _норм(текст: str) -> str:
    """Для сравнения фактов: регистр, неразрывные пробелы, числа без разделителей."""
    т = (текст or "").lower().replace(" ", " ").replace(" ", " ").replace("ё", "е")
    т = re.sub(r"(?<=\d)[ ](?=\d{3}\b)", "", т)          # 24 441 696 → 24441696
    т = re.sub(r"(?<=\d),(?=\d)", ".", т)                # 26 731,5 → 26731.5
    return re.sub(r"\s+", " ", т)


def есть_факт(ответ: str, варианты: list[str]) -> bool:
    текст = _норм(ответ)
    for в in варианты:
        if в.startswith("re:"):
            if re.search(в[3:], текст, re.IGNORECASE):
                return True
        elif _норм(в) in текст:
            return True
    return False


def загрузить(путь: str) -> list[dict]:
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    вопросы = данные["вопросы"] if isinstance(данные, dict) else данные
    for в in вопросы:
        if not в.get("вопрос") or not в.get("ожидание"):
            raise ValueError(f"У вопроса {в.get('id', '?')} нет текста или ожидания")
        if not в.get("ловушка") and not в.get("факты"):
            raise ValueError(f"У вопроса {в['id']} нет фактов для проверки")
    return вопросы


