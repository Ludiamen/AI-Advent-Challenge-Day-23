"""План длинного флоу: какие инструменты и в каком порядке собирается звать агент.

Задание Дня 20 требует «корректности выбора и порядка вызовов». Чтобы её можно
было проверить, нужно то, с чем сверять: без плана есть только журнал
случившегося, а он любой порядок объявит правильным задним числом.

Поэтому длинный флоу начинается с отдельного, дешёвого круга: модель видит
список доступных инструментов и вопрос человека — и называет шаги. Ничего при
этом не вызывается. План уходит в протокол и на экран ДО первого обращения к
чужой системе, и человек видит, что агент собрался делать.

План — намерение, а не закон. Модель в ходе работы узнаёт то, чего не знала,
когда планировала: задача оказалась закрытой, в памяти нет ни строчки по теме.
Запрещать шаг вне плана значило бы запретить узнавать. Поэтому отклонения
разрешены и помечаются: в конце флоу сверка показывает, что из плана сделано,
что пропущено и что появилось сверх него (flow.py, класс Сверка).

Разбор ответа модели намеренно терпимый. План — вспомогательная вещь: если
модель прислала мусор вместо JSON, правильнее выполнить флоу без плана и
сказать об этом, чем отказать человеку в работе из-за формата.

Публичное API:
  ШагПлана / План                     — разобранный план
  разобрать(текст, доступные, порядок) -> План
  промпт(вопрос, инструменты)         -> (системное сообщение, сообщение пользователя)
  СИСТЕМА                             — правила планирования для модели
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

# Поиск первого полного объекта JSON в ответе модели — та же задача, что у
# маршрутизатора памяти, и решена она там же. Второй копии этой функции в
# проекте быть не должно: разбор ответов слабых моделей полон тонкостей
# (обрывки после объекта, «}» внутри строки), и чинить их надо в одном месте.
from agent.memory.router import _первый_объект as первый_объект
from agent.orchestra.order import Порядок

# Больше шагов в плане не бывает: это длинный флоу, а не программа. Предел
# нужен, чтобы модель, увлёкшаяся перечислением, не назначила двадцать вызовов,
# которые всё равно не уместятся в бюджет исполнения.
ПРЕДЕЛ_ШАГОВ = 12

СИСТЕМА = """\
Ты планируешь работу инженерного агента с внешними системами (MCP).

Тебе дан вопрос человека и список доступных инструментов. Назови шаги: какой
инструмент вызвать и зачем. Ничего не вызывай — сейчас только план.

Правила:
  * бери только инструменты из списка, имена переписывай точно;
  * порядок важен: сначала получить данные, потом обработать, потом сохранить
    или записать в чужую систему;
  * не планируй лишнего: шаг, без которого ответ не изменится, не нужен;
  * если для ответа хватит того, что уже известно, верни пустой список шагов.

Ответ — только JSON, без пояснений вокруг:
{"цель": "что должно получиться", "шаги": [{"инструмент": "сервер__инструмент",
 "зачем": "что этот вызов даёт"}]}"""


@dataclass
class ШагПлана:
    """Один намеченный вызов."""

    место: int = 0
    инструмент: str = ""
    зачем: str = ""
    известен: bool = True     # есть ли такой инструмент среди доступных
    сделан: bool = False      # заполняется сверкой после исполнения

    @property
    def сервер(self) -> str:
        return self.инструмент.split("__", 1)[0] if "__" in self.инструмент else ""

    def словами(self) -> str:
        хвост = f" — {self.зачем}" if self.зачем else ""
        метка = "" if self.известен else " (такого инструмента нет)"
        return f"{self.место}. {self.инструмент}{метка}{хвост}"

    def to_dict(self) -> dict[str, Any]:
        return {"место": self.место, "инструмент": self.инструмент, "зачем": self.зачем,
                "известен": self.известен, "сервер": self.сервер, "сделан": self.сделан}


@dataclass
class План:
    """Что агент собирается сделать и что с этим планом не так."""

    цель: str = ""
    шаги: list[ШагПлана] = field(default_factory=list)
    замечания: list[str] = field(default_factory=list)
    модель: str = ""
    текст: str = ""           # сырой ответ модели — на случай разбирательства

    @property
    def пуст(self) -> bool:
        return not self.шаги

    def инструменты(self) -> list[str]:
        return [ш.инструмент for ш in self.шаги]

    def серверы(self) -> list[str]:
        видно: list[str] = []
        for шаг in self.шаги:
            if шаг.сервер and шаг.сервер not in видно:
                видно.append(шаг.сервер)
        return видно

    def словами(self) -> str:
        if self.пуст:
            return f"План пуст: {self.цель or 'инструменты не нужны'}"
        цепочка = " → ".join(ш.инструмент for ш in self.шаги)
        голова = f"Цель: {self.цель}. " if self.цель else ""
        return f"{голова}{len(self.шаги)} шаг(ов): {цепочка}"

    def для_модели(self) -> str:
        """План словами — он кладётся в системное сообщение круга исполнения."""
        строки = [f"Цель: {self.цель}"] if self.цель else []
        строки += [ш.словами() for ш in self.шаги]
        return "\n".join(строки)

    def to_dict(self) -> dict[str, Any]:
        return {"цель": self.цель, "шаги": [ш.to_dict() for ш in self.шаги],
                "замечания": list(self.замечания), "модель": self.модель,
                "инструменты": self.инструменты(), "серверы": self.серверы()}

    @classmethod
    def from_dict(cls, данные: dict[str, Any] | None) -> "План":
        данные = данные or {}
        шаги = [ШагПлана(место=int(ш.get("место", номер)),
                         инструмент=str(ш.get("инструмент", "")),
                         зачем=str(ш.get("зачем", "")),
                         известен=bool(ш.get("известен", True)),
                         сделан=bool(ш.get("сделан", False)))
                for номер, ш in enumerate(данные.get("шаги", []), 1)]
        return cls(цель=str(данные.get("цель", "")), шаги=шаги,
                   замечания=[str(з) for з in данные.get("замечания", [])],
                   модель=str(данные.get("модель", "")))


def промпт(вопрос: str, инструменты: list[dict[str, str]]) -> list[dict[str, str]]:
    """Сообщения для круга планирования.

    Инструменты перечисляются строкой «имя — заголовок», а не JSON-схемами:
    для выбора хватает названия и назначения, а схемы стоили бы столько же,
    сколько сам разговор (тот самый квадратичный рост из лекции).
    """
    список = "\n".join(f"  {и['имя']} — {и.get('описание', '')}".rstrip()
                       for и in инструменты) or "  (инструментов нет)"
    return [
        {"role": "system", "content": СИСТЕМА},
        {"role": "user", "content": f"Доступные инструменты:\n{список}\n\nВопрос человека: {вопрос}"},
    ]


def разобрать(текст: str, доступные: list[str] | None = None,
              порядок: Порядок | None = None, модель: str = "") -> План:
    """Превращает ответ модели в план и сразу отмечает, что с ним не так."""
    данные = первый_объект(текст or "")
    if not isinstance(данные, dict):
        return План(замечания=["ответ модели не разобран как JSON — флоу идёт без плана"],
                    модель=модель, текст=(текст or "")[:600])

    цель = str(данные.get("цель", "") or "").strip()
    сырые = данные.get("шаги", [])
    if not isinstance(сырые, list):
        сырые = []

    известные = set(доступные or [])
    шаги: list[ШагПлана] = []
    замечания: list[str] = []
    for шаг in сырые[:ПРЕДЕЛ_ШАГОВ]:
        if isinstance(шаг, str):
            шаг = {"инструмент": шаг}
        if not isinstance(шаг, dict):
            continue
        имя = str(шаг.get("инструмент", "") or шаг.get("tool", "")).strip()
        if not имя:
            continue
        есть = not известные or имя in известные
        if not есть:
            замечания.append(f"шаг {len(шаги) + 1}: инструмента «{имя}» нет среди доступных")
        шаги.append(ШагПлана(место=len(шаги) + 1, инструмент=имя,
                             зачем=str(шаг.get("зачем", "") or шаг.get("why", "")).strip(),
                             известен=есть))
    if len(сырые) > ПРЕДЕЛ_ШАГОВ:
        замечания.append(f"в плане было {len(сырые)} шагов — оставлены первые {ПРЕДЕЛ_ШАГОВ}")

    план = План(цель=цель, шаги=шаги, замечания=замечания, модель=модель,
                текст=(текст or "")[:600])
    if порядок is not None and шаги:
        план.замечания.extend(порядок.проверить_план(план.инструменты()))
    return план


__all__ = ["План", "ШагПлана", "разобрать", "промпт", "СИСТЕМА", "ПРЕДЕЛ_ШАГОВ"]
