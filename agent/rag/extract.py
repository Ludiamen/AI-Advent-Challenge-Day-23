"""Документ → блоки текста с местом: страница и путь раздела.

Всё, что дальше делает индекс, опирается на то, что здесь сохранено место
каждого куска текста. Разбиение по структуре режет по разделам, а ссылка на
источник в ответе агента (следующие дни недели) называет страницу и пункт.
Плоский текст без этих пометок годился бы только для резки «по 500 токенов».

Что умеет:
  PDF   текстовый слой — постранично через pdftotext (poppler), запасной путь —
        pypdf. Страница, где текста почти нет, считается сканом и уходит в
        tesseract: картинку страницы рисует pdftoppm, распознанный текст
        кладётся в кэш, чтобы вторая индексация не ждала OCR снова.
  XLSX  каждый лист — раздел; строка таблицы становится строкой
        «шапка: значение; шапка: значение», иначе число без названия столбца
        для поиска бессмысленно.
  MD    заголовки «#» задают путь раздела.
  PY    раздел — функция или класс верхнего уровня.
  TXT   абзацы без разделов.

Колонтитулы PDF вычищаются: строка, которая повторяется на половине страниц
(«Электронный документ подписан ЭП…»), — это не содержание, а шум, который
иначе попадал бы в каждый чанк и делал их похожими друг на друга.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
import tempfile
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime

# Какие файлы берём и каким способом читаем.
РАСШИРЕНИЯ = {
    ".pdf": "pdf", ".xlsx": "таблица", ".xlsm": "таблица",
    ".md": "markdown", ".markdown": "markdown", ".txt": "текст", ".py": "код",
}

# Меньше стольких букв на странице PDF — значит, текстового слоя нет и нужен OCR.
# Номер страницы или одинокий колонтитул дают 2–70 символов, настоящая
# страница договора — тысячи.
МИН_ТЕКСТА_СТРАНИЦЫ = 80
# Разрешение картинки для OCR: 300 точек — стандарт для tesseract; меньше —
# теряется мелкий шрифт реквизитов, больше — страница распознаётся в разы дольше.
ТОЧЕК_НА_ДЮЙМ = 300
ЯЗЫКИ_OCR = "rus+eng"
ОЖИДАНИЕ_OCR = 180

# Номер пункта в начале абзаца: «2.», «2.2.», «2.3.1.1.», «4.7 » (без точки тоже бывает).
ПУНКТ = re.compile(r"^(\d{1,2}(?:\.\d{1,2}){0,4})\.?\s+(?=\S)")
# Заголовок раздела договора: «3. Порядок расчетов» — короткая строка без точки в конце.
ЗАГОЛОВОК_РАЗДЕЛА = re.compile(r"^(\d{1,2})\.\s+([А-ЯЁA-Z][^\n]{2,90})$")
ПРИЛОЖЕНИЕ = re.compile(r"^(?:ПРИЛОЖЕНИЕ|Приложение)\s*№?\s*(\d+[а-я]?)\b", re.UNICODE)
ГОЛЫЙ_НОМЕР = re.compile(r"^\d{1,2}(?:\.\d{1,2}){1,4}\.?$")
МАРКЕР_СПИСКА = re.compile(r"^(?:[-–—•·▪]|\d{1,2}\)|[а-я]\))\s+")
НАЧАЛО_ДОГОВОРА = re.compile(r"^(?:ДОГОВОР|Договор|Дополнительное соглашение|Спецификация|Счет|Счёт)\b")


class ОшибкаИзвлечения(RuntimeError):
    """Файл не прочитать: формат не поддержан или внешняя программа не отвечает."""


@dataclass
class Блок:
    """Кусок текста документа вместе с тем, где он лежит.

    `раздел` — путь сверху вниз: («Приложение № 4», «1. Предмет Договора»).
    `пункт` — номер пункта, с которого начинается абзац («3.4»), если он есть.
    `страница` — номер страницы PDF или номер листа таблицы (с единицы).
    """

    текст: str
    страница: int
    раздел: tuple[str, ...] = ()
    вид: str = "текст"          # «заголовок» | «текст» | «строка»
    пункт: str = ""
    распознан: bool = False     # текст получен OCR, а не из текстового слоя


@dataclass
class Документ:
    путь: str
    источник: str               # путь относительно каталога документов — это и есть ссылка
    название: str
    вид: str                    # pdf | таблица | markdown | текст | код
    sha1: str
    блоки: list[Блок] = field(default_factory=list)
    страниц: int = 0
    распознано: list[int] = field(default_factory=list)   # номера страниц, прошедших OCR
    замечания: list[str] = field(default_factory=list)

    @property
    def символов(self) -> int:
        return sum(len(б.текст) for б in self.блоки)

    @property
    def текст(self) -> str:
        return "\n".join(б.текст for б in self.блоки)

    def кратко(self) -> dict:
        return {
            "источник": self.источник, "название": self.название, "вид": self.вид,
            "страниц": self.страниц, "блоков": len(self.блоки), "символов": self.символов,
            "распознано_страниц": len(self.распознано), "замечания": list(self.замечания),
        }


# --- поиск файлов --------------------------------------------------------------

def найти_документы(каталог: str) -> list[str]:
    """Все поддержанные файлы каталога (с подкаталогами), в стабильном порядке.

    Временные файлы офиса «~$…» и скрытые пропускаются: первые — это замок
    открытой в Excel книги, а не документ, и openpyxl на них падает.
    """
    if not os.path.isdir(каталог):
        raise ОшибкаИзвлечения(f"Каталог документов не найден: {каталог}")
    найдено = []
    for корень, каталоги, файлы in os.walk(каталог):
        каталоги[:] = sorted(к for к in каталоги if not к.startswith("."))
        for имя in sorted(файлы):
            if имя.startswith((".", "~$")):
                continue
            if os.path.splitext(имя)[1].lower() in РАСШИРЕНИЯ:
                найдено.append(os.path.join(корень, имя))
    return найдено


def хэш_файла(путь: str) -> str:
    h = hashlib.sha1()
    with open(путь, "rb") as f:
        for кусок in iter(lambda: f.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest()


def ocr_доступен() -> tuple[bool, str]:
    """Можно ли распознавать сканы, и если нет — почему (для замечания в отчёте)."""
    if not shutil.which("tesseract"):
        return False, "tesseract не установлен (sudo apt install tesseract-ocr tesseract-ocr-rus)"
    if not shutil.which("pdftoppm"):
        return False, "pdftoppm не установлен (пакет poppler-utils)"
    try:
        языки = subprocess.run(["tesseract", "--list-langs"], capture_output=True,
                               text=True, timeout=20).stdout.split()
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f"tesseract не отвечает: {exc}"
    if "rus" not in языки:
        return False, "у tesseract нет русского языка (пакет tesseract-ocr-rus)"
    return True, ""


# --- общий вход ----------------------------------------------------------------

def извлечь(путь: str, каталог: str = "", кэш_ocr: str = "", ocr: bool = True) -> Документ:
    """Прочитать документ целиком. `каталог` нужен, чтобы источник был относительным."""
    путь = os.path.abspath(путь)
    вид = РАСШИРЕНИЯ.get(os.path.splitext(путь)[1].lower())
    if not вид:
        raise ОшибкаИзвлечения(f"Формат не поддержан: {os.path.basename(путь)}")
    источник = os.path.relpath(путь, каталог) if каталог else os.path.basename(путь)
    документ = Документ(путь=путь, источник=источник, название=_название_файла(путь),
                        вид=вид, sha1=хэш_файла(путь))
    if вид == "pdf":
        _из_pdf(документ, кэш_ocr, ocr)
    elif вид == "таблица":
        _из_таблицы(документ)
    elif вид == "markdown":
        _из_markdown(документ)
    elif вид == "код":
        _из_кода(документ)
    else:
        _из_текста(документ)
    return документ


def _название_файла(путь: str) -> str:
    имя = os.path.splitext(os.path.basename(путь))[0]
    return re.sub(r"[_\s]+", " ", имя).strip()


# --- PDF -----------------------------------------------------------------------

def _страниц_pdf(путь: str) -> int:
    try:
        from pypdf import PdfReader
        return len(PdfReader(путь).pages)
    except Exception:  # noqa: BLE001 — битый PDF всё равно попробует pdftotext
        pass
    if shutil.which("pdfinfo"):
        вывод = subprocess.run(["pdfinfo", путь], capture_output=True, text=True, timeout=30).stdout
        найдено = re.search(r"^Pages:\s+(\d+)", вывод, re.M)
        if найдено:
            return int(найдено.group(1))
    raise ОшибкаИзвлечения(f"Не удалось узнать число страниц: {os.path.basename(путь)}")


def _текст_страницы(путь: str, номер: int) -> str:
    if shutil.which("pdftotext"):
        готово = subprocess.run(["pdftotext", "-enc", "UTF-8", "-f", str(номер), "-l", str(номер),
                                 путь, "-"], capture_output=True, timeout=60)
        if готово.returncode == 0:
            return готово.stdout.decode("utf-8", "replace")
    from pypdf import PdfReader
    return PdfReader(путь).pages[номер - 1].extract_text() or ""


def _распознать(путь: str, номер: int, sha1: str, кэш: str) -> str:
    """OCR одной страницы с кэшем по хэшу файла: сканы не распознаются дважды."""
    файл_кэша = os.path.join(кэш, f"{sha1[:16]}-{номер:03d}.txt") if кэш else ""
    if файл_кэша and os.path.exists(файл_кэша):
        with open(файл_кэша, encoding="utf-8") as f:
            return f.read()
    with tempfile.TemporaryDirectory(prefix="ocr-") as tmp:
        основа = os.path.join(tmp, "стр")
        subprocess.run(["pdftoppm", "-r", str(ТОЧЕК_НА_ДЮЙМ), "-f", str(номер), "-l", str(номер),
                        "-png", "-gray", "-singlefile", путь, основа],
                       check=True, capture_output=True, timeout=ОЖИДАНИЕ_OCR)
        готово = subprocess.run(["tesseract", основа + ".png", "stdout", "-l", ЯЗЫКИ_OCR,
                                 "--psm", "3"], capture_output=True, timeout=ОЖИДАНИЕ_OCR)
        if готово.returncode != 0:
            raise ОшибкаИзвлечения(готово.stderr.decode("utf-8", "replace").strip()[:200])
        текст = готово.stdout.decode("utf-8", "replace")
    if файл_кэша:
        os.makedirs(кэш, exist_ok=True)
        with open(файл_кэша, "w", encoding="utf-8") as f:
            f.write(текст)
    return текст


def _из_pdf(документ: Документ, кэш: str, ocr: bool) -> None:
    документ.страниц = _страниц_pdf(документ.путь)
    можно_ocr, почему_нет = ocr_доступен() if ocr else (False, "OCR выключен")
    страницы: list[tuple[int, list[str], bool]] = []
    без_текста: list[int] = []
    for номер in range(1, документ.страниц + 1):
        текст = _текст_страницы(документ.путь, номер)
        распознан = False
        if len(re.sub(r"\s", "", текст)) < МИН_ТЕКСТА_СТРАНИЦЫ:
            if можно_ocr:
                try:
                    текст = _распознать(документ.путь, номер, документ.sha1, кэш)
                    распознан = True
                    документ.распознано.append(номер)
                except (ОшибкаИзвлечения, subprocess.SubprocessError, OSError) as exc:
                    документ.замечания.append(f"стр. {номер}: OCR не удался — {exc}")
            else:
                без_текста.append(номер)
        страницы.append((номер, текст.splitlines(), распознан))
    if без_текста:
        документ.замечания.append(
            f"без текстового слоя страниц: {len(без_текста)} из {документ.страниц} — "
            f"не распознаны: {почему_нет}")

    шум = _колонтитулы([строки for _, строки, _ in страницы])
    состояние = _Разметка()
    for номер, строки, распознан in страницы:
        чистые = [с for с in строки if _норм(с) not in шум and not re.fullmatch(r"\s*\d{1,3}\s*", с)]
        документ.блоки.extend(состояние.разметить(чистые, номер, распознан))
    заголовок = next((б.текст for б in документ.блоки[:60]
                      if НАЧАЛО_ДОГОВОРА.match(б.текст) and len(б.текст) < 160), "")
    if заголовок:
        документ.название = заголовок.rstrip(" .:")


def _норм(строка: str) -> str:
    return re.sub(r"\s+", " ", строка).strip().lower()


def _колонтитулы(страницы: list[list[str]]) -> set[str]:
    """Строки, которые повторяются на половине страниц и больше, — колонтитулы."""
    if len(страницы) < 3:
        return set()
    счёт: Counter[str] = Counter()
    for строки in страницы:
        счёт.update({_норм(с) for с in строки if len(_норм(с)) >= 12})
    порог = max(3, len(страницы) // 2)
    return {с for с, раз in счёт.items() if раз >= порог}


class _Разметка:
    """Склейка строк PDF в абзацы и слежение за текущим разделом.

    pdftotext переносит строки там, где кончилась ширина листа, а не абзац.
    Новый абзац начинается с номера пункта, маркера списка, заголовка или
    пустой строки; всё остальное приклеивается к текущему абзацу. Состояние
    живёт через страницы: раздел «3. Порядок расчетов» продолжается и на
    следующем листе.
    """

    def __init__(self) -> None:
        self.приложение = ""
        self.раздел = ""

    def _раздел_по_пункту(self, пункт: str) -> None:
        """Заголовка нет, а пункт «2.1» уже идёт — значит, начался раздел 2.

        На сканах заголовки разделов часто съедены печатью или шумом («ThA Р»
        вместо «1. ПРЕДМЕТ ДОГОВОРА»), а номера пунктов распознаются. Без этого
        весь договор оставался бы одним разделом, и стратегии «структура» не за
        что было бы зацепиться. Берутся только номера с точкой внутри: «20»
        в начале перенесённой строки — это число, а не пункт.
        """
        найдено = re.match(r"^(\d{1,2})\.(\d{1,2})", пункт)
        if not найдено:
            return
        номер, подпункт = int(найдено.group(1)), int(найдено.group(2))
        if not self.раздел or self.раздел.startswith("Раздел "):
            if self.раздел != f"Раздел {номер}":
                self.раздел = f"Раздел {номер}"
            return
        # Поверх настоящего заголовка — только переход к следующему разделу с
        # его первого пункта. Опечатка нумерации («3.3.1» внутри раздела 2 в
        # договоре VPN) раздел не переключает.
        текущий = re.match(r"^(\d{1,2})\.", self.раздел)
        if текущий and номер == int(текущий.group(1)) + 1 and подпункт == 1:
            self.раздел = f"Раздел {номер}"

    def путь(self) -> tuple[str, ...]:
        return tuple(ч for ч in (self.приложение, self.раздел) if ч)

    def разметить(self, строки: list[str], страница: int, распознан: bool) -> list[Блок]:
        блоки: list[Блок] = []
        абзац: list[str] = []
        пункт = ""

        def закрыть() -> None:
            nonlocal абзац, пункт
            текст = re.sub(r"\s+", " ", " ".join(абзац)).strip()
            if текст:
                блоки.append(Блок(текст, страница, self.путь(), "текст", пункт, распознан))
            абзац, пункт = [], ""

        for сырая in строки:
            строка = сырая.strip()
            if not строка:
                # На сканах номер пункта часто стоит отдельной строкой, а текст
                # пункта идёт после пустой: «4.13.» ⏎⏎ «Также Заказчик…». Голый
                # номер ждёт свой текст, иначе пункт остался бы без номера.
                if not (len(абзац) == 1 and ГОЛЫЙ_НОМЕР.match(абзац[0])):
                    закрыть()
                continue
            if ГОЛЫЙ_НОМЕР.match(строка):
                закрыть()
                пункт = строка.rstrip(".")
                self._раздел_по_пункту(пункт)
                абзац.append(строка)
                continue
            if ПРИЛОЖЕНИЕ.match(строка) and len(строка) < 60:
                закрыть()
                self.приложение = re.sub(r"\s+", " ", ПРИЛОЖЕНИЕ.match(строка).group(0)).strip()
                self.раздел = ""
                блоки.append(Блок(строка, страница, self.путь(), "заголовок", "", распознан))
                continue
            if _похоже_на_заголовок(строка):
                закрыть()
                self.раздел = re.sub(r"\s+", " ", строка)
                блоки.append(Блок(строка, страница, self.путь(), "заголовок",
                                  строка.split(".")[0], распознан))
                continue
            номер = ПУНКТ.match(строка)
            if номер or МАРКЕР_СПИСКА.match(строка):
                закрыть()
                пункт = номер.group(1) if номер else ""
                self._раздел_по_пункту(пункт)
            абзац.append(строка)
        закрыть()
        return блоки


def _похоже_на_заголовок(строка: str) -> bool:
    """«3. Порядок расчетов» — да; «1. Оператор начал предоставление Услуги, а …» — нет."""
    найдено = ЗАГОЛОВОК_РАЗДЕЛА.match(строка)
    if not найдено:
        return False
    хвост = найдено.group(2)
    буквы = [с for с in хвост if с.isalpha()]
    капсом = len(буквы) >= 6 and sum(с.isupper() for с in буквы) / len(буквы) > 0.8
    # Заголовок капсом узнаётся и с точкой в конце: так их печатают в договорах
    # с оформлением «2. СРОК ДЕЙСТВИЯ ДОГОВОРА.», и так их отдаёт OCR.
    конец = (",", ";", ":") if капсом else (".", ",", ";", ":")
    return (not хвост.rstrip().endswith(конец)
            and len(хвост.split()) <= 10 and "," not in хвост)


# --- таблицы -------------------------------------------------------------------

def _ячейка(значение) -> str:
    if значение is None:
        return ""
    if isinstance(значение, (datetime, date)):
        return значение.strftime("%d.%m.%Y")
    if isinstance(значение, float):
        return f"{значение:.2f}".rstrip("0").rstrip(".") if значение % 1 else str(int(значение))
    return re.sub(r"\s+", " ", str(значение)).strip()


def _из_таблицы(документ: Документ) -> None:
    """Лист → раздел, строка → «шапка: значение; …».

    Шапка — та строка из первых двенадцати, где больше всего непустых текстовых
    ячеек. У бюджетных форм она редко первая: сверху идут название формы и
    указания («УСТАНОВИТЕ ФИЛЬТР ПО СТОЛБЦУ D»), и они тоже попадают в индекс —
    отдельным блоком-заголовком листа.
    """
    try:
        from openpyxl import load_workbook
    except ImportError as exc:  # pragma: no cover — зависимость в requirements.txt
        raise ОшибкаИзвлечения("Для таблиц нужен пакет openpyxl") from exc
    книга = load_workbook(документ.путь, read_only=True, data_only=True)
    try:
        for номер, лист in enumerate(книга.worksheets, start=1):
            строки = [[_ячейка(з) for з in ряд] for ряд in лист.iter_rows(values_only=True)]
            строки = [р for р in строки if any(р)]
            if not строки:
                continue
            путь = (f"Лист «{лист.title}»",)
            кандидаты = строки[:12]
            шапка_i = max(range(len(кандидаты)),
                          key=lambda i: (sum(1 for з in кандидаты[i]
                                             if з and not _число(з)), -i))
            шапка = строки[шапка_i]
            вступление = [" ".join(з for з in р if з) for р in строки[:шапка_i]]
            документ.блоки.append(Блок(
                "; ".join([f"Лист «{лист.title}»"] + вступление), номер, путь, "заголовок"))
            for ряд in строки[шапка_i + 1:]:
                пары = _пары(ряд, шапка)
                if пары:
                    документ.блоки.append(Блок("; ".join(пары), номер, путь, "строка"))
        документ.страниц = len(книга.worksheets)
    finally:
        книга.close()


# Сколько одинаковых значений подряд сворачивать в одну запись. Бюджетная форма
# «Аренда МРГ» несёт 37 месячных столбцов с одной суммой: без свёртки строка
# вырастала до тысячи символов повторов, таблица — до 770 тысяч символов и 900
# чанков, и индекс тонул в числах, одинаковых для всех запросов.
СВЕРНУТЬ_ПОВТОРЫ = 3


def _пары(ряд: list[str], шапка: list[str]) -> list[str]:
    """«шапка: значение» по непустым ячейкам; повтор одного значения — одной парой."""
    def имя(i: int) -> str:
        return шапка[i] if i < len(шапка) and шапка[i] else f"столбец {i + 1}"

    пары: list[str] = []
    i = 0
    while i < len(ряд):
        значение = ряд[i]
        if not значение:
            i += 1
            continue
        j = i
        while j + 1 < len(ряд) and ряд[j + 1] == значение:
            j += 1
        if j - i + 1 >= СВЕРНУТЬ_ПОВТОРЫ:
            пары.append(f"{имя(i)}…{имя(j)} (×{j - i + 1}): {значение}")
        else:
            пары.extend(f"{имя(к)}: {значение}" for к in range(i, j + 1))
        i = j + 1
    return пары


def _число(текст: str) -> bool:
    return bool(re.fullmatch(r"[-+]?[\d\s]+(?:[.,]\d+)?%?", текст))


# --- Markdown, код, текст ------------------------------------------------------

def _прочитать(путь: str) -> str:
    with open(путь, encoding="utf-8", errors="replace") as f:
        return f.read()


def _абзацы(текст: str) -> list[str]:
    return [re.sub(r"[ \t]+", " ", а).strip() for а in re.split(r"\n\s*\n", текст) if а.strip()]


def _из_markdown(документ: Документ) -> None:
    путь: list[str] = []
    буфер: list[str] = []

    def сбросить() -> None:
        for абзац in _абзацы("\n".join(буфер)):
            документ.блоки.append(Блок(абзац, 1, tuple(путь)))
        буфер.clear()

    for строка in _прочитать(документ.путь).splitlines():
        найдено = re.match(r"^(#{1,6})\s+(.+?)\s*#*$", строка)
        if найдено:
            сбросить()
            уровень = len(найдено.group(1))
            del путь[уровень - 1:]
            путь.extend([""] * (уровень - 1 - len(путь)))
            путь.append(найдено.group(2))
            путь[:] = [ч for ч in путь if ч]
            if документ.название == _название_файла(документ.путь) and уровень == 1:
                документ.название = найдено.group(2)
            документ.блоки.append(Блок(найдено.group(2), 1, tuple(путь), "заголовок"))
        else:
            буфер.append(строка)
    сбросить()
    документ.страниц = 1


def _из_кода(документ: Документ) -> None:
    """Раздел — функция или класс верхнего уровня; всё до первого — «модуль»."""
    раздел = "модуль"
    буфер: list[str] = []

    def сбросить() -> None:
        текст = "\n".join(буфер).strip()
        if текст:
            документ.блоки.append(Блок(текст, 1, (раздел,)))
        буфер.clear()

    for строка in _прочитать(документ.путь).splitlines():
        найдено = re.match(r"^(?:async\s+)?(def|class)\s+(\w+)", строка)
        if найдено:
            сбросить()
            раздел = f"{найдено.group(1)} {найдено.group(2)}"
        буфер.append(строка)
    сбросить()
    документ.страниц = 1


def _из_текста(документ: Документ) -> None:
    for абзац in _абзацы(_прочитать(документ.путь)):
        документ.блоки.append(Блок(абзац, 1))
    документ.страниц = 1
