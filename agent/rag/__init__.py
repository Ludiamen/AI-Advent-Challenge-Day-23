"""Индекс документов: извлечение → разбиение на чанки → эмбеддинги → хранилище.

Пятая неделя курса — RAG. Первый её день строит нижний этаж: из набора
документов (PDF с текстом и сканы, таблицы Excel, Markdown, код) получается
локальный индекс, где у каждого фрагмента есть вектор и паспорт — откуда он,
из какого раздела и какой страницы. Дальше по неделе на этот этаж встанут
поиск в работе агента, ссылки на источники в ответе и реранкинг.

Слои пакета и почему они разделены:

  extract.py   документ → блоки текста с номером страницы и путём раздела.
               PDF без текстового слоя распознаётся tesseract, таблица
               становится строками «шапка: значение».
  chunking.py  блоки → чанки. Две стратегии: «фикс» режет по числу токенов с
               перекрытием, «структура» — по разделам документа.
  embed.py     текст → вектор. Ollama с bge-m3 локально; хэш-эмбеддер без
               модели — для тестов и для работы без Ollama.
  store.py     SQLite: чанки, метаданные и векторы; поиск по косинусу.
  indexer.py   весь конвейер одной функцией и отчёт о том, что сделано.
  evaluate.py  сравнение стратегий: статистика чанков и эталонные вопросы.
  answer.py    RAG-запрос: фрагменты в промпт, ссылки [n] (День 22).
  qa.py        контрольные вопросы: правила и судья по режимам (День 22–23).
  rerank.py    второй этап: кросс-энкодер, эвристика, LLM-реранкер (День 23).
  rewrite.py   переписывание запроса в 2–3 поисковых и слияние RRF (День 23).
  retrieval.py поиск в два этапа и четыре режима: база, фильтр, rewrite, полный.
  calibrate.py подбор реранкера, порога и top-K на вопросах Дня 21.

Стратегия и эмбеддер подключаются по имени, а не зашиты: реранкинг и другие
модели следующих дней встают сюда же, не трогая извлечение и хранилище.
"""

