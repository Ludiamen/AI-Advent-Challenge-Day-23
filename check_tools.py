def часть_1(отчёт: Отчёт, ящик: amcp.Toolbox, файл_чтения: str) -> None:
    отчёт.часть(1, "Инструмент зарегистрирован на сервере")
    осмотр = ящик.осмотры[0]
    рукопожатие = осмотр.рукопожатие
    отчёт.пункт(осмотр.ок, f"соединение со своим сервером за {_секунды(осмотр.подключение_с)}"
                           + (f", протокол {рукопожатие.протокол}" if рукопожатие else ""))
    if рукопожатие:
        отчёт(f"      сервер {рукопожатие.имя} {рукопожатие.версия} "
              f"(«{рукопожатие.заголовок}»); умеет: {', '.join(рукопожатие.возможности)}")

    имена = {и.имя for и in ящик.инструменты}
    отчёт.пункт(имена == ЧИТАЮЩИЕ | МЕНЯЮЩИЕ,
                f"tools/list вернул {len(имена)} инструментов: {', '.join(sorted(имена))}")

    # Сверка с кодом: сервер поднимается в этом же процессе и спрашивается напрямую.
    import anyio
    from mcp import Client
    import tracker_server

    свой = tracker_server.создать_сервер(tracker_server.Трекер(адрес="http://127.0.0.1:1"),
                                         запись=True)

    async def объявлено():
        async with Client(свой) as клиент:
            return {и.name: и.description for и in (await клиент.list_tools()).tools}

    в_коде = anyio.run(объявлено)
    отчёт.пункт(set(в_коде) == имена,
                "список совпадает с объявленным в tracker_server.py")

    пометки = {и.имя: и.доступ for и in ящик.инструменты}
    отчёт.пункт(all(пометки[и] == "только чтение" for и in ЧИТАЮЩИЕ),
                "читающие инструменты помечены readOnlyHint: "
                + ", ".join(sorted(ЧИТАЮЩИЕ)))
    отчёт.пункт(all(пометки[и] != "только чтение" for и in МЕНЯЮЩИЕ),
                "меняющие помечены как меняющие данные: " + ", ".join(sorted(МЕНЯЮЩИЕ)))
    отчёт.пункт(all(и.описание for и in ящик.инструменты),
                "у каждого инструмента есть описание для модели")

    with amcp.Toolbox(["tracker"], файл_чтения) as только_чтение:
        доступные = {и.имя for и in только_чтение.инструменты}
    отчёт.пункт(доступные == ЧИТАЮЩИЕ,
                "без TRACKER_WRITE=1 меняющих инструментов в списке нет "
                f"({len(доступные)} вместо {len(ЧИТАЮЩИЕ | МЕНЯЮЩИЕ)}) — "
                "так сервер подключают к настоящему Трекеру")


def часть_2(отчёт: Отчёт, ящик: amcp.Toolbox) -> None:
    отчёт.часть(2, "Входные параметры описаны")
    for инструмент in ящик.инструменты:
        схема = инструмент.входная_схема
        try:
            validator_for(схема).check_schema(схема)
            верна = схема.get("type") == "object"
            причина = "" if верна else f"тип схемы «{схема.get('type')}», а нужен object"
        except SchemaError as сбой:
            верна, причина = False, str(сбой).splitlines()[0]
        параметры = инструмент.parameters()
        без_описания = [п.имя for п in параметры if not п.описание]
        отчёт.пункт(верна and not без_описания,
                    f"{инструмент.имя}: схема JSON Schema корректна, параметров "
                    f"{len(параметры)}, все с описанием"
                    + (f" — {причина}" if причина else "")
                    + (f" — без описания: {', '.join(без_описания)}" if без_описания else ""))
        if параметры:
            отчёт("      " + "; ".join(
                f"{п.имя}{'*' if п.обязательный else ''} ({п.тип})" for п in параметры))

    задача = ящик.найти("tracker__get_issue")
    обязательные = задача.входная_схема.get("required", [])
    отчёт.пункт(обязательные == ["key"],
                f"обязательные параметры объявлены: get_issue требует {обязательные}")

    предел = ящик.вызвать("tracker__list_issues", {"limit": 99})
    отчёт.пункт(not предел.ок and "50" in предел.текст,
                "выход за границы отклонён схемой: limit=99 при пределе 50")
    выдумка = ящик.вызвать("tracker__get_issue", {"key": "../../etc/passwd"})
    отчёт.пункт(not выдумка.ок and "ключ задачи" in выдумка.текст,
                "аргумент от модели проверяется до запроса к API: «../../etc/passwd» отклонён")


def часть_3(отчёт: Отчёт, ящик: amcp.Toolbox, мок: МокТрекера) -> None:
    отчёт.часть(3, "Результат возвращается и совпадает с самим API")

    # Список задач: сверяем с прямым запросом к API мимо MCP.
    через_mcp = ящик.вызвать("tracker__list_issues", {"queue": "MIG", "status": "open"})
    напрямую = мок.запрос("POST", "/v3/issues/_search",
                          json={"filter": {"queue": "MIG", "status": "open"}})
    ключи_mcp = [з["ключ"] for з in (через_mcp.данные or {}).get("задачи", [])]
    ключи_api = [з["key"] for з in напрямую.json()]
    отчёт.пункт(через_mcp.ок and ключи_mcp == ключи_api,
                f"list_issues: {len(ключи_mcp)} задач совпали с прямым запросом к API "
                f"({', '.join(ключи_mcp) or '—'})")
    отчёт.пункт((через_mcp.данные or {}).get("найдено") == int(
        напрямую.headers.get("X-Total-Count", -1)),
        f"счётчик найденного взят из заголовка API X-Total-Count = "
        f"{напрямую.headers.get('X-Total-Count')}")

    # Одна задача: поля выжимки совпадают с полями API.
    ключ = ключи_api[0] if ключи_api else "MIG-1"
    одна = ящик.вызвать("tracker__get_issue", {"key": ключ, "comments": 5})
    сырая = мок.запрос("GET", f"/v3/issues/{ключ}").json()
    данные = одна.данные or {}
    совпало = (данные.get("ключ") == сырая["key"]
               and данные.get("тема") == сырая["summary"]
               and данные.get("статус_код") == сырая["status"]["key"])
    отчёт.пункт(одна.ок and совпало,
                f"get_issue {ключ}: ключ, тема и статус совпали с ответом API "
                f"(«{сырая['summary'][:40]}…», статус {сырая['status']['display']})")

    комментарии_api = мок.запрос("GET", f"/v3/issues/{ключ}/comments").json()
    отчёт.пункт(len(данные.get("комментарии", [])) == min(5, len(комментарии_api)),
                f"комментарии пришли из API: {len(данные.get('комментарии', []))} "
                f"из {len(комментарии_api)}")

    переходы_api = мок.запрос("GET", f"/v3/issues/{ключ}/transitions").json()
    статусы_api = {п["to"]["key"] for п in переходы_api}
    статусы_mcp = {п["статус"] for п in данные.get("можно_перевести_в", [])}
    отчёт.пункт(статусы_mcp == статусы_api,
                f"доступные статусы взяты из жизненного цикла API: "
                f"{', '.join(sorted(статусы_mcp)) or '—'}")

    # Что именно экономится. У одной задачи выжимка не всегда короче: в неё
    # добавлены доступные статусы, которых в ответе API нет вовсе. Экономия
    # видна там, где она и нужна, — на списках и на служебных полях, которые
    # модели не пригодятся никогда.
    служебные = ("statusStartTime", "updatedBy", "cloudUid", "passportUid", "version",
                 "boards", "votes", "favorite")
    лишнее = [поле for поле in служебные if поле in одна.текст]
    отчёт.пункт(not лишнее,
                "служебных полей API в выжимке нет: "
                + ", ".join(служебные[:4]) + "… " + (f"(нашлись: {лишнее})" if лишнее else ""))

    список_mcp = ящик.вызвать("tracker__list_issues", {"limit": 50})
    список_api = мок.запрос("POST", "/v3/issues/_search",
                            json={"filter": {}}, params={"perPage": 50})
    экономия = 100 - round(100 * len(список_mcp.текст) / max(1, len(список_api.text)))
    отчёт.пункт(len(список_mcp.текст) < len(список_api.text),
                f"на списке из {len((список_mcp.данные or {}).get('задачи', []))} задач выжимка "
                f"короче ответа API: {len(список_mcp.текст)} символов против "
                f"{len(список_api.text)} — на {экономия}% меньше в каждом запросе к модели")


def часть_4(отчёт: Отчёт, агент: MemoryAgent, модель: str) -> tuple[bool, dict]:
    отчёт.часть(4, "Агент вызывает инструмент и использует результат")
    вопрос = "Посмотри в трекере: какие задачи переноса сейчас в работе и что горит по срокам?"
    отчёт(f"  Вопрос модели ({модель}): «{вопрос}»")
    начало = time.monotonic()
    try:
        ответ = агент.ask(вопрос)
    except AgentError as сбой:
        отчёт.пункт(False, f"модель не ответила: {сбой}")
        return False, {}

    отчёт.пункт(bool(ответ.вызовы),
                f"модель сама позвала инструменты: {len(ответ.вызовы)} вызовов "
                f"({', '.join(sorted({в['полное_имя'] for в in ответ.вызовы}))})")
    for вызов in ответ.вызовы[:6]:
        отчёт(f"      ↳ {вызов['полное_имя']}({json.dumps(вызов['аргументы'], ensure_ascii=False)})"
              f" — {'ок' if вызов['ок'] else 'ошибка'}, {вызов['секунд']} с")
    отчёт.пункт(all(в["ок"] for в in ответ.вызовы), "все вызовы отработали без ошибок")

    из_трекера = [к for к in ("MIG-2", "MIG-3", "MIG-5", "SUP-11") if к in ответ.text]
    отчёт.пункт(bool(из_трекера),
                f"в ответе есть данные из трекера, которых не было в промпте: "
                f"{', '.join(из_трекера) or 'ни одного ключа задачи'}")
    журнал = [з for з in агент.memory.journal(50) if з["правило"] == "вызов-инструмента"]
    отчёт.пункт(len(журнал) >= len(ответ.вызовы),
                f"каждый вызов записан в журнал памяти: записей {len(журнал)}")
    отчёт(f"      расход: {ответ.usage.get('total_tokens')} токенов, "
          f"{_секунды(time.monotonic() - начало)} на весь цикл")
    отчёт("")
    отчёт("  Ответ агента (начало):")
    for строка in ответ.text.strip().splitlines()[:6]:
        отчёт(f"      {строка[:100]}")
    return True, ответ.usage


def часть_5(отчёт: Отчёт, агент: MemoryAgent, мок: МокТрекера, модель: str) -> None:
    отчёт.часть(5, "Изменение — только с подтверждения человека")
    задача = "MIG-7"
    было = len(мок.запрос("GET", f"/v3/issues/{задача}/comments").json())
    просьба = (f"Добавь в трекере к задаче {задача} комментарий: "
               "«Проверено агентом: импорт журналов начнём после MIG-2».")
    отчёт(f"  Просьба ({модель}): «{просьба}»")
    try:
        ответ = агент.ask(просьба)
    except AgentError as сбой:
        отчёт.пункт(False, f"модель не ответила: {сбой}")
        return

    отчёт.пункт(not ответ.вызовы or all(не_меняет(в) for в in ответ.вызовы),
                "меняющий вызов НЕ выполнен сразу")
    заявки = агент.pending_calls()
    отчёт.пункт(bool(заявки), f"появилась заявка: "
                              f"{заявки[-1]['словами'] if заявки else 'ни одной'}")
    стало = len(мок.запрос("GET", f"/v3/issues/{задача}/comments").json())
    отчёт.пункт(стало == было,
                f"в трекере пока ничего не изменилось: комментариев {стало}, было {было}")
    if not заявки:
        return

    номер = заявки[-1]["номер"]
    результат = агент.confirm_call(номер)
    отчёт.пункт(результат.ок, f"после подтверждения заявка №{номер} исполнена")
    комментарии = мок.запрос("GET", f"/v3/issues/{задача}/comments").json()
    отчёт.пункт(len(комментарии) == было + 1,
                f"комментарий появился в самом API: было {было}, стало {len(комментарии)}")
    if комментарии:
        отчёт(f"      последний: «{комментарии[-1]['text'][:80]}»")
    заявка = агент.memory.calls.get(номер)
    отчёт.пункт(заявка.состояние == ВЫПОЛНЕНА,
                f"заявка закрыта состоянием «{заявка.состояние}» и повторно не исполнится")

    # Отклонение: заявка заводится вручную, вызова не происходит вовсе.
    ручная = агент.memory.request_call(
        инструмент="tracker__move_issue", аргументы={"key": задача, "status": "closed"},
        сервер="tracker", зачем="проверка отклонения")
    агент.reject_call(ручная.номер, "статус закрывает тимлид")
    отклонённая = агент.memory.calls.get(ручная.номер)
    состояние = мок.запрос("GET", f"/v3/issues/{задача}").json()
    отчёт.пункт(отклонённая.состояние == ОТКЛОНЕНА and состояние["status"]["key"] != "closed",
                "отклонённая заявка не меняет ничего: задача осталась в статусе "
                f"«{состояние['status']['display']}»")


def не_меняет(вызов: dict) -> bool:
    return вызов["инструмент"] not in МЕНЯЮЩИЕ


def часть_6(отчёт: Отчёт, ящик: amcp.Toolbox, каталог: str) -> None:
    отчёт.часть(6, "Сбои названы понятно")
    случаи = [
        ("задачи нет в трекере", lambda: ящик.вызвать("tracker__get_issue", {"key": "MIG-999"}),
         "404"),
        ("ключ задачи выдуман моделью",
         lambda: ящик.вызвать("tracker__get_issue", {"key": "задача про тайлы"}),
         "не похоже на ключ задачи"),
        ("недопустимый переход",
         lambda: ящик.вызвать("tracker__move_issue", {"key": "MIG-4", "status": "closed"}),
         "можно перевести только"),
    ]
    for подпись, вызов, признак in случаи:
        итог = вызов()
        отчёт.пункт(not итог.ок and признак in итог.текст,
                    f"{подпись}: {итог.текст[:110]}")

    # Трекер не отвечает и токен не принят — отдельные серверы со своей настройкой.
    мимо = os.path.join(каталог, "нет-трекера.json")
    with open(мимо, "w", encoding="utf-8") as файл:
        json.dump({"mcpServers": {"tracker": {
            "command": "${PYTHON}", "args": [os.path.join(КОРЕНЬ, "tracker_server.py")],
            "env": {"TRACKER_URL": f"http://127.0.0.1:{_свободный_порт()}",
                    "TRACKER_TOKEN": "mock-token", "TRACKER_ORG": "mock-org"},
            "таймаут": 40}}}, файл, ensure_ascii=False)
    with amcp.Toolbox(["tracker"], мимо) as мёртвый:
        итог = мёртвый.вызвать("tracker__list_issues", {})
    отчёт.пункт(not итог.ок and "tracker_api.py" in итог.текст,
                f"трекер не отвечает: {итог.текст[:110]}")

    плохой = os.path.join(каталог, "плохой-токен.json")
    with open(плохой, "w", encoding="utf-8") as файл:
        json.dump({"mcpServers": {"tracker": {
            "command": "${PYTHON}", "args": [os.path.join(КОРЕНЬ, "tracker_server.py")],
            "env": {"TRACKER_URL": os.environ.get("CHECK_TRACKER_URL", ""),
                    "TRACKER_TOKEN": "wrong-token", "TRACKER_ORG": "mock-org"},
            "таймаут": 40}}}, файл, ensure_ascii=False)
    with amcp.Toolbox(["tracker"], плохой) as чужой:
        итог = чужой.вызвать("tracker__list_issues", {})
    отчёт.пункт(not итог.ок and "TRACKER_TOKEN" in итог.текст,
                f"токен не принят: {итог.текст[:110]}")


def часть_7(отчёт: Отчёт, агент: MemoryAgent, ящик: amcp.Toolbox,
            расход_с_инструментами: dict, модель: str, без_модели: bool) -> None:
    отчёт.часть(7, "Цена инструментов")
    схема = ящик.токенов()
    отчёт.пункт(схема > 0, f"описания {len(ящик.инструменты)} инструментов занимают "
                           f"≈ {схема} токенов В КАЖДОМ запросе, пока они подключены")
    for инструмент in sorted(ящик.инструменты, key=lambda и: -и.tokens()):
        отчёт(f"      {инструмент.полное_имя}: ≈ {инструмент.tokens()} ток.")
    if без_модели or not расход_с_инструментами:
        отчёт("  (сравнение с ответом без инструментов пропущено: нет живых вызовов)")
        return

    прежний = агент.toolbox
    агент.toolbox = None
    try:
        обычный = агент.ask("Чем векторные тайлы лучше картинок MapServer? Коротко.")
    except AgentError as сбой:
        отчёт.пункт(False, f"контрольный вопрос без инструментов не прошёл: {сбой}")
        return
    finally:
        агент.toolbox = прежний

    с_инстр = расход_с_инструментами.get("prompt_tokens", 0)
    без_инстр = обычный.usage.get("prompt_tokens", 0)
    отчёт.пункт(True, f"вход с инструментами {с_инстр} ток., без инструментов {без_инстр} ток. "
                      f"(разница {с_инстр - без_инстр:+d})")
    отчёт("      Разница — не только схема: с инструментами в запрос уходят ещё и их "
          "ответы, и так на каждом круге. Отсюда и «квадратичный рост» из лекции.")


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Проверка задания Дня 17: свой инструмент MCP вокруг API.")
    разбор.add_argument("--модель", dest="model", default="ds-flash",
                        help="какой моделью проверять живые вызовы (по умолчанию ds-flash)")
    разбор.add_argument("--без-модели", dest="offline", action="store_true",
                        help="пропустить части с живыми вызовами модели")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ",
                        help="дописать отчёт в markdown-файл")
    аргументы = разбор.parse_args()

    отчёт = Отчёт()
    отчёт(f"Проверка Дня 17: свой инструмент MCP вокруг API трекера")
    отчёт(f"Время: {time.strftime('%Y-%m-%d %H:%M')}; модель: "
          + ("не вызывается" if аргументы.offline else аргументы.model))
    начало = time.monotonic()

    мок = МокТрекера()
    мок.запустить()
    os.environ["CHECK_TRACKER_URL"] = мок.адрес
    каталог = tempfile.mkdtemp(prefix="check-tools-")
    память = os.path.join(каталог, "memory")
    файл = _файл_серверов(каталог, мок.адрес, запись=True)
    # Второй файл — тот же сервер без разрешения на запись: так его подключают к
    # настоящему Трекеру, и список инструментов у него короче.
    каталог_чтения = os.path.join(каталог, "чтение")
    os.makedirs(каталог_чтения, exist_ok=True)
    файл_чтения = _файл_серверов(каталог_чтения, мок.адрес, запись=False)

    агент = MemoryAgent(model_key=аргументы.model, base_dir=память, tools=["tracker"],
                        mcp_config=файл, judge_semantic=False, router_mode="выкл")
    try:
        агент.подключить_инструменты()
        ящик = агент.toolbox
        часть_1(отчёт, ящик, файл_чтения)
        часть_2(отчёт, ящик)
        часть_3(отчёт, ящик, мок)
        расход: dict = {}
        if not аргументы.offline:
            ок, расход = часть_4(отчёт, агент, аргументы.model)
            if ок:
                часть_5(отчёт, агент, мок, аргументы.model)
        else:
            отчёт.часть(4, "Агент вызывает инструмент и использует результат")
            отчёт("  (пропущено: запуск с «--без-модели»)")
        часть_6(отчёт, ящик, каталог)
        часть_7(отчёт, агент, ящик, расход, аргументы.model, аргументы.offline)
    finally:
        агент.close()
        мок.остановить()

    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}. "
          f"Данные мок-трекера остались в {мок.данные}")

    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as файл_отчёта:
            файл_отчёта.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
