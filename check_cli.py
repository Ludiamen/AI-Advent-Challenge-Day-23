# --- отчёт ------------------------------------------------------------------------

def отчёт_в_markdown(итоги: list[Итог], модель: str, секунд: float) -> str:
    всего = sum(len(и.сошлось) for и in итоги)
    сошлось = sum(1 for и in итоги for _, ок in и.сошлось if ок)
    строки = [
        "# Результат консольной проверки Дня 23",
        "",
        f"Прогон: `python check_cli.py`, модель для живых вызовов **{модель or 'по роли'}**, "
        f"память в `{ПАМЯТЬ_ОТН}/`.",
        f"Дата: {time.strftime('%Y-%m-%d %H:%M')}. Заняло {секунд / 60:.1f} мин.",
        "",
        f"**Ожиданий проверено: {всего}, сошлось: {сошлось}, "
        f"расхождений: {всего - сошлось}.**",
        "",
        "Каждая строка — отдельный процесс. Проверяются девять пластов: второй этап",
        "поиска этого дня (часть 23: реранкер, порог отсечения, top-K до и после,",
        "rewrite, сравнение режимов на десяти контрольных вопросах), RAG-запрос",
        "Дня 22 (часть 22: ответ с RAG и без, ловушка, контрольные вопросы с",
        "правилами и судьёй), индекс документов (День 21, часть 0: OCR,",
        "две стратегии, bge-m3, SQLite, сравнение, MCP-сервер docs), оркестровка (День 20:",
        "маршрут серверов, длинный флоу, порядок вызовов, пауза на",
        "подтверждении), конвейеры (День 19), планировщик с работником (День 18),",
        "свой инструмент MCP вокруг API трекера с заявками на изменение (День 17),",
        "подключение MCP из Дня 16 и наследство Дней 11–15 — чтобы видеть, что",
        "не сломалось.",
        "",
        "## Сводка",
        "",
        "| шаг | проверка | команда | итог | секунд |",
        "|---|---|---|---|---|",
    ]
    for и in итоги:
        ключи = (и.команда.replace(f"--память-в {ПАМЯТЬ_ОТН} ", "")
                 .replace(f"--модель {модель} ", "").strip())
        строки.append(f"| {и.шаг.номер} | {и.шаг.название} | `{ключи}` | "
                      f"{'ок' if и.удача else '**расхождение**'} | {и.секунд:.1f} |")
    строки += ["", "## Подробности", ""]
    for и in итоги:
        строки.append(f"### {и.шаг.номер}. {и.шаг.название}")
        строки.append("")
        строки.append(f"```\n$ python {и.команда}\n```")
        if и.шаг.фон:
            строки.append("")
            строки.append(f"Во время шага работал сервер: `python {' '.join(и.шаг.фон[1:])}`")
        строки.append("")
        for описание, ок in и.сошлось:
            строки.append(f"- {'✓' if ок else '✗'} {описание}")
        строки.append("")
        строки_вывода = и.вывод.strip().splitlines()
        кусок = "\n".join(строки_вывода[:40])
        # Провал доказательного скрипта обычно в хвосте вывода, за первыми
        # сорока строками: без этого отчёт говорил «провалов не 0», но не какой.
        хвост = [с for с in строки_вывода[40:] if "✗" in с]
        if хвост:
            кусок += "\n… строки с ✗ дальше в выводе:\n" + "\n".join(хвост)
        if кусок:
            # Четыре кавычки: в выводе бывают тройные, и они рвали бы разметку.
            строки += ["<details><summary>вывод</summary>", "", "````", кусок, "````", "",
                       "</details>", ""]
