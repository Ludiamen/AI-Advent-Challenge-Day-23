#!/usr/bin/env python3
"""Проверка задания Дня 22: первый RAG-запрос и сравнение с ответом без RAG.

Задание: функция «вопрос → поиск релевантных чанков → объединение с вопросом →
запрос к LLM», сравнение ответа без RAG и с RAG, десять контрольных вопросов с
ожиданием и источниками, агент с двумя режимами. Скрипт идёт по этим пунктам
на настоящем индексе Дня 21, живой модели и живом судье, а агента проверяет
отдельным процессом cli.py — так, как им пользуется человек.

  Часть 1  ИНДЕКС. Индекс собран, эмбеддер локальный, контрольный набор на месте.
  Часть 2  ЦЕПОЧКА ЗАПРОСА. Один вопрос по шагам: что нашёл поиск, что ушло в
           промпт (блоки и токены), что ответила модель, на какие [n] сослалась
           и какие это файлы, разделы и страницы.
  Часть 3  ДВА РЕЖИМА НА ОДНОМ ВОПРОСЕ. Та же модель и та же роль; разница —
           только фрагменты. Без RAG — нет ни источников, ни точной цифры.
  Часть 4  ЛОВУШКА. Ответа в документах нет: с RAG — «В документах этого нет»,
           без RAG — судья проверяет, не выдумана ли конкретика.
  Часть 5  КОНТРОЛЬНЫЕ ВОПРОСЫ. Десять вопросов в обоих режимах: правила
           (ключевые факты, источник найден и процитирован) и судья.
  Часть 6  АГЕНТ С ДВУМЯ РЕЖИМАМИ. cli.py --сравнить-rag отдельным процессом.

Запуск:
    python check_rag_answer.py                    # всё, модель ds-flash, судья groq-20b
    python check_rag_answer.py --без-судьи        # только правила
    python check_rag_answer.py --в RESULTS.md     # дописать протокол в файл
"""

from __future__ import annotations

import argparse
import functools
import os
import subprocess
import sys
import time

print = functools.partial(print, flush=True)

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КОРЕНЬ)

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(КОРЕНЬ, ".env"))

from agent import catalog  # noqa: E402
from agent.llm import Client  # noqa: E402
from agent.rag import Индексатор  # noqa: E402
from agent.rag import qa  # noqa: E402
from agent.rag.answer import БЕЗ_RAG, С_RAG, НЕТ_В_ДОКУМЕНТАХ, Отвечатель, паспорт_строкой  # noqa: E402
from check_tools import LINE, Отчёт, _секунды  # noqa: E402

ВОПРОС = "Какая неустойка за просрочку оплаты предусмотрена договором с ВымпелКомом?"
ЛОВУШКА = "Сколько стоит подписка на Microsoft Office 365 в бюджете ИТ на 2026 год?"


def часть_1(отчёт: Отчёт, индексатор: Индексатор) -> list[dict]:
    отчёт.часть(1, "Индекс Дня 21 и контрольный набор")
    индексы = {и["стратегия"]: и for и in индексатор.хранилище.индексы()}
    и = индексы.get("структура")
    отчёт.пункт(bool(и), f"индекс «структура»: чанков {и['чанков'] if и else 0}, "
                         f"{и['эмбеддер'] if и else '—'}, вектор {и['размерность'] if и else 0}")
    отчёт.пункт(not индексатор.эмбеддер.проверить(), f"эмбеддер {индексатор.эмбеддер.имя} отвечает")
    вопросы = qa.загрузить(qa.путь_по_умолчанию())
    ловушек = sum(bool(в.get("ловушка")) for в in вопросы)
    отчёт.пункт(len(вопросы) == 10 and ловушек == 2,
                f"контрольных вопросов {len(вопросы)}, из них ловушек {ловушек}; у каждого "
                "ожидание, у вопросов с ответом — факты и источники")
    for в in вопросы:
        источники = "; ".join(f"{и['файл']} › {и['раздел']}" for и in в.get("источники", [])) or "—"
        отчёт(f"    {в['id']}{' (ловушка)' if в.get('ловушка') else ''}: {в['вопрос']}")
        отчёт(f"        ожидание: {в['ожидание']}")
        отчёт(f"        источники: {источники}")
    return вопросы


def часть_2(отчёт: Отчёт, отвечатель: Отвечатель, модель: str):
    отчёт.часть(2, "Цепочка RAG-запроса по шагам")
    отчёт(f"  вопрос: «{ВОПРОС}»")
    найдено = отвечатель.найти(ВОПРОС)
    прошли, отсеяно, секунд = найдено
    отчёт.пункт(bool(прошли), f"1) поиск: {len(прошли)} фрагментов за {_секунды(секунд)} "
                              f"(порог {отвечатель.порог}, отсеяно {len(отсеяно)})")
    for i, н in enumerate(прошли, 1):
        отчёт(f"       [{i}] {паспорт_строкой(н)} · {н.оценка:.3f}")
    ответ = отвечатель.ответить(ВОПРОС, С_RAG, модель, найдено=найдено)
    фрагменты = [б for б in ответ.блоки if б.layer == "документы"]
    отчёт.пункт(len(фрагменты) == len(прошли),
                f"2) промпт: роль + правила + {len(фрагменты)} фрагментов с паспортом + вопрос; "
                f"≈ {sum(б.tokens for б in ответ.блоки)} ток. по оценке, "
                f"{ответ.токенов_вход} ток. по счёту провайдера")
    отчёт.пункт("Вопрос:" in ответ.сообщения[1]["content"] and "[1]" in ответ.сообщения[1]["content"],
                "   фрагменты пронумерованы, вопрос стоит после них")
    отчёт.пункт(bool(ответ.текст) and not ответ.ошибка,
                f"3) модель {ответ.модель}: {_секунды(ответ.секунд_модели)}, выход {ответ.токенов_выход} ток.")
    for строка in ответ.текст.splitlines():
        if строка.strip():
            отчёт(f"       > {строка}")
    отчёт.пункт(bool(ответ.цитаты) and not ответ.выдуманные_ссылки,
                f"4) ссылки в ответе: {ответ.цитаты}; на несуществующие номера — "
                f"{ответ.выдуманные_ссылки or 'нет'}")
    for и in ответ.источники:
        отчёт(f"       [{и['n']}] {и['source']} · {и['section']}"
              + (f", п. {и['clause']}" if и["clause"] else "") + f" · стр. {и['pages']}")
    отчёт.пункт(any("Вымпелком" in и["source"] for и in ответ.источники),
                "   источник — договор с ВымпелКомом (скан, текст получен OCR)")
    отчёт.пункт(qa.есть_факт(ответ.текст, ["re:0\\.2\\s*%"]), "   в ответе «0,2 %»")
    return ответ


def часть_3(отчёт: Отчёт, отвечатель: Отвечатель, модель: str, с_rag) -> None:
    отчёт.часть(3, "Тот же вопрос без RAG — та же модель, та же роль")
    без = отвечатель.ответить(ВОПРОС, БЕЗ_RAG, модель)
    for строка in без.текст.splitlines():
        if строка.strip():
            отчёт(f"       > {строка}")
    отчёт.пункт(без.модель == с_rag.модель, f"модель одна: {без.модель}")
    отчёт.пункт(с_rag.сообщения[0]["content"].startswith(без.сообщения[0]["content"]),
                "системный промпт без RAG — начало промпта с RAG: разница только в правилах и фрагментах")
    отчёт.пункт(not без.фрагменты and not без.источники, "без RAG нет ни фрагментов, ни источников")
    отчёт(f"  цена контекста: вход без RAG {без.токенов_вход} ток., с RAG {с_rag.токенов_вход} ток.")
    точно = qa.есть_факт(без.текст, ["re:0\\.2\\s*%"])
    отчёт(f"  «0,2 %» без RAG: {'есть' if точно else 'нет'} — точную ставку модели взять неоткуда")


def часть_4(отчёт: Отчёт, отвечатель: Отвечатель, клиент, модель: str, судья: bool) -> None:
    отчёт.часть(4, "Ловушка: ответа в документах нет")
    вопрос = {"id": "ловушка", "ловушка": True, "вопрос": ЛОВУШКА,
              "ожидание": "В документах этого нет.", "факты": [], "источники": []}
    for режим, имя in ((БЕЗ_RAG, "без RAG"), (С_RAG, "с RAG")):
        ответ = отвечатель.ответить(ЛОВУШКА, режим, модель)
        оценка = qa.по_правилам(вопрос, ответ)
        if судья:
            qa.судить(клиент, вопрос, оценка)
        отчёт(f"  {имя}: «{' '.join(ответ.текст.split())[:260]}»")
        отчёт(f"      судья: {оценка.судья or '—'}{', выдумка' if оценка.выдумка else ''}"
              + (f" — {оценка.пояснение}" if оценка.пояснение else ""))
        if режим == С_RAG:
            отчёт.пункт(ответ.отказ, f"с RAG — «{НЕТ_В_ДОКУМЕНТАХ}», хотя фрагментов в промпте "
                                     f"{len(ответ.фрагменты)} (бюджетные таблицы похожи на вопрос)")


def часть_5(отчёт: Отчёт, отвечатель: Отвечатель, вопросы: list[dict], модель: str,
            судья: bool) -> dict:
    отчёт.часть(5, "Десять контрольных вопросов в обоих режимах")
    прогон = qa.прогнать(отвечатель, вопросы, судья, модель)
    # Отчёт — в свой каталог: RAG-QA.md в корне с Дня 23 — сравнение пяти
    # режимов, и регрессия Дня 22 в чек-листе затирала его двумя.
    путь = qa.записать(прогон, os.path.join(КОРЕНЬ, "reports", "rag-22"))
    текст = qa.в_markdown(прогон).split("## Ответы целиком")[0]
    for строка in текст.splitlines():
        if строка.startswith("|"):
            отчёт("  " + строка)
    без, с = прогон.итог(БЕЗ_RAG), прогон.итог(С_RAG)
    отчёт.пункт(с["верно_по_правилам"] > без["верно_по_правилам"],
                f"с RAG верно по правилам {с['верно_по_правилам']} из 10 против "
                f"{без['верно_по_правилам']} без RAG")
    отчёт.пункт(с["ловушек_пройдено"] == с["ловушек"],
                f"с RAG обе ловушки — «в документах этого нет» ({с['ловушек_пройдено']} из {с['ловушек']})")
    if судья:
        # Без RAG модель то выдумывает, то честно отказывается: бывало и 1, и 7.
        # Утверждение дня — что с RAG выдумок нет или меньше, а не что без RAG
        # их обязательно больше нуля.
        отчёт.пункт(с["выдумок"] == 0 or с["выдумок"] < без["выдумок"],
                    f"выдуманная конкретика по судье: с RAG {с['выдумок']}, без RAG {без['выдумок']}")
    отчёт.пункт(с["источник_процитирован"] >= с["с_источником"] - 2,
                f"с RAG нужный источник найден в {с['источник_найден']} и процитирован в "
                f"{с['источник_процитирован']} из {с['с_источником']} вопросов с ответом")
    отчёт.пункт(os.path.exists(путь), f"отчёт с ответами целиком: {os.path.relpath(путь, КОРЕНЬ)}")
    return прогон.to_dict()


def часть_6(отчёт: Отчёт, модель: str) -> None:
    отчёт.часть(6, "Агент с двумя режимами — отдельным процессом cli.py")
    вопрос = "Сколько стоит базовая лицензия OpenScape Business V2 для АТС?"
    готово = subprocess.run(
        [sys.executable, os.path.join(КОРЕНЬ, "cli.py"), "--память-в",
         os.path.join(КОРЕНЬ, "memory"), "--модель", модель, "--сравнить-rag", вопрос],
        capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=300, cwd=КОРЕНЬ)
    вывод = готово.stdout + готово.stderr
    отчёт(f"  $ python cli.py --сравнить-rag «{вопрос}»")
    for строка in вывод.splitlines():
        if строка.startswith(("БЕЗ RAG", "С RAG", "  [", "Источники")) or "34" in строка:
            отчёт("    " + строка[:160])
    отчёт.пункт(готово.returncode == 0 and "Вы:" not in вывод, "команда завершилась сама, без диалога")
    отчёт.пункт("БЕЗ RAG" in вывод and "С RAG" in вывод, "оба режима в одном ответе агента")
    отчёт.пункт("34 640" in вывод or "34640" in вывод, "с RAG — 34 640 из листа «4.Лицензии АТС»")
    отчёт.пункт("Лицензии АТС" in вывод, "источник назван: лист «4.Лицензии АТС»")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 22: первый RAG-запрос.")
    разбор.add_argument("--модель", dest="model", default="", help="модель ответов (по роли — ds-flash)")
    разбор.add_argument("--без-судьи", dest="no_judge", action="store_true")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ")
    аргументы = разбор.parse_args()

    модель = аргументы.model or catalog.for_role("ответ-по-документам", 0)
    отчёт = Отчёт()
    начало = time.monotonic()
    индексатор = Индексатор()
    клиент = Client()
    отвечатель = Отвечатель(индексатор, клиент)
    отчёт(LINE)
    отчёт(f"Проверка Дня 22: первый RAG-запрос · модель {модель} · судья "
          f"{'выключен' if аргументы.no_judge else catalog.for_role('судья-ответов', 0)}")
    try:
        вопросы = часть_1(отчёт, индексатор)
        с_rag = часть_2(отчёт, отвечатель, модель)
        часть_3(отчёт, отвечатель, модель, с_rag)
        часть_4(отчёт, отвечатель, клиент, модель, not аргументы.no_judge)
        часть_5(отчёт, отвечатель, вопросы, модель, not аргументы.no_judge)
        часть_6(отчёт, модель)
    finally:
        клиент.close()
    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
