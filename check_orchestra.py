def часть_3(отчёт: Отчёт, агент: MemoryAgent, серверы: list) -> dict:
    отчёт.часть(3, "Маршрут моделью: выбор по описаниям серверов")
    м = маршруты.Маршрутизатор(серверы, клиент=агент.client)
    итоги: dict[str, list[str]] = {}
    ожидания = [
        ("Что в работе по задачам миграции?", {"tracker"}),
        ("Как в документации django устроены геополя PointField?", {"deepwiki"}),
        ("Найди в памяти, что мы решали про порядок миграции, и сохрани отчёт файлом",
         {"pipeline"}),
        (f"Разбери задачу {ЗАДАЧА}: прочитай её в трекере и подними, что о ней знает "
         "наша память", {"tracker", "pipeline"}),
    ]
    for вопрос, нужно in ожидания:
        маршрут = м.выбрать(вопрос)
        итоги[вопрос] = маршрут.серверы
        отчёт.пункт(нужно <= set(маршрут.серверы),
                    f"«{вопрос[:46]}…» → {маршрут.серверы} ({маршрут.способ})")
    способы = {м.выбрать(в).способ for в, _ in ожидания[:2]}
    отчёт.пункт(способы <= {маршруты.МОДЕЛЬ, маршруты.ОБА},
                f"выбор делает модель (правила лишь добирают пропущенное): {способы}")
    последний = list(итоги.values())[-1]
    отчёт.пункт(len(последний) >= 2,
                f"на запросе из двух частей выбраны оба сервера: {последний}")
    return итоги


def часть_4(отчёт: Отчёт, агент: MemoryAgent, вопрос: str) -> dict:
    отчёт.часть(4, "План: что агент собирается сделать, до первого вызова")
    агент._направить(вопрос)
    агент.подключить_инструменты()
    оркестр = агент._оркестр()
    план = оркестр.план(вопрос)
    доступные = {и.полное_имя for и in агент.toolbox.инструменты}
    отчёт.пункт(bool(план.шаги), f"план составлен: {план.словами()[:120]}")
    отчёт.пункт(all(ш.инструмент in доступные for ш in план.шаги),
                "все инструменты плана существуют: " + ", ".join(план.инструменты()))
    отчёт.пункт(len(план.серверы()) >= 2,
                f"план пересекает несколько серверов: {план.серверы()}")
    замечания = агент.правила_порядка.проверить_план(план.инструменты())
    отчёт.пункт(not замечания,
                "порядок в плане не нарушает правил зависимостей"
                + (f" (замечания: {замечания})" if замечания else ""))
    отчёт.пункт(all(ш.зачем for ш in план.шаги),
                "у каждого шага записано, зачем он нужен")
    return план.to_dict()


def часть_5(отчёт: Отчёт, агент: MemoryAgent, база: str, отчёты: str,
            вопрос: str) -> dict:
    отчёт.часть(5, "Длинный флоу: вызовы к разным серверам подряд")
    начало = time.monotonic()
    флоу = агент.флоу(вопрос)
    отчёт(f"      флоу №{флоу['номер']} за {_секунды(time.monotonic() - начало)}: "
          f"кругов {флоу['кругов']}, вызовов {флоу['вызовов']}")
    for шаг in флоу["шаги"]:
        метка = f"по плану {шаг['по_плану']}" if шаг["по_плану"] else "сверх плана"
        отчёт(f"      {шаг['место']}. {шаг['инструмент']} [{шаг['состояние']}, {метка}]")

    сделанные = [ш for ш in флоу["шаги"] if ш["состояние"] == "выполнен"]
