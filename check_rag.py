# Стандартная страница — 1800 знаков: так считают переводчики и издатели, и так
# «20–30 страниц» из задания превращается в число, которое можно проверить.
ЗНАКОВ_НА_СТРАНИЦУ = 1800
ПОЛЯ_ПАСПОРТА = ("chunk_id", "source", "title", "section", "pages", "strategy", "tokens")


def часть_1(отчёт: Отчёт, индексатор: rag.Индексатор) -> list:
    отчёт.часть(1, "Документы прочитаны")
    можно, почему = ocr_доступен()
    отчёт(f"  OCR: {'tesseract готов' if можно else почему}")
    старт = time.monotonic()
    документы = индексатор.извлечь()
    отчёт(f"  извлечение {_секунды(time.monotonic() - старт)} (OCR берётся из кэша, если был)")
    for д in документы:
        единица = "листов" if д.вид == "таблица" else "стр."
        ocr = f", OCR {len(д.распознано)} стр." if д.распознано else ""
        отчёт.пункт(д.символов > 0, f"{д.источник} — {д.вид}, {единица} {д.страниц}, "
                                    f"символов {д.символов}{ocr}")
        for з in д.замечания:
            отчёт(f"      ⚠ {з}")
    страниц_pdf = sum(д.страниц for д in документы if д.вид == "pdf")
    распознано = sum(len(д.распознано) for д in документы)
    символов = sum(д.символов for д in документы)
    отчёт.пункт(страниц_pdf >= 20, f"страниц PDF {страниц_pdf} (из них сканов, прошедших OCR, "
                                    f"{распознано}) — задание просит 20–30")
    отчёт.пункт(символов >= 20 * ЗНАКОВ_НА_СТРАНИЦУ,
                f"символов текста {символов} ≈ {символов // ЗНАКОВ_НА_СТРАНИЦУ} стандартных страниц")
    return документы


def часть_2(отчёт: Отчёт, индексатор: rag.Индексатор, документы: list,
            пересобрать: bool) -> dict:
    отчёт.часть(2, "Сборка индекса: чанки → эмбеддинги → SQLite")
    индексы = {и["стратегия"] for и in индексатор.хранилище.индексы()}
    свежий = индексы >= set(rag.СТРАТЕГИИ) and not пересобрать
    итог = индексатор.построить(документы=документы)
    for с, д in итог["стратегии"].items():
        отчёт.пункт(д["чанков"] > 0,
                    f"«{с}» {д['параметры']}: чанков {д['чанков']}, вектор {д['размерность']}, "
                    f"векторы {_секунды(д['секунд_векторов'])}, из кэша {д['из_кэша']}")
    if свежий:
        отчёт("  (индекс уже был — векторы взяты из кэша, это и проверяется ниже)")
    повтор = индексатор.построить(документы=документы)
    все_из_кэша = all(д["из_кэша"] == д["чанков"] for д in повтор["стратегии"].values())
    отчёт.пункт(все_из_кэша, f"повторная сборка берёт все векторы из кэша: "
                             f"{_секунды(повтор['секунд'])} на обе стратегии")
    return итог


def часть_3(отчёт: Отчёт, индексатор: rag.Индексатор) -> None:
    отчёт.часть(3, "Чанки и их метаданные")
    хранилище = индексатор.хранилище
    все_ид: list[str] = []
    for с in rag.СТРАТЕГИИ:
        чанки = хранилище.чанки(с)
        все_ид += [ч.chunk_id for ч in чанки]
        без_полей = [ч.chunk_id for ч in чанки
                     if not all(ч.паспорт().get(п) not in (None, "") for п in ПОЛЯ_ПАСПОРТА)]
        отчёт.пункт(not без_полей, f"«{с}»: у всех {len(чанки)} чанков заполнены "
                                   f"{', '.join(ПОЛЯ_ПАСПОРТА)}" +
                    (f" — пусто у {без_полей[:3]}" if без_полей else ""))
        пример = next((ч for ч in чанки if ч.пункт), чанки[0])
        отчёт(f"      пример: {пример.паспорт()}")
    отчёт.пункт(len(все_ид) == len(set(все_ид)), f"chunk_id уникальны: {len(все_ид)} на обе стратегии")

    фикс = хранилище.индекс("фикс")["параметры"]
    чанки = хранилище.чанки("фикс")
    большие = [ч for ч in чанки if ч.токенов > фикс["размер"] * 1.1]
    отчёт.пункт(not большие, f"«фикс» держит размер {фикс['размер']} токенов "
                             f"(больше — {len(большие)})")
    перекрыты = 0
    пар = 0
    for до, после in zip(чанки, чанки[1:]):
        if до.источник != после.источник:
            continue
        пар += 1
        if " ".join(после.текст.split()[:4]) in до.текст:
            перекрыты += 1
    отчёт.пункт(перекрыты == пар, f"«фикс» перекрывается: {перекрыты} из {пар} соседних пар "
                                  f"начинаются внутри предыдущего чанка")
    структура = хранилище.чанки("структура")
    смешанные = [ч for ч in структура if len({р.split(" › ")[0] for р in ч.разделы}) > 1]
    отчёт.пункт(not смешанные, f"«структура» не смешивает верхние разделы: чанков "
                               f"{len(структура)}, смешанных {len(смешанные)}")


def часть_4(отчёт: Отчёт, индексатор: rag.Индексатор) -> None:
    отчёт.часть(4, "Эмбеддинги")
    э = индексатор.эмбеддер
    а, б, в = э.векторы(["Срок ежемесячной оплаты услуг — не позднее 20 числа месяца",
                         "До какого числа надо платить за связь каждый месяц?",
                         "Лицензии на антивирус Касперского для филиалов"])
    отчёт.пункт(True, f"эмбеддер {э.имя}, размерность {len(а)}")
    длины = [float(np.linalg.norm(x)) for x in (а, б, в)]
    отчёт.пункт(all(abs(д - 1) < 1e-3 for д in длины),
                f"векторы нормированы по длине: {', '.join(f'{д:.4f}' for д in длины)}")
    близко, далеко = float(np.dot(а, б)), float(np.dot(а, в))
    отчёт.пункт(близко > далеко, f"перефразировка ближе постороннего: косинус {близко:.3f} "
                                 f"против {далеко:.3f}")


def часть_5(отчёт: Отчёт, база: str) -> None:
    отчёт.часть(5, "Индекс на диске — прямым SQL, мимо нашего кода")
    отчёт(f"  файл: {база} ({os.path.getsize(база) // 1024} КБ)")
    с = sqlite3.connect(база)
    try:
        таблицы = {р[0] for р in с.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        отчёт.пункт({"индексы", "документы", "чанки", "кэш_векторов"} <= таблицы,
                    f"таблицы: {', '.join(sorted(таблицы))}")
        for стратегия, эмбеддер, размерность in с.execute(
                "SELECT стратегия, эмбеддер, размерность FROM индексы ORDER BY стратегия").fetchall():
            n, длины = с.execute("SELECT COUNT(*), GROUP_CONCAT(DISTINCT LENGTH(вектор)) "
                                 "FROM чанки WHERE стратегия=?", (стратегия,)).fetchone()
            отчёт.пункт(str(длины) == str(размерность * 4),
                        f"«{стратегия}»: строк {n}, вектор в BLOB {длины} байт = {размерность} × float32 "
                        f"({эмбеддер})")
            ряд = с.execute("SELECT вектор, источник, раздел FROM чанки WHERE стратегия=? LIMIT 1",
                            (стратегия,)).fetchone()
            вектор = np.frombuffer(ряд[0], dtype=np.float32)
            отчёт.пункт(abs(float(np.linalg.norm(вектор)) - 1) < 1e-3,
                        f"вектор первого чанка из BLOB нормирован: {float(np.linalg.norm(вектор)):.4f} "
                        f"({ряд[1]} · {ряд[2][:40]})")
    finally:
        с.close()


def часть_6(отчёт: Отчёт, индексатор: rag.Индексатор) -> None:
    отчёт.часть(6, "Поиск через MCP-сервер docs отдельным процессом")
    os.environ["RAG_DIR"] = os.path.dirname(индексатор.база)
    os.environ["DOCS_DIR"] = индексатор.каталог
    os.environ["RAG_EMBEDDER"] = индексатор.эмбеддер.имя
    ящик = amcp.Toolbox(["docs"], os.path.join(КОРЕНЬ, "mcp-servers.json"))
    try:
        ящик.открыть()
        имена = sorted(и.полное_имя for и in ящик.инструменты)
        отчёт.пункт("docs__search_docs" in имена, f"инструменты: {', '.join(имена)}")
        вопрос = "До какого числа нужно оплачивать услуги связи по договору VPN?"
        итог = ящик.вызвать("docs__search_docs", {"query": вопрос, "limit": 3})
        отчёт.пункт(итог.ок, f"вызов за {_секунды(итог.секунд)}" + ("" if итог.ок else f": {итог.текст}"))
        находки = (итог.данные or {}).get("hits", [])
        отчёт(f"  «{вопрос}»")
        for н in находки:
            отчёт(f"    {н['rank']}. [{н['score']:.3f}] {н['source']} · {н['section']}, "
                  f"п. {н['clause'] or '—'} · стр. {н['pages']} · {н['chunk_id']}")
        отчёт.пункт(any("20 числа" in н["text"] for н in находки),
                    "среди первых трёх — пункт договора со сроком «не позднее 20 числа»")
        отчёт.пункт(bool(находки) and all(н.get("source") and н.get("chunk_id") for н in находки),
                    "у каждой находки есть источник и chunk_id — есть на что сослаться")
    finally:
        ящик.close()


def часть_7(отчёт: Отчёт, индексатор: rag.Индексатор, документы: list) -> dict:
    отчёт.часть(7, "Сравнение двух стратегий")
    сравнение = evaluate.сравнить(индексатор, документы=документы)
    путь = evaluate.записать(сравнение, os.path.dirname(индексатор.база))
    for строка in evaluate.в_markdown(сравнение).splitlines():
        if строка.startswith("|") or строка.startswith("По MRR"):
            отчёт("  " + строка)
        if строка.startswith("### По вопросам"):
            break
    н = сравнение["нарезка"]
    отчёт.пункт(н["структура"]["доля_разорванных"] <= н["фикс"]["доля_разорванных"],
                f"«структура» режет абзацы и строки не чаще «фикс»: "
                f"{н['структура']['доля_разорванных']:.0%} против {н['фикс']['доля_разорванных']:.0%}")
    поиск = сравнение.get("поиск")
    отчёт.пункт(bool(поиск), f"эталонных вопросов: {поиск['вопросов'] if поиск else 0}")
    if поиск:
        лучшая = evaluate.лучшая(сравнение)
        отчёт.пункт(all(м["hit@5"] > 0 for м in поиск["стратегии"].values()),
                    "обе стратегии хоть что-то находят (hit@5 > 0)")
        отчёт(f"  по MRR выигрывает «{лучшая}»")
    отчёт.пункт(os.path.exists(путь), f"отчёт записан: {os.path.relpath(путь, КОРЕНЬ)}")
    return сравнение


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 21: индексация документов.")
    разбор.add_argument("--эмбеддер", dest="embedder", default="ollama",
                        help="ollama[:модель] (по умолчанию) или хэш — тогда индекс временный")
    разбор.add_argument("--пересобрать", dest="rebuild", action="store_true",
                        help="стереть готовый индекс и собрать заново")
    разбор.add_argument("--документы-из", dest="docs", default="", metavar="ПУТЬ")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ",
                        help="дописать отчёт в файл")
    аргументы = разбор.parse_args()

    отчёт = Отчёт()
    начало = time.monotonic()
    временный = ""
    индекс = ""
    if аргументы.embedder in ("хэш", "hash"):
        временный = tempfile.mkdtemp(prefix="check-rag-")
        индекс = временный
    индексатор = rag.Индексатор(документы=аргументы.docs, индекс=индекс,
                                эмбеддер=аргументы.embedder)
    беда = индексатор.эмбеддер.проверить()
    if беда:
        print(f"Эмбеддер недоступен: {беда}", file=sys.stderr)
        return 2
    if аргументы.rebuild:
        for с in rag.СТРАТЕГИИ:
            индексатор.хранилище.удалить(с)

    отчёт(LINE)
    отчёт(f"Проверка Дня 21: индекс документов · {индексатор.каталог}")
    отчёт(f"Эмбеддер {индексатор.эмбеддер.имя} · индекс {индексатор.база}")
    try:
        документы = часть_1(отчёт, индексатор)
        часть_2(отчёт, индексатор, документы, аргументы.rebuild)
        часть_3(отчёт, индексатор)
        часть_4(отчёт, индексатор)
        часть_5(отчёт, индексатор.база)
        часть_6(отчёт, индексатор)
        часть_7(отчёт, индексатор, документы)
    finally:
        if временный:
            import shutil
            shutil.rmtree(временный, ignore_errors=True)

    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
