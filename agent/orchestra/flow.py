"""Оркестр: длинный флоу — план, вызовы инструментов разных серверов, сверка.

Это ответ на главное требование Дня 20: «длинный флоу взаимодействия с
несколькими MCP-серверами». Обычный ответ агента (agent.py) даёт модели три
круга инструментов и на этом останавливается — сознательно: разговор не должен
незаметно превращаться в получасовую работу. Флоу — другая вещь, и запускают
его отдельно: у него есть план, бюджет, протокол и право остановиться и
подождать человека.

Порядок такой:

  1. Маршрут (routing.py) — какие серверы вообще поднимать под этот запрос.
     Делается до флоу, снаружи: флоу получает уже открытый инструментарий.
  2. План (plan.py) — отдельный дешёвый круг модели без инструментов: какие
     вызовы и в каком порядке. Ничего не выполняется, план виден человеку.
  3. Исполнение — круги модели с инструментами. Каждая просьба о вызове
     проходит три заслона: есть ли такой инструмент, пускает ли правило
     порядка (order.py), не меняет ли он чужие данные без подтверждения.
  4. Сверка — что из плана сделано, что пропущено, что появилось сверх него и
     соблюдён ли порядок. Это и есть проверяемый ответ на «корректность выбора
     и порядка вызовов».

Отклонение от плана — не ошибка. Модель узнаёт в работе то, чего не знала,
когда планировала: задача закрыта, в памяти пусто, документация не отвечает.
Запрещать шаг вне плана значило бы запрещать узнавать. Поэтому отклонения
разрешены и попадают в сверку, а блокируется только нарушение порядка — там
цена другая: комментарий, написанный до чтения задачи, сочинён моделью.

Бюджета два: круги модели и вызовы инструментов. Одного мало — круг без
вызовов (модель «думает вслух») и круг с пятью вызовами стоят по-разному, а
кончиться может и то и другое. Исчерпан любой — флоу закрывается честно, со
списком несделанного, а не молчанием.

Публичное API:
  Оркестр(клиент, ящик, хранилище, порядок, ...)
      .запустить(вопрос, основа, ...) -> Флоу
      .продолжить(номер, основа)      -> Флоу
  Сверка / сверить(план, шаги)        — план против факта
  ОшибкаФлоу
"""

from __future__ import annotations

import logging
import time
from dataclasses import dataclass, field
from typing import Any, Callable

from agent.orchestra import plan as планирование
from agent.orchestra.order import Порядок
from agent.orchestra.plan import План
from agent.orchestra.store import (
    ГОТОВ, ЖДЁТ, ОБОРВАН, ОЖИДАНИЕ, ОТКАЗАНО, ОТКЛОНЁН, ОТЛОЖЕН, ОШИБКА, СБОЙ,
    ВЫПОЛНЕН, FlowStore, Флоу, ШагФлоу)

log = logging.getLogger("agent.orchestra")

# Бюджет по умолчанию. Восемь кругов — это заметно больше трёх кругов обычного
# ответа и хватает на шесть-семь вызовов вперемежку с рассуждением; двенадцать
# вызовов — потолок, за которым флоу уже не «длинный», а бесконечный.
ПРЕДЕЛ_КРУГОВ = 8
ПРЕДЕЛ_ВЫЗОВОВ = 12

# Сколько символов ответа инструмента кладётся в протокол шага. Модели уходит
# полный ответ — обрезается только то, что хранится.
ПРЕДЕЛ_ТЕКСТА = 1200


class ОшибкаФлоу(RuntimeError):
    """Флоу нельзя запустить или продолжить."""


@dataclass
class Сверка:
    """План против факта: выбор и порядок вызовов."""

    в_плане: int = 0
    по_плану: int = 0
    пропущено: list[str] = field(default_factory=list)
    сверх_плана: list[str] = field(default_factory=list)
    отклонено: list[str] = field(default_factory=list)    # не пущены правилом порядка
    порядок_ок: bool = True
    последовательность: list[str] = field(default_factory=list)

    @property
    def по_плану_целиком(self) -> bool:
        return self.в_плане > 0 and self.по_плану == self.в_плане and not self.пропущено

    def словами(self) -> str:
        if not self.в_плане:
            цепочка = " → ".join(self.последовательность) or "вызовов не было"
            return f"Плана не было; вызовы: {цепочка}"
        части = [f"по плану {self.по_плану} из {self.в_плане}"]
        if self.пропущено:
            части.append(f"пропущено: {', '.join(self.пропущено)}")
        if self.сверх_плана:
            части.append(f"сверх плана: {', '.join(self.сверх_плана)}")
        if self.отклонено:
            части.append(f"остановлено по порядку: {', '.join(self.отклонено)}")
        части.append("порядок соблюдён" if self.порядок_ок else "порядок нарушен")
        return "; ".join(части)

    def to_dict(self) -> dict[str, Any]:
        return {"в_плане": self.в_плане, "по_плану": self.по_плану,
                "пропущено": list(self.пропущено), "сверх_плана": list(self.сверх_плана),
                "отклонено": list(self.отклонено), "порядок_ок": self.порядок_ок,
                "последовательность": list(self.последовательность),
                "словами": self.словами()}


def сверить(план: План, шаги: list[ШагФлоу]) -> Сверка:
    """Сравнивает намеченное с сделанным.

    Порядок считается соблюдённым, если шаги плана, которые действительно
    выполнились, идут в фактической цепочке в том же относительном порядке.
    Лишние вызовы между ними порядок не ломают: они ничего не переставляют.
    """
    сделанные = [ш.инструмент for ш in шаги if ш.состояние == ВЫПОЛНЕН and ш.ок]
    сверка = Сверка(в_плане=len(план.шаги), последовательность=list(сделанные))
    сверка.отклонено = [ш.инструмент for ш in шаги if ш.состояние == ОТКЛОНЁН]

    осталось = list(сделанные)
    из_плана: list[str] = []
    for шаг in план.шаги:
        if шаг.инструмент in осталось:
            осталось.remove(шаг.инструмент)
            из_плана.append(шаг.инструмент)
            шаг.сделан = True
            сверка.по_плану += 1
        else:
            сверка.пропущено.append(шаг.инструмент)
    сверка.сверх_плана = осталось

    # Относительный порядок: выкинуть из факта всё, чего нет в плане, и сравнить
    # с последовательностью плана, оставив только выполненные его шаги.
    ожидаемый = [ш.инструмент for ш in план.шаги if ш.сделан]
    фактический = [и for и in сделанные if и in ожидаемый]
    # Повторы одного инструмента сравниваются по первому вхождению: план не
    # обещает, сколько раз инструмент позовут, он обещает очерёдность.
    видно: list[str] = []
    for имя in фактический:
        if имя not in видно:
            видно.append(имя)
    сверка.порядок_ок = видно == list(dict.fromkeys(ожидаемый)) and not сверка.отклонено
    return сверка


class Оркестр:
    """Исполнитель длинного флоу: план, круги вызовов, пауза, сверка."""

    def __init__(
        self,
        клиент: Any,
        ящик: Any,
        хранилище: FlowStore,
        порядок: Порядок | None = None,
        *,
        модель: str = "",
        модель_плана: str = "",
        кругов: int = ПРЕДЕЛ_КРУГОВ,
        вызовов: int = ПРЕДЕЛ_ВЫЗОВОВ,
        подтверждать: bool = True,
        заявка: Callable[[str, dict[str, Any], str], int] | None = None,
        читать_заявку: Callable[[int], dict[str, Any] | None] | None = None,
        кто: str = "",
        пользователь: str = "",
    ) -> None:
        self.клиент = клиент
        self.ящик = ящик
        self.хранилище = хранилище
        self.порядок = порядок or Порядок()
        self.модель = модель
        self.модель_плана = модель_плана or модель
        self.кругов = max(1, int(кругов))
        self.вызовов = max(1, int(вызовов))
        self.подтверждать = подтверждать
        self._завести_заявку = заявка
        self._прочитать_заявку = читать_заявку
        self.кто = кто
        self.пользователь = пользователь

    # --- план -----------------------------------------------------------------

    def план(self, вопрос: str) -> План:
        """Отдельный круг без инструментов: что агент собирается делать."""
        from agent.llm import LLMError

        перечень = [{"имя": и.полное_имя, "описание": и.заголовок or и.описание[:100]}
                    for и in self.ящик.инструменты]
        доступные = [и["имя"] for и in перечень]
        ключ = self.модель_плана or self.модель
        try:
            ответ = self.клиент.call(ключ, планирование.промпт(вопрос, перечень),
                                     max_tokens=700, temperature=0.0)
        except LLMError as exc:
            return План(замечания=[f"план не составлен: {exc}"], модель=ключ)
        return планирование.разобрать(ответ.text, доступные, self.порядок,
                                      модель=ответ.model_key)

    # --- запуск и продолжение -------------------------------------------------

    def запустить(self, вопрос: str, основа: list[dict[str, Any]],
                  маршрут: dict[str, Any] | None = None, задача: str = "",
                  планировать: bool = True) -> Флоу:
        """Полный флоу от плана до сверки. «основа» — сообщения обычного промпта."""
        вопрос = (вопрос or "").strip()
        if not вопрос:
            raise ОшибкаФлоу("Пустой вопрос: с чего начинать флоу?")
        if not getattr(self.ящик, "инструменты", None):
            raise ОшибкаФлоу(
                "Инструменты недоступны: длинный флоу без них — это обычный вопрос. "
                "Проверьте маршрут и доступность серверов.")

        серверы = sorted({и.сервер for и in self.ящик.инструменты})
        запись = self.хранилище.начать(
            вопрос, серверы=серверы, маршрут=маршрут or {}, кто=self.кто,
            пользователь=self.пользователь, задача=задача, модель=self.модель)
        начало = time.monotonic()

        план = self.план(вопрос) if планировать else План(
            замечания=["план не запрашивался"])
        self.хранилище.записать_план(запись.номер, план.to_dict())
        запись.план = план.to_dict()
        запись.цель = план.цель

        return self._круги(запись, основа, план, цепочка=[], круг=1, начало=начало)

    def продолжить(self, номер: int, основа: list[dict[str, Any]]) -> Флоу:
        """Возобновляет флоу, остановленный на подтверждении.

        Результат подтверждённого вызова берётся из заявки: исполнил его
        confirm_call, и переделывать вызов было бы вторым изменением чужих
        данных на одно «да» человека.
        """
        запись = self.хранилище.флоу(int(номер))
        if запись is None:
            raise ОшибкаФлоу(f"Флоу №{номер} нет.")
        if not запись.ждёт:
            raise ОшибкаФлоу(f"Флоу №{номер} не ждёт подтверждения: он {запись.состояние}.")

        ожидание = dict(запись.ожидание or {})
        решение = self._прочитать_заявку(запись.заявка) if self._прочитать_заявку else None
        if решение is None:
            raise ОшибкаФлоу(f"Заявки №{запись.заявка} нет — продолжать нечего.")
        состояние = str(решение.get("состояние", ""))
        if состояние == "ждёт":
            raise ОшибкаФлоу(
                f"Заявка №{запись.заявка} ещё не решена: подтвердите или отклоните её "
                f"(«--подтвердить {запись.заявка}»), тогда флоу продолжится.")

        место = len(запись.шаги) + 1
        инструмент = str(ожидание.get("инструмент", ""))
        if состояние == "выполнена":
            результат = решение.get("результат") or {}
            текст = str(результат.get("текст", "")) or "Вызов выполнен."
            for_модели = f"Вызов выполнен после подтверждения человеком.\n{текст}"
            self.хранилище.записать_шаг(
                запись.номер, место, инструмент, состояние=ВЫПОЛНЕН, ок=True,
                аргументы=ожидание.get("аргументы"), текст=текст[:ПРЕДЕЛ_ТЕКСТА],
                причина=f"подтверждена заявка №{запись.заявка}",
                круг=запись.кругов, по_плану=int(ожидание.get("по_плану", 0)),
                зачем=str(ожидание.get("зачем", "")))
        else:
            почему = str(решение.get("почему", "")) or "человек отклонил вызов"
            for_модели = (f"Вызов не выполнен: {почему}. Продолжай без него и скажи "
                          "человеку, чего в итоге не сделано.")
            self.хранилище.записать_шаг(
                запись.номер, место, инструмент,
                состояние=ОТКАЗАНО if состояние == "отклонена" else ОШИБКА, ок=False,
                аргументы=ожидание.get("аргументы"), причина=почему, круг=запись.кругов,
                по_плану=int(ожидание.get("по_плану", 0)),
                зачем=str(ожидание.get("зачем", "")))

        цепочка = list(запись.цепочка or [])
        цепочка.append({"role": "tool", "tool_call_id": str(ожидание.get("ид", "")),
                        "name": инструмент, "content": for_модели})
        self.хранилище.возобновить(запись.номер)

        свежая = self.хранилище.флоу(запись.номер)
        план = План.from_dict(свежая.план)
        return self._круги(свежая, основа, план, цепочка, круг=свежая.кругов + 1,
                           начало=time.monotonic() - свежая.секунд)

    # --- круги ----------------------------------------------------------------

    def _круги(self, запись: Флоу, основа: list[dict[str, Any]], план: План,
               цепочка: list[dict[str, Any]], круг: int, начало: float) -> Флоу:
        """Основной цикл: спросить модель, исполнить просьбы, повторить."""
        from agent.llm import LLMError

        инструменты = self.ящик.для_модели()
        наставление = {"role": "system", "content": self._наставление(план)}
        напомнили = False

        while круг <= self.кругов:
            сообщения = list(основа) + [наставление] + цепочка
            try:
                ответ = self.клиент.call(self.модель, сообщения, tools=инструменты)
            except LLMError as exc:
                return self._закрыть(запись, план, СБОЙ, "", f"модель не ответила: {exc}",
                                     начало)
            self.хранилище.отметить_круг(запись.номер, круг)
            запись.кругов = круг

            if not ответ.tool_calls:
                текст = (ответ.text or "").strip()
                осталось = self._несделанное(запись.номер, план)
                if осталось and not напомнили:
                    # Модели свойственно объявлять работу законченной на полпути.
                    # Одно напоминание — не спор: если пункт не нужен, она скажет
                    # об этом словами, и это попадёт в ответ человеку.
                    напомнили = True
                    цепочка.append(ответ.message or {"role": "assistant", "content": текст})
                    цепочка.append({"role": "system", "content":
                                    "Не сделаны пункты плана: " + ", ".join(осталось) +
                                    ". Выполни их или объясни, почему они не нужны."})
                    круг += 1
                    continue
                return self._закрыть(запись, план, ГОТОВ, текст, "", начало)

            цепочка.append(ответ.message)
            for место, просьба in enumerate(ответ.tool_calls):
                итог = self._просьба(запись, план, просьба, круг)
                if итог[0] == "пауза":
                    # Ответ на саму отложенную просьбу придёт после подтверждения —
                    # его допишет «продолжить». А вот остальные просьбы этого круга
                    # ответ получают сразу: протокол function calling требует
                    # сообщение роли tool на КАЖДЫЙ tool_call_id, иначе следующий
                    # запрос после паузы провалится с ошибкой формата.
                    for прочая in ответ.tool_calls[место + 1:]:
                        self._отложить(запись, прочая, круг)
                        цепочка.append({"role": "tool", "tool_call_id": прочая.ид,
                                        "name": прочая.имя, "content":
                                        "Вызов отложен: флоу ждёт подтверждения человека. "
                                        "Повтори его после продолжения, если он ещё нужен."})
                    self.хранилище.приостановить(запись.номер, итог[2], итог[3], цепочка,
                                                 секунд=time.monotonic() - начало)
                    return self.хранилище.флоу(запись.номер)
                цепочка.append({"role": "tool", "tool_call_id": просьба.ид,
                                "name": просьба.имя, "content": итог[1]})

            if self._израсходован(запись.номер):
                return self._добрать(запись, план, основа, наставление, цепочка, начало)
            круг += 1

        return self._добрать(запись, план, основа, наставление, цепочка, начало,
                             причина="кончились круги модели")

    def _просьба(self, запись: Флоу, план: План, просьба: Any,
                 круг: int) -> tuple[str, str, int, dict[str, Any]]:
        """Одна просьба о вызове. Возвращает («ответ»|«пауза», текст, заявка, ожидание)."""
        место = len(self.хранилище.шаги(запись.номер)) + 1
        по_плану, зачем = self._из_плана(план, просьба.имя)

        if просьба.ошибка:
            self.хранилище.записать_шаг(
                запись.номер, место, просьба.имя, состояние=ОШИБКА, ок=False,
                причина=просьба.ошибка, круг=круг, по_плану=по_плану, зачем=зачем)
            return ("ответ", f"Вызов не выполнен: {просьба.ошибка}. "
                             "Пришли аргументы корректным объектом JSON.", 0, {})

        инструмент = self.ящик.найти(просьба.имя)
        if инструмент is None:
            доступные = ", ".join(и.полное_имя for и in self.ящик.инструменты)
            self.хранилище.записать_шаг(
                запись.номер, место, просьба.имя, состояние=ОШИБКА, ок=False,
                аргументы=просьба.аргументы, причина="такого инструмента нет", круг=круг,
                по_плану=по_плану, зачем=зачем)
            return ("ответ", f"Вызов не выполнен: инструмента «{просьба.имя}» нет. "
                             f"Доступны: {доступные}.", 0, {})

        # Заслон порядка. Считаются только успешные вызовы: неудачное чтение
        # задачи данных не дало, а значит, и права писать в неё не открыло.
        сделано = [ш.инструмент for ш in self.хранилище.шаги(запись.номер)
                   if ш.состояние == ВЫПОЛНЕН and ш.ок]
        вердикт = self.порядок.проверить(просьба.имя, сделано)
        if not вердикт.можно:
            self.хранилище.записать_шаг(
                запись.номер, место, просьба.имя, состояние=ОТКЛОНЁН, ок=False,
                аргументы=просьба.аргументы, причина=вердикт.почему, круг=круг,
                по_плану=по_плану, зачем=зачем)
            log.info("Флоу %d: «%s» отклонён по порядку", запись.номер, просьба.имя)
            return ("ответ", f"Вызов не выполнен: нарушен порядок. {вердикт.почему}",
                    0, {})

        # Заслон подтверждения. Для флоу он означает паузу, а не отказ: всё
        # добытое сохраняется, и после «да» работа продолжится с этого места.
        if self.подтверждать and self.ящик.меняет(просьба.имя, просьба.аргументы):
            if self._завести_заявку is None:
                self.хранилище.записать_шаг(
                    запись.номер, место, просьба.имя, состояние=ОТКАЗАНО, ок=False,
                    аргументы=просьба.аргументы, причина="некому подтвердить вызов",
                    круг=круг, по_плану=по_плану, зачем=зачем)
                return ("ответ", "Вызов не выполнен: меняющий вызов требует подтверждения "
                                 "человека, а подтверждать некому.", 0, {})
            номер = self._завести_заявку(просьба.имя, просьба.аргументы, запись.запрос)
            self.хранилище.записать_шаг(
                запись.номер, место, просьба.имя, состояние=ОЖИДАНИЕ, ок=False,
                аргументы=просьба.аргументы, круг=круг, по_плану=по_плану, зачем=зачем,
                причина=f"заявка №{номер} ждёт человека")
            ожидание = {"инструмент": просьба.имя, "аргументы": просьба.аргументы,
                        "ид": просьба.ид, "по_плану": по_плану, "зачем": зачем,
                        "место": место}
            return ("пауза", "", номер, ожидание)

        начало = time.monotonic()
        try:
            результат = self.ящик.вызвать(просьба.имя, просьба.аргументы)
        except Exception as exc:     # ToolboxError и всё, что вылезет из сеанса
            self.хранилище.записать_шаг(
                запись.номер, место, просьба.имя, состояние=ОШИБКА, ок=False,
                аргументы=просьба.аргументы, причина=str(exc)[:300], круг=круг,
                по_плану=по_плану, зачем=зачем, секунд=time.monotonic() - начало)
            return ("ответ", f"Вызов не выполнен: {exc}", 0, {})

        self.хранилище.записать_шаг(
            запись.номер, место, просьба.имя,
            состояние=ВЫПОЛНЕН if результат.ок else ОШИБКА, ок=bool(результат.ок),
            аргументы=просьба.аргументы, текст=результат.текст[:ПРЕДЕЛ_ТЕКСТА],
            причина="" if результат.ок else результат.текст[:200], круг=круг,
            по_плану=по_плану, зачем=зачем, секунд=time.monotonic() - начало)
        return ("ответ", результат.для_модели(), 0, {})

    def _отложить(self, запись: Флоу, просьба: Any, круг: int) -> None:
        место = len(self.хранилище.шаги(запись.номер)) + 1
        self.хранилище.записать_шаг(
            запись.номер, место, просьба.имя, состояние=ОТЛОЖЕН, ок=False,
            аргументы=getattr(просьба, "аргументы", {}), круг=круг,
            причина="флоу остановлен на подтверждении раньше этого вызова")

    # --- завершение -----------------------------------------------------------

    def _добрать(self, запись: Флоу, план: План, основа: list[dict[str, Any]],
                 наставление: dict[str, str], цепочка: list[dict[str, Any]],
                 начало: float, причина: str = "кончился бюджет вызовов") -> Флоу:
        """Бюджет исчерпан: просим ответить словами по тому, что уже добыто."""
        from agent.llm import LLMError

        хватит = {"role": "system", "content":
                  f"Инструменты больше недоступны: {причина}. Ответь по тому, что уже "
                  "получено, и честно скажи, чего сделать не удалось."}
        try:
            ответ = self.клиент.call(self.модель, list(основа) + [наставление] + цепочка
                                     + [хватит])
            текст = (ответ.text or "").strip()
        except LLMError as exc:
            текст = ""
            причина = f"{причина}; ответ без инструментов не получен: {exc}"
        if not текст:
            текст = ("Флоу остановлен: " + причина +
                     ". Что успели получить — в протоколе шагов.")
        return self._закрыть(запись, план, ОБОРВАН, текст, причина, начало)

    def _закрыть(self, запись: Флоу, план: План, состояние: str, итог: str,
                 ошибка: str, начало: float) -> Флоу:
        шаги = self.хранилище.шаги(запись.номер)
        сверка = сверить(план, шаги)
        self.хранилище.записать_план(запись.номер, план.to_dict())   # с отметками «сделан»
        return self.хранилище.завершить(
            запись.номер, состояние, итог=итог, ошибка=ошибка,
            сверка=сверка.to_dict(), секунд=time.monotonic() - начало)

    # --- мелочи ---------------------------------------------------------------

    def _наставление(self, план: План) -> str:
        """Системное сообщение круга исполнения: план и правила работы во флоу."""
        строки = ["Ты выполняешь длинный флоу: несколько вызовов инструментов подряд, "
                  "возможно с разных серверов."]
        if план.шаги:
            строки.append("План, который ты сам составил:\n" + план.для_модели())
            строки.append("Иди по плану. Отклоняйся, если данные того требуют, но скажи "
                          "об отклонении в итоговом ответе.")
        else:
            строки.append("Плана нет — действуй по обстоятельствам, но не зови инструменты "
                          "без нужды.")
        if len(self.порядок):
            строки.append("Порядок вызовов проверяется кодом: " + self.порядок.словами() +
                          ". Нарушенный вызов не исполнится.")
        строки.append("Данные бери вызовами, а не по памяти разговора. Когда все пункты "
                      "сделаны, ответь словами: что получилось и чего сделать не удалось.")
        return "\n\n".join(строки)

    def _из_плана(self, план: План, инструмент: str) -> tuple[int, str]:
        """Какому пункту плана соответствует вызов. 0 — вызов сверх плана."""
        for шаг in план.шаги:
            if шаг.инструмент == инструмент:
                return шаг.место, шаг.зачем
        return 0, ""

    def _несделанное(self, номер: int, план: План) -> list[str]:
        сделано = {ш.инструмент for ш in self.хранилище.шаги(номер)
                   if ш.состояние == ВЫПОЛНЕН and ш.ок}
        return [ш.инструмент for ш in план.шаги
                if ш.известен and ш.инструмент not in сделано]

    def _израсходован(self, номер: int) -> bool:
        запись = self.хранилище.флоу(номер, с_шагами=False)
        return bool(запись and запись.вызовов >= self.вызовов)


