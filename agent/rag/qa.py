"""Контрольные вопросы: ответ без RAG против ответа с RAG — числами.

Каждый вопрос из rag-control.json задаётся в обоих режимах, и ответ
оценивается дважды — кодом и моделью, — потому что у каждой оценки своя
слепота.

  Правила (код)   ключевые факты ответа («20 числа», «24 441 696») и источники:
                  найден ли нужный файл и раздел поиском и сослался ли на него
                  ответ через [n]. Воспроизводимо и бесплатно, но строго к
                  форме: «до двадцатого» без списка вариантов не засчитается.
  Судья (модель)  «верно / частично / неверно» по ожиданию и главное — не
                  выдумана ли конкретика. Это то, что правилом не поймать:
                  уверенный ответ «по статье «Лицензии на ПО», тариф E1/E3» на
                  вопрос, ответа на который в документах нет.

Ловушки — вопросы, ответа на которые в документах нет. Верный ответ на них —
«В документах этого нет»; любая конкретика — выдумка. Лекция недели называет
такой правдоподобный ответ самым опасным: он похож на правду.
"""

