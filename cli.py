def _аргументы_кратко(аргументы: dict) -> str:
    куски = []
    for ключ, значение in (аргументы or {}).items():
        текст = значение if isinstance(значение, str) else json.dumps(значение, ensure_ascii=False)
        текст = str(текст).replace("\n", " ")
        куски.append(f"{ключ}={текст if len(текст) <= 40 else текст[:40] + '…'}")
    return ", ".join(куски)


def показать_вызовы(ответ) -> None:
    """Что агент позвал ради этого ответа и что теперь ждёт подтверждения."""
    # Маршрут (День 20): какие серверы подняли ради этого ответа. Без этой
    # строки выбор агента остаётся невидимым — человек видит только вызовы и
    # не знает, из чего выбирали и почему чего-то не выбрали.
    маршрут = getattr(ответ, "маршрут", None)
    if маршрут and маршрут.get("серверы"):
        print(f"  ↳ маршрут ({маршрут.get('способ', '')}): "
              + ", ".join(маршрут["серверы"]))
    for вызов in ответ.вызовы:
        итог = f"за {_секунды(вызов['секунд'])}" if вызов["ок"] else "ОШИБКА"
        print(f"  ↳ {вызов['полное_имя']}({_аргументы_кратко(вызов['аргументы'])}) — {итог}")
        if not вызов["ок"]:
            print(f"     {вызов['текст'][:300]}")
        elif вызов["обрезан"]:
            print("     (ответ инструмента обрезан по длине)")
    for заявка in ответ.заявки:
        print(f"  ! Заявка {заявка['словами']} — меняет данные, нужен ваш ответ.")
        print(f"    Исполнить: --подтвердить {заявка['номер']} · "
              f"отклонить: --отклонить {заявка['номер']}")
    # Конвейер, выполненный ради этого ответа (День 19). Модель пишет итог
    # словами, а какие были шаги и что во что передалось — видно только здесь.
    прогон = getattr(ответ, "прогон", None)
    if прогон:
        print(f"  ↳ конвейер «{прогон['конвейер']}» — {прогон['состояние']}, "
              f"{прогон['сделано']} из {прогон['шагов']} шагов"
              + (f": {прогон['итог']}" if прогон.get("итог") else ""))
        for шаг in прогон.get("шаги", []):
            получил = "; ".join(шаг.get("получил", [])) or "—"
            print(f"     {шаг['шаг']} → {шаг['инструмент']}: получил {получил}")


def показать_свежее(ответ) -> None:
    """Что накопил работник, пока человека не было: сводка и напоминания.

    Печатается один раз: агент помечает их прочитанными, отдавая ответ. Иначе
    одна и та же сводка висела бы под каждым ответом и перестала бы читаться.
    """
    for напоминание in getattr(ответ, "напоминания", []) or []:
        print(f"  ⏰ Напоминание ({_время_коротко(напоминание['создано'])}): "
              f"{напоминание['текст']}")
    сводка = getattr(ответ, "сводка", None)
    if not сводка:
        return
    print(f"\n  📋 Свежая сводка №{сводка['номер']} "
          f"({_время_коротко(сводка['создана'])}, за {сводка['цифры'].get('окно', {}).get('за', '—')}):")
    текст = сводка["текст"] or scheduler_digest.словами(сводка["цифры"])
    for строка in текст.splitlines():
        print(f"     {строка}")


def _время_коротко(момент: str) -> str:
    """Время без даты, если это сегодня, — в консоли так читается быстрее."""
    момент = (момент or "").replace("T", " ")[:19]
    if not момент:
        return "—"
    сегодня = datetime.now().strftime("%Y-%m-%d")
    return момент[11:] if момент.startswith(сегодня) else момент


