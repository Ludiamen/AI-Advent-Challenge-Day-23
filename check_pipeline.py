def _файл_серверов(каталог: str, адрес: str, база: str, отчёты: str,
                   модель: str = "") -> str:
    """Свой mcp-servers.json: мок трекера, конвейеры и планировщик на временной базе."""
    путь = os.path.join(каталог, "mcp-servers.json")
    окружение_трекера = {"TRACKER_URL": адрес, "TRACKER_TOKEN": "mock-token",
                         "TRACKER_ORG": "mock-org", "TRACKER_QUEUE": "MIG",
                         "TRACKER_WRITE": "1"}
    окружение_конвейеров = {
        "SCHEDULER_DB": база, "REPORTS_DIR": отчёты,
        "MEMORY_DIR": os.path.dirname(база),
        "PIPELINES_FILE": os.path.join(КОРЕНЬ, "pipelines.json"),
        "MCP_CONFIG": путь,
        "PIPELINE_MODEL": модель or "нет",
        "GROQ_API_KEY": os.getenv("GROQ_API_KEY", ""),
        "ZAI_API_KEY": os.getenv("ZAI_API_KEY", ""),
        "DEEPSEEK_API_KEY": os.getenv("DEEPSEEK_API_KEY", ""),
    }
    with open(путь, "w", encoding="utf-8") as файл:
        json.dump({"mcpServers": {
            "tracker": {"command": "${PYTHON}",
                        "args": [os.path.join(КОРЕНЬ, "tracker_server.py")],
                        "env": окружение_трекера, "таймаут": 40},
            "pipeline": {"command": "${PYTHON}",
                         "args": [os.path.join(КОРЕНЬ, "pipeline_server.py")],
                         "env": окружение_конвейеров,
                         "конвейеры": {"run_pipeline": "pipeline"},
                         "своё": True, "таймаут": 180},
            "scheduler": {"command": "${PYTHON}",
                          "args": [os.path.join(КОРЕНЬ, "scheduler_server.py")],
                          "env": {"SCHEDULER_DB": база},
                          "планирует": {"schedule_job": "tool"},
                          "своё": True, "таймаут": 40},
        }}, файл, ensure_ascii=False)
    return путь


