#!/usr/bin/env python3
"""Проверка задания Дня 17: свой MCP-сервер вокруг API и вызов из агента.

Задание требует трёх вещей от сервера — регистрация инструмента, описание
входных параметров, возврат результата — и двух от агента: вызвать инструмент
из приложения и использовать результат. Скрипт устроен по этим пунктам.

  Часть 1  РЕГИСТРАЦИЯ. Свой сервер tracker_server.py поднимается как настоящий
           MCP-сервер (stdio), отдаёт tools/list, и список сверяется с тем, что
           объявлено в коде. Проверяются пометки поведения: читающие помечены
           readOnlyHint, меняющие — нет. Без разрешения на запись меняющих
           инструментов в списке нет вовсе.
  Часть 2  ВХОДНЫЕ ПАРАМЕТРЫ. Каждая inputSchema — корректная JSON Schema типа
           object; у каждого параметра есть описание (по нему модель и выбирает
           значения); обязательные объявлены; выход за границы отклоняется.
  Часть 3  ВОЗВРАТ РЕЗУЛЬТАТА. Главная проверка дня: то, что вернул инструмент,
           сверяется с ответом самого API, запрошенным независимо — своим
           httpx-запросом мимо MCP. Заодно видно, насколько выжимка короче
           сырого ответа: это и есть экономия токенов.
  Часть 4  АГЕНТ ВЫЗЫВАЕТ И ИСПОЛЬЗУЕТ. Живой вопрос модели с инструментами:
           модель сама решает позвать инструмент, агент исполняет вызов, и в
           ответе появляются данные, которых в промпте не было.
  Часть 5  ИЗМЕНЕНИЕ ТОЛЬКО С ПОДТВЕРЖДЕНИЕМ. Модель просит изменить данные —
           вызова не происходит, появляется заявка. Подтверждение исполняет её,
           и изменение видно в самом API. Отклонённая заявка не меняет ничего.
  Часть 6  СБОИ. Трекер не отвечает, токен не принят, задачи нет, ключ задачи
           выдуман моделью — каждый случай даёт понятную причину, а не стек.
  Часть 7  ЦЕНА. Во сколько токенов обходится список инструментов в каждом
           запросе и сколько стоит ответ с инструментами против ответа без них.

Мок-трекер (tracker_api.py) скрипт поднимает сам на свободном порту и гасит в
конце: проверка не должна зависеть от того, что кто-то что-то запустил заранее.

Запуск:
    python check_tools.py                    # всё, включая живые вызовы модели
    python check_tools.py --без-модели       # части 1-3, 6, 7: ни одного запроса к LLM
    python check_tools.py --модель ds-flash  # какой моделью проверять
    python check_tools.py --в RESULTS.md     # дописать отчёт в файл
"""

