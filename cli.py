def _индексатор(аргументы) -> "rag.Индексатор":
    return rag.Индексатор(документы=аргументы.rag_docs, индекс=аргументы.rag_dir,
                          эмбеддер=аргументы.rag_embedder, ocr=not аргументы.rag_no_ocr)


class _Ход:
    """Печать хода долгой работы: в терминале — строка на месте, в файле — вехи.

    Индексация на CPU идёт минуты. Без хода терминал молчит, и это выглядит как
    зависание; но в выводе скрипта (check_cli.py) сотни строк «12/340» — мусор,
    поэтому без терминала печатается только смена этапа.
    """

    def __init__(self) -> None:
        self.этап = ""
        self.терминал = sys.stdout.isatty()

    def __call__(self, этап: str, сделано: int, всего: int, что: str) -> None:
        if этап != self.этап:
            if self.терминал and self.этап:
                print()
            self.этап = этап
            if not self.терминал:
                print(f"  … {этап}" + (f": {всего}" if всего > 1 else ""), flush=True)
        if self.терминал:
            хвост = f" — {что}" if что else ""
            print(f"\r  … {этап}: {сделано}/{всего}{хвост}"[:110].ljust(110), end="", flush=True)

    def закончить(self) -> None:
        if self.терминал and self.этап:
            print()


def показать_извлечённое(аргументы) -> int:
    индексатор = _индексатор(аргументы)
    ход = _Ход()
    документы = индексатор.извлечь(ход)
    ход.закончить()
    print(LINE)
    print(f"Документы из {индексатор.каталог}")
    print(LINE)
    for д in документы:
        единица = "листов" if д.вид == "таблица" else "стр."
        print(f"● {д.источник}  [{д.вид}, {единица} {д.страниц}, символов {д.символов}]")
        if д.название != os.path.splitext(os.path.basename(д.источник))[0]:
            print(f"  название: {д.название}")
        разделы = []
        for б in д.блоки:
            путь = " › ".join(б.раздел)
            if путь and путь not in разделы:
                разделы.append(путь)
        if разделы:
            print(f"  разделов {len(разделы)}: " + "; ".join(разделы[:6])
                  + (" …" if len(разделы) > 6 else ""))
        if д.распознано:
            print(f"  распознано OCR страниц: {len(д.распознано)}")
        for замечание in д.замечания:
            print(f"  ⚠ {замечание}")
    всего = sum(д.символов for д in документы)
    страниц = sum(д.страниц for д in документы if д.вид == "pdf")
    print(LINE)
    print(f"Документов {len(документы)}, страниц PDF {страниц}, символов {всего}"
          f" (≈ {всего // 1800} стандартных страниц текста).")
    return 0


def собрать_индекс(аргументы) -> int:
    стратегии = list(rag.СТРАТЕГИИ) if аргументы.rag_build == "обе" else [аргументы.rag_build]
    if стратегии[0] not in rag.СТРАТЕГИИ:
        print(f"Нет стратегии «{аргументы.rag_build}». Есть: {', '.join(rag.СТРАТЕГИИ)}, обе",
              file=sys.stderr)
        return 1
    индексатор = _индексатор(аргументы)
    print(f"Индексация {индексатор.каталог} → {индексатор.база}")
    print(f"Эмбеддер: {индексатор.эмбеддер.имя}; стратегии: {', '.join(стратегии)}")
    ход = _Ход()
    try:
        отчёт = индексатор.построить(стратегии, аргументы.rag_size, аргументы.rag_overlap,
                                     аргументы.rag_max, прогресс=ход)
    finally:
        ход.закончить()
    print(LINE)
    for д in отчёт["документы"]:
        пометка = f", OCR стр. {д['распознано_страниц']}" if д["распознано_страниц"] else ""
        print(f"  {д['источник']:<58} символов {д['символов']:>7}{пометка}")
        for замечание in д["замечания"]:
            print(f"      ⚠ {замечание}")
    print(LINE)
    for стратегия, с in отчёт["стратегии"].items():
        параметры = ", ".join(f"{к} {з}" for к, з in с["параметры"].items())
        print(f"«{стратегия}» ({параметры}): чанков {с['чанков']}, токенов {с['токенов_всего']}, "
              f"размер мин/медиана/макс {с['мин']}/{с['медиана']}/{с['макс']}; "
              f"вектор {с['размерность']}; из кэша {с['из_кэша']}; "
              f"векторы {с['секунд_векторов']} с")
    print(f"Готово за {отчёт['секунд']} с (извлечение {отчёт['секунд_извлечения']} с).")
    return 0


