class Работник:
    """Работник отдельным процессом — так он и живёт в жизни."""

    def __init__(self, база: str, конфиг: str, тик: float = 1.0) -> None:
        self.база, self.конфиг, self.тик = база, конфиг, тик
        self.процесс: subprocess.Popen | None = None
        self.журнал = ""

    def запустить(self, секунд: float) -> None:
        файл = tempfile.NamedTemporaryFile("w+", delete=False, suffix=".log")
        self.вывод = файл
        self.процесс = subprocess.Popen(
            [sys.executable, os.path.join(КОРЕНЬ, "worker.py"),
             "--база", self.база, "--mcp-файл", self.конфиг, "--тик", str(self.тик),
             "--сколько", str(секунд), "--без-модели"],
            stdout=файл, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)

    def дождаться(self, предел: float = 120) -> str:
        if self.процесс is None:
            return ""
        self.процесс.wait(timeout=предел)
        self.вывод.flush()
        with open(self.вывод.name, encoding="utf-8") as файл:
            self.журнал = файл.read()
        self.процесс = None
        return self.журнал

    def остановить(self) -> None:
        if self.процесс is not None:
            self.процесс.terminate()
            try:
                self.процесс.wait(timeout=10)
            except subprocess.TimeoutExpired:  # pragma: no cover
                self.процесс.kill()
            self.процесс = None


def _прямо_из_базы(база: str, запрос: str, параметры: tuple = ()) -> list[tuple]:
    """Запрос к файлу SQLite мимо нашего кода — чтобы данные проверялись, а не пересказывались."""
    соединение = sqlite3.connect(база)
    try:
        return соединение.execute(запрос, параметры).fetchall()
    finally:
        соединение.close()


def _ждать(условие, предел: float = 30, шаг: float = 0.5) -> bool:
    """Ждёт, пока фоновый процесс сделает своё дело. Время — не «sleep наугад»."""
    срок = time.monotonic() + предел
    while time.monotonic() < срок:
        if условие():
            return True
        time.sleep(шаг)
    return False


