"""Маршрутизатор серверов: какие MCP-серверы поднимать под конкретный запрос.

До Дня 20 набор серверов называл человек ключом «--инструменты tracker». Это
работало, пока серверов было два. Их девять, и у них полсотни
инструментов почти на одиннадцать тысяч токенов; отдавать модели все описания в
каждом запросе — это тот самый квадратичный рост, о котором предупреждала
лекция: список инструментов платится в каждом запросе разговора, а не один
раз.

Поэтому выбор серверов стал отдельным дешёвым кругом. Модель видит не схемы
инструментов, а девять строк «имя — описание», и называет серверы, без которых
на запрос не ответить. Дальше поднимаются только они. Круг стоит сотни токенов
и экономит тысячи — и, что важнее, сужает выбор: из четырёх инструментов
выбирают точнее, чем из шестидесяти.

Три страховки поверх выбора модели:

  * Правила по темам (поле «темы» в mcp-servers.json) — запасной путь и добор.
    Запасной: модель маршрутизации бесплатная, а бесплатные модели отвечают
    429; без правил агент в такой момент остался бы вовсе без инструментов.
    Добор: когда модель уже решила, что инструменты нужны, правила добавляют
    к её выбору то, что она пропустила. Ошибки тут несимметричны — лишний
    сервер стоит токенов, недостающий стоит сорванной работы. С решением
    «инструменты не нужны вовсе» правила не спорят: это ответ, а не пропуск.
  * Пометка «по_просьбе» — сервер берётся, только если человек назвал его сам,
    именем или темой. Так стоит настоящий Яндекс.Трекер рядом с моком:
    инструменты у них одинаковые, и «заодно» писать в боевую систему нельзя.
  * Поле «замещает» — два сервера с одинаковыми по смыслу инструментами не
    открываются разом. Иначе модель выбирала бы между tracker__add_comment и
    tracker-real__add_comment по звучанию имени.

Маршрут — это не только список серверов, но и причина по каждому: она уходит в
протокол флоу и на экран. «Почему агент полез в трекер» человек должен узнавать
из записи, а не из догадок.

Публичное API:
  Маршрут                       — решение: серверы, причины, что отсеяно
  Маршрутизатор(серверы, клиент)
      .выбрать(запрос, названные) -> Маршрут
      .описания()                 -> список серверов для промпта и показа
  РОЛЬ                          — роль модели в catalog.py
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any

from agent.mcp.config import Server
from agent.memory.router import _первый_объект as первый_объект

log = logging.getLogger("agent.orchestra")

РОЛЬ = "выбор-серверов"

# Сколько букв слова темы считать основой. Русский язык склоняет всё, и тема
# «настоящий трекер» не встречается в запросе «посмотри в настоящем трекере»
# ни одной буквой совпадения по целой строке. Тот же приём, что в поиске по
# памяти Дня 19: сравниваются основы слов, а не слова.
ОСНОВА = 6

# Как получен маршрут.
ЧЕЛОВЕК = "человек"      # серверы названы ключом «--инструменты»
МОДЕЛЬ = "модель"        # выбрал круг маршрутизации
ПРАВИЛА = "правила"      # модель недоступна или промолчала — сработали темы
ОБА = "модель и правила"  # модель выбрала, правила добрали пропущенное
ВСЁ = "всё"              # выбора не было: берём всё, что готово
ПУСТО = "пусто"          # инструменты для этого запроса не нужны

СИСТЕМА = """\
Ты — маршрутизатор инструментов инженерного агента. Тебе дан список серверов
MCP с описаниями и запрос человека. Назови ВСЕ серверы, без которых на запрос
не ответить, — и только их.

Правила:
  * лишний сервер стоит токенов в каждом запросе, недостающий — сорванной
    работы: в запросе из двух частей нужны оба сервера;
  * сервер с пометкой «только по явной просьбе» бери, лишь если человек назвал
    его сам;
  * если данные из внешних систем не нужны вовсе, верни пустой список.

Ответ — только JSON, без пояснений вокруг:
{"серверы": ["имя"], "почему": {"имя": "зачем он здесь"}}"""


@dataclass
class Маршрут:
    """Какие серверы выбраны под запрос и почему."""

    запрос: str = ""
    серверы: list[str] = field(default_factory=list)
    почему: dict[str, str] = field(default_factory=dict)
    способ: str = ВСЁ
    отсеяно: list[dict[str, str]] = field(default_factory=list)
    кандидаты: list[str] = field(default_factory=list)   # что дали правила
    модель: str = ""
    ошибка: str = ""

    @property
    def пуст(self) -> bool:
        return not self.серверы

    def словами(self) -> str:
        если_нет = "инструменты не нужны" if self.способ == ПУСТО else "ни один сервер не выбран"
        выбрано = ", ".join(self.серверы) or если_нет
        хвост = f"; отсеяны: {', '.join(о['сервер'] for о in self.отсеяно)}" if self.отсеяно else ""
        return f"Маршрут ({self.способ}): {выбрано}{хвост}"

    def to_dict(self) -> dict[str, Any]:
        return {"запрос": self.запрос, "серверы": list(self.серверы),
                "почему": dict(self.почему), "способ": self.способ,
                "отсеяно": [dict(о) for о in self.отсеяно],
                "кандидаты": list(self.кандидаты), "модель": self.модель,
                "ошибка": self.ошибка}

    @classmethod
    def from_dict(cls, данные: dict[str, Any] | None) -> "Маршрут":
        данные = данные or {}
        return cls(запрос=str(данные.get("запрос", "")),
                   серверы=[str(с) for с in данные.get("серверы", [])],
                   почему={str(к): str(з) for к, з in (данные.get("почему") or {}).items()},
                   способ=str(данные.get("способ", ВСЁ)),
                   отсеяно=[dict(о) for о in данные.get("отсеяно", [])],
                   кандидаты=[str(с) for с in данные.get("кандидаты", [])],
                   модель=str(данные.get("модель", "")),
                   ошибка=str(данные.get("ошибка", "")))


class Маршрутизатор:
    """Выбирает серверы под запрос: сперва моделью, при сбое — по темам."""

    def __init__(self, серверы: list[Server], клиент: Any = None, модель: str = "") -> None:
        self.серверы = list(серверы)
        self.клиент = клиент
        self.модель = модель

    # --- что видно маршрутизатору ---------------------------------------------

    def описания(self) -> list[dict[str, Any]]:
        """Серверы для промпта и для показа человеку — без секретов."""
        строки = []
        for сервер in self.серверы:
            строки.append({
                "имя": сервер.имя,
                "описание": сервер.описание or "(без описания)",
                "по_просьбе": сервер.по_просьбе,
                "своё": сервер.своё,
                "готов": сервер.готов,
                "почему_не_готов": сервер.почему_не_готов,
                "темы": list(сервер.темы),
            })
        return строки

    def _сервер(self, имя: str) -> Server | None:
        for сервер in self.серверы:
            if сервер.имя == имя:
                return сервер
        return None

    # --- выбор ----------------------------------------------------------------

    def выбрать(self, запрос: str, названные: list[str] | None = None) -> Маршрут:
        """Главный вход: запрос человека → список серверов с причинами.

        «названные» — то, что человек указал явно. Такой выбор модель не
        пересматривает: человек знает, чего хочет. Но фильтры применяются и к
        нему — иначе «--инструменты tracker,tracker-real» открыло бы оба
        одинаковых сервера сразу.
        """
        запрос = (запрос or "").strip()
        готовые = [с for с in self.серверы if с.готов]
        не_готовы = [{"сервер": с.имя, "почему": с.почему_не_готов}
                     for с in self.серверы if not с.готов]

        if названные:
            выбор = {и: "назван человеком" for и in названные if self._сервер(и)}
            неизвестные = [{"сервер": и, "почему": "такого сервера нет в mcp-servers.json"}
                           for и in названные if not self._сервер(и)]
            маршрут = self._собрать(запрос, выбор, ЧЕЛОВЕК, названные)
            маршрут.отсеяно.extend(неизвестные)
            маршрут.отсеяно.extend(
                о for о in не_готовы if о["сервер"] in названные)
            return маршрут

        по_темам = self._по_темам(запрос, готовые)
        маршрут: Маршрут | None = None
        if self.клиент is not None:
            выбор, модель, ошибка = self._моделью(запрос, готовые)
            if ошибка:
                log.info("Маршрутизатор серверов: %s — работают правила", ошибка)
            elif выбор:
                # Правила добирают то, что модель пропустила. Ошибки здесь
                # несимметричны: лишний сервер стоит токенов, недостающий —
                # сорванной работы. Живой замер показал, что дешёвая модель на
                # запросе из двух частей («прочитай в трекере и подними, что
                # знает память») называет один сервер из двух, и флоу потом
                # выдумывает недостающее вместо того, чтобы его найти.
                добор = {и: п for и, п in по_темам.items() if и not in выбор}
                способ = МОДЕЛЬ if not добор else ОБА
                маршрут = self._собрать(запрос, {**выбор, **добор}, способ, названные)
                маршрут.модель = модель
            else:
                # Пустой ответ модели — это ответ: «внешние данные не нужны», и
                # правила с ним не спорят. Они добирают пропущенное, когда
                # модель уже решила, что инструменты нужны, — но решение «не
                # нужны вовсе» принимает она, а не совпадение слова в запросе.
                маршрут = Маршрут(запрос=запрос, способ=ПУСТО, модель=модель)
            if маршрут is None:
                маршрут = self._собрать(запрос, по_темам, ПРАВИЛА, названные)
                маршрут.ошибка = ошибка
                маршрут.модель = модель
        else:
            маршрут = self._собрать(запрос, по_темам, ПРАВИЛА, названные)

        маршрут.кандидаты = sorted(по_темам)
        маршрут.отсеяно.extend(не_готовы)
        return маршрут

    def _по_темам(self, запрос: str, готовые: list[Server]) -> dict[str, str]:
        """Запасной путь: сервер берётся, если его тема встретилась в запросе."""
        низкий = запрос.lower()
        выбор: dict[str, str] = {}
        for сервер in готовые:
            for тема in сервер.темы:
                if совпало(тема, низкий):
                    выбор[сервер.имя] = f"в запросе есть «{тема}»"
                    break
        return выбор

    def _моделью(self, запрос: str, готовые: list[Server]) -> tuple[dict[str, str], str, str]:
        """Круг выбора: описания серверов → имена. Возвращает (выбор, модель, ошибка)."""
        from agent.llm import LLMError    # местный импорт: модуль работает и без модели

        перечень = "\n".join(
            f"  {с.имя} — {с.описание or 'без описания'}"
            + (" [только по явной просьбе]" if с.по_просьбе else "")
            for с in готовые) or "  (серверов нет)"
        сообщения = [
            {"role": "system", "content": СИСТЕМА},
            {"role": "user", "content": f"Серверы:\n{перечень}\n\nЗапрос человека: {запрос}"},
        ]
        ключ = self.модель
        if not ключ:
            from agent import catalog
            ключ = catalog.for_role(РОЛЬ)
        try:
            ответ = self.клиент.call(ключ, сообщения, max_tokens=300, temperature=0.0,
                                     low_effort=True)
        except LLMError as exc:
            return {}, ключ, f"модель маршрутизации не ответила: {exc}"

        данные = первый_объект(ответ.text or "")
        if not isinstance(данные, dict):
            return {}, ответ.model_key, "ответ маршрутизатора не разобран как JSON"
        имена = данные.get("серверы", [])
        if isinstance(имена, str):
            имена = [имена]
        if not isinstance(имена, list):
            return {}, ответ.model_key, "в ответе маршрутизатора нет списка «серверы»"
        причины = данные.get("почему") or {}
        выбор: dict[str, str] = {}
        for имя in имена:
            имя = str(имя).strip()
            if not имя:
                continue
            причина = причины.get(имя) if isinstance(причины, dict) else ""
            выбор[имя] = str(причина or "выбран маршрутизатором")
        return выбор, ответ.model_key, ""

    # --- фильтры --------------------------------------------------------------

    def _собрать(self, запрос: str, выбор: dict[str, str], способ: str,
                 названные: list[str] | None) -> Маршрут:
        """Применяет к сырому выбору три фильтра и объясняет каждый отказ."""
        низкий = (запрос or "").lower()
        названные = [и for и in (названные or [])]
        серверы: list[str] = []
        почему: dict[str, str] = {}
        отсеяно: list[dict[str, str]] = []

        for имя, причина in выбор.items():
            сервер = self._сервер(имя)
            if сервер is None:
                отсеяно.append({"сервер": имя, "почему": "нет в mcp-servers.json"})
                continue
            if not сервер.готов:
                отсеяно.append({"сервер": имя, "почему": сервер.почему_не_готов})
                continue
            if сервер.по_просьбе and not self._назван(сервер, низкий, названные):
                отсеяно.append({"сервер": имя,
                                "почему": "берётся только по явной просьбе человека"})
                continue
            серверы.append(имя)
            почему[имя] = причина

        # Замещение — последним: сначала надо знать, кто вообще прошёл фильтры.
        for имя in list(серверы):
            сервер = self._сервер(имя)
            кого = сервер.замещает if сервер else ""
            if кого and кого in серверы:
                серверы.remove(кого)
                почему.pop(кого, None)
                отсеяно.append({"сервер": кого, "почему": f"заменён сервером «{имя}»"})

        return Маршрут(запрос=запрос, серверы=серверы, почему=почему,
                       способ=способ if серверы else (ПУСТО if способ != ЧЕЛОВЕК else способ),
                       отсеяно=отсеяно)

    @staticmethod
    def _назван(сервер: Server, низкий: str, названные: list[str]) -> bool:
        """Назвал ли человек сервер сам — ключом или словами в запросе."""
        if сервер.имя in названные:
            return True
        if сервер.имя.lower() in низкий:
            return True
        return any(совпало(тема, низкий) for тема in сервер.темы)


def совпало(тема: str, текст: str) -> bool:
    """Есть ли тема в тексте запроса — с поправкой на падежи.

    Тема из одного слова обычно и так записана основой («задач», «отчёт»), а
    тема из нескольких сравнивается по основам каждого слова: иначе
    «настоящий трекер» не найдётся в «посмотри в настоящем трекере».
    """
    тема = (тема or "").strip().lower()
    if not тема:
        return False
    if тема in текст:
        return True
    слова = тема.split()
    if len(слова) < 2:
        return False
    return all(слово[:ОСНОВА] in текст for слово in слова)


