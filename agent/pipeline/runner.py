"""Исполнитель конвейера: вызвать шаги по порядку и передать данные дальше.

Здесь собирается всё, что требует задание дня: цепочка выполняется сама
(никто не подсказывает ей следующий шаг), данные между шагами передаются по
объявленным ссылкам, а не пересказом, и каждый шаг оставляет след — что в него
ушло и что он вернул.

Правило сбоя выбрано человеком в начале дня: первый же упавший шаг
останавливает прогон. Причина простая — конвейер кончается сохранением
отчёта, и отчёт, собранный из половины данных, хуже, чем его отсутствие: он
выглядит как настоящий. Поэтому прогон закрывается состоянием «сбой», в
протоколе видно, на каком шаге встали, а всё, что успело выполниться, остаётся
записанным.

Исполнитель не знает, чем ему звать инструменты: ему дают «ящик» — что угодно
с методом .вызвать(имя, аргументы). В агенте это Toolbox (открытые соединения
MCP), в MCP-сервере конвейеров — его собственный ящик, который свои
инструменты зовёт напрямую, а чужие — как клиент MCP. Благодаря этому один и
тот же код исполняет конвейер и из консоли, и со страницы, и из работника по
расписанию, и по просьбе модели.

Публичное API:
  Исполнитель(ящик, хранилище=None, кто="")
  .выполнить(конвейер, вход=None, зачем="", задание=0) -> Прогон
  выполнить(конвейер, ящик, …)                          — то же одной функцией
"""

from __future__ import annotations

import logging
import time
from datetime import datetime
from typing import Any, Callable

from agent.pipeline.spec import Конвейер, ОшибкаКонвейера, Шаг
from agent.pipeline.store import ГОТОВ, СБОЙ, PipelineStore, Прогон, ШагПрогона
from agent.pipeline.values import ОшибкаПодстановки, коротко, подставить

log = logging.getLogger("agent.pipeline")

# Поля результата, в которых инструменты называют созданный файл: по ним
# исполнитель понимает, чем кончился конвейер, и кладёт это в итог прогона.
ПОЛЯ_ИТОГА = ("путь", "файл", "отчёт", "path", "file")


def _сейчас() -> datetime:
    return datetime.now().replace(microsecond=0)


def _строка(момент: datetime) -> str:
    return момент.replace(microsecond=0).isoformat(sep=" ")


class Исполнитель:
    """Выполняет конвейер шаг за шагом и пишет протокол."""

    def __init__(self, ящик: Any, хранилище: PipelineStore | None = None, кто: str = "",
                 часы: Callable[[], datetime] | None = None) -> None:
        self.ящик = ящик
        self.хранилище = хранилище
        self.кто = кто
        self.часы = часы or _сейчас

    def выполнить(self, конвейер: Конвейер, вход: dict[str, Any] | None = None,
                  зачем: str = "", задание: int = 0) -> Прогон:
        """Один прогон конвейера. Исключений наружу не выходит, кроме ошибки описания.

        Ошибка описания (нет такого входа, ссылка в никуда) — это ошибка
        человека, написавшего конвейер, и она должна прийти сразу, до записи
        прогона. Всё остальное — обстоятельства: упавший сервер, ошибка
        инструмента, пустое поле в ответе — становится прогоном в состоянии
        «сбой», который видно в истории.
        """
        конвейер.проверить()
        значения = конвейер.собрать_вход(вход)     # ОшибкаКонвейера — наружу

        начало = time.monotonic()
        сейчас = self.часы()
        прогон = self._начать(конвейер, значения, зачем, задание, сейчас)
        портфель: dict[str, Any] = {"вход": dict(значения)}

        for место, шаг in enumerate(конвейер.шаги, 1):
            запись = self._шаг(прогон, место, шаг, портфель)
            прогон.шаги.append(запись)
            прогон.сделано = len([ш for ш in прогон.шаги if ш.ок])
            if not запись.ок:
                прогон.секунд = time.monotonic() - начало
                return self._закрыть(прогон, СБОЙ, ошибка=запись.ошибка)
            портфель[шаг.имя] = {"данные": запись.выход, "текст": запись.текст, "ок": True}

        прогон.секунд = time.monotonic() - начало
        return self._закрыть(прогон, ГОТОВ, итог=self._итог(прогон))

    # --- один шаг -------------------------------------------------------------

    def _шаг(self, прогон: Прогон, место: int, шаг: Шаг,
             портфель: dict[str, Any]) -> ШагПрогона:
        """Подставляет аргументы, зовёт инструмент и записывает след."""
        начало = time.monotonic()
        сейчас = self.часы()
        try:
            аргументы, след = подставить(шаг.аргументы, портфель)
        except ОшибкаПодстановки as exc:
            # Данные не доехали: предыдущий шаг вернул не то, что обещано в
            # описании. Это и есть «некорректная передача», и увидеть её надо
            # целиком — с путём, который не нашёлся.
            return self._записать(прогон, место, шаг, ок=False, вход=шаг.аргументы,
                                  след=[], ошибка=str(exc), секунд=time.monotonic() - начало,
                                  сейчас=сейчас)

        try:
            результат = self.ящик.вызвать(шаг.инструмент, аргументы)
        except Exception as exc:  # noqa: BLE001 — сбой вызова не должен ронять прогон
            return self._записать(прогон, место, шаг, ок=False, вход=аргументы, след=след,
                                  ошибка=f"{type(exc).__name__}: {exc}",
                                  секунд=time.monotonic() - начало, сейчас=сейчас)

        ок = bool(getattr(результат, "ок", True))
        текст = getattr(результат, "текст", "") or ""
        данные = getattr(результат, "данные", None)
        ошибка = "" if ок else (текст or "инструмент ответил ошибкой без пояснения")
        log.info("Конвейер «%s» шаг %d «%s» (%s): %s", прогон.конвейер, место, шаг.имя,
                 шаг.инструмент, "ок" if ок else "сбой")
        return self._записать(прогон, место, шаг, ок=ок, вход=аргументы, след=след,
                              выход=данные, текст=текст, ошибка=ошибка,
                              секунд=time.monotonic() - начало, сейчас=сейчас)

    # --- запись ---------------------------------------------------------------

    def _начать(self, конвейер: Конвейер, значения: dict[str, Any], зачем: str,
                задание: int, сейчас: datetime) -> Прогон:
        if self.хранилище is not None:
            return self.хранилище.начать(
                конвейер=конвейер.имя, шагов=len(конвейер.шаги), вход=значения,
                зачем=зачем, кто=self.кто, задание=задание, сейчас=сейчас)
        return Прогон(конвейер=конвейер.имя, начат=_строка(сейчас), вход=dict(значения),
                      шагов=len(конвейер.шаги), зачем=зачем, кто=self.кто, задание=задание)

    def _записать(self, прогон: Прогон, место: int, шаг: Шаг, ок: bool, вход: Any,
                  след: list[tuple[str, str]], выход: Any = None, текст: str = "",
                  ошибка: str = "", секунд: float = 0.0,
                  сейчас: datetime | None = None) -> ШагПрогона:
        if self.хранилище is not None:
            return self.хранилище.записать_шаг(
                прогон=прогон.номер, место=место, имя=шаг.имя, инструмент=шаг.инструмент,
                ок=ок, вход=вход, подстановки=след, выход=выход, текст=текст,
                секунд=секунд, ошибка=ошибка, сейчас=сейчас)
        return ШагПрогона(
            прогон=прогон.номер, место=место, имя=шаг.имя, инструмент=шаг.инструмент,
            начат=_строка(сейчас or self.часы()), секунд=секунд, ок=ок, вход=вход,
            подстановки=[[п, з] for п, з in след], выход=выход, текст=текст, ошибка=ошибка)

    def _закрыть(self, прогон: Прогон, состояние: str, итог: str = "",
                 ошибка: str = "") -> Прогон:
        прогон.состояние = состояние
        прогон.итог = итог
        прогон.ошибка = ошибка
        прогон.кончен = _строка(self.часы())
        if self.хранилище is not None:
            закрытый = self.хранилище.завершить(
                прогон.номер, состояние, итог=итог, ошибка=ошибка, секунд=прогон.секунд)
            закрытый.шаги = прогон.шаги
            return закрытый
        return прогон

    @staticmethod
    def _итог(прогон: Прогон) -> str:
        """Чем кончился конвейер — одной строкой: путь файла или последний текст."""
        if not прогон.шаги:
            return ""
        последний = прогон.шаги[-1]
        данные = последний.выход
        if isinstance(данные, dict):
            for поле in ПОЛЯ_ИТОГА:
                значение = данные.get(поле)
                if isinstance(значение, str) and значение.strip():
                    return значение.strip()
        return коротко(последний.текст or данные, предел=200)


def выполнить(конвейер: Конвейер, ящик: Any, вход: dict[str, Any] | None = None,
              хранилище: PipelineStore | None = None, зачем: str = "", кто: str = "",
              задание: int = 0) -> Прогон:
    """Один прогон конвейера без создания исполнителя — для скриптов и проверок."""
    return Исполнитель(ящик, хранилище, кто).выполнить(
        конвейер, вход=вход, зачем=зачем, задание=задание)


__all__ = ["Исполнитель", "выполнить", "ОшибкаКонвейера", "Прогон", "ШагПрогона"]
