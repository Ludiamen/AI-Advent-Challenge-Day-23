"""Расписание задания: как человек его пишет и когда наступает срок.

Расписание в этом проекте задаётся словами, а не cron-строкой:

    через 15м            один раз, через четверть часа  (отложенное задание)
    каждые 30м           снова и снова, раз в полчаса    (периодическое)
    ежедневно в 09:00    раз в сутки в это время
    в 18:30              один раз, в ближайшие 18:30

Почему не cron. Расписание пишут двое: человек в консоли и модель в аргументах
вызова. Человеку «каждые 30м» читается без справочника, а модель в такой форме
не ошибается — в отличие от «*/30 * * * *», где легко перепутать минуты с
часами, и ошибка выяснится только через сутки. Цена решения честная: «по
будням в 9 и 18» здесь выразить нельзя; понадобится — добавится отдельной
формой, а не пятью полями со звёздочками.

Время везде местное и «наивное» (без часового пояса): работник, консоль и
страница живут на одной машине, а хранить UTC ради красоты значило бы каждый
раз переводить его обратно для показа.

Публичное API:
  разобрать(текст)  -> Расписание     — понять строку человека
  Расписание        .первый(сейчас)   — когда срок в первый раз
                    .следующий(сейчас)— когда в следующий (None — больше не надо)
                    .пропущено(срок, сейчас) — сколько сроков прошло мимо
  ОшибкаРасписания                    — строку понять не удалось
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any

ОДНОКРАТНО = "однократно"
ИНТЕРВАЛ = "интервал"
ЕЖЕДНЕВНО = "ежедневно"
ВИДЫ = (ОДНОКРАТНО, ИНТЕРВАЛ, ЕЖЕДНЕВНО)

# Нижняя граница интервала. Секунда — не «разумный период опроса», а защита от
# нуля: задание с интервалом 0 крутилось бы в цикле работника без остановки.
# Разумный период выбирает человек, и в примерах это минуты.
МИНИМУМ = 1
# Верхняя граница — год. Дальше начинаются вопросы про високосные годы и
# переводы часов, на которые «каждые 400 дней» всё равно не отвечает.
МАКСИМУМ = 366 * 24 * 3600

ПРИМЕРЫ = "«через 15м», «каждые 30м», «ежедневно в 09:00», «в 18:30»"

# Единицы времени во всех падежах, которые встречаются в живой записи.
ЕДИНИЦЫ: dict[str, int] = {
    "с": 1, "сек": 1, "секунда": 1, "секунды": 1, "секунду": 1, "секунд": 1,
    "м": 60, "мин": 60, "минута": 60, "минуты": 60, "минуту": 60, "минут": 60,
    "ч": 3600, "час": 3600, "часа": 3600, "часов": 3600,
    "д": 86400, "день": 86400, "дня": 86400, "дней": 86400, "сутки": 86400,
}

_ЧЕРЕЗ = re.compile(r"^через\s+(\d+)\s*([а-я]*)$")
_КАЖДЫЕ = re.compile(r"^кажд(?:ые|ый|ую|ое)\s+(\d*)\s*([а-я]+)$")
_ЕЖЕДНЕВНО = re.compile(r"^(?:ежедневно|каждый\s+день|ежесуточно)\s+в\s+(\d{1,2})[:.](\d{2})$")
_ВРЕМЯ = re.compile(r"^в\s+(\d{1,2})[:.](\d{2})$")


class ОшибкаРасписания(ValueError):
    """Строка расписания не разобрана: в сообщении сказано, как надо."""


def _единица(слово: str, текст: str) -> int:
    секунд = ЕДИНИЦЫ.get(слово)
    if секунд is None:
        раз = ", ".join(sorted({"с", "м", "ч", "д"}))
        raise ОшибкаРасписания(
            f"В расписании «{текст}» непонятна единица времени «{слово}». "
            f"Бывают: {раз} (секунды, минуты, часы, дни). Примеры: {ПРИМЕРЫ}.")
    return секунд


def _проверить(секунд: int, текст: str) -> int:
    if секунд < МИНИМУМ:
        raise ОшибкаРасписания(
            f"Расписание «{текст}»: промежуток должен быть хотя бы {МИНИМУМ} с.")
    if секунд > МАКСИМУМ:
        raise ОшибкаРасписания(
            f"Расписание «{текст}»: промежуток больше года планировщик не считает.")
    return секунд


def _время(часы: str, минуты: str, текст: str) -> tuple[int, int]:
    час, минута = int(часы), int(минуты)
    if час > 23 or минута > 59:
        raise ОшибкаРасписания(
            f"Расписание «{текст}»: такого времени не бывает. Часы 0–23, минуты 0–59.")
    return час, минута


@dataclass(frozen=True)
class Расписание:
    """Разобранное расписание: вид, промежуток или время суток."""

    как: str
    секунд: int = 0
    час: int = 0
    минута: int = 0
    текст: str = ""

    @property
    def повторяется(self) -> bool:
        """Периодическое (снова и снова) или отложенное (один раз)."""
        return self.как != ОДНОКРАТНО

    @property
    def по_времени(self) -> bool:
        """Срок задан временем суток, а не промежутком."""
        return self.как == ЕЖЕДНЕВНО or (self.как == ОДНОКРАТНО and self.секунд == 0)

    def словами(self) -> str:
        """Как показать расписание человеку, если он написал его иначе."""
        if self.как == ЕЖЕДНЕВНО:
            return f"ежедневно в {self.час:02d}:{self.минута:02d}"
        if self.по_времени:
            return f"один раз в {self.час:02d}:{self.минута:02d}"
        промежуток = _промежуток_словами(self.секунд)
        if not self.повторяется:
            return f"один раз через {промежуток}"
        # «каждые 1 час» — не по-русски; для единицы у каждой меры своя форма.
        один = {"1 час": "каждый час", "1 день": "каждый день",
                "1 минута": "каждую минуту", "1 секунда": "каждую секунду"}
        return один.get(промежуток, f"каждые {промежуток}")

    # --- сроки ---------------------------------------------------------------

    def первый(self, сейчас: datetime | None = None) -> datetime:
        """Когда задание сработает в первый раз после создания."""
        сейчас = сейчас or datetime.now()
        if self.по_времени:
            return _ближайшее(сейчас, self.час, self.минута)
        return сейчас + timedelta(seconds=self.секунд)

    def следующий(self, сейчас: datetime | None = None) -> datetime | None:
        """Когда задание сработает снова. None — больше не сработает.

        Считается от «сейчас», а не от прошедшего срока: пропущенные сроки
        планировщик не догоняет (см. пропущено). Работник мог стоять ночь, и
        десяток одинаковых запусков подряд не дал бы ничего, кроме расхода.
        """
        сейчас = сейчас or datetime.now()
        if self.как == ОДНОКРАТНО:
            return None
        if self.как == ЕЖЕДНЕВНО:
            return _ближайшее(сейчас, self.час, self.минута)
        return сейчас + timedelta(seconds=self.секунд)

    def пропущено(self, срок: datetime, сейчас: datetime | None = None) -> int:
        """Сколько сроков прошло мимо, пока работника не было.

        Число не для расчётов, а для честности: в журнале запуска видно, что
        задание должно было сработать не один раз, но работника не было.
        """
        сейчас = сейчас or datetime.now()
        if сейчас <= срок or self.как == ОДНОКРАТНО:
            return 0
        промежуток = 86400 if self.как == ЕЖЕДНЕВНО else self.секунд
        return int((сейчас - срок).total_seconds() // промежуток)

    def to_dict(self) -> dict[str, Any]:
        return {"как": self.как, "секунд": self.секунд, "час": self.час,
                "минута": self.минута, "текст": self.текст, "словами": self.словами(),
                "повторяется": self.повторяется}


def _промежуток_словами(секунд: int) -> str:
    for предел, единица, имена in ((86400, 86400, ("день", "дня", "дней")),
                                  (3600, 3600, ("час", "часа", "часов")),
                                  (60, 60, ("минута", "минуты", "минут")),
                                  (1, 1, ("секунда", "секунды", "секунд"))):
        if секунд >= предел and секунд % единица == 0:
            сколько = секунд // единица
            return f"{сколько} {_склонение(сколько, имена)}"
    return f"{секунд} {_склонение(секунд, ('секунда', 'секунды', 'секунд'))}"


def _склонение(сколько: int, формы: tuple[str, str, str]) -> str:
    сотня, десяток = сколько % 100, сколько % 10
    if 11 <= сотня <= 14 or десяток == 0 or десяток >= 5:
        return формы[2]
    return формы[0] if десяток == 1 else формы[1]


def _ближайшее(сейчас: datetime, час: int, минута: int) -> datetime:
    """Ближайший момент HH:MM строго после «сейчас»."""
    срок = сейчас.replace(hour=час, minute=минута, second=0, microsecond=0)
    if срок <= сейчас:
        срок += timedelta(days=1)
    return срок


def разобрать(текст: str) -> Расписание:
    """Понимает строку расписания. Не понял — объясняет, как пишут."""
    исходный = (текст or "").strip()
    строка = " ".join(исходный.lower().replace("ё", "е").split())
    if not строка:
        raise ОшибкаРасписания(f"Расписание не задано. Примеры: {ПРИМЕРЫ}.")

    совпало = _ЧЕРЕЗ.match(строка)
    if совпало:
        число, слово = совпало.group(1), совпало.group(2) or "м"
        секунд = _проверить(int(число) * _единица(слово, исходный), исходный)
        return Расписание(как=ОДНОКРАТНО, секунд=секунд, текст=исходный)

    совпало = _КАЖДЫЕ.match(строка)
    if совпало:
        число, слово = совпало.group(1), совпало.group(2)
        # «каждый час» и «каждые сутки» — числа нет, оно равно единице.
        секунд = _проверить(int(число or 1) * _единица(слово, исходный), исходный)
        return Расписание(как=ИНТЕРВАЛ, секунд=секунд, текст=исходный)

    совпало = _ЕЖЕДНЕВНО.match(строка)
    if совпало:
        час, минута = _время(совпало.group(1), совпало.group(2), исходный)
        return Расписание(как=ЕЖЕДНЕВНО, час=час, минута=минута, текст=исходный)

    совпало = _ВРЕМЯ.match(строка)
    if совпало:
        час, минута = _время(совпало.group(1), совпало.group(2), исходный)
        return Расписание(как=ОДНОКРАТНО, час=час, минута=минута, текст=исходный)

    raise ОшибкаРасписания(
        f"Не понял расписание «{исходный}». Бывает так: {ПРИМЕРЫ}. "
        "Единицы: с, м, ч, д.")


def из_словаря(данные: dict[str, Any]) -> Расписание:
    """Собирает расписание из полей, прочитанных из базы."""
    как = str(данные.get("как", ИНТЕРВАЛ))
    if как not in ВИДЫ:
        raise ОшибкаРасписания(f"Неизвестный вид расписания «{как}».")
    return Расписание(как=как, секунд=int(данные.get("секунд", 0)),
                      час=int(данные.get("час", 0)), минута=int(данные.get("минута", 0)),
                      текст=str(данные.get("текст", "")))
