def _да(значение: bool | None) -> str:
    return "—" if значение is None else ("✓" if значение else "✗")


def в_markdown(прогон: Прогон) -> str:
    режимы = прогон.режимы
    итоги = {р: прогон.итог(р) for р in режимы}
    n = итоги[режимы[0]]["вопросов"]
    rag = [р for р in режимы if р != БЕЗ_RAG]

    def строка(имя: str, f, только_rag: bool = False) -> str:
        ячейки = ["—" if только_rag and р == БЕЗ_RAG else f(итоги[р]) for р in режимы]
        return f"| {имя} | " + " | ".join(ячейки) + " |"

    строки = [
        "# Контрольные вопросы: сравнение режимов",
        "",
        f"Прогон {прогон.когда}: модель ответов `{прогон.модель}` (одна на все режимы), "
        f"судья `{прогон.модель_судьи or 'выключен'}`, {n} вопросов × {len(режимы)} режимов, "
        f"{прогон.секунд:.0f} с. Режимы отличаются только тем, какие фрагменты попали в "
        "промпт: та же роль, тот же вопрос, то же требование ссылаться на фрагменты [n].",
        "",
        "Режимы: " + "; ".join(f"«{имя_режима(р)}»" for р in режимы) + ".",
        "",
        "## Итог",
        "",
        "| показатель | " + " | ".join(имя_режима(р) for р in режимы) + " |",
        "|---|" + "---:|" * len(режимы),
        строка("верно по правилам (все факты, ловушка — отказ)", lambda x: f"{x['верно_по_правилам']} из {n}"),
        строка("ключевых фактов в ответах", lambda x: f"{x['найдено_фактов']} из {x['фактов']}"),
        строка("ловушек пройдено («в документах этого нет»)", lambda x: f"{x['ловушек_пройдено']} из {x['ловушек']}"),
        строка("судья: верно / частично / неверно", lambda x: f"{x['судья_верно']} / {x['судья_частично']} / {x['судья_неверно']}"),
        строка("судья нашёл выдуманную конкретику", lambda x: str(x["выдумок"])),
        строка("нужный источник среди фрагментов промпта", lambda x: f"{x['источник_найден']} из {x['с_источником']}", True),
        строка("ответ сослался на нужный источник [n]", lambda x: f"{x['источник_процитирован']} из {x['с_источником']}", True),
        строка("опора на контекст: числа ответа есть во фрагментах", lambda x: f"{x['чисел_в_контексте']} из {x['чисел']}", True),
        строка("фрагментов в промпте, в среднем", lambda x: f"{x['фрагментов']:.1f}", True),
        строка("токенов вход / выход", lambda x: f"{x['токенов_вход']} / {x['токенов_выход']}"),
        строка("стоимость ответов, $", lambda x: f"{x['стоимость']:.4f}"),
        строка("время поиска / всего, с", lambda x: f"{x['секунд_поиска']} / {x['секунд']}"),
        "",
        "## По вопросам",
        "",
        "| # | вопрос | ожидание | " + " | ".join(имя_режима(р) for р in режимы) + " |",
        "|---|---|---|" + "---|" * len(режимы),
    ]
    for в in прогон.вопросы:
        о = прогон.оценки.get(в["id"], {})
        if not all(о.get(р) for р in режимы):
            continue
        метка = " (ловушка)" if в.get("ловушка") else ""
        ячейки = []
        for р in режимы:
            x = о[р]
            ячейка = f"{_да(x.верно_по_правилам)} · {x.судья or '—'}" + (" · выдумка" if x.выдумка else "")
            if р in rag:
                ячейка += f" · {_да(x.источник_процитирован)}"
            ячейки.append(ячейка)
        строки.append(f"| {в['id']}{метка} | {в['вопрос']} | {в['ожидание']} | " + " | ".join(ячейки) + " |")
    строки += ["", "В клетке: правила · судья · (у режимов с RAG) процитирован ли нужный источник.",
               "", "## Ответы целиком", ""]
    for в in прогон.вопросы:
        о = прогон.оценки.get(в["id"], {})
        строки += [f"### {в['id']}. {в['вопрос']}", "", f"**Ожидание:** {в['ожидание']}", ""]
        for режим in режимы:
            x = о.get(режим)
            if not x or not x.ответ:
                continue
            a = x.ответ
            строки.append(f"**{имя_режима(режим)}** — правила {_да(x.верно_по_правилам)}, судья «{x.судья or '—'}»"
                          + (", выдумка" if x.выдумка else "") + (f": {x.пояснение}" if x.пояснение else ""))
            строки.append("")
            if a.отбор is not None and a.отбор.переписано and a.отбор.переписано.запросы:
                строки.append("Запросы: " + " · ".join(f"«{з}»" for з in a.отбор.запросы))
                строки.append("")
            строки += ["> " + с if с else ">" for с in (a.текст or a.ошибка).splitlines()]
            if режим != БЕЗ_RAG and a.фрагменты:
                строки.append("")
                for i, н in enumerate(a.фрагменты, 1):
                    отметка = " ← процитирован" if i in a.цитаты else ""
                    ч = н.чанк
                    второй = f" · реранк {н.реранк:.3f} (было {н.место_до})" if н.реранк is not None else ""
                    строки.append(f"- [{i}] {ч.источник} · {ч.раздел}"
                                  + (f" · стр. {ч.страницы}" if ч.страницы else "")
                                  + f" · cos {н.оценка:.3f}{второй}{отметка}")
            строки.append("")
    return "\n".join(строки) + "\n"


def записать(прогон: Прогон, каталог_индекса: str) -> str:
    """JSON — рядом с индексом (для страницы), Markdown — в корень проекта."""
    from agent.rag.indexer import КОРЕНЬ
    каталог_индекса = os.path.abspath(каталог_индекса)
    os.makedirs(каталог_индекса, exist_ok=True)
    from agent.rag.evaluate import записать_атомарно
    записать_атомарно(os.path.join(каталог_индекса, "qa.json"),
                      json.dumps(прогон.to_dict(), ensure_ascii=False, indent=1))
    свой = каталог_индекса != os.path.abspath(os.path.join(КОРЕНЬ, "index"))
    путь = os.path.join(каталог_индекса if свой else КОРЕНЬ, "RAG-QA.md")
    записать_атомарно(путь, в_markdown(прогон))
    return путь


def прочитать(каталог_индекса: str) -> dict | None:
    путь = os.path.join(os.path.abspath(каталог_индекса), "qa.json")
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as f:
        return json.load(f)
