"""Разбиение документа на чанки — две стратегии, которые сравниваются между собой.

«фикс» — то, что лекция называет разбиением по фиксированному размеру: текст
документа идёт сплошной лентой слов, чанк набирается до `размер` токенов,
следующий начинается на `перекрытие` токенов раньше конца предыдущего.
Структуры стратегия не видит нарочно: граница может пройти посреди пункта
договора или строки таблицы, и перекрытие — единственная страховка от того,
что фраза «Срок оплаты: не позднее» окажется в одном чанке, а «20 числа» — в
другом. Документы между собой не смешиваются: файл — всегда граница.

«структура» — чанк равен разделу документа: разделу договора («3. Порядок
расчетов»), приложению, листу таблицы, главе Markdown, функции кода. Раздел
длиннее `макс` делится по границам абзацев и пунктов, а не посреди слова;
соседние крошечные разделы одного приложения склеиваются, чтобы не плодить
чанки из одного заголовка. Знание о структуре даёт и второе преимущество:
в текст для вектора добавляется строка «документ › раздел», и чанк «3.5. Срок
ежемесячной оплаты…» знает, что он о договоре с Ростелекомом. Фиксированной
стратегии такую строку дать нечем — её чанк может лежать в двух разделах сразу.

Размеры считаются оценкой токенов проекта (agent/tokens.py): у bge-m3 свой
токенизатор, но разница единицы процентов, а честное сравнение стратегий
требует лишь одной и той же линейки для обеих.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field

from agent.rag.extract import Блок, Документ
from agent.tokens import estimate

ФИКС = "фикс"
СТРУКТУРА = "структура"
СТРАТЕГИИ = (ФИКС, СТРУКТУРА)
# Латинский код стратегии — для chunk_id, который уходит в URL и в аргументы
# инструментов MCP. Кириллица там возможна, но лишний повод для экранирования.
КОД = {ФИКС: "fixed", СТРУКТУРА: "struct"}

# Лекция: «где-то 500–1000 токенов», перекрытие подбирается опытом. 500 и 75
# (15 %) — нижняя граница диапазона: пункты договора короткие, и большой чанк
# растворил бы нужный пункт среди соседних.
РАЗМЕР = 500
ПЕРЕКРЫТИЕ = 75
# Структурному чанку позволено быть больше: он режется по смыслу, и раздел в
# 700 токенов лучше целиком, чем пополам.
МАКС = 700
МИН = 120

РАЗДЕЛИТЕЛЬ = " › "


@dataclass
class Чанк:
    """Фрагмент документа с паспортом: всё, что нужно для ссылки на источник."""

    chunk_id: str
    стратегия: str
    источник: str
    название: str
    номер: int                     # порядковый номер чанка внутри документа
    текст: str
    раздел: str                    # раздел, где чанк начинается
    разделы: list[str] = field(default_factory=list)   # все разделы, которые он задел
    страница_с: int = 0
    страница_по: int = 0
    пункт: str = ""                # номер пункта, с которого начинается чанк
    токенов: int = 0
    распознан: bool = False        # хоть часть текста получена OCR
    контекст: str = ""             # строка «документ › раздел» для вектора

    @property
    def текст_для_вектора(self) -> str:
        return f"{self.контекст}\n{self.текст}" if self.контекст else self.текст

    @property
    def страницы(self) -> str:
        if not self.страница_с:
            return ""
        if self.страница_с == self.страница_по:
            return str(self.страница_с)
        return f"{self.страница_с}–{self.страница_по}"

    def паспорт(self) -> dict:
        """Метаданные без текста — для таблиц и ответов инструментов."""
        return {
            "chunk_id": self.chunk_id, "strategy": self.стратегия, "source": self.источник,
            "title": self.название, "section": self.раздел, "sections": list(self.разделы),
            "pages": self.страницы, "clause": self.пункт, "tokens": self.токенов,
            "ocr": self.распознан, "position": self.номер,
        }


def нарезать(документ: Документ, стратегия: str, размер: int = РАЗМЕР,
             перекрытие: int = ПЕРЕКРЫТИЕ, макс: int = МАКС, мин: int = МИН) -> list[Чанк]:
    if стратегия == ФИКС:
        if перекрытие >= размер:
            raise ValueError("Перекрытие должно быть меньше размера чанка")
        return _фикс(документ, размер, перекрытие)
    if стратегия == СТРУКТУРА:
        if мин >= макс:
            raise ValueError("Минимальный размер раздела должен быть меньше максимального")
        return _структура(документ, макс, мин)
    raise ValueError(f"Нет стратегии «{стратегия}». Есть: {', '.join(СТРАТЕГИИ)}")


def _id(стратегия: str, источник: str, номер: int) -> str:
    return f"{КОД[стратегия]}-{hashlib.sha1(источник.encode()).hexdigest()[:8]}-{номер:04d}"


def _путь(блок: Блок) -> str:
    return РАЗДЕЛИТЕЛЬ.join(блок.раздел) or "(начало документа)"


def _собрать(документ: Документ, стратегия: str, номер: int, блоки: list[Блок],
             текст: str, контекст: str = "") -> Чанк:
    разделы: list[str] = []
    for б in блоки:
        if _путь(б) not in разделы:
            разделы.append(_путь(б))
    пункт = next((б.пункт for б in блоки if б.пункт), "")
    return Чанк(
        chunk_id=_id(стратегия, документ.источник, номер), стратегия=стратегия,
        источник=документ.источник, название=документ.название, номер=номер,
        текст=текст, раздел=разделы[0] if разделы else "", разделы=разделы,
        страница_с=min(б.страница for б in блоки), страница_по=max(б.страница for б in блоки),
        пункт=пункт, токенов=estimate(текст), распознан=any(б.распознан for б in блоки),
        контекст=контекст,
    )


# --- фиксированный размер ------------------------------------------------------

def _фикс(документ: Документ, размер: int, перекрытие: int) -> list[Чанк]:
    """Лента слов документа, окно в `размер` токенов, шаг назад на `перекрытие`."""
    слова: list[tuple[str, int, int]] = []     # слово, его токены, номер блока
    for i, блок in enumerate(документ.блоки):
        for слово in блок.текст.split():
            слова.append((слово, max(1, estimate(слово + " ")), i))
    чанки: list[Чанк] = []
    начало = 0
    while начало < len(слова):
        конец, набрано = начало, 0
        while конец < len(слова) and (набрано + слова[конец][1] <= размер or конец == начало):
            набрано += слова[конец][1]
            конец += 1
        блоки = [документ.блоки[i] for i in sorted({с[2] for с in слова[начало:конец]})]
        текст = " ".join(с[0] for с in слова[начало:конец])
        чанки.append(_собрать(документ, ФИКС, len(чанки), блоки, текст))
        if конец >= len(слова):
            break
        # Шаг назад на перекрытие, но хотя бы на одно слово вперёд — иначе
        # одно огромное «слово» (строка таблицы без пробелов) зациклило бы резку.
        назад, откат = 0, конец
        while откат > начало + 1 and назад + слова[откат - 1][1] <= перекрытие:
            откат -= 1
            назад += слова[откат][1]
        начало = откат
    return чанки


# --- по структуре --------------------------------------------------------------

def _группы(документ: Документ) -> list[list[Блок]]:
    """Подряд идущие блоки с одним путём раздела — одна группа."""
    группы: list[list[Блок]] = []
    for блок in документ.блоки:
        if группы and группы[-1][0].раздел == блок.раздел:
            группы[-1].append(блок)
        else:
            группы.append([блок])
    return группы


def _куски_блока(блок: Блок, макс: int) -> list[str]:
    """Блок длиннее предела — по предложениям, в крайнем случае по словам."""
    if estimate(блок.текст) <= макс:
        return [блок.текст]
    куски, текущий = [], ""
    for часть in re.split(r"(?<=[.;!?])\s+", блок.текст):
        if estimate(часть) > макс:
            слова = часть.split()
            шаг = max(1, len(слова) * макс // max(1, estimate(часть)))
            части = [" ".join(слова[i:i + шаг]) for i in range(0, len(слова), шаг)]
        else:
            части = [часть]
        for ч in части:
            if текущий and estimate(текущий + " " + ч) > макс:
                куски.append(текущий)
                текущий = ч
            else:
                текущий = f"{текущий} {ч}".strip()
    if текущий:
        куски.append(текущий)
    return куски


def _структура(документ: Документ, макс: int, мин: int) -> list[Чанк]:
    группы = _группы(документ)
    # Склейка мелочи: раздел короче `мин` присоединяется к следующему, если у
    # них общий верхний уровень (то же приложение, тот же лист) и вместе они
    # не выходят за предел. Заголовок без текста иначе стал бы целым чанком.
    слитые: list[list[Блок]] = []
    for группа in группы:
        if слитые:
            прошлая = слитые[-1]
            мало = estimate(" ".join(б.текст for б in прошлая)) < мин
            вместе = estimate(" ".join(б.текст for б in прошлая + группа)) <= макс
            тот_же_верх = прошлая[0].раздел[:1] == группа[0].раздел[:1]
            if мало and вместе and тот_же_верх:
                прошлая.extend(группа)
                continue
        слитые.append(list(группа))

    чанки: list[Чанк] = []
    for группа in слитые:
        контекст = f"{документ.название}{РАЗДЕЛИТЕЛЬ}{_путь(группа[0])}"
        # Упаковка блоков в чанки по порядку: блок целиком, пока влезает.
        пачка: list[Блок] = []
        тексты: list[str] = []

        def выпустить() -> None:
            if тексты:
                чанки.append(_собрать(документ, СТРУКТУРА, len(чанки), list(пачка),
                                      "\n".join(тексты), контекст))
            пачка.clear()
            тексты.clear()

        for блок in группа:
            for кусок in _куски_блока(блок, макс):
                if тексты and estimate("\n".join(тексты + [кусок])) > макс:
                    выпустить()
                пачка.append(блок)
                тексты.append(кусок)
        выпустить()
    return чанки


def статистика(чанки: list[Чанк]) -> dict:
    """Размеры чанков одной стратегии: сколько, минимум, медиана, 90-й процентиль."""
    if not чанки:
        return {"чанков": 0}
    размеры = sorted(ч.токенов for ч in чанки)

    def доля(p: float) -> int:
        return размеры[min(len(размеры) - 1, int(p * (len(размеры) - 1) + 0.5))]

    return {
        "чанков": len(чанки), "токенов_всего": sum(размеры), "мин": размеры[0],
        "медиана": доля(0.5), "p90": доля(0.9), "макс": размеры[-1],
        "среднее": round(sum(размеры) / len(размеры)),
    }
