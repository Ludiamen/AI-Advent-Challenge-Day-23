"""Текст → вектор. Два эмбеддера за одним интерфейсом.

  ollama  локальная модель через HTTP Ollama (по умолчанию bge-m3: многоязычная,
          русский знает хорошо, 1024 числа на вектор, до 8192 токенов на вход).
          Документы не покидают машину — для договоров и бюджетов это важно,
          и лекция недели называет приватность первой причиной локального RAG.
  хэш     без модели: слова и их основы раскладываются хэшем по координатам.
          Это «мешок слов», а не смысл — синонимов он не знает. Нужен тестам,
          чтобы не зависеть от установленной Ollama, и как честная нижняя
          планка: если модель не лучше мешка слов, с ней что-то не так.

Нормализация. Лекция советует «делить на максимум, чтобы вышло от нуля до
единицы», но для косинусного сходства нужна другая нормировка — на длину
вектора (L2). После неё косинус равен скалярному произведению, и поиск в
индексе сводится к одному умножению матрицы на вектор. Деление на максимум
длину не выравнивает, и тогда скалярное произведение считало бы близким
просто более «громкий» вектор.

Интерфейс рассчитан на следующие дни: у `векторы()` есть флаг `запрос` — моделям
семейства e5 запрос и документ помечаются по-разному («query:» / «passage:»),
bge-m3 такая пометка не нужна.
"""

from __future__ import annotations

import hashlib
import math
import os
import re

import httpx

OLLAMA_URL = "http://127.0.0.1:11434"
МОДЕЛЬ_ПО_УМОЛЧАНИЮ = "bge-m3"
ХЭШ = "хэш"
OLLAMA = "ollama"
# Сколько текстов в одном запросе к Ollama. Больше — быстрее, но на CPU один
# запрос с сотней чанков идёт минуты и упирается в таймаут без признаков жизни.
ПАЧКА = 16
ОЖИДАНИЕ = 600


class ОшибкаЭмбеддера(RuntimeError):
    """Эмбеддер недоступен или ответил не векторами."""


def нормировать(вектор: list[float]) -> list[float]:
    длина = math.sqrt(sum(x * x for x in вектор))
    return [x / длина for x in вектор] if длина else list(вектор)


class ЭмбеддерOllama:
    def __init__(self, модель: str = "", адрес: str = "") -> None:
        self.модель = модель or os.getenv("RAG_EMBED_MODEL") or МОДЕЛЬ_ПО_УМОЛЧАНИЮ
        self.адрес = (адрес or os.getenv("OLLAMA_URL") or OLLAMA_URL).rstrip("/")
        self.размерность = 0

    @property
    def имя(self) -> str:
        return f"{OLLAMA}:{self.модель}"

    def проверить(self) -> str:
        """Жива ли Ollama и скачана ли модель. Пустая строка — всё в порядке."""
        try:
            ответ = httpx.get(f"{self.адрес}/api/tags", timeout=5)
            ответ.raise_for_status()
        except httpx.HTTPError:
            return (f"Ollama не отвечает на {self.адрес}. Запустите «ollama serve» "
                    f"(или установите: curl -fsSL https://ollama.com/install.sh | sh)")
        модели = {м.get("name", "") for м in ответ.json().get("models", [])}
        if not any(м == self.модель or м.startswith(self.модель + ":") for м in модели):
            return f"В Ollama нет модели {self.модель}: выполните «ollama pull {self.модель}»"
        return ""

    def векторы(self, тексты: list[str], запрос: bool = False,
                прогресс=None) -> list[list[float]]:
        итог: list[list[float]] = []
        for начало in range(0, len(тексты), ПАЧКА):
            пачка = тексты[начало:начало + ПАЧКА]
            try:
                ответ = httpx.post(f"{self.адрес}/api/embed",
                                   json={"model": self.модель, "input": пачка},
                                   timeout=ОЖИДАНИЕ)
            except httpx.HTTPError as exc:
                raise ОшибкаЭмбеддера(f"Ollama не ответила: {exc}. {self.проверить()}") from exc
            if ответ.status_code != 200:
                raise ОшибкаЭмбеддера(
                    f"Ollama вернула {ответ.status_code}: {ответ.text[:200]}. {self.проверить()}")
            векторы = ответ.json().get("embeddings") or []
            if len(векторы) != len(пачка):
                raise ОшибкаЭмбеддера(
                    f"Ollama вернула {len(векторы)} векторов на {len(пачка)} текстов")
            итог.extend(нормировать(в) for в in векторы)
            if прогресс:
                прогресс(len(итог), len(тексты))
        if итог:
            self.размерность = len(итог[0])
        return итог


_СЛОВО = re.compile(r"\w+", re.UNICODE)


class ЭмбеддерХэш:
    """Мешок слов в 512 координатах: слово целиком и его основа из пяти букв.

    Хэш берётся из hashlib, а не встроенный hash(): тот случаен от запуска к
    запуску, и вчерашний индекс перестал бы совпадать с сегодняшним запросом.
    """

    размерность = 512
    имя = ХЭШ

    def проверить(self) -> str:
        return ""

    def _вектор(self, текст: str) -> list[float]:
        вектор = [0.0] * self.размерность
        for слово in _СЛОВО.findall(текст.lower()):
            for признак, вес in ((слово, 1.0), (слово[:5], 0.7)):
                код = hashlib.md5(признак.encode()).digest()
                индекс = int.from_bytes(код[:4], "little") % self.размерность
                вектор[индекс] += вес if код[4] & 1 else -вес
        return нормировать(вектор)

    def векторы(self, тексты: list[str], запрос: bool = False,
                прогресс=None) -> list[list[float]]:
        итог = [self._вектор(т) for т in тексты]
        if прогресс:
            прогресс(len(итог), len(тексты))
        return итог


def создать_эмбеддер(имя: str = ""):
    """«ollama», «ollama:bge-m3», «хэш». Пусто — из RAG_EMBEDDER, иначе ollama."""
    имя = (имя or os.getenv("RAG_EMBEDDER") or OLLAMA).strip()
    if имя in (ХЭШ, "hash"):
        return ЭмбеддерХэш()
    if имя == OLLAMA or имя.startswith(OLLAMA + ":"):
        return ЭмбеддерOllama(имя.partition(":")[2])
    raise ОшибкаЭмбеддера(f"Нет эмбеддера «{имя}». Есть: ollama[:модель], хэш")
