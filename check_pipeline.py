def часть_3(отчёт: Отчёт, ящик: amcp.Toolbox, база: str, отчёты: str) -> int:
    отчёт.часть(3, "Цепочка выполняется сама: один вызов — четыре шага")
    начало = time.monotonic()
    прогон = ящик.вызвать("pipeline__run_pipeline", {
        "pipeline": КОНВЕЙЕР, "input": {"имя": "отчёт-проверки"},
        "why": "проверка дня 19"})
    данные = прогон.данные or {}
    отчёт.пункт(прогон.ок and данные.get("состояние") == "готов",
                f"один вызов run_pipeline — цепочка целиком за "
                f"{_секунды(time.monotonic() - начало)}")
    отчёт.пункт(данные.get("сделано") == 4,
                f"шагов выполнено: {данные.get('сделано')} из {данные.get('шагов')}")

    номер = int(данные.get("прогон", 0))
    шаги = _шаги_из_базы(база, номер)
    отчёт.пункт(len(шаги) == 4, "протокол прогона нашёлся в SQLite прямым запросом мимо агента")
    порядок = [ш["имя"] for ш in шаги]
    отчёт.пункт(порядок == ["задачи", "память", "выжимка", "файл"],
                f"порядок шагов сохранён: {' → '.join(порядок)}")
    серверы = {ш["инструмент"].split("__")[0] for ш in шаги}
    отчёт.пункт(len(серверы) >= 2,
                f"цепочка пересекла границы серверов: {', '.join(sorted(серверы))}")
    for шаг in шаги:
        отчёт(f"      {шаг['место']}. {шаг['имя']} → {шаг['инструмент']}: "
              + ("ок" if шаг["ок"] else f"сбой ({шаг['ошибка']})"))

    файл = данные.get("итог", "")
    полный = файл if os.path.isabs(файл) else os.path.join(КОРЕНЬ, файл)
    отчёт.пункт(bool(файл) and os.path.exists(полный),
                f"последний шаг оставил файл на диске: {os.path.basename(полный)}")
    return номер


def часть_4(отчёт: Отчёт, ящик: amcp.Toolbox, база: str, мок: МокТрекера,
            прогон: int) -> None:
    отчёт.часть(4, "Данные передаются корректно: вход шага равен выходу предыдущего")
    шаги = {ш["имя"]: ш for ш in _шаги_из_базы(база, прогон)}

    задачи = (шаги["задачи"]["выход"] or {}).get("задачи", [])
    выжимка_вход = шаги["выжимка"]["вход"].get("data", {})
    отчёт.пункт(выжимка_вход.get("задачи") == задачи,
                f"выход шага «задачи» ({len(задачи)} задач) дословно равен входу «выжимки»")
    находки = (шаги["память"]["выход"] or {}).get("находки", [])
    отчёт.пункт(выжимка_вход.get("память") == находки,
                f"выход шага «память» ({len(находки)} записей) тоже доехал в «выжимку»")
    текст = (шаги["выжимка"]["выход"] or {}).get("текст", "")
    отчёт.пункт(шаги["файл"]["вход"].get("text") == текст,
                f"выход «выжимки» ({len(текст)} симв.) дословно равен входу шага «файл»")
    пути = [п[0] for п in шаги["файл"]["подстановки"]]
    отчёт.пункт("выжимка.данные.текст" in пути,
                f"в протоколе записано, ЧЕМ данные переданы: {', '.join(пути)}")

    # Сквозная проверка: меняем чужую систему её собственным API (мимо агента)
    # и смотрим, доедет ли новое значение до файла на диске.
    переходы = мок.запрос("GET", "/v3/issues/MIG-2/transitions").json()
    целевой = next((п for п in переходы
                    if "test" in (п.get("to", {}).get("key", "")).lower()), None)
    if целевой:
        мок.запрос("POST", f"/v3/issues/MIG-2/transitions/{целевой['id']}/_execute",
                   json={})
    стало = мок.запрос("GET", "/v3/issues/MIG-2").json().get("status", {}).get("display", "")
    отчёт.пункт(bool(целевой), f"MIG-2 переведена прямо через API трекера: {стало}")
    второй = ящик.вызвать("pipeline__run_pipeline", {
        "pipeline": КОНВЕЙЕР, "input": {"имя": "отчёт-после-правки"},
        "why": "сквозная проверка"})
    данные = второй.данные or {}
    номер = int(данные.get("прогон", 0))
    шаги2 = {ш["имя"]: ш for ш in _шаги_из_базы(база, номер)}
    задачи2 = (шаги2["задачи"]["выход"] or {}).get("задачи", [])
    статус = next((з.get("статус") for з in задачи2 if з.get("ключ") == "MIG-2"), "")
    отчёт.пункт("ест" in статус.lower(),
                f"первый шаг увидел новое состояние чужой системы: MIG-2 — {статус}")
    вход_файла = шаги2["файл"]["вход"].get("text", "")
    путь = данные.get("итог", "")
    полный = путь if os.path.isabs(путь) else os.path.join(КОРЕНЬ, путь)
    на_диске = open(полный, encoding="utf-8").read() if os.path.exists(полный) else ""
    отчёт.пункт(bool(вход_файла) and вход_файла[:60] in на_диске,
                "и то же самое лежит в файле отчёта: данные прошли всю цепочку до диска")


